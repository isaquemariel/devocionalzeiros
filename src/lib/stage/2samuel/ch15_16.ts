// ============================================================================
// 2 SAMUEL 15–16 — CENA VIVA. A CONSPIRAÇÃO DE ABSALÃO e a FUGA DESCALÇA do
// rei pelo monte das Oliveiras; e depois, do outro lado do cume, ZIBA com os
// jumentos albardados e SIMEI atirando pedras na encosta de Baurim.
//
// 2Sm 15 — A revolta não começa com um exército: começa com um CARRO, CAVALOS
// e CINQUENTA HOMENS QUE CORRESSEM ADIANTE. Absalão se levanta de madrugada e
// para AO LADO DO CAMINHO DA PORTA, e intercepta um por um os que sobem a
// juízo: "de que cidade és tu?" — e a cada resposta a mesma sentença montada,
// "olha, os teus negócios são bons e retos, PORÉM NÃO TENS QUEM TE OUÇA DA
// PARTE DO REI", e o suspiro calculado, "AH, QUEM ME DERA SER JUIZ NA TERRA".
// Quando o homem se chega para se inclinar diante dele, ele não deixa: estende
// a mão, PEGA E BEIJA. Quatro anos disso — "assim FURTAVA Absalão o coração dos
// homens de Israel". O golpe se abre com um pretexto religioso: o VOTO feito em
// Gesur, a ser pago em HEBROM, a cidade onde o próprio Davi fora ungido; o rei
// diz "vai em paz", e é a última coisa que os dois se dizem em paz. Vão espias
// por todas as tribos com uma senha de TROMBETA — "Absalão reina em Hebrom" —,
// vão DUZENTOS CONVIDADOS de Jerusalém que iam NA SUA SIMPLICIDADE, porque nada
// sabiam do negócio, e vem de Giló AITOFEL, o conselheiro de Davi. A conjuração
// se fortifica, e o povo IA CRESCENDO com Absalão. Um mensageiro chega ao
// palácio: "o coração de cada um em Israel segue a Absalão" — e Davi, que
// ganhara Jerusalém com uma tomada de fortaleza, a entrega sem golpe: "LEVANTAI-
// VOS, E FUJAMOS". Sai a pé com toda a casa, deixando DEZ CONCUBINAS para
// guardar a casa (e é sobre elas que a palavra de Natã vai cair, no cap. 16).
// Na última casa da saída o rei PARA, e todo o povo passa AO LADO DELE: os
// quereteus, os peleteus, e os SEISCENTOS GITEUS que tinham vindo de Gate a pé.
// A ITAI, o giteu, o rei manda voltar — "és estrangeiro, e também desterrado de
// teu lugar" — e recebe um dos maiores juramentos de lealdade da Bíblia: ⭐ "NO
// LUGAR EM QUE ESTIVER O REI MEU SENHOR, SEJA PARA MORTE SEJA PARA VIDA, AÍ
// CERTAMENTE ESTARÁ TAMBÉM O TEU SERVIDOR". Toda a terra chora A GRANDES VOZES
// enquanto o povo passa o ribeiro de CEDROM. Zadoque e os levitas trazem a ARCA
// — e o rei a MANDA DE VOLTA, no ato mais desarmado do livro: ⭐ "SE ACHAR
// GRAÇA NOS OLHOS DO SENHOR, ELE ME TORNARÁ A TRAZER… SE PORÉM DISSER: NÃO
// TENHO PRAZER EM TI; EIS-ME AQUI, FAÇA DE MIM COMO PARECER BEM AOS SEUS
// OLHOS". Sobe então a encosta do MONTE DAS OLIVEIRAS chorando, COM A CABEÇA
// COBERTA E OS PÉS DESCALÇOS, e todo o povo sobe assim, cobrindo cada um a sua
// cabeça. No meio da subida vem a notícia de que Aitofel está entre os
// conjurados, e o rei ora uma oração de uma linha só: "Ó SENHOR, PEÇO-TE QUE
// TORNE EM LOUCURA O CONSELHO DE AITOFEL". No cume, onde se adorava a Deus, a
// oração já vem respondida de pé: HUSAI, o arquita, com a ROUPA RASGADA e TERRA
// SOBRE A CABEÇA — mandado de volta como amigo do rei dentro da corte do filho,
// com Zadoque, Abiatar e os dois moços, Aimaás e Jônatas, por correio.
//
// 2Sm 16 — Passado um pouco do cume, ZIBA vem ao encontro com UM PAR DE
// JUMENTOS ALBARDADOS, duzentos pães, cem cachos de passas, cem de frutas de
// verão e um odre de vinho — e com uma acusação na boca contra o aleijado a
// quem ele servia: "HOJE ME RESTITUIRÁ A CASA DE ISRAEL O REINO DE MEU PAI".
// Numa frase Ziba fica com toda a fazenda de Mefibosete. Em BAURIM sai da
// linhagem da casa de Saul SIMEI, FILHO DE GERA, e vai AMALDIÇOANDO pela
// encosta, ATIRANDO PEDRAS contra o rei e contra todos os servos — com o povo e
// todos os valentes indo à direita e à esquerda, e ninguém o toca: "sai, sai,
// HOMEM DE SANGUE, e homem de Belial… eis-te agora na tua desgraça". Abisai
// pede a licença óbvia ("por que amaldiçoaria este CÃO MORTO ao rei meu
// senhor? deixa-me passar, e lhe tirarei a cabeça"), e o rei responde o cume
// espiritual do livro: ⭐ "ORA DEIXAI-O AMALDIÇOAR; POIS O SENHOR LHE DISSE:
// AMALDIÇOA A DAVI… PORVENTURA O SENHOR OLHARÁ PARA A MINHA MISÉRIA, E O SENHOR
// ME PAGARÁ COM BEM A SUA MALDIÇÃO DESTE DIA". E seguem: o rei por baixo,
// Simei ao longo do monte, defronte dele, caminhando, amaldiçoando, atirando
// pedras e LEVANTANDO POEIRA — até chegarem cansados e se refrescarem ali.
// Em Jerusalém, Absalão entra com todo o Israel, e Aitofel com ele; Husai grita
// "VIVA O REI, VIVA O REI!" e aguenta a desconfiança de frente ("é esta a tua
// beneficência para com o teu amigo?"). E vem o primeiro conselho de Aitofel: a
// TENDA ARMADA NO TERRAÇO e as concubinas do pai possuídas PERANTE OS OLHOS DE
// TODO O ISRAEL — o mesmo terraço de onde Davi vira Bate-Seba, cumprindo ao pé
// da letra o que Natã dissera em 12:11-12 ("à vista deste sol"). O capítulo
// fecha com a nota mais fria do narrador: o conselho de Aitofel, naqueles dias,
// era ouvido "COMO SE A PALAVRA DE DEUS SE CONSULTARA" — assim para com Davi
// como para com Absalão.
//
// A VOZ DE DEUS (regra do projeto): nestes dois capítulos o SENHOR NÃO FALA —
// não há um único `by:"deus"` aqui, e é deliberado. As duas frases que parecem
// oráculo são humanas: a oração de 15:31 é DE DAVI (`by:"rei"`, joelho no chão
// na encosta do Olival), e o "o Senhor lhe disse: Amaldiçoa a Davi" de 16:10-11
// é DAVI CITANDO — o balão sai da boca dele, não do céu, porque é ele quem lê a
// maldição de Simei como mandado do SENHOR. Até a arca, que é o único mediador
// visível da presença em cena (15:24-29), é mandada de volta sem dizer palavra:
// o palco a mostra com `glow` nos sacerdotes e depois a tira do quadro — o rei
// desce o monte sem sinal nenhum. Por isso a GLÓRIA aqui é baixa quase o tempo
// todo e só sobe em três lugares: na oração de 15:31, na entrega de 15:26 e na
// resposta a Abisai em 16:12 — os três momentos em que Davi entrega o resultado
// a Deus. FOGO desenhado só pelo `altar` de Hebrom e pela `campfire` do
// descanso; `env.fire` é ambiência. Nada de `multidao` no pranto de Cedrom, na
// subida descalça nem no apedrejamento: ali o luto é encenado por figuras
// individuais em `bow`/`kneel`/`lie`. A multidão festiva entra só duas vezes, e
// nas duas está do lado errado da história: 15:12 (o povo crescendo com
// Absalão) e 16:15 (a entrada em Jerusalém).
// ============================================================================

