// 2 SAMUEL 23–24 — CENA VIVA. O FECHO DO LIVRO: as ÚLTIMAS PALAVRAS DE DAVI e
// o rol dos seus VALENTES; depois o CENSO, a PESTE e a EIRA DE ARAÚNA, que é o
// chão onde um dia se levantará o templo.
//
// 2Sm 23 — "E estas são as últimas palavras de Davi". O oráculo se abre como um
// salmo e se apresenta em quatro títulos: DAVI, FILHO DE JESSÉ — o menino do
// rebanho; O HOMEM QUE FOI LEVANTADO EM ALTURA — o que Deus tirou do curral e
// pôs no trono; O UNGIDO DO DEUS DE JACÓ — o azeite de Samuel ainda escorrendo
// por cima de tudo; e O SUAVE EM SALMOS DE ISRAEL — a harpa, que foi a primeira
// coisa que o levou à casa do rei e é a última que ele nomeia de si. Então vem
// a confissão que dá autoridade ao resto: "O ESPÍRITO DO SENHOR FALOU POR MIM,
// E A SUA PALAVRA ESTÁ NA MINHA BOCA" — e Davi CITA o que ouviu: "Disse o Deus
// de Israel, A ROCHA DE ISRAEL A MIM ME FALOU: Haverá um justo que domine sobre
// os homens, que domine no temor de Deus". E o retrato desse rei justo é a
// imagem mais bonita que a Bíblia já fez de um governo: ⭐ "E SERÁ COMO A LUZ DA
// MANHÃ, QUANDO SAI O SOL, DA MANHÃ SEM NUVENS, QUANDO PELO SEU RESPLENDOR E
// PELA CHUVA A ERVA BROTA DA TERRA" — o justo não é o que pisa, é o que faz
// brotar. Aí o velho rei olha para a própria casa e não mente sobre ela: "AINDA
// QUE A MINHA CASA NÃO SEJA TAL PARA COM DEUS" — não é: houve Bate-Seba, houve
// Urias, houve Amnom, houve Absalão — "CONTUDO ESTABELECEU COMIGO UMA ALIANÇA
// ETERNA, QUE EM TUDO SERÁ BEM ORDENADO E GUARDADO, POIS TODA A MINHA SALVAÇÃO
// E TODO O MEU PRAZER ESTÁ NELE". A esperança dele não está na sua casa, está na
// aliança. E o contrário disso são os FILHOS DE BELIAL: espinhos que se lançam
// fora, que ninguém toca com a mão — quem os toca se arma de ferro e da haste de
// uma lança — e que a fogo são totalmente queimados NO MESMO LUGAR.
//   Depois o texto vira um monumento de pedra: OS PODEROSOS QUE DAVI TEVE.
// JOSEBE-BASSEBETE, o principal dos capitães, que se opôs a OITOCENTOS e os
// feriu de uma vez. ELEAZAR, filho de Dodó, que ficou de pé quando os homens de
// Israel se retiraram e feriu os filisteus ATÉ LHE CANSAR A MÃO E FICAR A MÃO
// PEGADA À ESPADA — "e naquele dia o SENHOR efetuou um grande livramento; e o
// povo voltou junto dele, SOMENTE A TOMAR O DESPOJO". SAMÁ, filho de Agé, que
// se pôs no meio de um PEDAÇO DE TERRA CHEIO DE LENTILHAS, quando todo o povo
// fugia, e defendeu aquele nada — porque nada que é de Deus é pequeno. E a cena
// que coroa o capítulo: três dos trinta descem NO TEMPO DA SEGA à CAVERNA DE
// ADULÃO; a multidão dos filisteus está acampada no vale de Refaim e a guarnição
// deles está em BELÉM, a cidade natal do rei. Davi diz em voz alta um desejo de
// homem cansado: ⭐ "QUEM ME DERA BEBER DA ÁGUA DA CISTERNA DE BELÉM, QUE ESTÁ
// JUNTO À PORTA!" — e os três ROMPEM PELO ARRAIAL DOS FILISTEUS, tiram a água e
// a trazem. Davi NÃO A QUIS BEBER: derramou-a perante o SENHOR — "beberia eu o
// sangue dos homens que foram com risco da sua vida?". Vem ABISAI, que alçou a
// lança contra trezentos; vem BENAIA, filho de Joiada, que feriu dois fortes
// heróis de Moabe, desceu a uma cova e matou ali um LEÃO NO TEMPO DA NEVE, e
// matou o egípcio de respeito ARRANCANDO-LHE A LANÇA DA MÃO e matando-o com a
// própria lança. E o rol dos trinta desce nome a nome, aldeia a aldeia, até o
// último — que o leitor deste livro não consegue mais ler sem estremecer:
// "URIAS, HETEU; TRINTA E SETE AO TODO".
//
// 2Sm 24 — A ira do SENHOR se torna a acender contra Israel, e Davi é incitado:
// "Vai, NUMERA a Israel e a Judá". JOABE, que não costuma ter escrúpulos, tem
// este: "ora, multiplique o SENHOR teu Deus a este povo cem vezes tanto quanto
// agora é… mas por que deseja o rei meu senhor este negócio?" — o povo é de
// Deus, e contar é começar a achar que é seu. A palavra do rei prevalece, e o
// exército sai a medir a herança: passam o JORDÃO, acampam em AROER, junto a
// JAZER, sobem a GILEADE e à terra baixa de HODSI, vão até DÃ-JAÃ e ao redor de
// SIDOM, à FORTALEZA DE TIRO e às cidades dos heveus e dos cananeus, e descem
// ao sul de Judá, a BERSEBA. NOVE MESES E VINTE DIAS de caminho para trazer um
// número: oitocentos mil homens de guerra em Israel, quinhentos mil em Judá. E
// então, tarde demais, PESA O CORAÇÃO DE DAVI: "muito pequei no que fiz". Pela
// manhã a palavra do SENHOR vem ao profeta GADE, vidente de Davi, e Gade põe
// diante do rei TRÊS COISAS: sete anos de fome, três meses de fuga diante dos
// inimigos, ou três dias de peste. A escolha de Davi é uma confissão de fé: ⭐
// "ESTOU EM GRANDE ANGÚSTIA; PORÉM CAIAMOS NAS MÃOS DO SENHOR, PORQUE MUITAS
// SÃO AS SUAS MISERICÓRDIAS; MAS NAS MÃOS DOS HOMENS NÃO CAIA EU". A peste vai
// desde a manhã até ao tempo determinado e, DESDE DÃ ATÉ BERSEBA — exatamente o
// caminho que os contadores fizeram —, morrem setenta mil. O ANJO estende a mão
// sobre Jerusalém para a destruir, e o SENHOR se arrepende daquele mal: "BASTA,
// AGORA RETIRA A TUA MÃO" — e o anjo do SENHOR está parado JUNTO À EIRA DE
// ARAÚNA, O JEBUSEU. Davi vê o anjo que feria o povo e faz a oração de um
// pastor: "eu sou o que pequei… PORÉM ESTAS OVELHAS QUE FIZERAM? seja, pois, a
// tua mão contra mim e contra a casa de meu pai". Gade manda subir e levantar um
// altar na eira. Araúna vê o rei chegando, sai, prostra-se com o rosto em terra
// e oferece tudo de graça: os bois para o holocausto, os TRILHOS e o APARELHO
// DOS BOIS para a lenha. E o livro termina na frase que resume o culto inteiro:
// ⭐ "NÃO, MAS POR PREÇO JUSTO TO COMPRAREI, PORQUE NÃO OFERECEREI AO SENHOR MEU
// DEUS HOLOCAUSTOS QUE NÃO ME CUSTEM NADA". Cinquenta siclos de prata, um altar
// edificado, holocaustos e ofertas pacíficas — e o SENHOR se aplaca para com a
// terra. Aquela eira comprada a preço é o monte Moriá (2Cr 3:1): o chão do
// templo que Salomão levantaria. O livro fecha com fogo aceso num lugar pago.
//
// A VOZ DE DEUS (regra do projeto). Três casos, e cada um resolvido de um jeito:
//  • 24:1 — "e incitou a Davi contra eles, DIZENDO: Vai, numera a Israel e a
//    Judá". Não há mediador nenhum na frase: é oráculo/incitamento sem boca
//    humana. É o ÚNICO `by:"deus"` destes dois capítulos, com `glory` alta e
//    ninguém no centro do palco — a glória aqui é terrível, não amável, e por
//    isso vem acompanhada de `storm` alto.
//  • 24:11-14 e 24:18 — a palavra vem "ao profeta GADE, vidente de Davi", e é
//    Gade quem a leva. Nada de voz do céu para as três coisas: em 24:12 o balão
//    é de GADE (`by:"homem"`, id `gade-profeta`) com `glow` alto, porque ele é o
//    mediador visível a quem a palavra foi entregue, e em 24:13,18 ele já está
//    falando a Davi cara a cara. O v.11 fica sem balão: é a narração da vinda da
//    palavra, e o palco a conta pela madrugada que rompe e pelo brilho no
//    profeta.
//  • 24:16 — "e disse AO ANJO que fazia a destruição entre o povo: Basta, agora
//    retira a tua mão". Aqui há mediador VISÍVEL em cena, e por isso o balão sai
//    do ANJO (`by:"anjo"`, id `anjo-destruidor`), não do céu: o motor precisa de
//    uma figura de onde a fala saia, e a figura legítima é a criatura enviada —
//    Deus continua sem ser desenhado, e o que o palco mostra é o braço estendido
//    baixando sobre a eira. (A deixa arrasta consigo a última linha narrativa do
//    versículo, que nomeia a eira de Araúna: aceitamos de propósito, porque é
//    justamente o lugar que a cena está mostrando.)
//  Em 23:2-3 quem fala é DAVI: ele CITA o que o Espírito e a Rocha de Israel lhe
//  disseram. O balão é dele (`by:"rei"`), com a glória subindo sobre o terraço —
//  citação de oráculo não é oráculo, e o mediador aqui é o próprio salmista.
//  Fogo desenhado só por `campfire` (os espinhos de 23:7, a fogueira de Adulão)
//  e por `altar` com `fire` (o holocausto de 24:25) — `env.fire` é ambiência.
//  Nos beats da peste (24:15) e da matança dos valentes NUNCA entra `multidao`,
//  que o motor desenha sempre comemorando; ali as mortes são figuras
//  individuais em `lie`. `multidao` só aparece onde há festa ou recenseamento:
//  a revista dos trinta (23:24) e a soma do povo (24:9).
// ============================================================================

