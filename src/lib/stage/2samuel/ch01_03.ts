// IRMÃO. Davi amaldiçoa a casa de Joabe e impõe o luto público — "RASGAI AS
// VOSSAS VESTES; E CINGI-VOS DE SACOS E IDE PRANTEANDO DIANTE DE ABNER" — e o
// próprio rei vai seguindo o féretro. Sobre a cova, a elegia curta e cortante:
// ⭐ "HAVIA DE MORRER ABNER COMO MORRE O VILÃO? As tuas mãos não estavam
// atadas, nem os teus pés carregados de grilhões". Jejua até o sol se pôr, e
// isso PARECEU BEM AOS OLHOS DE TODO O POVO — que entendeu naquele mesmo dia
// que não procedera do rei matar Abner. E fica a queixa: "eu hoje estou fraco,
// AINDA QUE UNGIDO REI; estes homens, filhos de Zeruia, são mais duros do que
// eu".
//
// A VOZ DE DEUS (regra do projeto): nestes três capítulos o SENHOR fala UMA
// única vez, e sem nenhum mediador visível — a consulta de 2:1 ("Sobe… para
// Hebrom"). Ali, e só ali, há `by:"deus"`: glória alta (0.88), Davi de joelhos
// e NENHUMA figura para a voz. Todo o resto da teologia do trecho sai de bocas
// humanas: "o ungido do Senhor" na sentença de Davi contra o amalequita (1:14,
// 16), a bênção sobre Jabes-Gileade (2:6), o juramento de Abner citando o que
// "o Senhor jurou a Davi" (3:9-10,18) — que é Abner falando, não voz do céu — e
// a entrega final do juízo, "o Senhor pagará ao malfeitor" (3:39).
//
// Duas decisões de direção que valem para o arquivo inteiro:
// • O LUTO NUNCA USA `multidao`. O motor desenha a multidão SEMPRE
//   comemorando, de braços erguidos: no pranto de Ziclague (1:11-12), no
//   cântico (1:19-27), no campo dos mortos (2:16,30-31) e no cortejo de Abner
//   (3:31-37) o povo é sempre figura individual em `bow`/`kneel`/`lie`. Ela
//   entra só duas vezes, onde o texto de fato festeja: a unção de Hebrom (2:4)
//   e as filhas dos filisteus que o cântico proíbe de saltar de contentamento
//   (1:20) — o contraste é o ponto do verso.
// • NO CÂNTICO (1:19-27) DAVI FICA EM CENA como o cantor, à beira do quadro,
//   enquanto a IMAGEM ATRÁS DELE MUDA a cada versículo: os altos, as ruas de
//   Gate, Gilboa sem orvalho, as armas no campo, os dois corpos que não se
//   separaram, as filhas de Israel, o cume de Jônatas e, no fim, o chão vazio
//   com a coroa, a espada, a lança e o arco. É por isso que o balão continua
//   sendo dele em todos os nove versos.
//
// Armas e realeza usam os props próprios — `sword`, `spear`, `bow`, `crown`,
// `pool`, `trumpet`, `chariot`, `horse` —, nunca `rod` (que é a vara de Arão).
