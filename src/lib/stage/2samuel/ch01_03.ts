// do arraial de Saul COM AS VESTES ROTAS E COM TERRA SOBRE A CABEÇA, se lança
// no chão e se inclina. A notícia vem em pedaços: o povo fugiu da batalha,
// muitos caíram, e também Saul e Jônatas foram mortos. Davi pergunta como ele
// sabe — e o moço inventa a versão que julga que vai agradar: chegou POR ACASO
// à montanha de Gilboa, viu o rei encostado sobre a sua lança com os carros e a
// cavalaria apertando-o, foi chamado, disse "Sou amalequita", e o próprio rei
// lhe pediu "arremessa-te sobre mim, e mata-me". Ele diz que se arremessou —
// e traz a prova: A COROA QUE TINHA NA CABEÇA E O BRACELETE QUE TRAZIA NO
// BRAÇO, postos aos pés de Davi. A recompensa que ele esperava não vem. Davi
// apanha as suas vestes e as RASGA, e assim fazem todos os homens que estavam
// com ele; e prantearam, e choraram, E JEJUARAM ATÉ À TARDE por Saul, por
// Jônatas, PELO POVO DO SENHOR E PELA CASA DE ISRAEL. Depois vem a sentença:
// "como não temeste tu estender a mão para matares AO UNGIDO DO SENHOR?" —
// e ⭐ "O TEU SANGUE SEJA SOBRE A TUA CABEÇA, PORQUE A TUA PRÓPRIA BOCA
// TESTIFICOU CONTRA TI". Então Davi LAMENTA a Saul e a Jônatas com a
// lamentação que mandou ENSINAR AOS FILHOS DE JUDÁ — O USO DO ARCO, escrito no
// livro de Jasher: "não o noticieis em Gate, não o publiqueis nas ruas de
// Ascalom"; "vós, montes de Gilboa, NEM ORVALHO, NEM CHUVA caia sobre vós",
// pois ali foi arrojado o escudo de Saul COMO SE NÃO FORA UNGIDO COM ÓLEO; o
// arco de Jônatas que nunca se retirou para trás e a espada de Saul que nunca
// voltou vazia; ⭐ "SAUL E JÔNATAS, TÃO AMADOS E QUERIDOS NA SUA VIDA, TAMBÉM
// NA SUA MORTE NÃO SE SEPARARAM"; as filhas de Israel que ele vestia de
// escarlata e de ouro, mandadas chorar; e o fecho pessoal, o mais nu do livro:
// "angustiado estou por ti, meu irmão Jônatas… MAIS MARAVILHOSO ME ERA O TEU
// AMOR DO QUE O AMOR DAS MULHERES. Como caíram os poderosos, E PERECERAM AS
// ARMAS DE GUERRA!".
//
// 2Sm 2 — Depois disto Davi CONSULTA AO SENHOR: "subirei a alguma das cidades
// de Judá?" — "Sobe." — "Para onde subirei?" — "PARA HEBROM." Sobe com as duas
// mulheres, Ainoã e Abigail, e com os homens e suas famílias, e vêm os homens
// de Judá e O UNGEM REI SOBRE A CASA DE JUDÁ. A primeira coisa que o novo rei
// faz é abençoar os HOMENS DE JABES-GILEADE, que sepultaram Saul. Do outro
// lado do Jordão, Abner toma Is-Bosete, filho de Saul, o faz passar a MAANAIM
// e o constitui rei sobre Gileade, os assuritas, Jizreel, Efraim, Benjamim e
// todo o Israel — dois anos de Is-Bosete contra SETE ANOS E SEIS MESES de Davi
// em Hebrom. Os dois reinos se encontram no TANQUE DE GIBEOM, assentados um de
// cada lado da água. "Deixa levantar os moços, e JOGUEM DIANTE DE NÓS" — doze
// de Benjamim e doze dos servos de Davi, e cada um lança mão da cabeça do
// outro e lhe crava A ESPADA no lado, e CAEM JUNTOS: por isso o lugar se chamou
