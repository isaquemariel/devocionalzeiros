// GAZELAS DO CAMPO, persegue Abner sem se desviar nem para a direita nem para
// a esquerda; três vezes Abner o manda desviar-se ("como levantaria eu o meu
// rosto diante de Joabe, teu irmão?"), e à terceira o fere COM O CONTO DA
// LANÇA pela quinta costela, e a lança lhe sai por detrás — e todos os que
