// 2Sm 3 — A guerra é LONGA: a casa de Davi se fortalecendo, a de Saul se
// enfraquecendo. Em Hebrom nascem SEIS FILHOS de seis mulheres — Amnom,
// Quileabe, Absalão, Adonias, Sefatias, Itreão (metade deles vai ensanguentar
// os capítulos seguintes). Abner se faz poderoso na casa de Saul, e Is-Bosete
// o acusa por RISPA, a concubina do pai: a ira de Abner é imediata — "SOU EU
// CABEÇA DE CÃO?" — e o juramento também: TRANSFERIR O REINO da casa de Saul e
