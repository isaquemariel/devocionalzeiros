// O JOVEM, COM ABSALÃO?". Aimaás se esquiva; Cusi responde com a frase que mata:
// "SEJAM COMO AQUELE JOVEM OS INIMIGOS DO REI MEU SENHOR". E o rei sobe à SALA
// QUE ESTAVA POR CIMA DA PORTA e chora andando: ⭐ "MEU FILHO ABSALÃO, MEU FILHO,
// MEU FILHO, ABSALÃO! QUEM ME DERA QUE EU MORRERA POR TI".
//
// A VOZ DE DEUS (regra do projeto): nestes dois capítulos DEUS NÃO FALA — não há
// um único `by:"deus"`, e isso é deliberado. Em 17:14 a ação é do SENHOR, mas o
// texto a NARRA entre parênteses, por dentro de uma deliberação humana: por isso
// o palco não abre balão nenhum ali — sobe a GLÓRIA (0.66) sobre a sala do
// conselho exatamente no instante em que Absalão escolhe o conselho errado, e
// desce de novo no versículo seguinte. É a única vez em 62 beats que a luz vem
// de cima sem que ninguém a invoque. Fora dali, a glória é sempre humana e
// pequena: sobe um pouco na hospitalidade de Barzilai (17:29) e na ordem do rei
// sobre o moço (18:5), e some por completo do 18:6 em diante — o bosque de
// Efraim é encenado com `night` alto, `verdure` alto e `glory` quase zero, e o
// capítulo termina em 0.02. NADA de `multidao` em 18:14-17 (a morte e a cova)
// nem em 18:33 (o choro na sala da porta): o motor desenha a multidão SEMPRE
// comemorando, de braços erguidos, e ali o quadro é de luto — figuras
// individuais em `lie`, `bow` e `kneel`. As armas e as montarias usam os props
// próprios: `spear` nos três dardos, `sword` na espada que o bosque superou,
// `donkey` no jumento que Aitofel albarda para ir morrer em casa e na mula que
// passa adiante sem o dono, `well` no poço de Baurim, `pillar` na coluna do Vale
// do Rei, `bed` nas camas de Barzilai, `trumpet` na buzina de Joabe.
// ============================================================================

