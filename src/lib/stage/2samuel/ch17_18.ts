// SOMENTE O REI — porque o homem a quem se busca é como se fossem todos, e
// assim o povo torna em paz, como a esposa torna a seu marido. A palavra
// pareceu boa aos olhos de Absalão e aos olhos de todos os anciãos de Israel:
// estava decidido. Mas a vaidade pede uma segunda opinião — "chamai agora
// também a Husai o arquita" — e entra na sala o amigo de Davi, que jurou servir
// ao filho como servira ao pai só para desfazer, de dentro, aquilo mesmo que
// acaba de ouvir. A obra-prima começa pela sentença nua: "O CONSELHO QUE
// AITOFEL DEU DESTA VEZ NÃO É BOM". E então Husai não argumenta: pinta. Bem
// conheces tu a teu pai e a seus homens, que são VALOROSOS e estão com o
// ESPÍRITO AMARGURADO, COMO A URSA NO CAMPO ROUBADA DOS CACHORROS; teu pai é
// homem de guerra e NÃO PASSARÁ A NOITE COM O POVO — estará escondido nalguma
// cova; e caindo alguns dos teus no princípio, o boato corre, e até o coração
// de leão desmaia. Em lugar dos doze mil rápidos, o quadro lento e lisonjeiro:
// ajuntar-se TODO O ISRAEL, DESDE DÃ ATÉ BERSEBA, EM MULTIDÃO COMO A AREIA DO
// MAR, e TU EM PESSOA no meio deles — cair sobre Davi como o orvalho cai sobre
// a terra, e arrastar com cordas ao ribeiro a cidade que o esconder, até não
// se achar ali nem uma só pedrinha. Absalão escolhe a areia do mar e perde a
// guerra; e o versículo 14 abre a cortina sobre o que estava acontecendo por
// dentro daquela escolha: ⭐ "PORÉM ASSIM O SENHOR O ORDENARA, PARA ANIQUILAR O
// BOM CONSELHO DE AITOFEL, PARA QUE O SENHOR TROUXESSE O MAL SOBRE ABSALÃO".
// Husai corre aos sacerdotes Zadoque e Abiatar; os dois moços, JÔNATAS e
// AIMAÁS, esperam junto à FONTE DE ROGEL porque não podem ser vistos entrar na
// cidade, e uma criada leva e traz o recado. Um moço os vê e delata; eles fogem
// a BAURIM, à casa de um homem que tinha um POÇO NO PÁTIO, e ali dentro descem
// — e a mulher da casa toma a tampa, estende-a sobre a boca do poço, espalha
// GRÃO DESCASCADO por cima, e ASSIM NADA SE SOUBE. Os servos de Absalão vêm,
// perguntam, ouvem "já passaram o vau das águas", buscam, não acham, e voltam.
// À noite Davi levanta todo o povo e passa o JORDÃO: pela luz da manhã NEM
// AINDA FALTAVA UM SÓ QUE NÃO TIVESSE PASSADO. E Aitofel, vendo que o seu
// conselho não fora seguido, ALBARDOU O JUMENTO, levantou-se, foi para sua casa
