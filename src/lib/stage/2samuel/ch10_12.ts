// Bate-Seba, nasce SALOMÃO, "e o Senhor o amou" — e por mão do profeta Natã lhe
// manda um segundo nome: JEDIDIAS, o amado do SENHOR. O capítulo fecha na
// guerra que ficara aberta: Joabe toma a CIDADE DAS ÁGUAS de Rabá e chama o rei
// para que o nome dele não seja aclamado sobre a cidade; e a COROA do rei de
// Rabá, de UM TALENTO DE OURO e pedras preciosas, é posta sobre a cabeça de
// Davi.
//
// A VOZ DE DEUS — nestes três capítulos o SENHOR não fala uma única vez em
// balão de voz do céu, e isso é proposital. Em 2Sm 10 não há oráculo nenhum: a
// única palavra sobre Deus é a de um soldado, Joabe, entregando a batalha a Ele
// ("faça o Senhor o que bem parecer aos seus olhos"). Em 2Sm 11 o SENHOR está
// calado do primeiro verso ao penúltimo — a única vez que Ele aparece é na
// última linha, e como JUÍZO NARRADO, não como fala; por isso o v.27 não tem
// `by`, só a luz caindo (glory 0.02). E em 2Sm 12 há MEDIADOR VISÍVEL: o SENHOR
// envia NATÃ, e é a boca de Natã que diz a parábola, o "tu és este homem", o
// "assim diz o Senhor Deus de Israel" dos vv.7-12, o perdão do v.13 e o nome
// Jedidias do v.25 (que o texto marca expressamente como enviado "pela mão do
// profeta Natã"). Por isso, em todos esses beats, `by: "homem"` com `nata` em
// primeiro lugar no elenco e `glow` nele — nunca `by: "deus"`. Deus não é
// desenhado; a Sua presença é a luz que sobe quando o profeta fala e volta
// quando o rei confessa.
// ============================================================================

