// entra na sala do trono para dizer quatro palavras: "TU ÉS ESTE HOMEM".
//
// 2Sm 10 — Morre NAÁS, rei dos filhos de Amom, e HANUM, seu filho, reina em seu
// lugar. Davi se lembra de uma bondade antiga ("usarei de benevolência com
// Hanum, filho de Naás, como seu pai usou de benevolência comigo") e manda os
// seus servos consolá-lo. Mas na corte de Rabá os PRÍNCIPES sopram no ouvido do
// rei moço a suspeita que arruína tudo: "porventura honra Davi a teu pai aos
// teus olhos, porque te enviou consoladores? Não te enviou antes Davi os seus
// servos para reconhecerem esta cidade, e para espiá-la, e para transtorná-la?".
// Hanum toma os embaixadores, RASPA METADE DA BARBA de cada um, CORTA-LHES
// METADE DAS VESTES ATÉ ÀS NÁDEGAS, e os despede assim pela estrada. Davi manda
// mensageiros ao encontro deles: "deixai-vos estar em JERICÓ, até que vos torne
// a crescer a barba, e então voltai" — a cidade das palmeiras vira sala de
// espera de homens envergonhados. Vendo-se abomináveis, os filhos de Amom
// alugam vinte mil homens de pé dos sírios de BETE-REOBE e de ZOBÁ, mil do rei
// de MAACA e doze mil dos homens de TOBE. Davi envia JOABE e todo o exército
// dos valentes. Amom ordena a batalha à ENTRADA DA PORTA e os sírios ficam À
// PARTE NO CAMPO: Joabe está cercado pela frente e pela retaguarda. Ele escolhe
// os melhores de Israel contra os sírios, entrega o restante do povo na mão de
// ABISAI, seu irmão, contra os filhos de Amom, e diz a frase que sustenta o
// capítulo inteiro: "esforça-te, pois, e esforcemo-nos pelo nosso povo, e pelas
// cidades de nosso Deus; e faça o Senhor o que bem parecer aos seus olhos". Os
// sírios fogem, Amom foge para dentro da cidade, e Joabe volta para Jerusalém.
// Os sírios tornam a refazer-se: HADADEZER faz sair os que estavam do outro
// lado do rio, e SOBAQUE, capitão do seu exército, marcha diante deles até
// HELÃ. Davi passa o Jordão em pessoa — e ali caem SETECENTOS CARROS e QUARENTA
// MIL CAVALEIROS, e Sobaque morre no campo. Todos os reis servos de Hadadezer
// fazem paz com Israel, e os sírios temem socorrer aos filhos de Amom.
//
// 2Sm 11 — A QUEDA. "Tendo decorrido um ano, no tempo em que os reis saem à
// guerra", Davi manda Joabe, os seus servos e todo o Israel cercar Rabá —
// "porém Davi ficou em Jerusalém". Numa TARDE ele se levanta do seu LEITO,
// passeia no TERRAÇO da casa real e vê, lá de cima, uma mulher que se lavava. A
// resposta à pergunta já é o aviso inteiro: "porventura não é esta BATE-SEBA,
// filha de Eliã, MULHER DE URIAS, O HETEU?". Ele manda mensageiros, ela vem, e
// o texto anota com frieza clínica que ela já estava purificada da sua
