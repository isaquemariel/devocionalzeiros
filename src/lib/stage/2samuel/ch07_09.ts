// ============================================================================
// 2 SAMUEL 7–9 — CENA VIVA. A CASA QUE DAVI QUERIA EDIFICAR e a CASA QUE O
// SENHOR PROMETEU EDIFICAR-LHE; as vitórias em redor; e o coxo à mesa do rei.
//
// 2Sm 7 — O rei está EM SUA CASA, e o SENHOR lhe deu DESCANSO de todos os seus
// inimigos em redor. É do descanso que nasce a inquietação: "EIS QUE EU MORO EM
// CASA DE CEDRO, E A ARCA DE DEUS MORA DENTRO DE CORTINAS". Natã responde
// depressa — "vai, e faze tudo quanto está no teu coração; porque o Senhor é
// contigo" — e NAQUELA MESMA NOITE a palavra do SENHOR vem ao profeta e desmente
// a pressa dele. A pergunta inverte a cena inteira: "EDIFICAR-ME-ÁS TU UMA CASA
// PARA MINHA HABITAÇÃO?" — porque em casa nenhuma habitou desde o dia em que fez
// subir os filhos de Israel do Egito, mas ANDOU EM TENDA E EM TABERNÁCULO, e em
// todo o lugar por onde andou nunca pediu a tribo alguma uma casa de cedro. Vem
// então a retrospectiva de pastor — "EU TE TOMEI DA MALHADA, DE DETRÁS DAS
// OVELHAS, PARA QUE FOSSES O SOBERANO SOBRE O MEU POVO" —, o "fui contigo por
// onde quer que foste", o LUGAR preparado para Israel, que ali será PLANTADO e
// não mais removido; e o anúncio que vira tudo do avesso: ⭐ "O SENHOR TE FAZ
// SABER QUE TE FARÁ CASA". Depois dele virá um da sua descendência, e Deus
// estabelecerá o reino dele; ESTE edificará uma casa ao Nome, e o trono do seu
// reino é confirmado PARA SEMPRE: "EU LHE SEREI POR PAI, E ELE ME SERÁ POR
// FILHO" — e se transgredir, castigo com VARA DE HOMENS e açoites de filhos de
// homens, mas a benignidade NÃO se aparta dele como se apartou de Saul. Conforme
// a todas estas palavras, e conforme a toda esta visão, assim falou Natã a Davi.
// E o rei ENTRA e FICA PERANTE O SENHOR: "QUEM SOU EU, SENHOR DEUS, E QUAL É A
// MINHA CASA?", "e ainda foi isto pouco aos teus olhos", "não há semelhante a
// ti", "e quem há como o teu povo, como Israel?", até o pedido final — "SÊ,
// POIS, AGORA SERVIDO DE ABENÇOAR A CASA DE TEU SERVO, PARA PERMANECER PARA
// SEMPRE DIANTE DE TI".
//
// 2Sm 8 — Depois disto, as vitórias em redor. Davi fere os filisteus e toma
// METEGUE-AMA das mãos deles; derrota os moabitas e OS MEDE COM CORDEL, fazendo-
// os deitar por terra — DOIS CORDÉIS para matar e UM CORDEL INTEIRO para deixar
// com vida. Fere Hadadezer, filho de Reobe, rei de Zobá, quando este ia recuperar
// o seu domínio SOBRE O RIO EUFRATES: mil carros, setecentos cavaleiros e vinte
// mil homens de pé — e Davi JARRETA todos os cavalos dos carros, reservando deles
// CEM CARROS. Os sírios de Damasco vêm socorrer e caem; Davi põe GUARNIÇÕES na
// Síria, e o refrão do capítulo soa pela primeira vez: ⭐ "E O SENHOR GUARDOU A
// DAVI POR ONDE QUER QUE IA". Os ESCUDOS DE OURO dos servos de Hadadezer vão
// para Jerusalém, e o BRONZE de Betá e de Berotai com eles. TOÍ, rei de Hamate,
// inimigo antigo de Hadadezer, manda seu filho JORÃO com VASOS DE PRATA, DE OURO
// E DE BRONZE — que o rei CONSAGRA AO SENHOR junto com a prata e o ouro de todas
// as nações sujeitadas: Síria, Moabe, Amom, filisteus, Amaleque. Davi GANHA NOME
// voltando de ferir os sírios no VALE DO SAL, põe guarnições em todo o Edom, e o
// refrão volta: "e o Senhor ajudava a Davi por onde quer que ia". O capítulo
// fecha em governo, não em guerra: "REINOU, POIS, DAVI SOBRE TODO O ISRAEL; E
// DAVI FAZIA DIREITO E JUSTIÇA A TODO O SEU POVO" — Joabe sobre o exército,
// Jeosafá cronista, Zadoque e Aimeleque sacerdotes, Seraías escrivão, Benaia
// sobre os quereteus e peleteus.
//
// 2Sm 9 — E então o livro para a guerra para fazer uma pergunta: "HÁ AINDA
// ALGUÉM QUE TENHA FICADO DA CASA DE SAUL, PARA QUE LHE FAÇA BENEVOLÊNCIA POR
// AMOR DE JÔNATAS?". Chamam ZIBA, servo da casa de Saul, que responde com
// cautela: "ainda há um filho de Jônatas, ALEIJADO DE AMBOS OS PÉS" — e está
// longe, em LO-DEBAR, em casa de Maquir, filho de Amiel. O rei manda buscá-lo.
// MEFIBOSETE vem, prostra-se com o rosto por terra, e ouve o contrário do que
// espera de um rei novo diante do neto do rei velho: "NÃO TEMAS… te restituirei
// todas as terras de Saul, teu pai, E TU SEMPRE COMERÁS PÃO À MINHA MESA". A
// resposta é o autorretrato do homem quebrado: ⭐ "QUEM É TEU SERVO, PARA TERES
// OLHADO PARA UM CÃO MORTO TAL COMO EU?". Ziba, com seus QUINZE FILHOS e VINTE
// SERVOS, é posto a lavrar a terra devolvida; e o capítulo repete quatro vezes a
// mesma linha, que é o ponto inteiro — Mefibosete COMIA À MESA DO REI, COMO UM
// DOS FILHOS DO REI. A última frase é seca e perfeita: "e era coxo de ambos os
// pés".
//
// A VOZ DE DEUS (regra do projeto): no cap. 7 o SENHOR fala o discurso mais
// importante do livro — e NÃO há um único `by:"deus"` aqui, de propósito. A
// palavra vem "a Natã" (v.4, que o palco encena como NARRAÇÃO, no quarto do
// profeta de madrugada) e é NATÃ quem a diz ao rei: por isso vv.5-16 são todos
// `by:"homem"` com `nata` sempre em PRIMEIRO lugar entre os `homem` do elenco e
// com `glow` alto — ele é o mediador visível, e a regra do projeto manda o balão
// sair dele. Nos vv.18-29 quem fala é DAVI (`by:"rei"`), sentado perante o
// SENHOR na tenda da arca. Nos caps. 8 e 9 o SENHOR não fala nenhuma vez: no 8 a
// teologia inteira está no refrão do narrador ("o Senhor guardou/ajudava a Davi
// por onde quer que ia"), encenado por GLÓRIA ALTA nos vv.6 e 14; no 9 ela está
// na benevolência do rei, e a glória sobe em 9:7 e 9:13. Enquanto Natã fala, o
// palco NÃO fica parado no salão: ele vai para dentro daquilo que a palavra
// nomeia — o tabernáculo do deserto, o arraial das tribos, a malhada de Belém, a
// terra plantada, o trono da promessa —, e o profeta continua em cena, dentro da
// visão que descreve, porque é dele que o balão tem de sair. Fogo desenhado só
// por `altar` com `fire` e pela `pillar` de fogo; `env.fire` é ambiência.
// ============================================================================

