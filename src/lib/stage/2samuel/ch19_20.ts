// 2Sm 20 — Da briga sai a revolta: SEBA, filho de Bicri, HOMEM DE BELIAL,
// benjamita, TOCA A BUZINA e grita o grito da secessão — ⭐ "NÃO TEMOS PARTE EM
// DAVI, NEM HERANÇA NO FILHO DE JESSÉ; CADA UM ÀS SUAS TENDAS, Ó ISRAEL". Todo
