// Gibeão e no cerco. FOGO desenhado nenhum: não há fogueira nem incêndio aqui
// — `env.fire` entra só como ambiência de arraial. E os objetos são os NOVOS:
// o `donkey` que Mefibosete diz que albardaria, a `sword` que cai do cinto de
// Joabe e reaparece na mão dele no beat seguinte, o `trumpet` que abre a
// revolta e a fecha, o `bed` da casa das concubinas, e o `throne` com a `crown`
// que o rei larga no chão da câmara enquanto chora.
