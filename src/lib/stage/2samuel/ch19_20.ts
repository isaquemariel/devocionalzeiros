// casa, põe-nas numa casa sob guarda, sustenta-as e não as possui: ENCERRADAS
// ATÉ AO DIA DA SUA MORTE, VIVENDO COMO VIÚVAS. Amasa é mandado convocar Judá
// em três dias e DEMORA-SE além do prazo; Abisai sai com os servos do rei; e
// junto à PEDRA GRANDE DE GIBEÃO Joabe encontra Amasa — cingido da sua roupa,
// e sobre ela um cinto com a ESPADA presa aos lombos, na bainha; e, adiantando-
// se ele, A ESPADA LHE CAI. "Vai bem, meu irmão?" — e a mão direita pega da
// barba para o beijo enquanto a esquerda fere na quinta costela: as entranhas
// por terra, sem segundo golpe. O corpo fica ENVOLTO NO SEU SANGUE NO MEIO DO
// CAMINHO, e todo o povo que chega PARA, até que o tiram para o campo e lançam
// sobre ele um manto. A perseguição segue até ABEL DE BETE-MAACA: levantam um
// baluarte contra a cidade e batem no muro para derrubá-lo — e então uma
// MULHER SÁBIA grita de dentro: "ouvi, ouvi, peço-vos que digais a Joabe:
// chega-te aqui, para que eu te fale". O argumento dela salva a cidade: ⭐ "SOU
// EU UMA DAS PACÍFICAS E DAS FIÉIS EM ISRAEL; E TU PROCURAS MATAR UMA CIDADE
// QUE É MÃE EM ISRAEL; POR QUE, POIS, DEVORARIAS A HERANÇA DO SENHOR?". Faz-se
// o acordo, a cabeça de Seba é lançada pelo muro, a buzina toca outra vez — e
// agora para dispersar, não para revoltar — e o capítulo fecha com a lista dos
// oficiais de Davi, o reino de pé outra vez.
//
// A VOZ DE DEUS (regra do projeto): nestes dois capítulos o SENHOR NÃO FALA —
// nem do céu, nem por mediador; não há um único `by:"deus"` aqui, e é
// deliberado. Deus só é NOMEADO na boca dos homens: no juramento de Joabe
