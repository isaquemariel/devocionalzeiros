// comparação de Mefibosete ("o rei meu senhor é como um anjo de Deus") e, o
// mais alto de todos, na pergunta da sábia de Abel ("por que devorarias A
// HERANÇA DO SENHOR?"). O que o palco faz no lugar de uma voz é a LUZ: a
// glória desaba no luto de Maanaim (night 0.66–0.8), sobe devagar quando o rei
// se assenta à porta, chega ao auge no BEIJO DE BARZILAI (glory 0.82 — o único
