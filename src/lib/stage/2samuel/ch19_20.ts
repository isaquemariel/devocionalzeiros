// Maanaim, "como o faz quando, envergonhado, foge da peleja", enquanto lá em
// cima, na câmara sobre a porta, o rei está com O ROSTO COBERTO e grita a alta
// voz: "MEU FILHO ABSALÃO, ABSALÃO MEU FILHO, MEU FILHO!". Então Joabe entra na
// casa do rei e dá a repreensão mais brutal e mais necessária do livro: hoje
// envergonhaste o rosto de todos os teus servos, que livraram a tua vida, e a
// de teus filhos, e de tuas filhas, e de tuas mulheres, e de tuas concubinas —
// ⭐ "AMANDO TU AOS TEUS INIMIGOS, E ODIANDO AOS TEUS AMIGOS". E o ultimato:
// levanta-te, sai, e fala conforme ao coração de teus servos, "porque pelo
// Senhor te juro que, se não saíres, NEM UM SÓ HOMEM FICARÁ CONTIGO ESTA
// NOITE". O rei se levanta e SE ASSENTA À PORTA, e todo o povo vem apresentar-
// se diante dele. Nas tribos há porfia — "por que vos calais, e não fazeis
// voltar o rei?" —, e Davi manda dizer aos anciãos de Judá pelos sacerdotes
// ZADOQUE e ABIATAR: "vós sois meus irmãos, meus ossos e minha carne"; e a
// AMASA, o capitão do arraial de Absalão, oferece o posto de Joabe. Judá se
// move como um só homem, e no VAU DO JORDÃO a volta vira procissão. Vem
// SIMEI, filho de Gera, às pressas, com MIL HOMENS DE BENJAMIM, e ZIBA com os
// seus QUINZE FILHOS e VINTE SERVOS, e a barca atravessa; Simei se prostra e
// confessa: "eu sou o primeiro que de toda a casa de José desci a encontrar-me
// com o rei meu senhor". Abisai quer matá-lo outra vez, e ouve a resposta de
// sempre: "porventura não sei que HOJE FUI FEITO REI SOBRE ISRAEL?" — e o
// juramento: não morrerás. Desce também MEFIBOSETE, que NÃO TINHA LAVADO OS
// PÉS, NEM FEITO A BARBA, NEM LAVADO AS VESTES desde o dia em que o rei saíra
// até ao dia em que voltou em paz; desmente a acusação — "o meu servo me
// enganou; porque o teu servo dizia: ALBARDAREI UM JUMENTO, e nele montarei, e
// irei com o rei; POIS O TEU SERVO É COXO" — e, mandado repartir as terras com
// o delator, responde como quem já perdeu tudo: "TOME ELE TAMBÉM TUDO; POIS JÁ
// VEIO O REI MEU SENHOR EM PAZ À SUA CASA". E vem BARZILAI, o gileadita, de
// OITENTA ANOS, que sustentara o rei em Maanaim, convidado a subir a Jerusalém
// e recusando com a fala mais humana da Bíblia: "poderia eu discernir entre o
// bom e o mau? poderia o teu servo ter gosto no que comer e beber? poderia eu
// mais ouvir a voz dos cantores e cantoras?" — pede só voltar para morrer na
// sua cidade, junto à sepultura de seu pai e de sua mãe, e manda QUIMÃ no seu
// lugar. O rei o beija e o abençoa. E o capítulo, que começou em choro, acaba
