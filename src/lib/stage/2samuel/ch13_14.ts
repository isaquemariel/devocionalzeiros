// 2 SAMUEL 13–14 — CENA VIVA. A ESPADA QUE NÃO SE APARTA DA CASA: o pecado de
// Davi cobrado dentro das próprias paredes dele — primeiro em TAMAR, depois em
// AMNOM, depois no exílio de ABSALÃO — e a MULHER SÁBIA DE TECOA, que ensina o
// rei aquilo que o rei não conseguia dizer a si mesmo.
//
// 2Sm 13 — Absalão, filho de Davi, tem uma IRMÃ FORMOSA, TAMAR; e AMNOM, o
// primogênito do rei, a ama. Angustia-se ATÉ ADOECER, porque ela é virgem e
// "parecia aos olhos de Amnom dificultoso fazer-lhe coisa alguma" — a casa do
// rei tem guardas, portas e costume, e nada daquilo o detém por dentro, só por
// fora. Entra então JONADABE, filho de Siméia, irmão de Davi, "homem mui
// sagaz": a sagacidade sem temor de Deus é o veneno deste capítulo. O conselho
// é uma engenharia inteira em um versículo — DEITA-TE NA TUA CAMA, FINGE-TE
// DOENTE, e quando teu pai vier visitar-te, PEDE A TAMAR. O rei, que devia
// proteger, é usado como instrumento: manda a filha à casa do irmão. E o texto
// então se demora, com um cuidado que dói, nos OBJETOS: a MASSA amassada, os
// BOLOS feitos DIANTE DOS SEUS OLHOS, os bolos cozidos, a FRIGIDEIRA tirada
// diante dele — e a recusa de comer. "FAZEI RETIRAR A TODOS DA MINHA PRESENÇA."
// Esvaziada a casa, vem o pedido, e vem dela a resistência mais lúcida da
// Escritura: "NÃO, MEU IRMÃO, NÃO ME FORCES, PORQUE NÃO SE FAZ ASSIM EM ISRAEL;
// NÃO FAÇAS TAL LOUCURA" — e a saída que ela mesma lhe oferece, "fala ao rei,
// porque não me negará a ti". Ele não quis dar ouvidos à sua voz. Depois vem a
// frase mais terrível do livro: ⭐ "MAIOR ERA O ÓDIO QUE SENTIU POR ELA DO QUE O
// AMOR COM QUE A AMARA" — e o segundo ultraje, pior que o primeiro para quem o
// sofre: "LEVANTA-TE, E VAI-TE", o moço chamado, a porta FECHADA APÓS ELA. Ela
// trazia a ROUPA DE MUITAS CORES das filhas virgens do rei: rasga-a, toma CINZA
// sobre a cabeça, PÕE AS MÃOS SOBRE A CABEÇA e vai ANDANDO E CLAMANDO pela rua.
// Absalão a cala ("ora, pois, minha irmã, cala-te; é teu irmão") e ela fica
// SOLITÁRIA em casa dele. Davi ouve tudo e a ira dele se acende — e nada mais:
// o rei que executou o homem da parábola de Natã não executa o filho. Absalão
// não fala com Amnom NEM MAL NEM BEM por DOIS ANOS INTEIROS, e no fim dos dois
// anos há TOSQUIADORES em BAAL-HAZOR: o convite ao rei, recusado com uma bênção;
// o convite a Amnom, arrancado à insistência. A ordem aos moços é fria como um
// contrato: "QUANDO O CORAÇÃO DE AMNOM ESTIVER ALEGRE DO VINHO… FERI A AMNOM,
// ENTÃO O MATAREIS; NÃO TEMAIS: PORQUE PORVENTURA NÃO SOU EU QUEM VO-LO
// ORDENEI?". Feito isto, os filhos do rei se levantam, MONTAM CADA UM NO SEU
// MULO e fogem. A notícia corre mais depressa que os mulos e chega inteiramente
// errada — "matou a TODOS os filhos do rei" —, e o rei rasga as vestes e se
// lança POR TERRA, com todos os servos de vestes rotas ao redor; é o sagaz
// Jonadabe, de novo, quem corrige a conta: só morreu Amnom. O moço da guarda vê
// muito povo pelo caminho, pelo lado do monte; os filhos do rei chegam e todos
// choram amargamente. E Absalão foge para TALMAI, rei de GESUR, e ali fica TRÊS
// ANOS — enquanto o coração do pai já está do lado de lá da fronteira.
//
// 2Sm 14 — JOABE, que lê o rei melhor do que o rei se lê, percebe que o coração
// de Davi ESTAVA INCLINADO PARA ABSALÃO. Manda buscar em TECOA uma MULHER
// SÁBIA e lhe põe as palavras na boca: finge-te de luto, não te unjas com óleo,
// sê como quem chora um morto há muitos dias. Diante do trono ela conta uma
// parábola de camponesa: dois filhos brigaram NO CAMPO, e NÃO HOUVE QUEM OS
// APARTASSE; um matou o outro; e agora TODA A LINHAGEM exige o vingador do
// sangue — e, matando o único que resta, APAGARÁ A BRASA QUE ME FICOU, sem
// deixar ao marido NOME NEM REMANESCENTE SOBRE A TERRA. Davi responde em três
// tempos, cada vez apertando mais o próprio laço, até jurar: "VIVE O SENHOR,
// QUE NÃO HÁ DE CAIR NO CHÃO NEM UM DOS CABELOS DE TEU FILHO". Aí a mulher vira
// a lâmina: "POR QUE, POIS, PENSASTE TU UMA TAL COISA CONTRA O POVO DE DEUS?…
// visto que o rei NÃO TORNA A TRAZER O SEU DESTERRADO" — e diz a melhor
// teologia do trecho inteiro: ⭐ "PORQUE CERTAMENTE MORREREMOS, E SEREMOS COMO
// ÁGUAS DERRAMADAS NA TERRA QUE NÃO SE AJUNTAM MAIS; DEUS, POIS, LHE NÃO TIRARÁ
// A VIDA, MAS COGITA MEIOS, PARA QUE NÃO FIQUE BANIDO DELE O SEU DESTERRADO".
// O rei reconhece a mão de Joabe por trás de tudo, e manda trazer Absalão — mas
// com uma condição que é meia graça e por isso é veneno: "TORNE PARA A SUA
// CASA, E NÃO VEJA A MINHA FACE". Segue então o retrato: em todo o Israel não
// havia homem TÃO BELO como Absalão, sem defeito DA PLANTA DO PÉ ATÉ À CABEÇA,
// e o CABELO tosquiado uma vez por ano pesava DUZENTOS SICLOS SEGUNDO O PESO
// REAL — a mesma cabeleira que um dia o prenderá ao carvalho. Três filhos e uma
// filha, TAMAR, formosa à vista: ele dá à filha o nome da irmã destruída.
// DOIS ANOS INTEIROS em Jerusalém sem ver a face do rei. Joabe, chamado, não
// vem; chamado segunda vez, não vem — então Absalão manda PÔR FOGO ao PEDAÇO DE
// CAMPO DE CEVADA do vizinho, e o general aparece na hora. "MELHOR ME FORA
// ESTAR AINDA LÁ… SE HÁ AINDA EM MIM ALGUMA CULPA, QUE ME MATE." E o capítulo
// fecha num beijo — o beijo que perdoa sem julgar, e que por isso não cura nada.
//
// A VOZ DE DEUS (regra do projeto): nestes dois capítulos o SENHOR NÃO FALA —
// nem do céu, nem por profeta, nem por teofania. Não há um único `by:"deus"`
// aqui, e o SILÊNCIO É O ASSUNTO. Depois de 12:10 ("não se apartará a espada da
// tua casa") Deus se cala e deixa a sentença correr pelas mãos dos próprios
// homens da casa. O palco encena esse silêncio com a GLÓRIA: em todo o cap. 13
// ela fica entre 0.02 e 0.12 — quase preta, mesmo de dia, mesmo na festa da
// tosquia —, e só volta a subir no cap. 14, e só na BOCA DA MULHER DE TECOA:
// 0.30 quando ela invoca "o Senhor teu Deus" (14:11), 0.52 no v.14 (a água
// derramada e o Deus que cogita meios para o banido), 0.44 no "anjo de Deus"
// (14:17,20). Nem Davi nem Joabe nem Absalão recebem `glow` — a única figura que
// carrega luz nestes dois capítulos é a viúva fingida de Tecoa, no momento em
// que diz a verdade. FOGO desenhado só por `campfire` (o forno dos bolos de
// Tamar, a brasa da parábola, o campo de cevada em chamas); `env.fire` é apenas
// ambiência. MULTIDÃO nenhuma no cap. 13: o motor sempre a desenha comemorando,
// e aqui não há nada a comemorar — o luto e a matança são encenados por figuras
// individuais em `lie`, `bow` e `kneel`.
// ============================================================================

