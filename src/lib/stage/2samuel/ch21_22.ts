// ============================================================================
// 2 SAMUEL 21–22 — CENA VIVA. A FOME DE TRÊS ANOS e o sangue dos gibeonitas, a
// vigília de RISPA sobre a penha, as quatro pelejas contra os gigantes — e
// depois, o GRANDE CÂNTICO de Davi, a teofania inteira cantada com a harpa.
//
// 2Sm 21 — Houve nos dias de Davi uma FOME DE TRÊS ANOS CONSECUTIVOS: ano após
// ano a terra de Judá não deu pão. Davi consultou ao SENHOR, e a resposta veio
// do alto, sem profeta e sem mediador: "É POR CAUSA DE SAUL E DA SUA CASA
// SANGUINÁRIA, PORQUE MATOU OS GIBEONITAS". Os gibeonitas não eram dos filhos
// de Israel — eram do RESTANTE DOS AMORREUS, aqueles que em Josué 9 enganaram
// a congregação e a quem Israel JUROU poupar; Saul, no seu zelo pela causa dos
// filhos de Israel e de Judá, procurou feri-los, e o juramento quebrado ficou
// clamando da terra. O rei os chama e pergunta que satisfação lhes dará; eles
// respondem que a questão não é de prata nem de ouro, e pedem SETE HOMENS dos
// filhos de Saul para os enforcarem ao SENHOR em GIBEÁ DE SAUL. Davi poupa
// MEFIBOSETE, filho de Jônatas, por causa do juramento do SENHOR que houvera
// entre ele e Jônatas, e entrega os DOIS FILHOS DE RISPA, filha de Aiá —
// Armoni e Mefibosete — e os CINCO FILHOS da irmã de Mical, que ela tivera de
// Adriel, o meolatita. Os sete caem juntamente, nos dias primeiros da sega, no
// princípio da sega das cevadas. E então vem a cena que ninguém esquece: RISPA
// toma um PANO DE CILÍCIO e o estende SOBRE UMA PENHA, e ali fica — desde o
// princípio da sega até que a ÁGUA DO CÉU caiu sobre eles — não deixando as
// aves do céu pousar sobre os corpos de dia, nem os animais do campo de noite.
// Uma mãe sozinha, meses a fio, guardando mortos. Contam a Davi o que fez a
// concubina de Saul, e o rei se levanta: vai buscar os ossos de Saul e de
// Jônatas com os moradores de JABES-GILEADE, que os haviam furtado da RUA DE
// BETE-SÃ, onde os filisteus os tinham pendurado depois de Gilboa; ajunta
// também os ossos dos enforcados e sepulta tudo na terra de Benjamim, em ZELA,
// na sepultura de QUIS, pai de Saul — "E DEPOIS DISTO DEUS SE APLACOU COM A
// TERRA". O capítulo fecha com QUATRO PELEJAS contra os gigantes de Gate:
// ISBI-BENOBE, de lança de trezentos siclos de cobre e espada nova, quase mata
// o rei cansado, e ABISAI o socorre — donde o juramento dos homens de Davi:
// "NUNCA MAIS SAIRÁS CONOSCO À PELEJA, PARA QUE NÃO APAGUES A LÂMPADA DE
// ISRAEL"; em Gobe, Sibecai, o husatita, fere a SAFE; ainda em Gobe, El-Hanã
// fere GOLIAS, O GITEU, cuja lança tinha a haste como ÓRGÃO DE TECELÃO; e em
// Gate, o homem de alta estatura com SEIS DEDOS EM CADA MÃO E EM CADA PÉ,
// VINTE E QUATRO AO TODO, que injuriava a Israel e caiu pela mão de Jônatas,
// filho de Simei, irmão de Davi.
//
// 2Sm 22 — O grande CÂNTICO (o Salmo 18), cantado no dia em que o SENHOR
// livrou Davi das mãos de todos os seus inimigos e das mãos de Saul. Começa em
// pedra: "O SENHOR É O MEU ROCHEDO, E O MEU LUGAR FORTE, E O MEU LIBERTADOR…
// o meu escudo, e a força da minha salvação, o meu alto retiro, e o meu
// refúgio". Depois desce ao fundo: as ONDAS DE MORTE o cercam, as torrentes
// dos ímpios o assombram, as CORDAS DO INFERNO o cingem e os LAÇOS DA MORTE o
// encontram — e do fundo o clamor sobe e chega AOS OUVIDOS DELE, no seu
// templo. A resposta é uma TEOFANIA descrita em imagens colossais, e o palco
// segue cada uma: a TERRA SE ABALA E TREME e os FUNDAMENTOS DOS CÉUS se movem;
// sobe FUMAÇA das narinas e da boca um FOGO DEVORADOR, e carvões se incendeiam
// dele; ele ABAIXA OS CÉUS E DESCE, com ESCURIDÃO DEBAIXO DOS PÉS; SOBE SOBRE
// UM QUERUBIM E VOA, e é visto SOBRE AS ASAS DO VENTO; põe as TREVAS POR
// TENDAS ao redor de si, ajuntamento de águas e nuvens dos céus; do resplendor
// da sua presença BRASAS DE FOGO se acendem; TROVEJA DESDE OS CÉUS, e o
// Altíssimo faz soar a sua voz; DISPARA FLECHAS e os dissipa, RAIOS e os
// perturba; aparecem as PROFUNDEZAS DO MAR e os FUNDAMENTOS DO MUNDO se
// descobrem pela repreensão do SENHOR, pelo sopro do vento das suas narinas. E
// então, no meio daquele fim de mundo, uma mão: "DESDE O ALTO ENVIOU, E ME
// TOMOU; TIROU-ME DAS MUITAS ÁGUAS" — e o pôs num LUGAR ESPAÇOSO. A segunda
// metade é a resposta do homem: a justiça e a pureza das mãos, o espelho de
// Deus ("com o benigno te mostras benigno… mas com o perverso te mostras
// rígido"), a LÂMPADA que ilumina as trevas, o ESQUADRÃO atravessado e o MURO
// saltado, os PÉS COMO OS DAS CERVAS, o ARCO DE COBRE quebrado pelos braços, o
// caminho alargado debaixo dos pés, os inimigos perseguidos até serem
// consumidos, as nações sujeitas. E o fecho, que é a ponte para o Novo
// Testamento: "VIVE O SENHOR, E BENDITO SEJA O MEU ROCHEDO… ELE É A TORRE DAS
// SALVAÇÕES DO SEU REI, E USA DE BENIGNIDADE COM O SEU UNGIDO, COM DAVI, E COM
// A SUA DESCENDÊNCIA PARA SEMPRE".
//
// A VOZ DE DEUS (regra do projeto): há UMA só voz do céu nestes dois capítulos
// — 21:1, a resposta à consulta sobre a fome, sem profeta e sem figura em cena
// (`by:"deus"`, glória alta, o rei de joelhos na terra rachada). No cap. 22
// NÃO existe um único `by:"deus"`, e isso é deliberado: o cântico é de DAVI ao
// SENHOR, e mesmo nos versículos em que Deus TROVEJA (22:14) quem descreve o
// trovão é o cantor — todos os 51 beats falam por `by:"rei"`, id `davi`, com a
// HARPA em cena como moldura. A teofania é encenada por AMBIENTE (storm, night,
// glory, water) e por props do céu (clouds, firmament, starfield, o `cherub` de
// 22:11), nunca por uma figura de Deus. Fogo desenhado só por `campfire` e por
// `pillar`/`altar` com `fire`. Rispa é sempre `mulherComum` — nunca `mulher`,
// que o motor desenha dourada e em pé —, e em 21:9-10 não há multidão alguma:
// os sete são figuras individuais em `lie`, e ela está sozinha na penha.
// ============================================================================

