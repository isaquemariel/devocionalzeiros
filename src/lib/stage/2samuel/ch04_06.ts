// A VOZ DE DEUS (regra do projeto): o SENHOR fala TRÊS vezes nestes capítulos e
// as três SEM MEDIADOR VISÍVEL — são consultas ao oráculo, respondidas do alto.
// São `by:"deus"`: 5:19 ("Sobe, porque certamente entregarei os filisteus nas
// tuas mãos"), 5:23 ("Não subirás; mas rodeia por detrás deles") e 5:24 (o
// sinal do estrondo pelas copas das amoreiras). Nos três a glória sobe a
// 0.82–0.94, nenhuma figura central é desenhada, e Davi aparece de joelhos ou
// escutando, nunca falando junto. Em 5:2 o SENHOR é CITADO pelas tribos ("e
// também o Senhor te disse: Tu apascentarás o meu povo") — ali quem fala é a
// congregação, não o céu, e o balão sai da multidão. Em 6:7 o SENHOR AGE e não
// fala: a ira que fere Uzá é encenada só por ambiente (glória dura + storm),
// sem balão nenhum — o silêncio é o ponto. FOGO desenhado só por `campfire` e
// por `altar` com `fire` (os sacrifícios de seis em seis passos, os holocaustos
// da tenda); `env.fire` é ambiência. As ARMAS são `sword` (a espada dos moços
// de Davi em 4:12) — nunca `rod`, que é a vara de Arão. O LEITO de Is-Bosete é
// `bed`, o TANQUE de Hebrom é `pool`, as HARPAS da folia são `harp`, e o CARRO
// NOVO de Abinadabe é `stall` com tag PRÓPRIA — não é o carro dos filisteus de
// 1Sm 6. `multidao` (que o motor sempre desenha comemorando) entra só onde há
// festa de verdade: as tribos em Hebrom (5:1-3) e a arca subindo (6:5,12-15,19).
// Na morte de Is-Bosete, na morte de Uzá e no fecho de Mical não há multidão
// nenhuma — só figuras individuais em `lie`, `bow` e `kneel`.
