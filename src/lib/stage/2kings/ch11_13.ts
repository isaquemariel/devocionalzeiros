// 2 REIS 11–13 — CENA VIVA. A RECÂMARA DOS LEITOS onde um bebê de colo é
// escondido enquanto a avó mata os netos, o COFRE COM UM BURACO NA TAMPA ao pé
// do altar, e a JANELA ABERTA PARA O ORIENTE de onde um profeta moribundo manda
// atirar a flecha do livramento com as suas mãos sobre as mãos do rei.
//
// 2Rs 11 — ATALIA E O MENINO ESCONDIDO. Vendo morto o filho, ATALIA "levantou-se
// e destruiu toda a descendência real": é a única vez em toda a Escritura em que
// a linhagem de Davi — a linhagem da promessa, o "não te faltará varão sobre o
// trono de Israel" — quase se apaga de vez, e quem quase a apaga é uma avó. Mas
// JEOSEBA, filha do rei Jorão e irmã de Acazias, TOMA JOÁS, filho de Acazias,
// FURTANDO-O DENTRE OS FILHOS DO REI, AOS QUAIS MATAVAM, e o esconde com a sua
// ama NA RECÂMARA — e depois na casa do SENHOR, SEIS ANOS, enquanto Atalia
// reinava sobre o país. A promessa de Deus cabe, por seis anos, num quarto de
// fundos do templo. No sétimo ano JOIADA, o sacerdote, manda buscar os
// centuriões, os capitães e os da guarda, faz com eles uma aliança dentro da
// casa do SENHOR, ajuramenta-os — E MOSTRA-LHES O FILHO DO REI. Depois dá as
// ordens de posto com a frieza de um plano militar: uma terça parte na casa do
// rei, outra à porta de Sur, outra à porta detrás dos da guarda, e as duas
// partes que saem no sábado junto ao rei; cada um COM AS SUAS ARMAS NA MÃO, e o
// que entrar entre as fileiras morre. E o sacerdote abre o arsenal do templo:
// dá-lhes AS LANÇAS E OS ESCUDOS QUE HAVIAM SIDO DO REI DAVI, guardados na casa
// do SENHOR desde as guerras do bisavô do menino. Então tiram o filho do rei,
// põem-lhe A COROA e dão-lhe O TESTEMUNHO — o cetro e a Lei na mesma mão —,
// ungem-no, batem as palmas e clamam "viva o rei!". Atalia ouve o clamor, vem à
// casa do SENHOR e vê o quadro que a condena: o rei JUNTO À COLUNA, CONFORME O
// COSTUME, os príncipes e os trombeteiros junto ao rei, e todo o povo da terra
// alegre e tocando as trombetas. Rasga as vestes e grita "traição! traição!" —
// a palavra certa dita pela boca errada. Joiada não a deixa morrer no templo:
// tiram-na para fora das fileiras e ela morre PELO CAMINHO DA ENTRADA DOS
// CAVALOS, à casa do rei. Depois vem A ALIANÇA — entre o SENHOR e o rei e o
// povo, para que fosse o povo do SENHOR —, e o povo desce à casa de Baal e a
// derruba com os altares e as imagens, e mata Matã, sacerdote de Baal, diante
// dos altares. O capítulo fecha com a idade do rei: SETE ANOS.
//
// 2Rs 12 — O COFRE DO TEMPLO. Joás fez o que era reto aos olhos do SENHOR
// "todos os dias em que o sacerdote Joiada o dirigia" — a ressalva mais honesta
// que a Escritura já escreveu sobre um homem bom. Os altos não se tiraram. O
// rei ordena aos sacerdotes que tomem o dinheiro das coisas santas e reparem as
// fendas da casa; e o capítulo é atravessado por um fracasso administrativo que
// dura duas décadas: NO ANO VINTE E TRÊS os sacerdotes AINDA NÃO TINHAM
// REPARADO as fendas. O rei os chama e lhes tira o dinheiro das mãos. E então
// Joiada inventa a coisa mais simples do mundo: TOMOU UM COFRE, FEZ-LHE UM
// BURACO NA TAMPA e o pôs AO PÉ DO ALTAR, À MÃO DIREITA DOS QUE ENTRAVAM na
// casa do SENHOR — e o dinheiro parou de sumir. Quando havia muito, o escrivão
// do rei subia com o sumo sacerdote, contavam e ENSACAVAM; e o davam aos
// carpinteiros, aos edificadores, aos pedreiros e aos cabouqueiros, e para
// comprar madeira e pedras de cantaria. Nada de taças, garfos, bacias nem
// trombetas: tudo para a obra. E a nota de honra que o texto faz questão de
// registrar: NÃO PEDIAM CONTAS aos homens em cujas mãos entregavam o dinheiro,
// PORQUE PROCEDIAM COM FIDELIDADE. No fim, HAZAEL sobe contra Gate, a toma, e
// vira o rosto para Jerusalém — e o rei que consertou a casa do SENHOR a
// esvazia: toma as coisas santas que Jeosafá, Jorão e Acazias consagraram e todo
// o ouro dos tesouros, e o manda a Hazael, que se desvia. E os seus próprios
// servos o ferem na casa de Milo, no caminho que desce para Sila.
//
// 2Rs 13 — A FLECHA DO LIVRAMENTO. Jeoacaz, filho de Jeú, e a opressão de
// Hazael e de Ben-Hadade todos os seus dias; o exército de Israel reduzido a
// CINQÜENTA CAVALEIROS, DEZ CARROS E DEZ MIL HOMENS DE PÉ, "porquanto o rei da
// Síria os tinha destruído e os tinha feito como o pó, trilhando-os". E, no meio
// da idolatria que não cessa, uma súplica é ouvida: o SENHOR dá UM SALVADOR a
// Israel, e o povo volta a habitar nas suas tendas. Depois Jeoás. E então a cena
// que fecha a vida do profeta: ELISEU ESTAVA DOENTE DA ENFERMIDADE DE QUE
// MORREU, e o rei de Israel desce a ele e CHORA SOBRE O SEU ROSTO dizendo
// exatamente as palavras que Eliseu dissera de Elias no redemoinho — "meu pai,
// meu pai, o carro de Israel, e seus cavaleiros!". O moribundo manda tomar o
// arco e as flechas, manda o rei pôr a mão sobre o arco — E PÕE AS SUAS MÃOS
// SOBRE AS MÃOS DO REI —, manda abrir a janela para o oriente e atirar: "a
// flecha do livramento do Senhor é a flecha do livramento contra os sírios".
// Depois manda ferir a terra com as flechas; e o rei fere TRÊS VEZES E CESSA. O
// homem de Deus se indigna muito: "cinco ou seis vezes a deverias ter ferido…
// porém agora só três vezes ferirás os sírios" — a fé medida em batidas de
// flecha no chão. Eliseu morre e o sepultam; e Deus dá ao profeta morto o último
// milagre: as tropas dos moabitas invadindo a terra à entrada do ano, um enterro
// interrompido às pressas, o corpo lançado NA SEPULTURA DE ELISEU — e o homem,
// tocando os ossos do profeta, REVIVEU E SE LEVANTOU SOBRE OS SEUS PÉS. Hazael
// morre; e Jeoás toma de Ben-Hadade as cidades TRÊS VEZES: exatamente a conta
// das flechas.
//
// A VOZ DE DEUS — nestes três capítulos Deus NÃO FALA em balão nenhum, e por
// isso não há aqui `by:"deus"` nem voz do céu. O SENHOR aparece só como sujeito
// da narração ("a ira do Senhor se acendeu", "o Senhor ouviu", "o Senhor deu um
// salvador", "o Senhor teve misericórdia deles… por amor da sua aliança com
// Abraão, Isaque e Jacó") — e narração se desenha com ambiente, não com balão:
// a glória sobe no quadro (13:4-5, 13:23) sem que nada seja desenhado no alto.
// As duas bocas que falam são humanas e estão SEMPRE em cena: JOIADA, o
// sacerdote (`anciao`, id `joiada`), que dá as ordens de posto e a sentença
// sobre Atalia, e ELISEU (`patriarca`, id `eliseu`), que dita a flecha do
// livramento do próprio leito de morte — os dois com `glow` alto, porque a
// palavra que carregam não é deles. Falam ainda ATALIA (`mulherComum`, id
// `atalia`, NUNCA `mulher`, que o motor desenha sempre dourada e em pé), o rei
// JOÁS (`rei`, id `joas-de-juda`) e o rei JEOÁS de Israel (`rei`, id
// `jeoas-de-israel`), e o povo em coro no "viva o rei!" (`multidao`).
//
// (A ARC grafa "cinqüenta" com trema, "descendência real" onde a memória diz
// semente real, "recâmara" sem "dos leitos", "cabouqueiros" e "pedras de
// cantaria" — os `q` seguem a ARC, letra por letra.)
// ============================================================================

