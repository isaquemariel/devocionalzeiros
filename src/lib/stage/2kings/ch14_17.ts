// poupar os filhos dos assassinos, o CARDO que pediu a filha do CEDRO, o muro
// de Jerusalém rasgado em quatrocentos côvados, a CASA SEPARADA do rei leproso,
// cinco reis do Norte matando-se em vinte anos, as grávidas de Tifsa fendidas,
// o ALTAR DE DAMASCO copiado por encomenda, o mar de cobre arrancado de sobre
// os bois — e Samaria caindo, com a lista das razões escrita por extenso.
//
// 2Rs 14 — AMAZIAS, filho de Joás, reina vinte e nove anos em Jerusalém e "fez
// o que era reto aos olhos do Senhor, ainda que não como seu pai Davi";
// tão-somente os altos não foram tirados. Firmado o reino, mata os servos que
// tinham matado seu pai — MAS NÃO OS FILHOS DELES, e o texto se dá ao trabalho
// de dizer por quê, citando o livro da lei de Moisés: "Não matarão os pais por
// causa dos filhos, e os filhos não matarão por causa dos pais; mas cada um
// será morto pelo seu pecado". Fere dez mil edomitas no VALE DO SAL, toma SELA
// e lhe muda o nome para Jocteel. E aí o coração se ensoberbece: manda desafio
// a JEOÁS de Israel — "Vem, vejamo-nos face a face" — e recebe de volta a mais
// seca das parábolas: "O cardo que estava no Líbano mandou dizer ao cedro que
// estava no Líbano: Dá tua filha por mulher a meu filho; mas os animais do
// campo, que estavam no Líbano, passaram e pisaram o cardo". Com o conselho:
// "gloria-te disso, e fica em tua casa". Amazias não ouve; em BETE-SEMES Judá
// é ferido, cada um foge para a sua tenda, o rei é preso, o MURO DE JERUSALÉM
// é rompido DESDE A PORTA DE EFRAIM ATÉ À PORTA DA ESQUINA, quatrocentos
// côvados, e o ouro, a prata, os vasos e os REFÉNS descem para Samaria. Amazias
// ainda vive quinze anos, conspiram contra ele, foge para LAQUIS e ali o matam;
// trazem-no EM CIMA DE CAVALOS. O povo faz rei AZARIAS, de dezesseis anos. No
// Norte, JEROBOÃO II restitui os termos de Israel desde a entrada de Hamate até
// ao mar da planície, conforme a palavra falada pelo ministério de JONAS, FILHO
// DE AMITAI, o de Gate-Hefer — porque o SENHOR viu que a miséria de Israel era
// muito amarga, e não havia "nem escravo, nem absolvido, nem quem ajudasse".
//
// 2Rs 15 — AZARIAS (Uzias) reina cinqüenta e dois anos e o SENHOR o fere: fica
// LEPROSO ATÉ AO DIA DA SUA MORTE e HABITA NUMA CASA SEPARADA, enquanto JOTÃO,
// seu filho, tem o cargo da casa, julgando o povo da terra. E então o Norte
// desaba em espiral: ZACARIAS reina SEIS MESES e SALUM o fere DIANTE DO POVO —
// e com ele acaba a palavra dita a Jeú, "teus filhos, até à quarta geração, se
// assentarão sobre o trono de Israel". SALUM reina UM MÊS INTEIRO e MENAÉM sobe
// de Tirza e o mata; Menaém fere TIFSA e A TODAS AS MULHERES GRÁVIDAS FENDE
// PELO MEIO, e depois compra a paz de PUL, rei da Assíria, com MIL TALENTOS DE
// PRATA tirados de cada homem poderoso, CINQÜENTA SICLOS por cabeça. PECAÍAS,
// dois anos, morre no PAÇO DA CASA DO REI pela mão de PECA, seu capitão, com
// Argobe, Arié e CINQÜENTA GILEADITAS. Nos dias de Peca vem TIGLATE-PILESER e
// leva Ijom, Abel-Bete-Maaca, Janoa, Quedes, Hazor, Gileade, a Galiléia e TODA
// A TERRA DE NAFTALI — o primeiro cativeiro. OSÉIAS conspira e mata Peca. Em
// Judá, JOTÃO edifica A PORTA ALTA DA CASA DO SENHOR, e nos seus dias começa o
// SENHOR a enviar contra Judá a Rezim e a Peca.
//
// 2Rs 16 — ACAZ anda no caminho dos reis de Israel e ATÉ A SEU FILHO FAZ PASSAR
// PELO FOGO. Cercado por Rezim e Peca, manda a Tiglate-Pileser o recado que
// define o reinado: "Eu sou teu servo e teu filho; sobe, e livra-me" — com a
// prata e o ouro da casa do SENHOR por presente. E em Damasco, indo encontrar-se
// com o senhor a quem se vendeu, VÊ UM ALTAR: manda ao sacerdote URIAS o desenho
// e o modelo, conforme toda a sua feitura, e Urias o edifica ANTES QUE O REI
// VIESSE DE DAMASCO. Acaz sacrifica nele, e tira O ALTAR DE COBRE de diante da
// casa do SENHOR para o lado do NORTE — "porém o altar de cobre será para mim,
// para nele inquirir". Corta as cintas das bases, tira O MAR DE SOBRE OS BOIS DE
// COBRE e o põe sobre um pavimento de pedra, e retira a coberta do sábado e a
// entrada real externa POR CAUSA DO REI DA ASSÍRIA. É a fé remodelada pelo gosto
// do império.
//
// 2Rs 17 — OSÉIAS, o último rei de Israel. SALMANESER sobe, ele fica servo e
// paga tributo; conspira com SÔ, REI DO EGITO, deixa de pagar, e o rei da
// Assíria o encerra na CASA DO CÁRCERE. Samaria é cercada TRÊS ANOS e no ano
// nono é tomada: Israel vai cativo para Hala, Habor, o RIO DE GOZÃ e as cidades
// dos medos. E então vem o capítulo mais explicativo do Antigo Testamento — A
// LISTA DAS RAZÕES: pecaram contra o SENHOR que os fizera subir do Egito;
// andaram nos estatutos das nações; edificaram altos EM TODAS AS SUAS CIDADES,
// DESDE A TORRE DOS ATALAIAS ATÉ À CIDADE FORTIFICADA; levantaram estátuas e
// imagens do bosque EM TODOS OS ALTOS OUTEIROS E DEBAIXO DE TODAS AS ÁRVORES
// VERDES; fizeram DOIS BEZERROS de fundição e adoraram todo o exército do céu;
// FIZERAM PASSAR PELO FOGO SEUS FILHOS E SUAS FILHAS, deram-se a adivinhações e
// a agouros, e VENDERAM-SE para fazer o mal. E o refrão que dói: "o SENHOR
// advertiu a Israel e a Judá, pelo ministério de todos os profetas e de todos os
// videntes, dizendo: Convertei-vos de vossos maus caminhos" — "porém não deram
// ouvidos; antes endureceram a sua cerviz, como a cerviz de seus pais". Fecha
// com os povos trazidos de Babilônia, Cuta, Ava, Hamate e Sefarvaim; os LEÕES
// mandados entre eles porque não temiam ao SENHOR; o sacerdote levado de volta a
// Betel para ensinar o costume do Deus da terra; e o resultado híbrido, dito com
// todas as letras: "temiam ao Senhor, mas também serviam a seus deuses" — cada
// nação com o seu, até ao dia de hoje.
//
// A VOZ DE DEUS — em 2Rs 14–17 o SENHOR NÃO FALA EM BALÃO NENHUMA VEZ, e isso é
// o ponto teológico destes quatro capítulos: é o trecho em que Ele já falou
// tudo e ninguém ouviu. As Suas palavras aparecem SEMPRE em segunda mão, dentro
// de um documento ou de uma memória: escritas no LIVRO DA LEI DE MOISÉS (14:6 —
// o balão é o rolo aberto na mesa, sem `by`), cumpridas como palavra dita a Jeú
// (15:12 — narração com glória sobre os quatro tronos), dadas pelo MINISTÉRIO
// DE UM PROFETA (14:25, a palavra por Jonas, filho de Amitai, narrada com o
// profeta em cena e glória alta; 17:13, `by: "patriarca"` na boca do profeta
// que adverte, com `glow` alto, porque o versículo põe boca de mediador na
// frase) e lembradas como ALIANÇA do Sinai (17:35-39 — narração, glória alta,
// as tábuas e a arca no quadro, sem balão nenhum). Nunca `by: "deus"`: não há
// nestes capítulos uma só teofania, um só sonho, um só oráculo direto — o céu
// está calado porque a boca já foi usada e recusada. As únicas falas em balão
// são humanas: o desafio de Amazias e a parábola do cardo (14:8-10, `by: "rei"`),
// o "eu sou teu servo e teu filho" de Acaz e a sua ordem a Urias (16:7 e 16:15,
// `by: "rei"`), o pedido dos povos transportados e a resposta do rei da Assíria
// (17:26-27, `by: "homem"` e `by: "rei"`).
// ============================================================================

