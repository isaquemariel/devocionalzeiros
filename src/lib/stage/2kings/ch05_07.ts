// sai com carne de menino, O FERRO DO MACHADO EMPRESTADO QUE VEM A NADAR, o
// monte cheio de CAVALOS E CARROS DE FOGO em redor de Eliseu, a fome que faz
// uma cabeça de jumento valer oitenta peças de prata — e quatro leprosos que
// entram num arraial sem ninguém dentro e descobrem que aquele é dia de boas
// novas.
//
// 2Rs 5 — NAAMÃ, capitão do exército do rei da Síria, é "um grande homem
// diante do seu senhor, e de muito respeito", porque por ele o SENHOR dera
// livramento aos sírios: e a frase se fecha com a palavra que arruína tudo —
// "era este homem herói valoroso, PORÉM LEPROSO". O remédio vem da boca mais
// pequena da casa: UMA MENINA levada presa numa das tropas da Síria, ao
// serviço da mulher dele, diz à sua senhora "antes o meu senhor estivesse
// diante do profeta que está em Samaria; ele o restauraria da sua lepra". O rei
// da Síria despacha carta e tesouro — dez talentos de prata, seis mil siclos de
// ouro e dez mudas de roupas — e o rei de Israel, lendo a carta, RASGA AS SUAS
// VESTES: "sou eu Deus, para matar e para vivificar…? vede que busca ocasião
// contra mim". Eliseu manda recado: "deixa-o vir a mim, e saberá que há profeta
// em Israel". Naamã para à porta com os seus cavalos e o seu carro, e o profeta
// NÃO SAI DE CASA: manda um mensageiro dizer "vai, e lava-te sete vezes no
// Jordão". A indignação é de quem já tinha ensaiado a cura na cabeça: "eis que
// eu dizia comigo: CERTAMENTE ELE SAIRÁ, PÔR-SE-Á EM PÉ, invocará o nome do
// Senhor seu Deus, e passará a sua mão sobre o lugar" — e alega ABANA E FARPAR,
// rios de Damasco, melhores do que todas as águas de Israel. Quem o salva são
// os criados, com a frase mais sábia do capítulo: "meu pai, SE O PROFETA TE
// DISSESSE ALGUMA GRANDE COISA, PORVENTURA NÃO A FARIAS?". Desce, mergulha sete
// vezes, "E A SUA CARNE TORNOU-SE COMO A CARNE DE UM MENINO". Volta com toda a
// comitiva, confessa "em toda a terra não há Deus senão em Israel", e Eliseu
// recusa a bênção: "vive o Senhor, em cuja presença estou, que não a
// aceitarei". Naamã pede então UMA CARGA DE TERRA QUE BASTE PARA CARREGAR DUAS
// MULAS, para não mais oferecer holocausto a outros deuses, e pede perdão
// adiantado pelas vezes em que tiver de se encurvar na CASA DE RIMOM, apoiando
// o seu senhor pela mão. E o capítulo acaba na direção contrária: GEAZI corre
// atrás do carro, inventa dois jovens dos filhos dos profetas, leva dois
// talentos de prata em dois sacos e duas mudas de roupas, esconde tudo em casa
// e mente na cara do seu senhor — "teu servo não foi nem a uma nem a outra
// parte". Eliseu: "porventura não foi contigo o meu coração…? a lepra de Naamã
// se pegará a ti" — e ele saiu de diante dele LEPROSO, BRANCO COMO A NEVE. A
// luz troca de dono entre 5:1 e 5:27.
//
// 2Rs 6 — Três histórias e um cerco. (1) O FERRO DO MACHADO: os filhos dos
// profetas dizem que o lugar em que habitam diante da face dele "nos é
// estreito", descem ao Jordão a cortar vigas, e a um deles o ferro cai na água
// — "AI, MEU SENHOR! ELE ERA EMPRESTADO", que é a aflição de quem é pobre e
// ainda deve. Eliseu pergunta onde caiu, corta um pau, lança-o ali, E FEZ
// FLUTUAR O FERRO. (2) A GUERRA SEM SEGREDO: o rei da Síria marca acampamento
// em conselho fechado e o homem de Deus avisa Israel toda vez; o rei turbado
// acusa traição dentro de casa e ouve de um servo que "o profeta Eliseu, que
// está em Israel, faz saber ao rei de Israel AS PALAVRAS QUE TU FALAS NO TEU
// QUARTO DE DORMIR". Cercam Dotã de noite com cavalos, carros e um grande
// exército. O moço se levanta muito cedo, vê a cidade cercada e grita "AI, MEU
// SENHOR! QUE FAREMOS?"; e vem a resposta que é o coração do livro — "não
// temas; PORQUE MAIS SÃO OS QUE ESTÃO CONOSCO DO QUE OS QUE ESTÃO COM ELES" —
// e a oração: "Senhor, peço-te que lhe abras os olhos, para que veja. E o
// Senhor abriu os olhos do moço, e viu; E EIS QUE O MONTE ESTAVA CHEIO DE
// CAVALOS E CARROS DE FOGO, EM REDOR DE ELISEU". Feridos de cegueira, os siros
// são guiados pelo próprio profeta até dentro de Samaria; e quando o rei pede
// licença para matá-los ("feri-los-ei, feri-los-ei, meu pai?"), a ordem é o
// avesso da guerra: "PÕE-LHES DIANTE PÃO E ÁGUA, PARA QUE COMAM E BEBAM, E SE
// VÃO PARA SEU SENHOR" — e não entraram mais tropas de sírios na terra de
// Israel. (3) O CERCO: Ben-Hadade volta com todo o exército e a fome em Samaria
// chega ao ponto em que UMA CABEÇA DE JUMENTO vale oitenta peças de prata e A
// QUARTA PARTE DE UM CABO DE ESTERCO DE POMBAS vale cinco. No muro, uma mulher
// brada por socorro e conta o pacto mais escuro da Escritura: cozeram o filho
// de uma e a outra escondeu o seu. O rei rasga as vestes andando pelo muro, e
// o povo vê que ELE TRAZIA CILÍCIO POR DENTRO, SOBRE A SUA CARNE — jejuava por
// baixo enquanto jurava tirar a cabeça de Eliseu.
//
// 2Rs 7 — Eliseu responde ao cerco com um preço: "AMANHÃ, QUASE A ESTE TEMPO,
// haverá uma medida de farinha por um siclo, e duas medidas de cevada por um
// siclo, à porta de Samaria". O senhor em cuja mão o rei se encostava zomba —
// "ainda que o SENHOR fizesse JANELAS NO CÉU, poder-se-ia fazer isso?" — e
// recebe a sentença exata: "eis que o verás com os teus olhos, PORÉM DISSO NÃO
// COMERÁS". A salvação entra pela porta de serviço: QUATRO HOMENS LEPROSOS à
// entrada da porta fazem a conta de quem não tem nada a perder — "para que
// estaremos nós aqui até morrermos?" — e passam ao arraial dos sírios ao
// crepúsculo. Não há ali ninguém: PORQUE O SENHOR FIZERA OUVIR NO ARRAIAL RUÍDO
// DE CARROS E RUÍDO DE CAVALOS, COMO O RUÍDO DE UM GRANDE EXÉRCITO, e eles
// fugiram deixando as suas tendas, os seus cavalos, os seus jumentos e o
// arraial como estava. Os leprosos comem, bebem, escondem prata, ouro e roupas
// — e param no meio do saque: "NÃO FAZEMOS BEM; ESTE DIA É DIA DE BOAS NOVAS, E
// NOS CALAMOS". Os porteiros anunciam, o rei de noite desconfia de cilada,
// mandam cavalos ver, e todo o caminho até ao Jordão está CHEIO DE ROUPAS E DE
// AVIAMENTOS que os sírios lançaram fora na pressa. O povo sai, saqueia, e o
// preço se cumpre à letra — e o senhor que zombou é atropelado à porta e morre,
// vendo com os olhos e não comendo, como falara o homem de Deus.
//
// A VOZ DE DEUS — nestes três capítulos o SENHOR não fala em balão de voz do
// céu uma única vez, e é de propósito: aqui Ele fala SEMPRE POR MEDIADOR, e o
// mediador é ELISEU (papel `patriarca`, id `eliseu`), com `glow` alto e sempre
// em cena — a ordem das sete imersões (5:10), o "mais são os que estão conosco"
// e a oração que abre os olhos do moço (6:16-17), a ordem de pôr pão e água
// diante dos cegos (6:22) e o preço de amanhã à porta de Samaria (7:1). Por
// isso NÃO existe `by: "deus"` em lugar nenhum deste arquivo. Os três milagres
// mudos do bloco são mudos mesmo: a carne que volta a ser de menino (5:14), o
// ferro que vem a nadar (6:6) e — o mais impressionante — 7:6, onde o SENHOR
// age em SOM e não em palavra: o ruído de carros e de um grande exército está
// contado só pelo ambiente (tempestade alta, noite) e pelas figuras em fuga,
// sem balão nenhum. Onde o balão traz "assim diz o SENHOR" (7:1), quem abre a
// boca é o profeta, e o balão é dele.
//
// NOTA DE MOTOR: `by` é sempre um PAPEL (o motor resolve
// `cast.find(id === by) ?? cast.find(role === by)`), por isso quem fala está
// sempre em cena e é SEMPRE O PRIMEIRO DO SEU PAPEL no `cast` daquele beat —
// é assim que "patriarca" quer dizer Eliseu, "homem" quer dizer Naamã no cap. 5
// e o senhor do braço do rei no cap. 7, e "servo" quer dizer Geazi.
// ============================================================================

import type { StageBeat, CastPlacement, StagePropSpec } from "@/lib/rpgStage";

const C = (role: string, dx: number, pose?: string, extra: Partial<CastPlacement> = {}): CastPlacement =>
  ({ role, dx, pose, ...extra });
const P = (kind: string, dx: number, scale = 1, fire?: number, dy?: number): StagePropSpec =>
  ({ kind, dx, scale, ...(fire != null ? { fire } : {}), ...(dy != null ? { dy } : {}) });
const b = (v: number, extra: Partial<StageBeat> = {}): StageBeat => ({ v, ...extra });

