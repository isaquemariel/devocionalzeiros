// ============================================================================
// 2 REIS 24–25 — CENA VIVA. O FIM DE JUDÁ: as tropas mandadas de quatro lados,
// as TRINCHEIRAS EM REDOR de Jerusalém, o pão que acaba, a porta ENTRE OS DOIS
// MUROS junto ao jardim do rei, os filhos de Zedequias mortos diante dos seus
// olhos, a casa do SENHOR em chamas, as DUAS COLUNAS medidas antes de serem
// quebradas — e, na última página, um homem tirado da casa da prisão que come
// pão à mesa do rei todos os dias da sua vida.
//
// 2Rs 24 — Nos dias de Jeoiaquim SUBIU NABUCODONOSOR, e o rei de Judá lhe fica
// TRÊS ANOS SERVO; depois se vira e se rebela. A resposta não vem de um
// exército só: o SENHOR envia contra ele as TROPAS DOS CALDEUS, as TROPAS DOS
// SÍRIOS, as TROPAS DOS MOABITAS e as TROPAS DOS FILHOS DE AMOM, "conforme a
// palavra do Senhor, que falara pelo ministério de seus servos, os profetas". E
// o livro diz por quê, sem rodeio: por causa dos PECADOS DE MANASSÉS, e por
// causa do SANGUE INOCENTE que ele derramou até encher Jerusalém — "e por isso
// o Senhor não quis perdoar". Jeoiaquim dorme com seus pais; JOAQUIM, o filho,
// reina três meses com dezoito anos, e a mãe dele, NEUSTA, filha de Elnatã, é
// anotada pelo nome. Entre um rei e outro cai a frase que fecha o mapa do
// mundo antigo: "E O REI DO EGITO NUNCA MAIS SAIU DA SUA TERRA; porque o rei de
// babilônia tomou tudo quanto era do rei do Egito, DESDE O RIO DO EGITO ATÉ AO
// RIO EUFRATES". Os servos de Nabucodonosor sobem, A CIDADE É CERCADA, e o
// próprio rei de babilônia vem quando já a estavam sitiando. Então Joaquim SAI
// AO REI DE BABILÔNIA — ele, sua mãe, seus servos, seus príncipes e seus
// oficiais — e é tomado preso no ano oitavo. Tiram dali TODOS OS TESOUROS DA
// CASA DO SENHOR e os tesouros da casa do rei, e PARTEM TODOS OS VASOS DE OURO
// QUE SALOMÃO FIZERA NO TEMPLO. Transportam a toda a Jerusalém: os príncipes,
// os homens valorosos, DEZ MIL PRESOS, os artífices e os ferreiros — "NINGUÉM
// FICOU SENÃO O POVO POBRE DA TERRA". No trono vazio o rei de babilônia põe
// MATANIAS, tio do menino levado, e lhe MUDA O NOME PARA ZEDEQUIAS: o último
// rei de Judá nem o próprio nome tem. E ele também se rebela.
//
// 2Rs 25 — No nono ano, no mês décimo, AOS DEZ DO MÊS, Nabucodonosor vem com
// todo o seu exército, acampa-se contra a cidade e LEVANTA CONTRA ELA
// TRINCHEIRAS EM REDOR. O cerco dura até ao undécimo ano. Aos nove do mês
// quarto a cidade se vê APERTADA PELA FOME, e "nem havia pão para o povo da
// terra". A cidade é invadida, e todos os homens de guerra fogem DE NOITE PELO
// CAMINHO DA PORTA, ENTRE OS DOIS MUROS QUE ESTAVAM JUNTO AO JARDIM DO REI — e
// o rei se vai pelo caminho da campina. O exército dos caldeus o persegue e o
// alcança NAS CAMPINAS DE JERICÓ; todo o seu exército se dispersa dele. Levam-no
// a RIBLA, e ali lhe é pronunciada a sentença: "e aos filhos de Zedequias
// mataram DIANTE DOS SEUS OLHOS; e VAZARAM OS OLHOS DE ZEDEQUIAS, e o ataram
// com DUAS CADEIAS DE BRONZE, e o levaram a babilônia" — a última coisa que
// aquele homem viu foi a morte dos seus filhos. No quinto mês vem NEBUZARADÃ,
// CAPITÃO DA GUARDA, e queima a casa do SENHOR, a casa do rei, todas as casas
// de Jerusalém, e todas as casas dos grandes; o exército derruba OS MUROS EM
// REDOR. Leva os presos, e deixa "dos mais pobres da terra" alguns PARA
// VINHEIROS E PARA LAVRADORES — é a única misericórdia do capítulo. E então o
// texto para tudo para MEDIR O BRONZE: as colunas de cobre, as bases, o MAR, as
// caldeiras, as pás, os apagadores, as colheres, os braseiros e as bacias — "o
// cobre de todos estes vasos NÃO TINHA PESO" —, e mede AS DUAS COLUNAS uma por
// uma: dezoito côvados de altura, capitel de cobre de três côvados, e A REDE E
// AS ROMÃS EM REDOR DO CAPITEL, tudo de cobre. São JAQUIM e BOAZ, as mesmas de
// 1Rs 7, contadas inteiras justamente na página em que viram sucata. Depois
// tomam SERAÍAS, o primeiro sacerdote, SOFONIAS, o segundo, e OS TRÊS GUARDAS
// DO UMBRAL DA PORTA, e o oficial dos homens de guerra, e o escrivão-mor, e
// sessenta homens do povo da terra — e o rei de babilônia os fere e os mata em
// Ribla, na terra de Hamate. Sobre o resto fica GEDALIAS, filho de Aicão, e a
// sua palavra em Mizpá é quase um evangelho pequeno: "servi ao rei de
// babilônia, e bem vos irá". Ao sétimo mês vem ISMAEL, filho de Netanias, DA
// DESCENDÊNCIA REAL, e dez homens com ele, e o ferem; e todo o povo, do menor
// até ao maior, foge AO EGITO — o caminho do êxodo andado ao contrário. E o
// livro acaba com uma luz do tamanho de uma janela: no ano trinta e sete do
// cativeiro, EVIL-MERODAQUE LEVANTA A CABEÇA DE JOAQUIM da casa da prisão, lhe
// fala benignamente, PÕE O SEU TRONO ACIMA DO TRONO DOS REIS que estavam com
// ele em babilônia, LHE MUDA AS ROUPAS DE PRISÃO, e ele COME PÃO DE CONTÍNUO NA
// SUA PRESENÇA TODOS OS DIAS DA SUA VIDA.
//
// A VOZ DE DEUS — nestes dois capítulos o SENHOR NÃO FALA UMA ÚNICA VEZ, e por
// isso não há aqui nenhum balão de voz do céu. O texto diz o que Ele FEZ —
// "enviou contra ele as tropas dos caldeus" (24:2), "conforme o mandado do
// Senhor" (24:3), "não quis perdoar" (24:4), "por causa da ira do SENHOR contra
// Jerusalém" (24:20) —, mas nunca o põe falando. Onde a palavra é atribuída à
// boca de alguém, essa boca é dos PROFETAS, e no passado: "conforme a palavra
// do Senhor, que falara pelo ministério de seus servos, os profetas" (24:2).
// Isso é MENÇÃO NARRATIVA, não discurso em cena: fica na barra do narrador, e o
// profeta aparece apenas como figura calada e luminosa no canto do quadro de
// 24:2 — o homem cuja palavra já tinha sido dita e agora está sendo cumprida.
// O único balão dos cinquenta versículos é humano e é de GEDALIAS em Mizpá
// (25:24), a última boca de Judá a prometer alguma coisa boa — e ele morre no
// versículo seguinte. Deus, aqui, é o silêncio que sobrou depois dos profetas.
// ============================================================================

