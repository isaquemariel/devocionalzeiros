// ============================================================================
// 2 REIS 3–4 — CENA VIVA. O vale seco que se enche de água sem vento e sem
// chuva, as águas VERMELHAS COMO SANGUE ao sol da manhã, o primogênito de Moabe
// queimado em cima do muro — e depois cinco milagres seguidos de ELISEU, um
// atrás do outro: a botija de azeite, o quarto de cima em Suném, o menino que
// espirra sete vezes, a morte na panela e os cem pães.
//
// 2Rs 3 — JORÃO, filho de Acabe, começa a reinar em Samaria no décimo oitavo
// ano de Jeosafá. O texto lhe dá meia absolvição e a retira na frase seguinte:
// "fez o que era mau aos olhos do Senhor; PORÉM NÃO COMO SEU PAI, NEM COMO SUA
// MÃE; porque tirou a estátua de Baal, que seu pai fizera" — e logo, "contudo
// aderiu aos pecados de Jeroboão, filho de Nebate". Derrubou o ídolo de fora e
// ficou com os bezerros de dentro. Do outro lado do mar Morto está MESA, REI DOS
// MOABITAS, que "era criador de gado" e pagava de tributo ao rei de Israel CEM
// MIL CORDEIROS E CEM MIL CARNEIROS COM A SUA LÃ; morto Acabe, ele se rebela.
// Jorão faz revista de todo o Israel e manda chamar Jeosafá, que responde com a
// mesma fórmula de sempre — "subirei; e eu serei como tu, o meu povo como o teu
// povo, e os meus cavalos como os teus cavalos" — e escolhe o caminho: PELO
// DESERTO DE EDOM. Três reis rodeiam SETE DIAS DE MARCHA e não há água para o
// exército nem para o gado que os segue. O rei de Israel já lê tudo como
// condenação ("o Senhor chamou a estes três reis, para entregá-los nas mãos dos
// moabitas"); é Jeosafá quem pergunta pelo profeta, e a resposta vem da boca de
// um SERVO, não de um sacerdote: "aqui está Eliseu, filho de Safate, QUE
// DERRAMAVA ÁGUA SOBRE AS MÃOS DE ELIAS" — o currículo do sucessor é ter sido
// criado de outro. Os três reis descem à tenda dele e levam a frase mais
// cortante do capítulo: "QUE TENHO EU CONTIGO? VAI AOS PROFETAS DE TEU PAI E AOS
// PROFETAS DE TUA MÃE". Só por amor de Jeosafá ele olha para aquele rosto. Então
// pede uma coisa que não se repete em lugar nenhum: "ORA, POIS, TRAZEI-ME UM
// MÚSICO" — e sucedeu que, TOCANDO O MÚSICO, VEIO SOBRE ELE A MÃO DO SENHOR. A
// palavra manda cavar: "fazei neste vale muitas covas… NÃO VEREIS VENTO, E NÃO
// VEREIS CHUVA; TODAVIA ESTE VALE SE ENCHERÁ DE TANTA ÁGUA, que bebereis vós, o
// vosso gado e os vossos animais". Pela manhã, à hora da oferta, "eis que vinham
// as águas pelo caminho de Edom; e a terra se encheu de água". Do outro lado, os
// moabitas se levantam de madrugada, o sol nasce em cima do vale alagado, e eles
// veem AS ÁGUAS VERMELHAS COMO SANGUE: "isto é sangue; certamente que os reis se
// destruíram à espada e se mataram um ao outro! Agora, pois, à presa, moabitas!".
// Correm ao despojo e caem no arraial de Israel. As cidades são arrasadas, cada
// um lança a sua pedra nos bons campos, as fontes são entupidas, as boas árvores
// cortadas, e só em QUIR-HARESETE ficam as pedras. Encurralado, Mesa toma
// setecentos homens que sacavam espada para romper contra o rei de Edom e não
// consegue — e faz então a coisa mais escura do livro: "tomou a seu filho
// primogênito, QUE HAVIA DE REINAR EM SEU LUGAR, e o ofereceu em holocausto sobre
// o muro". Houve grande indignação em Israel, e o exército voltou para a sua
// terra. Nenhum vencedor sai deste capítulo.
//
// 2Rs 4 — CINCO MILAGRES EM FILA, e cada um cabe numa casa. (1) A BOTIJA DE
// AZEITE: a viúva de um dos filhos dos profetas clama porque "veio o credor,
// para levar os meus dois filhos para serem servos". Eliseu pergunta o
// inventário — "dize-me que é o que tens em casa" — e a resposta é o fundo do
// poço: "tua serva não tem nada em casa, SENÃO UMA BOTIJA DE AZEITE". A ordem é
// pedir emprestadas vasilhas vazias aos vizinhos, "NÃO POUCAS", fechar a porta
// sobre si e sobre os filhos e ir despejando; e quando o filho diz "não há mais
// vasilha alguma", ENTÃO O AZEITE PAROU — o milagre tinha o tamanho da fé dela
// em vasilhas. Vende, paga a dívida, e ela e os filhos vivem do resto. (2) A
// SUNAMITA: uma mulher importante de Suném o constrange a comer pão e depois
// convence o marido — "façamos-lhe, pois, UM PEQUENO QUARTO JUNTO AO MURO, e
// ali lhe ponhamos UMA CAMA, UMA MESA, UMA CADEIRA E UM CANDEEIRO". Oferecida
// uma palavra ao rei ou ao capitão do exército, ela recusa com uma frase que é
// um lar inteiro: "EU HABITO NO MEIO DO MEU POVO". Geazi vê o que falta — "ora
// ela não tem filho, e seu marido é velho" — e vem a promessa: "a este tempo
// determinado, segundo o tempo da vida, ABRAÇARÁS UM FILHO". (3) O FILHO MORTO
// E RESSUSCITADO: crescido, o menino sai ao campo com o pai na sega e grita
// "AI, A MINHA CABEÇA! AI, A MINHA CABEÇA!"; levado à mãe, fica sobre os
// joelhos dela ATÉ AO MEIO-DIA, e morre. Ela sobe, o deita na CAMA DO HOMEM DE
// DEUS, fecha a porta, albarda a jumenta e corre ao Carmelo dizendo a todos
// "TUDO VAI BEM". Aos pés do profeta, pega-lhe os pés; Geazi vai retirá-la e
// ouve: "deixa-a, porque a sua alma está triste de amargura, E O SENHOR ME
// ENCOBRIU, E NÃO ME MANIFESTOU". O bordão mandado adiante não desperta
// ninguém. Eliseu entra, FECHA A PORTA SOBRE ELES AMBOS, ora, sobe à cama e se
// estende sobre o menino BOCA SOBRE BOCA, OLHOS SOBRE OLHOS, MÃOS SOBRE MÃOS —
// e a carne aquece; anda pela casa de uma parte para a outra, torna a subir, e
// O MENINO ESPIRROU SETE VEZES, E ABRIU OS OLHOS. (4) A MORTE NA PANELA: em
// Gilgal há fome, os filhos dos profetas estão assentados na presença dele, a
// panela grande vai ao lume, e um que saiu ao campo enche a capa de
// COLOCÍNTIDAS de uma parra brava "porque não as conheciam"; ao provar, o grito:
// "HOMEM DE DEUS, HÁ MORTE NA PANELA". Ele manda trazer farinha, deita na
// panela, e já não havia mal nenhum. (5) OS CEM PÃES: um homem vem de
// BAAL-SALISA com vinte pães de cevada e espigas verdes na sua palha; o servo
// mede a aritmética — "como hei de pôr isto diante de cem homens?" — e a palavra
// responde por cima dela: "COMERÃO, E SOBEJARÁ". E comeram, e ainda sobrou.
//
// A VOZ DE DEUS — nestes dois capítulos Deus NÃO fala em balão nenhuma vez, e
// isso é proposital: aqui a Sua voz tem sempre um mediador de carne, e o
// mediador é ELISEU (`patriarca`, id `eliseu`), com `glow` alto. Até em 3:15-19,
// onde o texto diz que "veio sobre ele A MÃO DO SENHOR" enquanto o músico
// tocava, quem abre a boca é o profeta — "assim diz o Senhor" sai da boca dele,
// e por isso o balão é dele, não voz do céu. Os dois milagres mudos do bloco —
// as águas que chegam pelo caminho de Edom (3:20) e o menino que espirra sete
// vezes (4:35) — acontecem SEM UMA PALAVRA: ali não há balão, só a glória
// subindo ao máximo e a água ou a vida entrando em cena. E o holocausto do
// primogênito sobre o muro (3:27) é o avesso disso: o único fogo de altar dos
// dois capítulos é o de um pai matando um filho por um deus que não responde —
// noite alta, glória no chão, e NENHUMA multidão festiva em cena.
// ============================================================================

