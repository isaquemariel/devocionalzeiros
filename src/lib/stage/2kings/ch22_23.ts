// 2 REIS 22–23 — CENA VIVA. O LIVRO DA LEI ACHADO NO MEIO DE UMA OBRA, as
// VESTES RASGADAS do rei de vinte e seis anos, a PROFETISA na segunda parte da
// cidade, e a maior faxina do Antigo Testamento — feita a pó, a fogo e a
// enxada, de Cedrom a Betel.
//
// 2Rs 22 — Josias tem OITO ANOS DE IDADE quando começa a reinar, e reina trinta
// e um anos em Jerusalém; o nome da mãe fica anotado como testemunha: JEDIDA,
// filha de Adaías, de Bozcate. "E fez o que era reto aos olhos do Senhor; e
// andou em todo o caminho de Davi, seu pai, e não se apartou dele nem para a
// direita nem para a esquerda." No ANO DÉCIMO OITAVO ele manda SAFÃ, o
// escrivão, à casa do SENHOR com uma ordem de obra, não de culto: que Hilquias
// tome o dinheiro que os GUARDAS DO UMBRAL DA PORTA ajuntaram do povo e o
// entregue na mão dos que têm cargo da obra, para REPARAREM AS FENDAS DA CASA —
// aos carpinteiros, aos edificadores e aos pedreiros, e para comprar madeira e
// pedras lavradas. E vem a linha mais bonita do capítulo, que é sobre dinheiro:
// "PORÉM NÃO SE PEDIU CONTA DO DINHEIRO QUE SE LHES ENTREGARA NAS SUAS MÃOS,
// PORQUANTO PROCEDIAM COM FIDELIDADE". É no meio dessa obra, entre o pó de
// pedra e a madeira nova, que o sumo sacerdote HILQUIAS levanta um rolo e diz
// seis palavras: "ACHEI O LIVRO DA LEI NA CASA DO SENHOR". Safã lê o livro, o
// leva ao rei, presta contas do dinheiro como quem cumpre pauta — "o sacerdote
// Hilquias me deu um livro" — e o lê diante do rei. "SUCEDEU, POIS, QUE,
// OUVINDO O REI AS PALAVRAS DO LIVRO DA LEI, RASGOU AS SUAS VESTES." O rei
// manda cinco homens da corte — Hilquias, Aicão filho de Safã, Acbor filho de
// Micaías, Safã o escrivão e Asaías o servo do rei — consultar o SENHOR, porque
// "grande é o furor do Senhor, que se acendeu contra nós". E a corte inteira vai
// bater à porta de uma casa comum: HULDA, A PROFETISA, mulher de Salum, o guarda
// das vestiduras, que habitava em Jerusalém NA SEGUNDA PARTE. A resposta dela
// tem duas metades. Sobre o LUGAR: "eis que trarei mal sobre este lugar… o meu
// furor se acendeu contra este lugar, e não se apagará". Sobre o REI: "porquanto
// o teu coração se enterneceu, e te humilhaste perante o Senhor… tu serás
// recolhido em paz à tua sepultura, e os teus olhos não verão todo o mal".
//
// 2Rs 23 — A obediência de Josias é física, e o texto a lista lugar por lugar.
// Ele ajunta os anciãos, sobe à casa do SENHOR com todo o povo, DESDE O MENOR
// ATÉ AO MAIOR, e lê aos ouvidos deles todas as palavras do livro da aliança.
// Depois SE PÕE EM PÉ JUNTO À COLUNA e faz a aliança perante o SENHOR — e todo
// o povo a apoia. Então começa a limpeza: os vasos feitos para Baal, para o
// bosque e para todo o exército dos céus saem do templo e ardem NOS CAMPOS DE
// CEDROM, e as cinzas vão para Betel; os sacerdotes que incensavam ao sol, à lua
// e aos planetas são destituídos; o ídolo do bosque é levado AO RIBEIRO DE
// CEDROM, queimado, desfeito EM PÓ, e o pó é lançado SOBRE AS SEPULTURAS DOS
// FILHOS DO POVO; as casas dos sodomitas que estavam na casa do SENHOR — onde as
// mulheres teciam casinhas para o bosque — vêm abaixo; os altos são profanados
// DESDE GEBA ATÉ BERSEBA, inclusive os que estavam à porta de Josué, o
// governador da cidade. TOFETE, no vale dos filhos de Hinom, é contaminada
// "para que ninguém fizesse passar a seu filho, ou sua filha, pelo fogo a
// Moloque". Os CAVALOS que os reis de Judá tinham dedicado ao sol são tirados da
// entrada da casa do SENHOR, e OS CARROS DO SOL QUEIMADOS A FOGO. Caem os
// altares do terraço do cenáculo de Acaz e os que Manassés fizera nos dois
// átrios; caem os altos que Salomão edificara à mão direita do MONTE DE MASITE a
// Astarote, a Quemós e a Milcom. Em BETEL, o altar de Jeroboão é derrubado e o
// alto queimado — e então vem a cena mais dura do livro: o rei se vira, VÊ AS
// SEPULTURAS QUE ESTAVAM ALI NO MONTE, manda tirar os ossos e OS QUEIMA SOBRE
// AQUELE ALTAR, cumprindo ao pé da letra a palavra que o homem de Deus gritara
// contra aquele altar em 1Rs 13. Só um túmulo é poupado: "QUE É ESTE MONUMENTO
// QUE VEJO?" — "é a sepultura do homem de Deus que veio de Judá" — "DEIXAI-O
// ESTAR; NINGUÉM MEXA NOS SEUS OSSOS". Depois de Samaria, a PÁSCOA: "nunca se
// celebrou tal páscoa como esta desde os dias dos juízes que julgaram a
// Israel". E o rei que não teve semelhante nem antes nem depois esbarra na
// sentença que já estava dada: "TODAVIA O SENHOR NÃO SE DEMOVEU DO ARDOR DA SUA
// GRANDE IRA", por causa de Manassés. O fim é rápido e escuro: Faraó Neco sobe
// ao Eufrates, Josias lhe vai ao encontro e é morto EM MEGIDO; os servos o
// levam NUM CARRO, MORTO, a Jerusalém. Jeoacaz reina três meses e é preso em
// RIBLA, na terra de Hamate; Eliaquim é feito rei, tem o nome mudado para
// JEOIAQUIM, e tributa a terra para pagar a prata e o ouro a Faraó.
//
// A VOZ DE DEUS — nestes dois capítulos o SENHOR fala quase sempre POR
// MEDIADOR, e por dois mediadores de naturezas diferentes. O primeiro é um
// OBJETO: o LIVRO DA LEI achado na casa. Nos beats em que o livro é lido
// (22:10, 22:11 e 23:2) a palavra chega pela BOCA DO LEITOR — Safã diante do
// rei, o rei diante do povo —, e por isso o balão sai de quem lê, com o rolo
// marcado com `tag` no palco: o objeto é o mediador, e o leitor é a sua voz. O
// segundo é uma PESSOA: HULDA, a profetisa, a única de todo o livro. Em
// 22:15-20 o "assim diz o Senhor Deus de Israel" está na boca dela, e por isso
// todo o oráculo sai como balão de `mulherComum` com Hulda em cena e em
// primeiro lugar no elenco — nunca voz do céu, nunca `mulher` (que o motor
// ignora a pose e desenha sempre dourada e em pé). Em 23:16-18 a palavra
// cumprida é a do HOMEM DE DEUS de 1Rs 13, e quem a cita em cena é Josias: o
// balão é do rei. Há UMA ÚNICA voz do céu nos dois capítulos, e é a que fecha o
// reinado: 23:27, "E DISSE O SENHOR: Também a Judá hei de tirar de diante da
// minha face" — ali não há profeta, nem sacerdote, nem livro na frase, não há
// mediador nenhum, e por isso `by: "deus"`, sem figura, com a glória subindo
// dourada sobre uma Jerusalém já escura. É a sentença passando por cima da
// melhor reforma que Judá teve.
// ============================================================================

