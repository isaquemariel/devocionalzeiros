// ============================================================================
// 2 REIS 18–19 — CENA VIVA. A SERPENTE DE METAL FEITA EM PEDAÇOS, o grito em
// judaico ao pé do AQUEDUTO DA PISCINA SUPERIOR, o povo que se cala em cima do
// muro, a CARTA ESTENDIDA PERANTE O SENHOR e o arraial cheio de cadáveres pela
// manhã cedo.
//
// 2Rs 18 — Ezequias, filho de Acaz, começa a reinar com vinte e cinco anos, e
// faz o que é reto aos olhos do Senhor "conforme tudo o que fizera Davi, seu
// pai". A reforma é física e é violenta: tira os altos, quebra as estátuas,
// deita abaixo os bosques — e FAZ EM PEDAÇOS A SERPENTE DE METAL QUE MOISÉS
// FIZERA, porque até àquele dia os filhos de Israel lhe queimavam incenso, e
// lhe chamaram NEUSTÃ. O objeto que um dia curou no deserto virou ídolo, e o
// rei o quebra. "No Senhor Deus de Israel confiou, de maneira que depois dele
// não houve quem lhe fosse semelhante entre todos os reis de Judá, nem entre
// os que foram antes dele": Ezequias se chega ao SENHOR, não se aparta dele, e
// se rebela contra o rei da Assíria. Enquanto isso, ao norte, a conta do outro
// reino fecha: Salmaneser sobe contra Samaria, a cerca três anos, a toma no
// ano nono de Oséias, e Israel é transportado a Hala, a Habor, junto ao rio de
// Gozã, e às cidades dos medos — "porquanto não obedeceram à voz do Senhor seu
// Deus". No ano décimo quarto de Ezequias, Senaqueribe toma todas as cidades
// fortificadas de Judá, e o rei de Jerusalém compra tempo: "Pequei; retira-te
// de mim; tudo o que me impuseres suportarei" — trezentos talentos de prata,
// trinta de ouro, a prata da casa do Senhor, e o OURO CORTADO DAS PORTAS DO
// TEMPLO E DAS OMBREIRAS. Não adianta. De Laquis vêm Tartã, Rabe-Saris e
// RABSAQUÉ com grande exército, e param AO PÉ DO AQUEDUTO DA PISCINA SUPERIOR,
// junto ao caminho do campo do lavandeiro. Saem-lhes Eliaquim, o mordomo,
// Sebna, o escrivão, e Joá, o cronista. O discurso de Rabsaqué é uma aula de
// guerra psicológica: o Egito é "aquele bordão de cana quebrada" que fura a mão
// de quem nele se encosta; o próprio SENHOR está ofendido porque Ezequias tirou
// os seus altos; toma dois mil cavalos, se achares cavaleiros para eles; e —
// pior — "o Senhor me disse: Sobe contra esta terra, e destrói-a", que é um
// homem alegando a voz de Deus para si. Os três pedem que fale em siríaco, para
// que o povo do muro não entenda; ele responde que é exatamente ao povo do muro
// que veio falar, e então SE PÕE EM PÉ E CLAMA EM ALTA VOZ EM JUDAICO,
// prometendo a cada um a sua vide, a sua figueira e a água da sua cisterna. E a
// resposta de Jerusalém é a linha mais alta do capítulo: "PORÉM CALOU-SE O
// POVO, E NÃO LHE RESPONDEU UMA SÓ PALAVRA; PORQUE MANDADO DO REI HAVIA,
// DIZENDO: NÃO LHE RESPONDEREIS". Os três voltam ao rei com as vestes rasgadas.
//
// 2Rs 19 — Ezequias rasga as vestes, se cobre de saco e ENTRA NA CASA DO
// SENHOR. Manda Eliaquim, Sebna e os anciãos dos sacerdotes, todos cobertos de
// sacos, ao profeta ISAÍAS, filho de Amós, com a imagem que resume o dia: "os
// filhos chegaram ao parto, e não há força para dá-los à luz" — e o pedido:
// "faze, pois, oração pelo restante que subsiste". Isaías responde sem
// hesitação: não temas as palavras que ouviste; "eis que porei nele um
// espírito, e ele ouvirá um rumor, e voltará para a sua terra; à espada o
// farei cair na sua terra". Rabsaqué volta e acha o rei pelejando contra Libna;
// chega o rumor de Tiraca, rei da Etiópia, e Senaqueribe manda a SEGUNDA CARTA:
// não te engane o teu Deus; olha o que fizeram os reis da Assíria a Gozã, a
// Harã, a Rezefe, aos filhos de Éden que estavam em Telassar. Então vem a cena
// que sustenta o livro inteiro: Ezequias recebe as cartas das mãos dos
// mensageiros, lê, SOBE À CASA DO SENHOR E AS ESTENDE PERANTE O SENHOR — o
// papel aberto diante da arca, entre os querubins — e ora: "só tu és Deus de
// todos os reinos da terra; tu fizeste os céus e a terra… livra-nos da sua
// mão; e assim saberão todos os reinos da terra que só tu és o Senhor Deus".
// A resposta desce pela boca de Isaías, e é a palavra mais longa do livro: a
// VIRGEM, A FILHA DE SIÃO, o despreza e dele zomba, e a filha de Jerusalém
// meneia a cabeça por detrás dele; o gabarolas que subiu ao alto dos montes
// para cortar os cedros do Líbano e secar com a planta dos pés os rios do
// Egito não passa de instrumento de um plano antigo; e o SENHOR lhe promete o
// ANZOL NO NARIZ e o FREIO NOS LÁBIOS, e o caminho de volta por onde veio. Ao
// rei fica o SINAL DOS TRÊS ANOS: este ano o que nascer por si, no seguinte o
// que daí proceder, e no terceiro semear, segar, plantar vinhas e comer os
// frutos — porque o que escapou da casa de Judá tornará a lançar raízes para
// baixo e dará fruto para cima. Naquela mesma noite SAI O ANJO DO SENHOR e
// fere no arraial dos assírios cento e oitenta e cinco mil; e, levantando-se
// pela manhã cedo, eis que todos eram cadáveres. Senaqueribe parte, volta e
// fica em Nínive — e ali, PROSTRADO NA CASA DE NISROQUE, SEU DEUS, os seus
// próprios filhos Adrameleque e Sarezer o ferem à espada.
//
// A VOZ DE DEUS — nestes dois capítulos o SENHOR não fala uma única vez em voz
// do céu, e é de propósito: este é o livro dos profetas, e aqui Ele age sempre
// por MEDIADOR. Em 19:6-7 e em 19:20-34 o texto põe a boca de ISAÍAS na frase
// ("E Isaías lhes disse", "Então Isaías, filho de Amós, mandou dizer a
// Ezequias") — por isso o balão é `by: "patriarca"`, com `isaias` em primeiro
// lugar no elenco e `glow` alto, e nunca `by: "deus"`. Em 19:35 Ele age sem
// dizer palavra: o ANJO DO SENHOR sai, fere, e o texto não lhe põe uma sílaba
// na boca — logo o beat não tem balão nenhum, só a figura luminosa de pé no
// meio dos corpos. E em 18:25 há a falsificação: RABSAQUÉ alega "o Senhor me
// disse: Sobe contra esta terra, e destrói-a" — ali o balão é de um HOMEM
// (`by: "homem"`, id `rabsaque`, sem glow nenhum, com a glória do ambiente no
// chão), porque quem fala é o assírio e não o SENHOR. A única glória que sobe
// nestes capítulos sobe onde Ezequias se ajoelha (19:14-19) e onde o profeta
// abre a boca.
// ============================================================================

