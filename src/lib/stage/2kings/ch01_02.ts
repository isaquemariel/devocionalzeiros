// 2 REIS 1–2 — CENA VIVA. A morte do filho de Acabe pelas grades de um quarto
// alto e a pergunta que atravessa o livro inteiro — "PORVENTURA NÃO HÁ DEUS EM
// ISRAEL?" —, o fogo que desce duas vezes sobre os capitães de cinquenta, e
// depois a saída mais estranha da Escritura: um profeta que não morre, levado
// vivo num REDEMOINHO, com um CARRO DE FOGO E CAVALOS DE FOGO abrindo caminho
// entre ele e o discípulo que se recusou a ficar para trás.
//
// 2Rs 1 — O livro abre com uma rachadura: "depois da morte de Acabe, Moabe se
// rebelou contra Israel". O império que Onri montou começa a se desmanchar no
// dia em que o pai morre — e o filho que herda o trono não cai numa batalha,
// cai em casa: "E CAIU ACAZIAS PELAS GRADES DE UM QUARTO ALTO, QUE TINHA EM
// SAMARIA, E ADOECEU". Da cama manda mensageiros a ECROM, cidade dos filisteus,
// consultar BAAL-ZEBUBE — "o senhor das moscas" — se sarará. O rei de Israel
// pergunta a um deus filisteu se vai viver. O anjo do SENHOR intercepta a
// comitiva pelo profeta: "Levanta-te, sobe para te encontrares com os
// mensageiros do rei de Samaria, e dize-lhes: PORVENTURA NÃO HÁ DEUS EM ISRAEL,
// PARA IRDES CONSULTAR A BAAL-ZEBUBE, DEUS DE ECROM?". E a sentença, curta como
// um selo: "Da cama, a que subiste, não descerás, mas sem falta morrerás".
// Os mensageiros voltam cedo demais, e o rei percebe pela pressa que alguma
// coisa aconteceu na estrada. Pergunta a coisa certa — "qual era a APARÊNCIA do
// homem?" — e a resposta é um retrato de duas linhas que dispensa nome: "era um
// homem peludo, e com os lombos cingidos de um cinto de couro". O rei reconhece
// na hora: "É ELIAS, O TISBITA". E em vez de se arrepender, manda tropa. O
// primeiro CAPITÃO DE CINQUENTA sobe ao cume onde o profeta está assentado e dá
// ordem a Deus pela boca do rei: "Homem de Deus, o rei diz: Desce". A resposta
// devolve a condição que ele mesmo usou: "SE EU, POIS, SOU HOMEM DE DEUS, DESÇA
// FOGO DO CÉU" — e desce, e consome cinquenta e um homens. O segundo capitão
// repete a cena com mais pressa ("desce depressa") e tem o mesmo fim. O
// terceiro é a única coisa nova do capítulo: sobe, e não ordena — PÕE-SE DE
// JOELHOS diante de Elias e pede pela vida dos seus: "seja, peço-te, preciosa
// aos teus olhos a minha vida, e a vida destes cinqüenta teus servos". O anjo
// então libera o profeta: "DESCE COM ESTE, NÃO TEMAS". Elias desce, atravessa o
// palácio e diz na cara do rei doente a mesma frase que mandara pela estrada.
// Acazias morre conforme a palavra; Jorão reina em seu lugar, "porquanto não
// tinha filho"; e o resto dos seus atos vira uma linha no livro das crônicas.
//
// 2Rs 2 — A SUBIDA. O narrador conta o fim antes de começar: "quando o SENHOR
// estava para elevar a Elias num redemoinho ao céu". Daí em diante tudo é
// caminhada, e a caminhada é uma despedida em três estações. De GILGAL a BETEL,
// de Betel a JERICÓ, de Jericó ao JORDÃO — três vezes Elias diz "FICA-TE AQUI"
// e três vezes Eliseu responde com o mesmo juramento inteiro: "VIVE O SENHOR, E
// VIVE A TUA ALMA, QUE NÃO TE DEIXAREI". E em cada cidade os FILHOS DOS
// PROFETAS saem ao encontro do discípulo com a mesma pergunta cruel — "sabes
// que o SENHOR hoje tomará o teu senhor por sobre a tua cabeça?" — e recebem a
// mesma resposta seca: "também eu bem o sei; CALAI-VOS". Cinquenta deles param
// de longe, defronte, para ver. No Jordão, Elias toma A SUA CAPA, dobra-a, fere
// as águas, "AS QUAIS SE DIVIDIRAM PARA OS DOIS LADOS; E PASSARAM AMBOS EM
// SECO" — o rio de Josué se abre outra vez, agora para dois homens só. Do outro
// lado vem a oferta e o pedido: "pede-me o que queres que te faça, antes que
// seja tomado de ti" — "PEÇO-TE QUE HAJA PORÇÃO DOBRADA DE TEU ESPÍRITO SOBRE
// MIM", que é a porção do primogênito, não o dobro do poder. "Coisa difícil
// pediste; SE ME VIRES quando for tomado de ti, assim se te fará". E então, no
// meio de uma conversa — "indo eles andando e falando" —, "eis que UM CARRO DE
// FOGO, COM CAVALOS DE FOGO, OS SEPAROU UM DO OUTRO; E ELIAS SUBIU AO CÉU NUM
// REDEMOINHO". Eliseu vê, e o grito que dá não é de medo: "MEU PAI, MEU PAI,
// CARROS DE ISRAEL, E SEUS CAVALEIROS!" — a defesa de Israel nunca esteve na
// cavalaria de Samaria, esteve neste velho. E nunca mais o viu. Rasga as
// próprias vestes em duas partes, levanta A CAPA QUE CAÍRA, volta à margem e
// faz a única pergunta que resta: "ONDE ESTÁ O SENHOR DEUS DE ELIAS?". As águas
// se dividem de um ao outro lado, e ele passa sozinho. Os filhos dos profetas
// veem de longe e entendem: "o espírito de Elias repousa sobre Eliseu" — e
// mesmo assim insistem em mandar cinquenta homens valentes procurar o corpo por
// três dias, em vão. Depois o primeiro milagre do sucessor não é fogo nem
// julgamento: é água. Os homens de Jericó reclamam que a cidade é boa mas "AS
// ÁGUAS SÃO MÁS, E A TERRA É ESTÉRIL"; ele pede UM PRATO NOVO COM SAL, sai ao
// manancial, lança o sal dentro e cura a fonte "até ao dia de hoje". E o fecho
// é duro de propósito: subindo a Betel, os meninos da cidade zombam do profeta
// careca — "sobe, calvo; sobe, calvo!" —, ele os amaldiçoa no nome do SENHOR, e
// duas ursas saem do bosque. Quem zomba do profeta que ficou não está brincando
// com um homem.
//
// A VOZ DE DEUS — nestes dois capítulos Deus não usa uma única vez a voz do céu
// sem mediador, e por isso NÃO HÁ NENHUM `by:"deus"` aqui. Em 1:3 e 1:15 o
// texto é explícito — "o ANJO DO SENHOR disse a Elias" —, então o balão sai do
// ANJO (`by:"anjo"`, figura luminosa em cena, glow no auge), nunca do alto sem
// figura. Em 1:4, 1:6 e 1:16 quem carrega o "assim diz o Senhor" é a boca de
// ELIAS (`by:"patriarca"`, id `elias`), e no capítulo 2 é ELISEU quem fala por
// Deus. As duas ações mais divinas dos dois capítulos são, as duas, MUDAS: o
// FOGO que desce sobre os capitães (1:10 e 1:12) e o CARRO DE FOGO que separa
// os dois amigos (2:11) não têm balão nenhum — ali há só `campfire` com `fire`
// no máximo, glória no auge e homens no chão, porque quando Deus responde por
// fogo Ele não argumenta. O redemoinho de 2:11 leva `storm` quase em 1 e o
// `chariot` e o `horse` de verdade: é a imagem central do livro e não se conta
// com prop parecido.
// ============================================================================

