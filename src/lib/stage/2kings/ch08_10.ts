// 2 REIS 8–10 — CENA VIVA. A MULHER que chega para clamar pela sua casa no
// exato instante em que contavam ao rei que o filho dela tinha voltado dos
// mortos; o COBERTOR MOLHADO estendido sobre o rosto de um rei doente; o VASO
// DE AZEITE derramado às escondidas numa câmara interior; e um homem que
// atravessa três capítulos ANDANDO FURIOSAMENTE.
//
// 2Rs 8 — A SUNAMITA E HAZAEL. Eliseu avisa a mulher de Suném — aquela cujo
// filho ele ressuscitara — que o SENHOR CHAMOU A FOME por sete anos: levanta-te
// e peregrina onde puderes peregrinar. Ela obedece, some sete anos na TERRA DOS
// FILISTEUS e volta para achar casa e terras nas mãos de outros; sai a clamar
// ao rei. E a Providência arma a cena: no momento em que ela entra, GEAZI está
// contando ao rei "todas as grandes obras que Eliseu tem feito" e chegou
// justamente na de ressuscitar um morto — "ó rei meu senhor, esta é a mulher, e
// este o seu filho a quem Eliseu ressuscitou". O rei manda restituir tudo, e
// mais AS RENDAS DAS TERRAS desde o dia em que ela partiu. Depois o capítulo
// vira para DAMASCO: Ben-Hadade doente manda Hazael com um presente de TUDO O
// QUE DE BOM HAVIA EM DAMASCO, QUARENTA CAMELOS CARREGADOS, para perguntar se
// sarará. A resposta de Eliseu vem em duas metades que não se contradizem —
// "vai, e dize-lhe: certamente viverás" (da doença ele não morreria) "porém, o
// Senhor me tem mostrado que certamente morrerá" (porque o mataria outra mão).
// Então o profeta faz a coisa mais terrível do capítulo: AFIRMA A VISTA e FITA
// OS OLHOS NELE ATÉ SE ENVERGONHAR — e CHORA. Chora porque já vê as fortalezas
// em fogo, os jovens à espada, os meninos despedaçados e as grávidas fendidas.
// Hazael responde com a modéstia dos que ainda não fizeram: "que é teu servo,
// que não é mais do que um cão, para fazer tão grande coisa?" — e recebe a
// sentença: "tu hás de ser rei da Síria". No outro dia, o cobertor, a água e o
// rosto do rei. Em Judá, o mesmo veneno por casamento: JEORÃO, filho de
// Jeosafá, anda no caminho dos reis de Israel PORQUE TINHA POR MULHER A FILHA
// DE ACABE; Edom se rebela e põe rei sobre si, Libna também se rebela — e só
// não cai tudo porque o SENHOR prometera a Davi UMA LÂMPADA para sempre. Depois
// ACAZIAS, filho dele e neto de Onri pelo lado da mãe, ATALIA: um ano de
// reinado, e o bastante para estar em Jizreel no dia errado.
//
// 2Rs 9 — A UNÇÃO DE JEÚ E A MATANÇA. Eliseu não vai: manda UM DOS FILHOS DOS
// PROFETAS com o vaso de azeite e instruções de assalto — cinge os lombos, vai
// a Ramote de Gileade, tira Jeú DO MEIO DE SEUS IRMÃOS, leva-o à CÂMARA
// INTERIOR, derrama o azeite, e ABRE A PORTA, FOGE, E NÃO TE DETENHAS. A
// profecia é a fatura de 1 Reis 21 chegando: ferirás a casa de Acabe para que
// eu VINGUE O SANGUE DOS MEUS SERVOS, OS PROFETAS, e os cães comerão a Jezabel
// no pedaço de campo de Jizreel. Os capitães, lá fora, riem: "por que veio a ti
// este louco?" — e quando ouvem o que o louco disse, tomam CADA UM A SUA ROUPA
// e a põem debaixo dele NO MAIS ALTO DEGRAU, tocam a buzina e gritam: JEÚ
// REINA. Daí em diante o capítulo é uma cavalgada. O ATALAIA DA TORRE DE
// JIZREEL vê uma tropa; mandam um cavaleiro, que não volta; mandam outro, que
// não volta; e então vem a frase que identifica um homem a quilômetros de
// distância pelo jeito de conduzir: "O ANDAR PARECE COMO O ANDAR DE JEÚ, FILHO
// DE NINSI, PORQUE ANDA FURIOSAMENTE". Jorão manda aparelhar o carro e sai ao
// encontro — e o texto põe os dois exatamente NO PEDAÇO DE CAMPO DE NABOTE, O
// JIZREELITA, a vinha do capítulo 21 de 1 Reis. "Há paz, Jeú?" "Que paz,
// enquanto as prostituições da tua mãe Jezabel e as suas feitiçarias são
// tantas?" A flecha sai pelo coração, e Bidcar lança o corpo no campo do homem
// apedrejado. Acazias foge pelo caminho da casa do jardim, é ferido À SUBIDA DE
// GUR e morre em Megido. E, em Jizreel, JEZABEL faz a última coisa que uma
// rainha pode fazer: PINTA-SE EM VOLTA DOS OLHOS, ENFEITA A CABEÇA e OLHA PELA
// JANELA, e recebe o assassino com o nome do outro regicida na boca — "teve paz
// Zinri, que matou a seu senhor?". "Quem é comigo? quem?" — e bastam dois ou
// três eunucos. O sangue salpica A PAREDE E OS CAVALOS. Quando vão sepultá-la,
// da filha de rei não acham senão A CAVEIRA, OS PÉS E AS PALMAS DAS MÃOS.
//
// 2Rs 10 — A CASA DE ACABE VARRIDA E A ARMADILHA DE BAAL. Acabe tinha SETENTA
// FILHOS em Samaria. Jeú escreve cartas com um desafio que é uma armadilha:
// escolhei o melhor e mais reto, ponde-o sobre o trono de seu pai, e PELEJAI.
// Eles temem muitíssimo — "dois reis não puderam resistir a ele" — e se
// rendem por escrito. A segunda carta pede as cabeças, e as cabeças chegam em
// cestos; ele manda pô-las em DOIS MONTÕES À ENTRADA DA PORTA, ATÉ AMANHÃ. Pela
// manhã, diante do povo, faz a confissão mais cínica e mais verdadeira do
// livro: "vós sois justos; eis que EU conspirei contra o meu senhor, e o matei;
// MAS QUEM FERIU A TODOS ESTES?" — e conclui que da palavra do SENHOR contra a
// casa de Acabe nada cairá em terra. No caminho, em BETE-EQUEDE DOS PASTORES,
// mata quarenta e dois irmãos de Acazias junto ao poço da casa da tosquia. E
// encontra JONADABE, FILHO DE RECABE: "é reto o teu coração para comigo, como o
// meu o é para contigo? Dá-me a mão" — e o faz subir ao carro com a frase que
// resume o homem: "VAI COMIGO, E VERÁS O MEU ZELO PARA COM O SENHOR". Então
// arma a maior emboscada do Antigo Testamento: "pouco serviu Acabe a Baal; Jeú,
// porém, muito o servirá". Apregoa ASSEMBLÉIA SOLENE, convoca todos os profetas,
// servos e sacerdotes de Baal sob pena de morte, manda o guarda-roupa TIRAR AS
// VESTIMENTAS para cada um deles (para que nenhum escape confundido com o povo)
// e revista a casa para que não haja ali nenhum servo do SENHOR. Oitenta homens
// esperam do lado de fora. Acabado o holocausto: "entrai, feri-os, não escape
// nenhum". Queimam as estátuas, derrubam a casa e fazem dela LATRINAS ATÉ AO
// DIA DE HOJE. E aí o texto vira a página e dá a nota: Jeú destruiu Baal, mas
// NÃO SE APARTOU DOS BEZERROS DE OURO QUE ESTAVAM EM BETEL E EM DÃ, e não andou
// com todo o coração na lei do SENHOR. Recebe quatro gerações no trono — e vê
// Hazael, o do cobertor, começar a diminuir os termos de Israel desde o Jordão.
//
// A VOZ DE DEUS — nestes três capítulos Deus NÃO É DESENHADO e NÃO RECEBE
// BALÃO: em 2 Reis a palavra anda sempre por boca de gente, e o texto faz
// questão de dizer de quem é a boca. Quem fala é ELISEU (`patriarca`, id
// `eliseu`), com `glow` alto, nas duas sentenças de Damasco (8:10,13); é O
// JOVEM FILHO DOS PROFETAS (`homem`, id `jovem-profeta-da-uncao`) em 9:6-10,
// que diz "assim diz o Senhor Deus de Israel" com o azeite escorrendo da mão —
// o balão sai DELE, não do céu; e é JEÚ (`rei`, id `jeu-rei`) em 9:26 e 10:10,
// quando CITA a sentença que o SENHOR pusera sobre Acabe e a palavra falada
// pelo ministério de Elias: ali a palavra é de Deus e a boca é do rei, e é
// assim que o texto conta. Em 10:30 o SENHOR fala a Jeú sem mediador nenhum na
// frase — e o beat fica em NARRAÇÃO, com a glória subindo sobre o trono e
// nenhuma figura desenhada para Deus: o capítulo inteiro é sobre um homem que
// ouviu bem e obedeceu pela metade, e a promessa das quatro gerações lhe chega
// como um veredicto lido em voz alta, não como uma conversa.
//
// (A ARC grafa "vaso de azeite" onde a memória diz botija, "buzina" onde a
// memória diz trombeta, "assembléia solene" com acento, "Bete-Equede dos
// pastores", "Zinri", "Ninsi", "undécimo" e "latrinas" — os `q` seguem a ARC.
// E cuidado com os dois nomes quase iguais: JORÃO é o rei de ISRAEL, filho de
// Acabe; JEORÃO é o rei de JUDÁ, filho de Jeosafá. O texto usa os dois na mesma
// página.)
// ============================================================================

import type { StageScript, StageBeat, CastPlacement, StagePropSpec } from "@/lib/rpgStage";

