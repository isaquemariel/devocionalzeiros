// ESTER 1–5 — CENA VIVA. Cinco capítulos passados inteiramente dentro de um
// império pagão, na fortaleza de Susã, onde o nome de Deus NÃO É DITO UMA ÚNICA
// VEZ. Não há profeta, não há altar, não há templo, não há oração em voz alta.
// O que vira a história são coincidências que ninguém atribui a ninguém: uma
// rainha que diz não numa festa de bêbados, uma órfã judia que ninguém sabe que
// é judia, um rolo de crônicas onde alguém anotou um nome, e uma forca de
// cinquenta côvados levantada por quem ia morrer nela.
//
// Et 1 — ASSUERO, o rei que reina "desde a India até a Etiópia, sobre cento e
// vinte e sete províncias", faz do seu império um mostruário: cento e oitenta
// dias mostrando "as riquezas da glória do seu reino", e depois SETE DIAS de
// banquete a todo o povo de Susã no pátio do jardim do palácio real. O texto
// para tudo para descrever a decoração — as tapeçarias de pano branco, verde e
// azul celeste, penduradas em cordões de linho fino e púrpura, em argolas de
// prata e COLUNAS DE MÁRMORE; os LEITOS DE OURO E DE PRATA sobre um pavimento
// de mármore vermelho, azul, branco e preto; os copos de ouro, todos
// diferentes uns dos outros; e o beber "por lei, SEM CONSTRANGIMENTO". A rainha
// VASTI dá o seu banquete às mulheres na casa real. No sétimo dia, com o
// coração alegre do vinho, o rei manda os sete camareiros — Meumã, Bizta,
// Harbona, Bigtá, Abagta, Zetar e Carcas — buscarem Vasti COM A COROA REAL,
// "para mostrar aos povos e aos príncipes a sua beleza". E o império inteiro
// trava numa palavra de duas letras: ela RECUSA. O rei chama os sábios que
// entendiam dos tempos, os sete príncipes dos persas e dos medos, e MEMUCÃ diz
// a frase que transforma um desaforo doméstico em questão de estado: "Não
// somente contra o rei pecou a rainha Vasti, porém também contra todos os
// príncipes". Sai um edito irrevogável, e partem CARTAS a todas as províncias,
// "a cada província segundo a sua escrita, e a cada povo segundo a sua língua".
// O trono do mundo conhecido gastou o seu poder para mandar que cada homem
// fosse senhor em sua casa.
//
// Et 2 — apaziguado o furor, o rei se LEMBRA de Vasti, e os servos inventam o
// remédio: que se ajuntem as moças na casa das mulheres, aos cuidados de HEGAI.
// Aí o texto abre a porta lateral por onde entra o livro inteiro: "Havia então
// um homem judeu na fortaleza de Susã, cujo nome era MARDOQUEU, filho de Jair,
// filho de Simei, filho de Quis, homem benjamita" — um dos transportados com
// Jeconias. Ele criara HADASSA, isto é, ESTER, filha do seu tio, órfã de pai e
// mãe, e a tomara por filha. Ester entra na casa das mulheres e "alcançou graça
// perante ele"; passa os doze meses da purificação — seis com óleo de mirra e
// seis com especiarias —, e, chegada a sua vez, "coisa nenhuma pediu, senão o
// que disse Hegai". Não declara o seu povo, porque Mardoqueu lhe ordenara; e
// ele passeia todos os dias diante do pátio da casa das mulheres. O rei a ama
// mais do que a todas, PÕE-LHE A COROA REAL NA CABEÇA e faz o banquete de
// Ester. E então, quase de passagem, dois camareiros dos guardas da porta,
// BIGTÃ E TERES, conspiram contra o rei; Mardoqueu descobre, avisa por Ester, e
// os dois são pendurados — "E FOI ESCRITO NAS CRÔNICAS PERANTE O REI". Ninguém
// agradece a Mardoqueu. Fica só a tinta no rolo, esperando quatro capítulos.
//
// Et 3 — HAMÃ, filho de Hamedata, o agagita, é engrandecido e tem o seu assento
// posto acima de todos os príncipes; todos os servos da porta do rei se
// inclinam e se prostram — "PORÉM MARDOQUEU NÃO SE INCLINAVA NEM SE
// PROSTRAVA". Hamã se enche de furor, e o furor não se contenta com um homem:
// ele procura destruir todos os judeus do reino. Lança-se PUR, isto é, A SORTE,
// perante Hamã, de dia em dia e de mês em mês, até ao duodécimo mês, o mês de
// Adar. Diante do rei ele constrói a acusação perfeita porque é quase toda
// verdade: "Existe espalhado e dividido entre os povos… um povo, cujas leis são
// diferentes das leis de todos os povos" — e oferece dez mil talentos de prata.
// O rei nem pergunta o nome do povo: TIRA O ANEL DA MÃO e o dá a Hamã, "Essa
// prata te é dada como também esse povo". Chamam-se os escrivães no dia treze
// do primeiro mês; escreve-se em nome do rei, sela-se com o anel do rei, e os
// correios saem com a ordem de destruir, matar e fazer perecer todos os judeus
// num só dia e saquear os seus bens. O capítulo fecha no contraste que é o
// quadro do livro: "E o rei e Hamã se assentaram a beber, porém a cidade de
// Susã estava confusa."
//
// Et 4 — Mardoqueu rasga as vestes, veste-se de SACO E CINZA e sai pelo meio da
// cidade clamando "com grande e amargo clamor"; chega até diante da porta do
// rei e para ali, porque ninguém vestido de saco podia entrar por ela. Em cada
// província há grande luto, jejum, choro e lamentação, e muitos deitados em
// saco e em cinza. Ester manda-lhe roupas, e ele não as aceita — o luto não é
// para ser vestido por cima. Então HATÁ, o camareiro, vai e vem entre os dois
// pela praça da cidade, levando a soma exata do dinheiro e A CÓPIA DA LEI
// ESCRITA. Ester responde com a lei que a prende: quem entrar no pátio interior
// sem ser chamado morre, salvo se o rei estender o CETRO DE OURO — "e eu nestes
// trinta dias não tenho sido chamada". E Mardoqueu manda de volta as duas
// frases que sustentam o livro: "quem sabe se para tal tempo como este chegaste
// a este reino?" e, dela, depois de três dias de jejum sem comer nem beber, de
// noite e de dia: "E ASSIM IREI TER COM O REI, AINDA QUE NÃO SEJA SEGUNDO A
// LEI; E SE PERECER, PERECI."
//
// Et 5 — ao terceiro dia Ester se veste com trajes reais e se põe no pátio
// interior, defronte do aposento do rei. O rei estende o cetro de ouro; ela
// chega e toca a ponta. "Até metade do reino se te dará" — e ela pede um
// jantar. No banquete do vinho, pedem-lhe outra vez, e ela pede outro jantar,
// para amanhã. Hamã sai dali "alegre e de bom ânimo", vê Mardoqueu à porta do
// rei, que não se levanta nem se move, e se enche de furor. Em casa, conta a
// ZERES, sua mulher, e aos amigos as suas riquezas, a multidão de seus filhos e
// tudo em que o rei o exaltou — e conclui: "Porém tudo isto não me satisfaz,
// enquanto eu vir o judeu Mardoqueu assentado à porta do rei." E é a mulher
// dele quem dá a ideia: uma FORCA DE CINQUENTA CÔVADOS, levantada esta noite.
//
// A VOZ DE DEUS — NÃO HÁ NENHUM `by:"deus"` neste arquivo, e é de propósito:
// Ester é o único livro em que Deus não é nomeado, e a cena tem de respeitar o
// silêncio em vez de corrigi-lo. Não há voz do céu, não há teofania, não há
// mediador profético. A `glory` deste roteiro é luz de PALÁCIO — ouro, mármore,
// lâmpadas, copos —, e por isso ela sobe nos banquetes e no esplendor persa e
// DESCE nos capítulos do decreto e do luto, onde o céu só tem nuvem e estrela.
// A providência aparece por objetos e por acaso, nunca por luz vinda de cima: o
// rolo das crônicas de 2:23 com a sua etiqueta própria, guardado para o
// capítulo 6; a mesa dos dois bebendo com a cidade parada atrás (3:15); a
// forca de cinquenta côvados que Zeres manda levantar (5:14) e que não tem prop
// no motor — é contada por uma `column` altíssima e pela pose de quem aponta
// para o alto, sem tag mentirosa pendurada nela. O único momento religioso
// explícito do trecho, o JEJUM de 4:16, é contado por noite alta, mesa vazia e
// figuras em `bow`/`kneel` — não por glória. E Ester e Vasti são sempre
// `mulherComum`, nunca `mulher`: `mulher` é figura de glória, ignora a pose e
// sai sempre dourada e em pé, e neste livro as duas rainhas precisam justamente
// de se curvar, de andar e de ficar de pé por escolha própria.
// ============================================================================

