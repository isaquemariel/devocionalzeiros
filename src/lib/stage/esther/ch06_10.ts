// ============================================================================
// ESTER 6–10 — CENA VIVA. O livro em que Deus não é nomeado uma única vez vira
// de lado numa NOITE SEM SONO, e daí em diante tudo o que estava armado contra
// os judeus cai em cima de quem armou: a forca, a carta, o anel, o dia treze
// de Adar. Não há profeta, não há altar, não há oração dita em voz alta —
// há uma coincidência atrás da outra, e é ali que este livro esconde Deus.
//
// ESTER 6 — "Naquela mesma noite fugiu o sono do rei". Um insone manda trazer
// o LIVRO DE REGISTRO DAS CRÔNICAS para o entediar, e o rolo se abre justamente
// na denúncia de Bigtã e Teres — o serviço que Mardoqueu prestou e pelo qual
// "coisa nenhuma se lhe fez". Nesse exato momento HAMÃ entra no pátio exterior
// para pedir a cabeça de Mardoqueu, e o rei pergunta primeiro: "Que se fará ao
// homem de cuja honra o rei se agrada?" Hamã, dizendo no seu coração "de quem
// se agradaria o rei mais do que de mim?", dita a sua própria humilhação: a
// VESTE REAL, o CAVALO em que o rei costuma andar, a COROA REAL NA CABEÇA DO
// CAVALO, e um dos príncipes mais nobres apregoando pela rua. E o rei fecha a
// armadilha com um nome: "faze assim para com o judeu Mardoqueu... e coisa
// nenhuma omitas de tudo quanto disseste". Hamã leva o cavalo pela rua da
// cidade, apregoando a honra do homem que queria enforcar, e volta para casa
// correndo, triste e de cabeça coberta. Zeres e os seus sábios pronunciam a
// sentença: "se Mardoqueu... é da descendência dos judeus, não prevalecerás
// contra ele". E os camareiros chegam para levá-lo depressa ao banquete.
//
// ESTER 7 — o segundo banquete do vinho. "Qual é a tua petição, rainha Ester?
// Até metade do reino." E a resposta não pede metade de nada: "dê-se-me a
// minha vida como minha petição, e o meu povo como meu desejo... fomos
// vendidos, eu e o meu povo, para nos destruírem, matarem, e aniquilarem de
// vez". O rei pergunta quem é, e o dedo aponta o convidado à mesa: "O homem, o
// opressor, e o inimigo, é este mau Hamã". O rei sai furioso para o jardim do
// palácio; Hamã fica para rogar pela vida e CAI PROSTRADO SOBRE O LEITO EM QUE
// ESTAVA ESTER — e é essa a cena que o rei encontra ao voltar. Quem dá o
// desfecho é um eunuco: HARBONA lembra que a forca de cinqüenta côvados feita
// para Mardoqueu está de pé junto à casa de Hamã. "Enforcai-o nela." E o furor
// do rei se aplacou.
//
// ESTER 8 — a casa de Hamã passa a Ester, e o ANEL tirado de Hamã passa a
// Mardoqueu. Ester se lança aos pés do rei e chora, e o cetro de ouro se
// estende outra vez: "como poderei ver o mal que sobrevirá ao meu povo? E como
// poderei ver a destruição da minha parentela?" A resposta é a lei persa
// batendo na porta: "o documento que se escreve em nome do rei, e que se sela
// com o anel do rei, não se pode revogar" — a primeira carta não volta atrás, e
// por isso se escreve a SEGUNDA, que dá aos judeus licença de se ajuntarem e
// defenderem a vida no mesmo dia treze de Adar. Os correios saem sobre GINETES
// VELOZES; e Mardoqueu sai da presença do rei com veste real azul-celeste e
// branca, uma GRANDE COROA DE OURO e capa de linho fino e púrpura — "e a
// cidade de Susã exultou e se alegrou". O capítulo fecha com o mundo virado:
// "muitos, dos povos da terra, se fizeram judeus, porque o temor dos judeus
// tinha caído sobre eles".
//
// ESTER 9 — o dia treze do duodécimo mês, o mês de Adar: o dia marcado para
// acabar com eles, "sucedeu o contrário". Os judeus se ajuntam nas suas
// cidades, ninguém lhes pode resistir, e até os sátrapas os auxiliam, porque o
// temor de Mardoqueu tinha caído sobre eles. Quinhentos homens na fortaleza de
// Susã, e os DEZ FILHOS DE HAMÃ nomeados um a um — Parsandata, Dalfom, Aspata,
// Porata, Adalia, Aridata, Farmasta, Arisai, Aridai e Vaisata. E TRÊS VEZES o
// texto repete a mesma frase, que é o pudor do livro inteiro: "porém ao despojo
// não estenderam a sua mão". Não era saque, era sobrevivência. Vem o segundo
// dia em Susã, os setenta e cinco mil nas províncias, e o descanso: o catorze e
// o quinze viram "dia de banquetes e de alegria, e de mandarem presentes uns
// aos outros, e dádivas aos pobres". Mardoqueu e a rainha Ester escrevem as
// cartas que estabelecem o PURIM — o nome vem do PUR, a sorte que Hamã lançou
// para escolher o dia da matança e que acabou marcando o dia da festa. "E
// escreveu-se no livro."
//
// ESTER 10 — três versículos de epílogo administrativo: o tributo imposto
// sobre a terra e sobre AS ILHAS DO MAR, os atos do poder do rei escritos no
// livro das crônicas dos reis da Média e da Pérsia, e o judeu Mardoqueu, "o
// segundo depois do rei Assuero", grande entre os judeus e estimado pela
// multidão de seus irmãos, "procurando o bem do seu povo, e proclamando a
// prosperidade de toda a sua descendência".
//
// A VOZ DE DEUS — em Ester, Deus não é nomeado nem uma vez, não há profeta, não
// há altar e não há oração dita em voz alta. Por isso NÃO EXISTE UM ÚNICO
// `by:"deus"` neste arquivo, e nenhuma cena carrega glória de teofania: o
// dourado que aparece aqui é luz de palácio — ouro, mármore, lâmpadas, coroa —,
// nunca presença divina. O eixo do livro é 6:1-3, e essa cena foi montada de
// propósito SEM NENHUM SINAL DO CÉU: a câmara de noite com as estrelas do lado
// de fora, o rei desperto, o rolo aberto e o escrivão lendo em voz alta o feito
// que ninguém pagou. Não há brilho nenhum sobre o rolo — só a coincidência de
// ele se abrir naquela página naquela noite, com Hamã já a caminho do pátio. A
// providência deste livro é escondida, e a cena tem de ficar escondida com ela.
// Todos os balões saem de bocas humanas: o rei Assuero, Ester, Hamã, os servos
// que ministravam diante do rei, Zeres e o eunuco Harbona.
// ============================================================================

