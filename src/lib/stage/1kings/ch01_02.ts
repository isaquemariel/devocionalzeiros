// ============================================================================
// 1 REIS 1–2 — CENA VIVA. O rei coberto de roupas que não se aquece, o filho que
// manda preparar CARROS para si mesmo, a MULA do pai descendo a Giom, e o
// trono que se confirma com três sepulturas ao pé dele.
//
// 1Rs 1 — DAVI está velho e entrado em dias: "cobriam-no de roupas, porém não
// se aquecia". Os servos buscam por TODOS OS TERMOS DE ISRAEL uma moça virgem
// que durma no seio do rei e o aqueça, e acham ABISAGUE, a sunamita —
// "sobremaneira formosa" —, que tem cuidado dele e o serve, "porém o rei não a
// conheceu". Enquanto o rei esfria, ADONIAS, filho de Hagite, se levanta
// dizendo "EU REINAREI", e prepara para si CARROS, e CAVALEIROS, e cinquenta
// homens que corram adiante dele. O texto então solta a linha mais devastadora
// do capítulo, e é sobre o pai, não sobre o filho: "e nunca seu pai o tinha
// contrariado, dizendo: Por que fizeste assim?". Ele tem entendimento com
// JOABE, filho de Zeruia, e com ABIATAR, o sacerdote; mas ZADOQUE, BENAIA,
// NATÃ, Simei, Rei e os poderosos de Davi não estão com ele. Adonias mata
// ovelhas, vacas e animais cevados JUNTO À PEDRA DE ZOELETE, perto da fonte de
// Rogel, e convida todos os seus irmãos e os homens de Judá — "porém a Natã, o
// profeta, e a Benaia, e aos poderosos, e a Salomão, seu irmão, não convidou".
// A convocação de fora fica sendo a lista de quem vai derrubá-lo. Natã monta o
// plano com BATE-SEBA: ela entra primeiro e lembra o juramento, ele entra
// depois e confirma as palavras dela. Na câmara do rei muito velho, com
// Abisague servindo ao lado, a mãe de Salomão se prostra e diz o que ninguém
// disse ao rei: "e agora eis que Adonias reina; e tu, ó rei meu senhor, não o
// sabes". Natã entra atrás dela e fecha o cerco. Então o velho jura: "VIVE O
// SENHOR, O QUAL REMIU A MINHA ALMA DE TODA A ANGÚSTIA" — e dá a ordem inteira
// numa respiração: ponham Salomão na MULA QUE É MINHA, desçam-no a GIOM, que
// Zadoque e Natã o unjam ali, TOQUEM A TROMBETA e digam "viva o rei Salomão!".
// Benaia responde "amém". Descem os quereteus e os peleteus, Zadoque toma o
// CHIFRE DE AZEITE DO TABERNÁCULO, unge o moço, toca a trombeta, e todo o povo
// grita — o povo toca GAITAS e se alegra com grande alegria, "de maneira que
// com o seu clamor A TERRA RETINIU". A festa de Adonias, a poucos passos dali,
// ouve o estrondo no fim da refeição. JÔNATAS, filho de Abiatar, entra com a
// notícia inteira, e ela termina com a frase que apaga o banquete: "e também
// Salomão está assentado no trono do reino". Os convidados estremecem, se
// levantam e "cada um se foi ao seu caminho". Adonias, sozinho, corre e se
// APEGA ÀS PONTAS DO ALTAR — e Salomão o poupa com uma condição de fio de
// navalha: "se for homem de bem, nem um de seus cabelos cairá em terra; se,
// porém, se achar nele maldade, morrerá". "Vai para tua casa."
//
// 1Rs 2 — AS ÚLTIMAS PALAVRAS DE DAVI. "Eu vou pelo caminho de toda a terra;
// esforça-te, pois, e sê homem." Primeiro a ordenança: andar nos caminhos do
// SENHOR, guardar os estatutos, os mandamentos, os juízos e os testemunhos
// "como está escrito na lei de Moisés". Depois os três encargos, e são contas
// velhas: JOABE, que matou Abner e Amasa e "em paz derramou o sangue de
// guerra, e pôs o sangue de guerra no cinto que tinha nos lombos, e nos
// sapatos que trazia nos pés" — "não permitas que suas cãs desçam à sepultura
// em paz"; os FILHOS DE BARZILAI, o gileadita, que estejam "entre os que comem
// à tua mesa", porque se chegaram a ele na fuga de Absalão; e SIMEI, filho de
// Gera, o de Baurim, cuja maldição atroz Davi jurou não punir com a espada —
// "mas agora não o tenhas por inculpável". Então Davi dorme com seus pais e é
// sepultado na CIDADE DE DAVI: quarenta anos de reinado, sete em Hebrom e
// trinta e três em Jerusalém. Salomão se assenta no trono, e o reino começa a
// se fortificar sobre quatro decisões. ADONIAS vem a Bate-Seba pedir ABISAGUE
// por mulher, e a mãe leva o pedido; o rei se levanta, se inclina diante dela e
// manda pôr uma cadeira à sua direita — e então explode: "pede também para ele
// o reino"; Benaia arremete contra ele. ABIATAR é despachado para ANATOTE, para
// os seus campos, poupado porque levou a arca diante de Davi — e assim se
// cumpre a palavra do SENHOR sobre a casa de Eli em Siló. JOABE ouve a notícia,
// foge para o tabernáculo do SENHOR e se apega às pontas do altar; mandado
// sair, responde "NÃO, PORÉM AQUI MORREREI" — e Benaia o fere ali, e ele é
// sepultado em sua casa, no deserto. SIMEI é posto sob juramento em Jerusalém,
// proibido de passar o RIBEIRO DE CEDROM; três anos depois dois servos seus
// fogem para Gate, ele albarda o jumento e vai buscá-los — e volta para morrer
// por isso. "Assim foi confirmado o reino na mão de Salomão."
//
// A VOZ DE DEUS — em 1Rs 1–2 o SENHOR não fala uma única vez em balão, e isso é
// deliberado: não há oráculo, não há sonho, não há profeta trazendo "assim diz
// o Senhor". Natã, que em 2Sm 12 entrou na sala do trono com a palavra de Deus
// na boca, aqui entra com POLÍTICA na boca — o conselho dele a Bate-Seba é
// estratégia humana, e por isso é `by:"homem"`, sem glória e sem glow de
// mensageiro. O nome do SENHOR aparece três vezes como JURAMENTO de homens
// ("vive o Senhor, o qual remiu a minha alma de toda a angústia", 1:29; "assim
// Deus me faça, e outro tanto", 2:23; "não te conjurei eu pelo Senhor", 2:42):
// são vozes de Davi e de Salomão, `by:"rei"`, e a glória sobe no ambiente sem
// que ninguém fale do alto. E o único juízo divino do bloco — "para cumprir a
// palavra do Senhor, que tinha falado sobre a casa de Eli em Siló" (2:27) — é
// NARRAÇÃO PURA: beat sem `by`, com Abiatar sozinho andando para os campos de
// Anatote e a luz caindo em cima dele. Deus não é desenhado e não é dublado:
// Ele é a conta que fecha, cem anos depois, sem uma palavra.
// ============================================================================

