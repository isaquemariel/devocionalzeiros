// 1 REIS 21–22 — CENA VIVA. A VINHA que um rei quis para horta, a CAMA em que
// ele virou o rosto para a parede, as CARTAS seladas com o sinete do rei, o
// homem apedrejado fora da cidade — e, no fim do livro, a FLECHA ATIRADA A ESMO
// que achou o rei disfarçado por entre as fivelas da couraça.
//
// 1Rs 21 — A VINHA DE NABOTE. NABOTE, o jizreelita, tinha uma vinha em Jizreel
// JUNTO AO PALÁCIO de Acabe. O rei a quer para horta e oferece o que parece
// generoso: outra vinha melhor, ou o seu valor em dinheiro. A recusa de Nabote
// não é teimosia de camponês, é LEI: "guarde-me o Senhor de que eu te dê a
// herança de meus pais" — em Israel a terra não se vendia perpetuamente (Lv
// 25:23; Nm 36:7), a leira era a parte que Deus dera ao clã na repartição de
// Josué. Acabe volta para casa DESGOSTOSO E INDIGNADO, deita-se na cama, VOLTA
// O ROSTO e NÃO COME PÃO — um rei fazendo birra de criança. Entra JEZABEL, e
// com ela entra outra teologia: "governas tu agora no reino de Israel?
// Levanta-te, come pão, e alegre-se o teu coração; eu te darei a vinha de
// Nabote". E arma tudo com frieza administrativa: CARTAS escritas EM NOME DE
// ACABE e SELADAS COM O SINETE DELE, mandadas aos anciãos e aos nobres da
// cidade de Nabote; um JEJUM apregoado (o jejum que se apregoava quando havia
// culpa oculta na terra), Nabote posto DIANTE DO POVO — no lugar de honra que
// se dá a quem se vai destruir —, e DOIS FILHOS DE BELIAL postos defronte dele
// para dizer as duas palavras que matam: "blasfemaste contra Deus e contra o
// rei". Levam-no para fora da cidade e o apedrejam. O recado de volta é seco
// como um recibo: "Nabote foi apedrejado, e morreu". E Jezabel a Acabe:
// "levanta-te, e possui a vinha". Enquanto ele desce para tomar posse, VEM A
// PALAVRA DO SENHOR A ELIAS — e o profeta o encontra no meio das videiras que
// ainda são de outro homem: "porventura não mataste e tomaste a herança?"; e a
// sentença, medida no mesmo lugar do crime: "no lugar em que os cães lamberam
// o sangue de Nabote lamberão também o teu próprio sangue"; e sobre Jezabel:
// "os cães comerão a Jezabel junto ao antemuro de Jizreel". O texto então faz o
// balanço — ninguém fora como Acabe, que SE VENDERA para fazer o mal, porque
// JEZABEL, SUA MULHER, O INCITAVA — e termina com a coisa mais inesperada do
// capítulo: ouvindo a sentença, Acabe RASGA AS VESTES, cobre a carne de SACO,
// jejua, JAZ EM SACO e ANDA MANSAMENTE. E o SENHOR pergunta a Elias: "não viste
// que Acabe se humilha perante mim?" — e adia o mal para os dias do filho.
// Misericórdia até para ele: é a única coisa mais assustadora que o juízo.
//
// 1Rs 22 — MICAÍAS E A MORTE DE ACABE. Três anos quietos, sem guerra entre a
// Síria e Israel. JEOSAFÁ, rei de Judá, desce para avistar-se com Acabe, que se
// lembra de RAMOTE DE GILEADE: é nossa, e está na mão do rei da Síria. Jeosafá
// entra inteiro ("serei como tu, e o meu povo como o teu povo, e os meus
// cavalos como os teus cavalos"), mas faz o pedido que salva o capítulo:
// "consulta hoje a palavra do Senhor". Ajuntam-se QUATROCENTOS profetas e todos
// dizem a mesma coisa em coro: "sobe, porque o Senhor a entregará na mão do
// rei". E Jeosafá, que ouviu quatrocentas bocas e não ouviu o SENHOR: "não há
// aqui ainda algum profeta do Senhor, ao qual possamos consultar?". A resposta
// de Acabe é uma confissão involuntária: há um, "porém eu o odeio, porque nunca
// profetiza de mim o que é bom, mas só o mal" — MICAÍAS, FILHO DE INLÁ. Os dois
// reis assentados CADA UM NO SEU TRONO, vestidos de trajes reais, NA PRAÇA À
// ENTRADA DA PORTA DE SAMARIA, com todos os profetas profetizando diante deles;
// e ZEDEQUIAS, FILHO DE QUENAANÁ, com CHIFRES DE FERRO na mão: "com estes
// ferirás aos sírios, até de todo os consumir". O mensageiro tenta alinhar
// Micaías ao coro pelo caminho; ele responde: "vive o Senhor que o que o Senhor
// me disser isso falarei". Diante do rei repete o coro com ironia tão evidente
// que Acabe o conjura a falar a verdade — e então vêm as duas VISÕES: "vi a
// todo o Israel disperso pelos montes, COMO OVELHAS QUE NÃO TEM PASTOR"; e "vi
// ao Senhor assentado sobre o seu trono, e todo o exército do céu estava junto
// a ele, à sua mão direita e à sua esquerda", e a pergunta "quem induzirá
// Acabe?", e o espírito que se apresenta: "eu sairei, e serei um espírito de
// mentira na boca de todos os seus profetas". Zedequias o fere no queixo;
// Micaías vai para a casa do cárcere com PÃO DE ANGÚSTIA E ÁGUA DE AMARGURA até
// que o rei volte em paz — e a réplica fecha a boca da praça: "se tu voltares
// em paz, o Senhor não tem falado por mim". Na batalha, Acabe SE DISFARÇA e
// manda Jeosafá vestir as suas próprias roupas; o rei da Síria manda pelejar só
// contra o rei de Israel; os capitães dos carros cercam Jeosafá por engano e
// desistem — e então UM HOMEM ARMA O ARCO E ATIRA A ESMO, e a flecha sem
// pontaria acha o rei disfarçado POR ENTRE AS FIVELAS E AS COURAÇAS. Ele manda
// o carreteiro tirá-lo do exército, mas fica SUSTENTADO NO CARRO defronte dos
// sírios até à tarde, e morre; o sangue corre para o fundo do carro. Lavam o
// carro NO TANQUE DE SAMARIA e os cães lambem o seu sangue, conforme à palavra
// que o SENHOR tinha falado. O livro fecha com dois reinados: JEOSAFÁ, que
// andou nos caminhos de Asa e fez o que era reto (embora os altos não se
// tirassem), expulsou o restante dos sodomitas e viu os seus NAVIOS DE TÁRSIS
// se quebrarem em EZIOM-GEBER; e ACAZIAS, filho de Acabe, que serviu a Baal.
//
// A VOZ DE DEUS — aqui a regra da casa se aplica em três camadas distintas.
// (1) SEM MEDIADOR: em 21:18 e 21:29 a palavra vem a Elias no ermo, sem figura
// nenhuma em cena além do profeta que ouve — é VOZ DO CÉU (`by:"deus"`), com a
// glória subindo no ambiente e nenhum corpo desenhado para Deus. (2) POR
// MEDIADOR VISÍVEL: os balões de 21:19-24 não são voz do céu, são ELIAS falando
// a Acabe no meio da vinha (`by:"patriarca"`, id `elias`) — a palavra é de Deus,
// a boca é do profeta, e é assim que o texto conta. (3) VISÃO RELATADA: no cap.
// 22 inteiro quem fala é MICAÍAS (`by:"homem"`, id `micaias`), INCLUSIVE nos
// vv.19-22, quando ele cita o SENHOR assentado no trono e o espírito de mentira
// que se apresenta. Ali o trono celestial é encenado com o prop `throne` e a
// glória no máximo, o exército do céu como `anjo` em `flyIdle` à direita e à
// esquerda, e o balão SAI DE MICAÍAS: Deus não é desenhado nem recebe balão
// dentro da visão de outro homem. Note ainda que os quatrocentos profetas de
// 22:6,12 falam "em nome do Senhor" e estão MENTINDO — por isso o coro deles
// tem `multidao` festiva e glória BAIXA, enquanto a glória só sobe quando
// Micaías abre a boca.
//
// (A ARC grafa "Jeosafá" onde a memória diz Josafá, "Quenaaná" onde a memória
// diz Quenaana, "por entre as fivelas e as couraças" onde a memória diz junturas
// e "navios de Társis" onde a memória diz naus — os `q` seguem a ARC.)
// ============================================================================

import type { StageScript, StageBeat, CastPlacement, StagePropSpec } from "@/lib/rpgStage";

const C = (role: string, dx: number, pose?: string, extra: Partial<CastPlacement> = {}): CastPlacement =>
  ({ role, dx, pose, ...extra });
const P = (kind: string, dx: number, scale = 1, fire?: number, dy?: number): StagePropSpec =>
  ({ kind, dx, scale, ...(fire != null ? { fire } : {}), ...(dy != null ? { dy } : {}) });
const b = (v: number, extra: Partial<StageBeat> = {}): StageBeat => ({ v, ...extra });
// voz do céu — SÓ onde não há mediador visível: 21:18 e 21:29, a palavra do
// SENHOR a Elias no ermo. Nunca no cap. 22 (lá quem fala é sempre Micaías).
const dv = (v: number, extra: Partial<StageBeat> = {}): StageBeat => b(v, { by: "deus", ...extra });

