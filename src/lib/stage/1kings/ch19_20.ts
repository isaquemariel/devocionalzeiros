// 1 REIS 19–20 — CENA VIVA. O ZIMBRO no deserto e o bolo cozido sobre as
// brasas, o VENTO, o TERREMOTO e o FOGO que passam sem o SENHOR dentro, a VOZ
// MANSA E DELICADA à boca da caverna de Horebe — e, do outro lado, o cerco de
// Samaria, o muro de Afeque caindo sobre vinte e sete mil e o profeta com
// CINZA SOBRE OS OLHOS à beira da estrada.
//
// 1Rs 19 — O DIA SEGUINTE AO CARMELO. Acabe conta a Jezabel tudo quanto Elias
// havia feito, "e como totalmente matara todos os profetas à espada"; e a
// rainha manda um mensageiro com o recado que quebra o homem que enfrentara
// sozinho quatrocentos e cinqüenta: "assim me façam os deuses, e outro tanto,
// se de certo amanhã a estas horas não puser a tua vida como a de um deles".
// Elias, que não fugira do fogo, foge do bilhete: desce a BERSEBA, que é de
// Judá, DEIXA ALI O SEU SERVO e entra sozinho no deserto, caminho de um dia.
// Senta-se debaixo de UM ZIMBRO e pede para si a morte — "já basta, ó Senhor;
// toma agora a minha vida, pois não sou melhor do que meus pais" — e dorme. E
// a resposta do céu à depressão do profeta não é repreensão nem sermão: é UM
// ANJO que o TOCA e diz "levanta-te, come". À sua cabeceira, um PÃO COZIDO
// SOBRE AS BRASAS e UMA BOTIJA DE ÁGUA. Ele come, bebe e torna a deitar-se —
// e o anjo VOLTA SEGUNDA VEZ, toca-o outra vez e diz a frase mais humana do
// livro: "levanta-te e come, porque te será muito longo o caminho". Com a
// força daquela comida ele caminha QUARENTA DIAS E QUARENTA NOITES até HOREBE,
// o monte de Deus. Ali entra numa CAVERNA e passa a noite, e vem a pergunta:
// "que fazes aqui, Elias?" — e a queixa, que ele repetirá palavra por palavra
// no fim: "tenho sido muito zeloso pelo Senhor Deus dos Exércitos… e SÓ EU
// FIQUEI, e buscam a minha vida para ma tirarem". A ordem é sair e pôr-se no
// monte perante o SENHOR. E então a sequência que é o coração do capítulo: um
// GRANDE E FORTE VENTO que fendia os montes e quebrava as penhas — porém o
// SENHOR não estava no vento; depois um TERREMOTO — o SENHOR não estava no
// terremoto; depois um FOGO — o SENHOR não estava no fogo; e DEPOIS DO FOGO
// UMA VOZ MANSA E DELICADA. Ao ouvi-la, Elias ENVOLVE O ROSTO NA SUA CAPA e
// sai à entrada da caverna. A mesma pergunta, a mesma queixa — e a resposta de
// Deus não é consolo, é MISSÃO: unge HAZAEL sobre a Síria, JEÚ sobre Israel e
// ELISEU, filho de Safate, profeta EM TEU LUGAR. E o desmentido do "só eu
// fiquei": "também deixei ficar em Israel SETE MIL: todos os joelhos que não
// se dobraram a Baal". Elias acha Eliseu LAVRANDO COM DOZE JUNTAS DE BOIS
// adiante dele, e ele com a duodécima, e passa por ele LANÇANDO A SUA CAPA
// SOBRE ELE. Eliseu pede para beijar o pai e a mãe, volta, TOMA A JUNTA DE
// BOIS, OS MATA, COZE AS CARNES COM OS APARELHOS DOS BOIS e dá ao povo —
// queima o próprio ganha-pão para não haver volta — e segue Elias, e o servia.
//
// 1Rs 20 — BEN-HADADE, rei da Síria, ajunta todo o seu exército, e com ele
// TRINTA E DOIS REIS, cavalos e carros, e cerca Samaria. A exigência chega em
// duas ondas: primeiro a prata, o ouro, as mulheres e os melhores dos filhos —
// e Acabe cede a tudo ("eu sou teu, e tudo quanto tenho") —, depois os SERVOS
// esquadrinhando a casa do rei e as casas dos seus servos e levando o que de
// precioso houver. Os anciãos da terra dão o único conselho firme do capítulo:
// "não lhe dês ouvidos, nem consintas". Vem a bravata do sírio — o PÓ DE
// SAMARIA não bastará para encher as mãos do povo que o segue — e a réplica
// que virou provérbio: "não se gabe quem se cinge das armas, como aquele que
// as descinge". Ben-Hadade está BEBENDO COM OS REIS NAS TENDAS quando manda
// pôr-se em ordem contra a cidade. Então um PROFETA se chega a Acabe: o SENHOR
// entregará toda aquela grande multidão nas suas mãos, e será PELOS MOÇOS DOS
// PRÍNCIPES DAS PROVÍNCIAS — duzentos e trinta e dois, com sete mil atrás.
// Saem AO MEIO-DIA, com Ben-Hadade embriagando-se nas tendas; a ordem
// arrogante ("tomai-os vivos") vira derrota, e o rei da Síria escapa A CAVALO.
// O profeta avisa: no decurso de um ano o rei da Síria subirá outra vez. E os
// servos de Ben-Hadade dão o conselho teológico errado: "seus deuses são
// deuses dos montes, por isso foram mais fortes do que nós; mas pelejemos com
// eles em CAMPO RASO" — e trocam os reis por capitães, cavalo por cavalo,
// carro por carro. No ano seguinte, em AFEQUE, os filhos de Israel acampam
// defronte deles "COMO DOIS PEQUENOS REBANHOS DE CABRAS", enquanto os sírios
// enchiam a terra. E o homem de Deus: porquanto os sírios disseram que o
// SENHOR é Deus dos montes e não Deus dos vales, toda aquela multidão será
// entregue. Sete dias acampados uns defronte dos outros; ao sétimo, cem mil de
// pé num dia — e o MURO DE AFEQUE cai sobre vinte e sete mil que restaram.
// Ben-Hadade foge escondendo-se DE CÂMARA EM CÂMARA; os servos põem SACOS AOS
// LOMBOS E CORDAS ÀS CABEÇAS e pedem a vida; Acabe o chama "MEU IRMÃO", o faz
// SUBIR AO CARRO e o deixa ir com uma aliança. E então o PROFETA DISFARÇADO:
// um dos filhos dos profetas manda o companheiro feri-lo, este recusa e um
// LEÃO o mata; outro homem o fere; ele se põe no caminho do rei DISFARÇADO COM
// CINZA SOBRE OS OLHOS e conta o caso do prisioneiro que se perdeu — "esta é a
// tua sentença; tu mesmo a pronunciaste". Tira a cinza, é reconhecido como um
// dos profetas, e dá a sentença verdadeira: "porquanto soltaste da mão o homem
// que eu havia posto para destruição, a tua vida será em lugar da sua vida, e
// o teu povo em lugar do seu povo". E o rei de Israel vai para a sua casa
// DESGOSTOSO E INDIGNADO, e chega a Samaria.
//
// A VOZ DE DEUS — 1Rs 19 tem os dois modos no mesmo capítulo, e a diferença é
// o mediador. Sob o ZIMBRO há um mediador visível: o ANJO DO SENHOR, que TOCA
// Elias duas vezes; por isso vv.5 e 7 são `by:"anjo"`, com a figura em cena e
// `glow` no máximo — nunca voz do céu. Em HOREBE não há mediador nenhum: a
// palavra vem à caverna e vem "depois do fogo", e por isso vv.9, 11, 13 e
// 15-18 são `by:"deus"`, balão dourado sem figura. O v.12 fica DELIBERADAMENTE
// SEM BALÃO: é o versículo em que o texto diz onde o SENHOR NÃO estava, e a
// direção o encena pelo ambiente — o fogo no auge, e no beat seguinte o
// silêncio, com `storm` a zero, `fire` a zero e a glória subindo a 0,92
// enquanto Elias envolve o rosto na capa. É o contraste entre os três e o
// quarto que faz o capítulo, e ele é feito com luz, não com legenda.
// Em 1Rs 20 o SENHOR nunca fala em voz do céu: há sempre uma boca humana na
// frase. Nos vv.13, 14 e 22 é o PROFETA de Samaria; no v.28 é o HOMEM DE DEUS
// de Afeque; nos vv.35-42 é UM DOS FILHOS DOS PROFETAS — o mesmo homem, antes
// e depois do disfarce de cinza. Em todos, `by:"homem"`, com o profeta em
// PRIMEIRO lugar no elenco e `glow` nele; o "assim diz o Senhor" é deixa da
// boca dele, e não do céu.
// ============================================================================

import type { StageScript, StageBeat, CastPlacement, StagePropSpec } from "@/lib/rpgStage";

const C = (role: string, dx: number, pose?: string, extra: Partial<CastPlacement> = {}): CastPlacement =>
  ({ role, dx, pose, ...extra });
const P = (kind: string, dx: number, scale = 1, fire?: number, dy?: number): StagePropSpec =>
  ({ kind, dx, scale, ...(fire != null ? { fire } : {}), ...(dy != null ? { dy } : {}) });
const b = (v: number, extra: Partial<StageBeat> = {}): StageBeat => ({ v, ...extra });
// voz do céu: só em Horebe (19:9,11,13,15-18), onde não há mediador visível.
const dv = (v: number, extra: Partial<StageBeat> = {}): StageBeat => b(v, { by: "deus", ...extra });

