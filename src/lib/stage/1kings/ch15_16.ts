// 1 REIS 15–16 — CENA VIVA. A CRÔNICA DOS REIS: a LÂMPADA que o SENHOR deixou
// acesa em Jerusalém por amor de Davi, o ÍDOLO DA RAINHA-MÃE queimado junto ao
// Cedrom, as PEDRAS DE RAMÁ que viram muro de Mizpá, o rei bêbado morto na casa
// do mordomo, o paço queimado sobre a cabeça de quem reinou SETE DIAS, o monte
// comprado por dois talentos de prata — e Jericó refundada sobre dois meninos.
//
// 1Rs 15 — Em JUDÁ reina ABIAS, filho de Roboão, três anos em Jerusalém, filho
// de MAACA, filha de Absalão. "Andou em todos os pecados que seu pai tinha
// cometido antes dele; e seu coração não foi perfeito para com o Senhor seu
// Deus como o coração de Davi, seu pai" — e mesmo assim o capítulo não começa
// com juízo, começa com uma luz: "por amor de Davi o Senhor seu Deus lhe deu
// uma LÂMPADA em Jerusalém, levantando a seu filho depois dele, e confirmando a
// Jerusalém". A razão está no versículo seguinte, e é uma frase que dói: Davi
// fez o que era reto todos os dias da sua vida, "senão só no negócio de Urias,
// o heteu". A guerra com Jeroboão nunca para. Abias dorme com seus pais e vem
// ASA, quarenta e um anos em Jerusalém, o primeiro rei desde Davi de quem se
// diz que fez o que era reto: TIROU DA TERRA OS SODOMITAS, removeu todos os
// ídolos que seus pais fizeram — e até a MAACA, sua avó, DEPÔS de ser rainha,
// porque tinha feito um horrível ídolo a Aserá; desfez o ídolo e o QUEIMOU
// JUNTO AO RIBEIRO DE CEDROM. Os altos não foram tirados, "todavia foi o
// coração de Asa reto para com o Senhor todos os seus dias". Depois vem a
// guerra com BAASA, que sobe contra Judá e EDIFICA RAMÁ para que a ninguém
// fosse permitido sair nem entrar a ter com Asa — um bloqueio de pedra à porta
// do reino. Asa tira a prata e o ouro que ficaram nos tesouros da casa do
// SENHOR e da casa do rei e os manda a BEN-HADADE, em Damasco: "vai, e anula o
// teu acordo com Baasa". O sírio dá ouvidos e fere Ijom, Dã, Abel-Bete-Maaca,
// toda a Quinerete e toda a terra de Naftali; Baasa larga a obra e fica em
// TIRZA. E então o quadro que salva o capítulo: Asa apregoa por TODA A JUDÁ que
// todos, SEM EXCEÇÃO, tragam as pedras e a madeira de Ramá — e com as pedras do
// bloqueio ele edifica GEBA DE BENJAMIM E MIZPÁ. Na velhice, "padeceu dos pés".
// No Norte, NADABE, filho de Jeroboão, reina dois anos e é ferido por BAASA em
// GIBETOM DOS FILISTEUS, no meio do próprio cerco do seu exército; e Baasa fere
// toda a casa de Jeroboão, "nada de Jeroboão deixou que tivesse fôlego",
// conforme a palavra dita pelo ministério de Aías, o silonita.
//
// 1Rs 16 — A palavra do SENHOR vem a JEÚ, FILHO DE HANANI, e é ele quem a leva
// à cara de Baasa: "porquanto te levantei do pó, e te pus por príncipe sobre o
// meu povo Israel, e tu tens andado no caminho de Jeroboão" — e a casa que
// nasceu de um golpe cairá por outro: "quem morrer dos de Baasa, na cidade, os
// cães o comerão; e o que dele morrer no campo, as aves do céu o comerão".
// Baasa dorme em Tirza e reina ELÁ, seu filho, que o texto congela num único
// gesto: BEBENDO E EMBRIAGANDO-SE EM CASA DE ARSA, o mordomo, quando ZINRI,
// capitão de metade dos carros, entra e o mata. Zinri assenta-se no trono e não
// deixa da casa de Baasa "homem algum, nem a seus parentes, nem a seus amigos"
// — e reina SETE DIAS. O arraial que estava acampado contra Gibetom ouve a
// notícia e no mesmo dia faz rei a ONRI, capitão do exército; Onri sobe, cerca
// Tirza, e Zinri, "vendo que a cidade era tomada, foi ao paço da casa do rei e
// QUEIMOU-A SOBRE SI; e morreu". O povo se parte em dois partidos, metade
// atrás de TIBNI, filho de Ginate, metade atrás de Onri; Onri prevalece, Tibni
// morre. E Onri COMPRA DE SEMER O MONTE DE SAMARIA POR DOIS TALENTOS DE PRATA,
// edifica nele e dá à cidade o nome do dono do monte. Por fim ACABE, seu filho,
// que "fez o que era mau aos olhos do Senhor, mais do que todos os que foram
// antes dele": como se fora pouco andar nos pecados de Jeroboão, toma por
// mulher a JEZABEL, filha de Etbaal, rei dos sidônios, serve a Baal e o adora,
// levanta-lhe altar na CASA DE BAAL que edificou em Samaria e ainda faz um
// ídolo. E o capítulo fecha com a frase mais sinistra dos dois: em seus dias
// HIEL, o betelita, edificou Jericó — "em ABIRÃO, seu primogênito, a fundou, e
// em SEGUBE, seu filho menor, pôs as suas portas", conforme a palavra que o
// SENHOR falara pelo ministério de Josué, filho de Num (Js 6:26).
//
// A VOZ DE DEUS — em 1Rs 15–16 o SENHOR NÃO FALA EM BALÃO NENHUMA VEZ, e isso
// é deliberado: são dois capítulos de crônica, onde Deus aparece como o juiz
// que registra ("fez o que era mau aos olhos do Senhor") e como a palavra que
// se cumpre atrás dos golpes de estado. A única vez que a Sua palavra é dita em
// cena, ela tem BOCA HUMANA: 16:1 conta que a palavra veio a JEÚ, FILHO DE
// HANANI — o beat é narração, com a glória caindo sobre o profeta sozinho no
// campo, sem balão —, e 16:2-4 são falados por ele diante do trono de Baasa,
// `by: "homem"` com `jeu-filho-de-hanani` em primeiro lugar no elenco e `glow`
// nele. Nunca `by: "deus"`. As outras duas falas dos capítulos são de homens: o
// recado de Asa a Ben-Hadade (15:19, `by: "rei"`, com Asa em primeiro no
// elenco) e o grito do arraial de Gibetom (16:16, `by: "homem"`, o arauto). O
// cumprimento da palavra de Aías (15:29) e da palavra de Jeú (16:12) entra como
// luz e como ruína no quadro, não como voz.
// ============================================================================

