// 1 REIS 11–12 — CENA VIVA. A CAPA NOVA rasgada em DOZE PEDAÇOS no campo fora
// de Jerusalém, o DEDO MÍNIMO mais grosso do que os lombos do pai, e os DOIS
// BEZERROS DE OURO postos um em Betel e outro em Dã.
//
// 1Rs 11 — A QUEDA DE SALOMÃO. O rei mais sábio da terra "amou muitas mulheres
// estrangeiras, além da filha de Faraó: moabitas, amonitas, edomitas, sidônias
// e hetéias" — justamente as nações de que o SENHOR tinha dito "não chegareis a
// elas, e elas não chegarão a vós; de outra maneira perverterão o vosso coração
// para seguirdes os seus deuses". Setecentas mulheres, princesas, e trezentas
// concubinas: "e suas mulheres lhe perverteram o coração". A ruína não é súbita
// — vem "no tempo da velhice de Salomão", quando o coração já não era perfeito
// para com o SENHOR seu Deus como o coração de Davi, seu pai. Ele segue
// ASTAROTE, deusa dos sidônios, e MILCOM, a abominação dos amonitas; edifica um
// alto a QUEMÓS, a abominação dos moabitas, SOBRE O MONTE QUE ESTÁ DIANTE DE
// JERUSALÉM — a fumaça do ídolo à vista do templo que ele mesmo levantou — e
// outro a MOLOQUE; "e assim fez para com todas as suas mulheres estrangeiras,
// as quais queimavam incenso e sacrificavam a seus deuses". Então o SENHOR se
// indigna, "porquanto desviara o seu coração do Senhor Deus de Israel, o qual
// DUAS VEZES lhe aparecera", e vem a sentença: "certamente rasgarei de ti este
// reino, e o darei a teu servo" — todavia não nos seus dias, por amor de Davi,
// e uma tribo ficará ao filho por amor de Jerusalém. E aí o SENHOR levanta os
// adversários. HADADE, O EDOMEU, da descendência do rei em Edom, salvo menino
// da matança em que Joabe ficou seis meses até destruir todo homem em Edom,
// criado na casa de Faraó, casado com a irmã de Tafnes, a rainha, e pai de
// Genubate: "despede-me, para que vá à minha terra". REZOM, filho de Eliada,
// que fugira de Hadadezer, junta um esquadrão, toma Damasco e reina sobre a
// Síria. E JEROBOÃO, FILHO DE NEBATE, efrateu de Zereda, servo de Salomão,
// filho de uma viúva chamada Zerua, "forte e valente", posto pelo próprio rei
// sobre todo o cargo da casa de José por causa da obra de Milo. No caminho,
// fora da cidade, os dois sozinhos no campo, o profeta AÍAS, O SILONITA, pega
// na ROUPA NOVA que tinha sobre si e a RASGA EM DOZE PEDAÇOS: "toma para ti os
// dez pedaços, porque assim diz o Senhor Deus de Israel: eis que rasgarei o
// reino da mão de Salomão, e a ti darei as dez tribos… e a seu filho darei uma
// tribo, para que Davi, meu servo, sempre tenha uma LÂMPADA diante de mim em
// Jerusalém". Salomão procura matá-lo; Jeroboão foge para o Egito, a SISAQUE, e
// ali fica até que Salomão morre. Quarenta anos de reinado, o sepulcro na
// cidade de Davi — e Roboão, seu filho, reina em seu lugar.
//
// 1Rs 12 — A DIVISÃO. Roboão vai a SIQUÉM, porque todo o Israel se reuniu ali
// para o fazerem rei — e quem chega do Egito para a assembleia é Jeroboão. O
// pedido do povo é uma única frase de trabalhador: "teu pai agravou o nosso
// jugo; agora, pois, alivia tu a dura servidão de teu pai, e o pesado jugo que
// nos impôs, e nós te serviremos". Três dias de prazo. Os ANCIÃOS que estiveram
// na presença de Salomão dizem a coisa mais sábia do capítulo — "se hoje fores
// servo deste povo, e o servires… todos os dias serão teus servos" — e o rei
// deixa o conselho deles para ouvir os JOVENS que haviam crescido com ele, que
// lhe ensinam a resposta que parte a nação: "meu dedo mínimo é mais grosso do
// que os lombos de meu pai… meu pai vos castigou com açoites, porém eu vos
// castigarei com escorpiões". Ao terceiro dia o rei responde duramente, "porque
// esta revolta vinha do Senhor, para confirmar a palavra que o Senhor tinha
// falado pelo ministério de Aías, o silonita". E o grito sobe: "que parte temos
// nós com Davi? Não há para nós herança no filho de Jessé. Às tuas tendas, ó
// Israel! Provê agora a tua casa, ó Davi". ADORÃO, o que estava sobre os
// tributos, é mandado ao povo e apedrejado até morrer, e Roboão se anima a
// subir ao carro para fugir para Jerusalém. Judá e Benjamim ajuntam cento e
// oitenta mil escolhidos para pelejar, mas a palavra vem a SEMAÍAS, homem de
// Deus: "não subireis nem pelejareis contra vossos irmãos, os filhos de Israel;
// volte cada um para a sua casa, porque EU É QUE FIZ ESTA OBRA" — e eles ouvem
// e voltam. Jeroboão edifica Siquém no monte de Efraim e edifica Penuel; e ali,
// sobre o que acabou de construir, o medo lhe fala no coração: se este povo
// subir a sacrificar na casa do SENHOR em Jerusalém, tornará ao seu senhor. É
// por medo, e não por teologia, que nascem OS DOIS BEZERROS DE OURO: "muito
// trabalho vos será o subir a Jerusalém; vês aqui teus deuses, ó Israel, que te
// fizeram subir da terra do Egito" — um em BETEL, outro em DÃ, "e este feito se
// tornou em pecado". Depois vêm as casas nos altos, os sacerdotes dos mais
// baixos do povo que não eram dos filhos de Levi, e uma festa no décimo quinto
// dia do OITAVO mês — um mês depois da festa de Judá —, "que ele tinha
// imaginado no seu coração".
//
// A VOZ DE DEUS — em 1Rs 11–12 o SENHOR fala três vezes, e cada vez de um jeito
// diferente. (1) Em 11:11-13, SEM MEDIADOR NENHUM: "assim disse o Senhor a
// Salomão", e não há profeta na sala — é a voz do céu (`by:"deus"`), glória
// alta, o rei velho sozinho e de joelhos no seu próprio salão, sem figura
// alguma para Deus. (2) Em 11:31-39 há MEDIADOR VISÍVEL e ele está com a capa
// rasgada nas mãos: quem fala é AÍAS, O SILONITA (`by:"homem"`, id
// `aias-silonita`, primeiro homem do elenco, com `glow`), porque o texto põe a
// palavra na boca dele — "e disse a Jeroboão… porque assim diz o Senhor Deus de
// Israel". Nunca voz do céu ali: o balão tem de sair de quem está rasgando os
// doze pedaços. (3) Em 12:22-24 o caminho tem duas pernas: a palavra vem
// primeiro A SEMAÍAS, na casa dele, e ali não há mediador entre Deus e o
// profeta — v.23 é voz do céu (`by:"deus"`); mas o que Roboão e os cento e
// oitenta mil ouvem em Jerusalém, no v.24, sai da boca de Semaías
// (`by:"homem"`, id `semaias`). Fora disso o SENHOR é presença narrada: a
// indignação de 11:9, a mão que levanta os adversários de 11:14 e 11:23, e a
// linha mais pesada do capítulo 12 — "porque esta revolta vinha do Senhor"
// (12:15) —, que não é fala nenhuma, é luz subindo por cima de uma catástrofe
// política. A ROUPA NOVA de Aías não recebe prop: não existe manto na paleta do
// motor, e etiquetar um rolo ou um caixote como "capa" faria o badge mentir —
// a cena é contada pela POSE (o profeta rasgando com as duas mãos erguidas, e
// Jeroboão recolhendo do chão os dez pedaços).
// ============================================================================

import type { StageScript, StageBeat, CastPlacement, StagePropSpec } from "@/lib/rpgStage";

const C = (role: string, dx: number, pose?: string, extra: Partial<CastPlacement> = {}): CastPlacement =>
  ({ role, dx, pose, ...extra });
const P = (kind: string, dx: number, scale = 1, fire?: number, dy?: number): StagePropSpec =>
  ({ kind, dx, scale, ...(fire != null ? { fire } : {}), ...(dy != null ? { dy } : {}) });
const b = (v: number, extra: Partial<StageBeat> = {}): StageBeat => ({ v, ...extra });
// voz do céu — só onde NÃO há mediador visível: 11:11-13 (a sentença sobre
// Salomão) e 12:23 (a palavra que desce sobre Semaías dentro da casa dele).
const dv = (v: number, q: string, extra: Partial<StageBeat> = {}): StageBeat =>
  b(v, { by: "deus", q, ...extra });

