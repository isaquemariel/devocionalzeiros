// ============================================================================
// 1 REIS 3–4 — CENA VIVA. O SONHO DE GIBEÃO, a espada levantada sobre um menino
// vivo, e o reino inteiro posto à mesa: doze provedores, um mês cada um, e um
// rei que sabe o nome das árvores desde o CEDRO DO LÍBANO até ao HISSOPO QUE
// NASCE NA PAREDE.
//
// 1Rs 3 — O capítulo abre com uma aliança de conveniência: Salomão SE APARENTA
// COM FARAÓ, rei do Egito, toma a filha dele e a traz à CIDADE DE DAVI — e o
// texto anota, quase entre parênteses, que ela fica ali "até que acabasse de
// edificar a sua casa, e a casa do SENHOR, e a muralha de Jerusalém em redor".
// Nada está pronto ainda, nem a casa do rei, nem a casa de Deus, nem o muro. E
// é essa a razão da nota seguinte, que o narrador faz questão de dar antes de
// qualquer elogio: "o povo sacrificava sobre os ALTOS; porque até àqueles dias
// ainda não se havia edificado casa ao nome do Senhor". Salomão AMAVA ao SENHOR
// e andava nos estatutos de Davi seu pai — "somente que nos altos sacrificava,
// e queimava incenso". Então ele sobe a GIBEÃO, "porque aquele era o ALTO
// MAIOR", e queima ali MIL HOLOCAUSTOS num altar só. E naquela noite, no monte,
// dormindo ao lado das brasas, ele ouve a pergunta mais perigosa da Bíblia:
// "PEDE O QUE QUERES QUE EU TE DÊ". A resposta é o que define o reinado
// inteiro. Ele não começa por si: começa pela beneficência que Deus usou com
// Davi, seu pai, "e lhe deste um filho que se assentasse no seu trono, como se
// vê neste dia". Depois se mede: "sou apenas um MENINO PEQUENO; não sei como
// sair, nem como entrar" — e mede o povo: "povo grande, que nem se pode contar,
// nem numerar". E pede uma coisa só: "A teu servo, pois, dá um CORAÇÃO
// ENTENDIDO para julgar a teu povo, para que prudentemente discirna entre o bem
// e o mal". "E esta palavra pareceu boa aos olhos do Senhor." A resposta vem
// pela conta do que ele NÃO pediu: não pediu muitos dias, nem riquezas, nem a
// vida dos seus inimigos — por isso recebe o que pediu E as duas coisas que
// deixou de pedir, com uma condição pendurada no fim: "e, se andares nos meus
// caminhos… também prolongarei os teus dias". Ele acorda — "e eis que era
// sonho" — desce a Jerusalém, põe-se PERANTE A ARCA DA ALIANÇA, sacrifica e faz
// um banquete a todos os seus servos. E o dom recebido é posto à prova no mesmo
// capítulo: DUAS MULHERES PROSTITUTAS, moradoras da mesma casa, dois filhos
// nascidos a três dias de distância, "nenhum estranho estava conosco na casa;
// somente nós duas naquela casa" — e um dos meninos morre de noite porque a mãe
// se deitou sobre ele. À MEIA-NOITE ela troca os meninos; pela manhã a outra se
// levanta para dar de mamar e vê o corpo: "eis que não era meu filho, que eu
// havia tido". Diante do trono a discussão é um pingue-pongue sem testemunha
// ("Não, mas o vivo é meu filho, e teu filho o morto"), e o rei repete as duas
// versões palavra por palavra para mostrar que são idênticas. Então ele manda
// buscar uma ESPADA e dá a ordem intolerável: "DIVIDI EM DUAS PARTES O MENINO
// VIVO; e dai metade a uma, e metade a outra". O que separa a mãe da rival não
// é um argumento: é uma víscera — "porque as suas ENTRANHAS SE LHE
// ENTERNECERAM por seu filho" — e a renúncia que sai daí: "dai-lhe o menino
// vivo, e de modo nenhum o mateis". A outra, fria: "nem teu nem meu seja;
// dividi-o". A sentença cabe numa frase: "Dai a esta o menino vivo… porque esta
// é sua mãe". E todo o Israel ouve, e TEME o rei, "porque viram que havia nele
// a sabedoria de Deus, para fazer justiça".
//
// 1Rs 4 — O capítulo é uma LISTA, e a lista é o retrato do reino: "Assim foi
// Salomão rei sobre todo o Israel". Vêm os príncipes um a um — AZARIAS, filho
// de Zadoque, sacerdote; ELIOREFE e AÍAS, filhos de Sisa, secretários; JEOSAFÁ,
// filho de Ailude, cronista; BENAIA, filho de Joiada, sobre o exército; ZADOQUE
// e ABIATAR, sacerdotes; AZARIAS, filho de Natã, sobre os provedores; ZABUDE,
// oficial-mor e AMIGO DO REI; AISAR, mordomo; ADONIRÃO, sobre o tributo. Depois
// os DOZE PROVEDORES, "e cada um tinha que abastecê-lo por um MÊS NO ANO": as
// montanhas de Efraim, a Sefelá de Bete-Semes, Arubote e Socó, o termo de Dor
// (onde o provedor é genro do rei, casado com TAFATE), o vale de Megido e
// Bete-Seã, Ramote de Gileade com as SESSENTA GRANDES CIDADES DE ARGOBE "com
// muros e ferrolhos de cobre", Maanaim, Naftali (com BASEMATE, a outra filha do
// rei), Aser e Alote, Issacar, Benjamim, e a terra de Siom e de Ogue, onde "só
// uma guarnição havia naquela terra". Feita a lista, o narrador levanta a
// câmera: Judá e Israel eram muitos "como a AREIA que está junto ao mar em
// multidão, COMENDO, E BEBENDO, E ALEGRANDO-SE"; o domínio ia desde o Rio até à
// terra dos filisteus e ao termo do Egito. Vem então a PROVISÃO DE UM DIA — não
// de um ano: trinta coros de flor de farinha e sessenta de farinha, dez bois
// cevados, vinte bois de pasto e cem carneiros, "afora os veados e as cabras
// montesas, e os corços, e aves cevadas". E a paz, na imagem que virou o retrato
// de todo o reinado: "cada um debaixo da SUA VIDEIRA, e debaixo da SUA
// FIGUEIRA, desde Dã até Berseba". Depois as CAVALARIÇAS — quarenta mil
// estrebarias para os carros, doze mil cavaleiros — e o detalhe administrativo
// que fecha o retrato: a cevada e a palha eram levadas "para o lugar onde
// estava, cada um segundo o seu cargo". O fecho é sobre a sabedoria: Deus lhe
// deu "largueza de coração, como a AREIA QUE ESTÁ NA PRAIA DO MAR"; ela excedeu
// a de todos os do oriente e a dos egípcios; excedeu Etã, Hemã, Calcol e Darda;
// deu TRÊS MIL PROVÉRBIOS e MIL E CINCO CÂNTICOS. E ele falou das ÁRVORES,
// "desde o cedro que está no Líbano até ao hissopo que nasce na parede", e dos
// animais, e das aves, e dos répteis, e dos peixes — e de todos os povos vinham
// ouvi-lo.
//
// A VOZ DE DEUS — em 1Rs 3 o SENHOR fala, e fala SEM MEDIADOR NENHUM: "em
// Gibeom apareceu o Senhor a Salomão DE NOITE EM SONHOS". Não há anjo, não há
// profeta, não há objeto de teofania — é oráculo interior, e por isso os vv.5 e
// 11-14 são `by: "deus"`, voz do céu, sem figura desenhada, com a glória subindo
// no ambiente enquanto Salomão dorme (`lie`) e depois se ajoelha. As respostas
// dos vv.6-9 são de Salomão (`by: "rei"`, `salomao` em primeiro lugar no
// elenco): o sonho é diálogo, não monólogo. O v.10 não tem `by` — "esta palavra
// pareceu boa aos olhos do Senhor" é juízo narrado, não fala; ali só a luz sobe.
// Em 1Rs 4 Deus NÃO FALA uma única vez: o capítulo é lista e retrato, e a única
// linha sobre Ele é narrada — "E deu Deus a Salomão sabedoria" (v.29), sem
// balão, só com a glória no auge sobre a praia do mar. E o juízo das duas
// mulheres (vv.16-28) é de propósito mudo do lado do céu: quem fala é o rei, e a
// sabedoria de Deus aparece nele, não sobre ele — "porque viram que HAVIA NELE
// a sabedoria de Deus, para fazer justiça".
// ============================================================================

import type { StageScript, StageBeat, CastPlacement, StagePropSpec } from "@/lib/rpgStage";

const C = (role: string, dx: number, pose?: string, extra: Partial<CastPlacement> = {}): CastPlacement =>
  ({ role, dx, pose, ...extra });
const P = (kind: string, dx: number, scale = 1, fire?: number, dy?: number): StagePropSpec =>
  ({ kind, dx, scale, ...(fire != null ? { fire } : {}), ...(dy != null ? { dy } : {}) });
const b = (v: number, extra: Partial<StageBeat> = {}): StageBeat => ({ v, ...extra });
// voz do céu: em 1Rs 3 o SENHOR fala em SONHO, sem mediador visível nenhum —
// nem anjo, nem profeta, nem fogo. Balão dourado, sem figura.
const dv = (v: number, q?: string, extra: Partial<StageBeat> = {}): StageBeat =>
  b(v, { by: "deus", ...(q ? { q } : {}), ...extra });

