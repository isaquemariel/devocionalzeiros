// 1 REIS 17–18 — CENA VIVA. A entrada de ELIAS, o tisbita, sem genealogia e sem
// aviso; os CORVOS que servem pão e carne de manhã e de tarde; o ribeiro que
// seca na cara do profeta que anunciou a seca; o punhado de farinha e o pouco
// azeite que não acabam; o menino morto que desce vivo do quarto de cima — e o
// MONTE CARMELO, com dois altares, doze pedras, um rego cheio de água e o fogo
// do SENHOR caindo sobre tudo.
//
// 1Rs 17 — Não há apresentação nenhuma: "Então Elias, o tisbita, dos moradores
// de Gileade, disse a Acabe". O homem entra no salão do rei que casou com
// Jezabel e fecha o céu com uma frase: "VIVE O SENHOR DEUS DE ISRAEL, PERANTE
// CUJA FACE ESTOU, QUE NESTES ANOS NEM ORVALHO NEM CHUVA HAVERÁ, SENÃO SEGUNDO
// A MINHA PALAVRA". Depois disso a palavra do SENHOR o esconde: "retira-te
// daqui, e vai para o oriente, e esconde-te junto ao ribeiro de QUERITE, que
// está diante do Jordão" — beberá do ribeiro, e Deus tem ORDENADO AOS CORVOS
// que ali o sustentem. E as aves imundas da Lei viram garçons do céu: pão e
// carne pela manhã, pão e carne à noite, e a água correndo aos seus pés. Até
// que vem o verso mais curto e mais duro do capítulo: "passados dias, o ribeiro
// se secou, PORQUE NÃO TINHA HAVIDO CHUVA NA TERRA". A seca que ele mesmo
// anunciou chega ao leito de onde ele bebia. Então a palavra o manda para
// SAREPTA, QUE É DE SIDOM — a terra de Jezabel, o quintal de Baal —, sustentado
// por uma viúva pagã e sem nada. Ele a encontra à porta da cidade APANHANDO
// LENHA, pede água, pede um bocado de pão, e recebe de volta o inventário da
// morte: "nem um bolo tenho, senão somente UM PUNHADO DE FARINHA NUMA PANELA, e
// UM POUCO DE AZEITE NUMA BOTIJA; e vês aqui apanhei dois cavacos, e vou
// prepará-lo para mim e para o meu filho, PARA QUE O COMAMOS, E MORRAMOS". A
// resposta começa por "não temas" e termina numa exigência escandalosa — "faze
// dele PRIMEIRO para mim um bolo pequeno" — sustentada por uma promessa: "a
// farinha da panela não se acabará, e o azeite da botija não faltará até ao dia
// em que o SENHOR dê chuva sobre a terra". E assim comeu ela, e ele, e a sua
// casa, MUITOS DIAS. Depois destas coisas o filho adoece até que nele nenhum
// fôlego fica, e a mãe acusa o hóspede: "que tenho eu contigo, homem de Deus?
// vieste tu a mim para trazeres à memória a minha iniquidade, e matares a meu
// filho?". Elias toma o menino do regaço dela, sobe ao QUARTO DE CIMA onde ele
// mesmo habitava, o deita na SUA PRÓPRIA CAMA e discute com Deus: "também até a
// esta viúva, com quem me hospedo, afligiste?". Estende-se sobre o menino TRÊS
// VEZES e ora a oração mais nua da Bíblia: "rogo-te que a alma deste menino
// torne a entrar nele". O SENHOR ouve a voz de Elias; a alma volta; o profeta
// desce a criança e a entrega à mãe com quatro palavras — "VÊS AÍ, TEU FILHO
// VIVE" —, e é a mulher de Sidom, não o rei de Israel, quem faz a confissão que
// fecha o capítulo: "nisto conheço agora que tu és homem de Deus, e que a
// palavra do SENHOR na tua boca é verdade".
//
// 1Rs 18 — O CARMELO. Ao terceiro ano a palavra volta: "vai, apresenta-te a
// Acabe; porque darei chuva sobre a terra" — e a fome estava EXTREMA em
// Samaria. Entra OBADIAS, o mordomo do palácio, um homem que temia muito ao
// SENHOR e que, enquanto Jezabel destruía os profetas, ESCONDEU CEM DELES, de
// cinquenta em cinquenta, numa cova, sustentando-os com pão e água debaixo do
// nariz da rainha. O rei o manda percorrer as fontes atrás de erva "para que em
// vida conservemos os cavalos e mulas" — e é no caminho que Elias o encontra.
// O pavor do mordomo é uma cena inteira: ele se prostra, reconhece o profeta,
// e depois enumera três anos de buscas, reinos jurando que não o acharam, e o
// medo concreto de que "o Espírito do SENHOR te tomasse, não sei para onde" e
// Acabe o mate por um recado falso. O juramento de Elias o sossega: "vive o
// SENHOR dos Exércitos, perante cuja face estou, que deveras hoje me
// apresentarei a ele". O encontro dos dois homens cabe numa acusação e numa
// devolução: "ÉS TU O PERTURBADOR DE ISRAEL?" — "eu não tenho perturbado a
// Israel, MAS TU E A CASA DE TEU PAI, porque deixastes os mandamentos do SENHOR,
// e seguistes a Baalim". Então a convocação: todo o Israel ao monte Carmelo,
// com os QUATROCENTOS E CINQUENTA profetas de Baal e os quatrocentos de Aserá
// que comem da mesa de Jezabel. No cume, a pergunta que divide o livro — "ATÉ
// QUANDO COXEAREIS ENTRE DOIS PENSAMENTOS? Se o SENHOR é Deus, segui-o, e se
// Baal, segui-o" — e a resposta mais eloquente do capítulo: "porém o povo nada
// lhe respondeu". Dois bezerros, duas lenhas, nenhum fogo posto embaixo, e a
// regra: "o deus que responder por meio de fogo esse será Deus". A manhã
// inteira dos profetas de Baal — "Ah! Baal, responde-nos!", o SALTAR SOBRE O
// ALTAR, o escárnio de Elias ao meio-dia ("clamai em altas vozes, porque ele é
// um deus… talvez esteja dormindo, e despertará"), as facas e as lancetas até
// derramarem sangue sobre si, e o veredito de três negativas: "não houve voz,
// nem resposta, nem atenção alguma". Aí Elias chama o povo para perto, RESTAURA
// O ALTAR DO SENHOR QUE ESTAVA QUEBRADO com DOZE PEDRAS conforme o número das
// tribos, abre um REGO em redor, arma a lenha, divide o bezerro — e manda
// derramar QUATRO CÂNTAROS DE ÁGUA, três vezes, até a água correr ao redor do
// altar e o rego encher. A oração dura duas frases; o fogo do SENHOR cai e
// consome o holocausto, e a lenha, e as pedras, e o pó, E AINDA LAMBE A ÁGUA QUE
// ESTAVA NO REGO. Todo o povo cai sobre os rostos: "SÓ O SENHOR É DEUS! SÓ O
// SENHOR É DEUS!". Os profetas de Baal descem ao ribeiro de QUISOM e ali morrem.
// E então a chuva: Elias sobe ao cume, se inclina por terra e PÕE O ROSTO ENTRE
// OS JOELHOS, e manda o moço olhar para o lado do mar sete vezes; à sétima vem
// a notícia do tamanho de uma mão — "eis aqui uma pequena nuvem, como a mão de
// um homem, subindo do mar". Os céus se enegrecem, o vento vem, cai grande
// chuva, Acabe sobe ao carro para Jizreel — e a mão do SENHOR está sobre Elias,
// que cinge os lombos e CORRE ADIANTE DO CARRO DO REI até à entrada da cidade.
//
// A VOZ DE DEUS — nestes dois capítulos Ele fala de dois modos, e a diferença é
// o mediador. SEM mediador (17:2-4, 17:8-9, 18:1) é a "palavra do SENHOR" que
// vem ao profeta sozinho na estrada ou no leito seco do ribeiro: `by:"deus"`,
// balão dourado, glória alta, NENHUMA figura de Deus no palco. Mas 17:1 NÃO é
// voz do céu — quem fala a Acabe é ELIAS (`by:"patriarca"`, id `elias`), e a
// palavra é dele "perante cuja face estou"; o mesmo vale para 17:13-14 ("assim
// diz o Senhor Deus de Israel" sai da boca do hóspede), para as orações de
// 17:20-21 e 18:36-37, e para toda a pregação do Carmelo. E o clímax do livro
// inteiro — 18:38, o FOGO QUE CAI — é ação de Deus SEM UMA PALAVRA: ali não há
// balão nenhum, só o `altar` com `fire` no máximo, a glória no auge e o povo no
// chão. O silêncio é proposital: em 18:26 e 18:29 Baal não responde três vezes,
// e quando o SENHOR responde Ele não argumenta — Ele consome as pedras.
// ============================================================================

import type { StageScript, StageBeat, CastPlacement, StagePropSpec } from "@/lib/rpgStage";

const C = (role: string, dx: number, pose?: string, extra: Partial<CastPlacement> = {}): CastPlacement =>
  ({ role, dx, pose, ...extra });
const P = (kind: string, dx: number, scale = 1, fire?: number, dy?: number): StagePropSpec =>
  ({ kind, dx, scale, ...(fire != null ? { fire } : {}), ...(dy != null ? { dy } : {}) });
const b = (v: number, extra: Partial<StageBeat> = {}): StageBeat => ({ v, ...extra });
// VOZ DO CÉU — só onde não há mediador visível: 17:2-4, 17:8-9 e 18:1. Em todo o
// resto quem fala é ELIAS, e o balão sai dele (ver "A VOZ DE DEUS" no cabeçalho).
const dv = (v: number, extra: Partial<StageBeat> = {}): StageBeat => b(v, { by: "deus", ...extra });

