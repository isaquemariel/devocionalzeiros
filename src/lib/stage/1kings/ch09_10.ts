// 1 REIS 9–10 — CENA VIVA. A SEGUNDA APARIÇÃO do SENHOR a Salomão, com a
// promessa e a ameaça pregadas na mesma casa recém-acabada; e, do outro lado do
// aviso, o auge do esplendor: a RAINHA DE SABÁ ficando fora de si e o TRONO DE
// MARFIM com doze leões nos seis degraus.
//
// 1Rs 9 — Acabada a casa do SENHOR, a casa do rei "e todo o desejo de Salomão,
// que lhe veio à vontade fazer", o SENHOR TORNA A APARECER-LHE, "como lhe tinha
// aparecido em Gibeom". A palavra começa em pura graça: "ouvi a tua oração, e a
// súplica que fizeste perante mim; santifiquei a casa que edificaste, a fim de
// pôr ali o meu nome para sempre; e os meus olhos e o meu coração estarão ali
// todos os dias". Vem então a condição — andar como Davi andou, com inteireza
// de coração e com sinceridade — e a promessa: "não te faltará sucessor sobre o
// trono de Israel". E vem o aviso, que é a cena mais escura destes dois
// capítulos: se vós e vossos filhos vos apartardes e servirdes a outros deuses,
// "então destruirei a Israel da terra que lhes dei; e a esta casa, que
// santifiquei a meu nome, lançarei longe da minha presença; e Israel será por
// provérbio e motejo, entre todos os povos". A casa TÃO EXALTADA fará com que
// todo o que por ela passar pasme e assobie, e pergunte: "por que fez o Senhor
// assim a esta terra e a esta casa?" — e a resposta já está escrita: "porque
// deixaram ao Senhor seu Deus". Depois do oráculo, o inventário de vinte anos
// de obra: as VINTE CIDADES da Galiléia dadas a Hirão, que sai de Tiro para
// vê-las e não as acha boas aos seus olhos — "que cidades são estas que me
// deste, irmão meu?" — e as chama TERRA DE CABUL, "até hoje"; e mesmo assim
// manda os cento e vinte talentos de ouro. A leva do tributo levanta Milo, o
// muro de Jerusalém, Hasor, Megido e Gezer — Gezer que Faraó subira e tomara e
// queimara a fogo, e dera em dote à filha, mulher de Salomão. Sobem também
// Bete-Horom a baixa, Baalate, TADMOR no deserto, as cidades das provisões, as
// dos carros e as dos cavaleiros. O que restou dos amorreus, heteus, perizeus,
// heveus e jebuseus é reduzido a tributo servil; dos filhos de Israel, porém,
// "não fez Salomão servo algum" — eram homens de guerra, criados, príncipes,
// capitães e chefes dos carros e dos cavaleiros, e quinhentos e cinqüenta
// oficiais davam ordens à obra. A filha de Faraó sobe da Cidade de Davi para a
// casa que ele lhe edificara. Três vezes por ano o rei oferece holocaustos e
// pacíficos sobre o altar, "e assim acabou a casa". E o capítulo termina no mar:
// NAUS em EZIOM-GEBER, junto a Elate, à praia do MAR DE SUFE, na terra de Edom;
// Hirão manda com elas os seus servos, marinheiros que sabiam do mar, com os
// servos de Salomão — e de OFIR vêm quatrocentos e vinte talentos de ouro.
//
// 1Rs 10 — A RAINHA DE SABÁ ouve a fama de Salomão "acerca do nome do SENHOR" e
// vem prová-lo com questões difíceis, numa comitiva imensa, com camelos
// carregados de especiarias, muitíssimo ouro e pedras preciosas. Diz-lhe tudo
// quanto tinha no coração, e ele lhe responde a tudo: "nada houve que não lhe
// pudesse esclarecer". Ela vê a sabedoria, a casa que ele edificara, a comida da
// mesa, o assentar dos servos, o estar dos criados e as vestes deles, os
// copeiros, e os holocaustos que ele oferecia na casa do SENHOR — e FICOU FORA
// DE SI. A confissão é o coração do capítulo: "era verdade a palavra que ouvi na
// minha terra… e eu não cria naquelas palavras, até que vim e os meus olhos o
// viram; eis que não me disseram metade"; e a bênção não termina nele: "bendito
// seja o Senhor teu Deus… porque o Senhor ama a Israel para sempre, por isso te
// estabeleceu rei, para fazeres juízo e justiça". Ela dá cento e vinte talentos
// de ouro e especiaria em abundância que nunca mais se viu. Depois vem o OURO
// puro do relato: seiscentos e sessenta e seis talentos por ano; duzentos
// PAVESES e trezentos ESCUDOS de ouro batido postos na CASA DO BOSQUE DO LÍBANO;
// e o GRANDE TRONO DE MARFIM revestido de ouro puríssimo, com seis degraus, o
// alto redondo por detrás, encostos de ambos os lados do assento, DOIS LEÕES
// junto aos encostos e DOZE LEÕES sobre os seis degraus — "nunca se tinha feito
// obra semelhante em nenhum dos reinos". Todas as taças de beber eram de ouro, e
// prata não havia, "porque nos dias de Salomão não tinha valor algum". As naus
// de Társis voltavam de três em três anos com ouro, prata, marfim, bugios e
// pavões. Toda a terra buscava a face do rei, e cada um trazia o seu presente de
// ano em ano. Mil e quatrocentos carros, doze mil cavaleiros; a prata como
// pedras em Jerusalém e os cedros como os sicômoros das planícies; e o comércio
// dos cavalos do Egito, o carro por seiscentos siclos de prata e o cavalo por
// cento e cinqüenta, revendidos aos reis dos heteus e da Síria.
//
// A VOZ DE DEUS — nestes dois capítulos o SENHOR fala UMA VEZ SÓ, e sem
// mediador nenhum: 9:3-9, a segunda aparição, "como lhe tinha aparecido em
// Gibeom". Não há profeta, não há anjo, não há objeto por onde a palavra passe —
// é oráculo direto ao rei, de noite, no átrio da casa que ele acabou de
// construir. Por isso esses sete beats são `by: "deus"`: voz do céu, balão
// dourado e centralizado, sem figura, com Salomão de joelhos em cena e a glória
// no ambiente. A exceção deliberada é o bloco 9:7-9: continua sendo a mesma voz,
// mas o que ela descreve é a RUÍNA — a casa lançada longe da presença de Deus e
// o passante que pasma e assobia. Ali a `glory` cai a quase nada e a `night`
// sobe ao máximo do trecho: a voz continua sendo do céu, mas o quadro já é o
// exílio, e é de propósito que o capítulo 10 inteiro venha logo depois com a
// luz no auge — o esplendor de Salomão está pintado por cima de um aviso.
// Em 1Rs 10 Deus não fala: quem O louva é uma estrangeira, e a confissão de
// 10:9 sai da boca dela (`by: "mulherComum"`, `rainha-de-saba` em primeiro
// lugar no elenco), nunca do alto.
// ============================================================================

import type { StageScript, StageBeat, CastPlacement, StagePropSpec } from "@/lib/rpgStage";

const C = (role: string, dx: number, pose?: string, extra: Partial<CastPlacement> = {}): CastPlacement =>
  ({ role, dx, pose, ...extra });
const P = (kind: string, dx: number, scale = 1, fire?: number, dy?: number): StagePropSpec =>
  ({ kind, dx, scale, ...(fire != null ? { fire } : {}), ...(dy != null ? { dy } : {}) });
const b = (v: number, extra: Partial<StageBeat> = {}): StageBeat => ({ v, ...extra });
// VOZ DO CÉU — só em 9:3-9, a segunda aparição do SENHOR a Salomão. Sem
// mediador visível: nada de figura, nada de anjo — balão dourado e centralizado.
const dv = (v: number, q: string, extra: Partial<StageBeat> = {}): StageBeat =>
  b(v, { by: "deus", q, ...extra });

