// 1 REIS 13–14 — CENA VIVA. O ALTAR QUE SE FENDE em Betel, a MÃO DO REI que
// seca no ar, o CARVALHO da estrada, a mentira de um profeta velho, o LEÃO
// parado junto ao cadáver sem tocar nele — e, no capítulo seguinte, uma rainha
// disfarçada diante de um profeta CEGO que a chama pelo nome antes que ela
// abra a boca.
//
// 1Rs 13 — O HOMEM DE DEUS DE JUDÁ. Jeroboão está junto ao ALTAR de Betel,
// para queimar incenso, quando "por ordem do Senhor" chega de Judá um homem de
// Deus. Ele não fala ao rei: clama CONTRA O ALTAR. "Altar, altar! Assim diz o
// Senhor: Eis que um filho nascerá à casa de Davi, cujo nome será JOSIAS, o
// qual sacrificará sobre ti os sacerdotes dos altos que sobre ti queimam
// incenso, e ossos de homens se queimarão sobre ti" — uma profecia que só se
// cumpre TREZENTOS ANOS DEPOIS (2Rs 23:15-16), e que já vem com garantia
// datada: "Eis que o altar se fenderá, e a cinza, que nele está, se
// derramará". Jeroboão estende a mão de sobre o altar e grita "Pegai-o!" — e a
// mão que ele estendeu SECA no ar, e ele não pode tornar a trazê-la a si; e o
// altar se fende, e a cinza se derrama, exatamente como o sinal apontara. O
// rei que mandava prender agora suplica: "roga por mim, para que se me
// restitua a minha mão" — o homem de Deus ora, e a mão fica como dantes.
// Depois vem o convite ("vem comigo para casa, e conforta-te; e dar-te-ei um
// presente") e a recusa inteira, com a ordem que ele recebera na boca: "ainda
// que me desses metade da tua casa… não comerás pão nem beberás água; e não
// voltarás pelo caminho por onde vieste". E ele se vai POR OUTRO CAMINHO.
// Então entra a segunda metade do capítulo, que é a mais estranha da Bíblia
// inteira: em Betel morava um VELHO PROFETA. Os filhos lhe contam tudo, ele
// manda albardar um jumento, sai atrás do homem de Judá e o acha ASSENTADO
// DEBAIXO DE UM CARVALHO. Convida-o, é recusado, e então mente com a voz de
// Deus na boca: "também eu sou profeta como tu, e um anjo me falou por ordem
// do Senhor, dizendo: Faze-o voltar contigo à tua casa, para que coma pão e
// beba água" — e o texto fecha o versículo sem nenhum comentário moral, só com
// quatro palavras entre parênteses: "(porém mentiu-lhe)". O homem volta e
// come. E é ali, À MESA, que a palavra VERDADEIRA do Senhor vem — e vem sobre
// o próprio mentiroso, que tem de clamar contra o hóspede que ele mesmo
// enganou: "porquanto foste rebelde à ordem do Senhor… o teu cadáver não
// entrará no sepulcro de teus pais". No caminho de volta um LEÃO o encontra e
// o mata. E aqui a cena para: o cadáver estendido no caminho, O JUMENTO
// PARADO JUNTO A ELE e O LEÃO PARADO JUNTO AO CADÁVER — o leão não devorou o
// corpo nem despedaçou o jumento. Não é um acidente de estrada; é uma sentença
// executada e depois montada como quadro para quem passasse ver. O velho vai
// buscá-lo, o põe sobre o jumento, o pranteia ("Ah, irmão meu!"), o sepulta no
// SEU PRÓPRIO SEPULCRO e manda aos filhos: quando eu morrer, ponde os meus
// ossos junto aos ossos dele — "porque certamente se cumprirá o que pela
// palavra do Senhor exclamou contra o altar que está em Betel". E o capítulo
// fecha com o versículo mais frio de todos: depois de ver o altar fender-se,
// a mão secar e um profeta morrer, "nem depois destas coisas deixou Jeroboão o
// seu mau caminho".
//
// 1Rs 14 — O DISFARCE INÚTIL. ABIAS, filho de Jeroboão, adoece. O rei que
// levantou dois bezerros de ouro não manda consultar os seus bezerros: manda a
// mulher DISFARÇAR-SE e ir a SILÓ, à casa de AÍAS, o profeta que lhe anunciara
// o reino — com dez pães, bolos e uma botija de mel, como quem paga uma
// consulta de aldeia. Mas Aías "não podia ver, porque os seus olhos estavam já
// escurecidos por causa da sua velhice" — e o SENHOR já lhe dissera o que ela
// ia fazer: "há de ser que, entrando ela, fingirá ser outra". O disfarce é
// derrotado pelo RUÍDO DOS PÉS: ouvindo os passos à porta, o cego fala antes
// que ela se anuncie — "Entra, mulher de Jeroboão; por que te disfarças assim?
// Pois eu sou enviado a ti com duras novas". E as novas são a casa inteira:
// porque fizeste outros deuses e imagens de fundição e me lançaste para trás
// das tuas costas, o SENHOR lançará fora os descendentes de Jeroboão "como se
// lança fora o esterco"; e o sinal é imediato e doméstico — "entrando os teus
// pés na cidade, o menino morrerá" —, mas esse menino será o ÚNICO da casa a
// ter sepultura, "porquanto se achou nele coisa boa para com o Senhor Deus de
// Israel". Ela volta a Tirza, pisa o limiar da porta, e o menino morre. Depois
// o livro fecha as contas: vinte e dois anos de reinado, Jeroboão dorme com
// seus pais e Nadabe reina em seu lugar. E o quadro passa para JUDÁ, com
// ROBOÃO: o povo edifica altos, estátuas e imagens de Aserá "sobre todo o alto
// outeiro e debaixo de toda a árvore verde", e há sodomitas na terra. No
// quinto ano sobe SISAQUE, rei do Egito, contra Jerusalém, e "tomou os
// tesouros da casa do Senhor e os tesouros da casa do rei; e LEVOU TUDO" —
// inclusive os ESCUDOS DE OURO que Salomão fizera. Roboão manda fazer, em
// lugar deles, ESCUDOS DE COBRE, e entrega-os à guarda da porta; e toda vez
// que o rei entra na casa do Senhor os guardas os levam e depois os tornam à
// câmara. É o retrato exato de um reino em declínio: o ouro trocado por cobre,
// e a procissão continuando como se nada tivesse mudado.
//
// A VOZ DE DEUS — nestes dois capítulos Deus fala o tempo todo, e quase sempre
// por BOCA HUMANA. Em 1Rs 13 não há uma única voz do céu: a palavra que rasga
// o altar sai do HOMEM DE DEUS DE JUDÁ (`by:"homem"`, id `homem-de-deus-de-juda`,
// vv.2-3,8-9,16-17) e a sentença de morte sai do PROFETA VELHO DE BETEL
// (`by:"anciao"`, id `profeta-velho-de-betel`, vv.12-15,18,21-22,26-27,30-32).
// O v.20 é o eixo do capítulo: "a palavra do Senhor veio ao profeta que o
// tinha feito voltar" — o mediador da verdade é o mesmo homem que acabou de
// mentir, e por isso o balão dos vv.21-22 é DELE, com a glória subindo em cima
// de quem não a merecia. O anjo do v.18 NÃO entra em cena e NÃO tem balão: é
// um anjo citado dentro de uma mentira, e desenhá-lo seria dar corpo à mentira
// — ali a glória CAI em vez de subir. Em 1Rs 14 há um único momento sem
// mediador visível: o v.5, "porém o Senhor disse a Aías", com o profeta cego
// sozinho na casa de Siló — `by:"deus"`, glória alta, nenhuma figura. Tudo o
// que vem depois (vv.6-16), embora seja "assim diz o Senhor Deus de Israel", é
// AÍAS falando (`by:"homem"`, id `aias-silonita`).
//
// O LEÃO NÃO TEM PROP — e é de propósito. O motor não ilustra leão, e etiquetar
// um `rebanho` ou um `calf` no lugar dele mentiria duas vezes (`calf` é ídolo
// fundido, `rebanho` é gado manso). A cena dos vv.24-25,28 é contada pelo
// ENQUADRAMENTO, que é justamente o que o texto sublinha: o cadáver em `lie`
// no meio do caminho, o `donkey` PARADO ao lado sem fugir, `night` no alto e
// `storm` em ZERO — nada se mexe. A imobilidade é o milagre; um bicho desenhado
// destruiria exatamente o que o versículo quer dizer.
// ============================================================================

import type { StageScript, StageBeat, CastPlacement, StagePropSpec } from "@/lib/rpgStage";

const C = (role: string, dx: number, pose?: string, extra: Partial<CastPlacement> = {}): CastPlacement =>
  ({ role, dx, pose, ...extra });
const P = (kind: string, dx: number, scale = 1, fire?: number, dy?: number): StagePropSpec =>
  ({ kind, dx, scale, ...(fire != null ? { fire } : {}), ...(dy != null ? { dy } : {}) });
const b = (v: number, extra: Partial<StageBeat> = {}): StageBeat => ({ v, ...extra });
// voz do céu — usada UMA única vez nestes dois capítulos (14:5), quando o
// SENHOR fala a Aías sem mediador visível nenhum. Ver "A VOZ DE DEUS" acima.
const dv = (v: number, extra: Partial<StageBeat> = {}): StageBeat => b(v, { by: "deus", ...extra });

