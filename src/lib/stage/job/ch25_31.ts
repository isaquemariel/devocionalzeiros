// JÓ 25–31 — CENA VIVA. O FIM DO DEBATE E A DEFESA FINAL. Sete capítulos em que
// o cerco se desmancha: o terceiro discurso de Bildade tem SEIS versículos e
// acaba a meio, Zofar já não abre a boca, e a partir daí é Jó sozinho até à
// última linha — "acabaram-se as palavras de Jó". Nenhum dos quatro se levanta
// da cinza, e por isso o palco NÃO mostra quatro homens sentados cento e
// sessenta e sete vezes: mostra o que a fala VÊ. A lua que não resplandece, a
// terra suspensa sobre o nada, as colunas do céu que tremem, a serpente
// enroscadiça, a casa da traça, a cabana do guarda, o vento oriental, a veia da
// prata, o poço de mina cortado longe dos homens, o mineiro pendurado a
// oscilar, a vereda que a ave de rapina ignora, o abismo e o mar que respondem
// "não está em mim", o peso dado ao vento, a lâmpada sobre a cabeça, a rocha
// que corria ribeiros de azeite, a cadeira na rua, os olhos do cego e os pés do
// coxo, os cães do rebanho, as malvas e as raízes dos zimbros, o rosto em que
// se cospe, a lama, a harpa que virou luto, as balanças fiéis e os cardos em
// vez de trigo. O falante fica na BORDA do quadro; a imagem dele ocupa o centro.
//
// JÓ 25 — BILDADE, O SUÍTA, PELA TERCEIRA VEZ, e o discurso mais curto do
// livro: seis versículos, e nem um argumento novo. "Com ele estão domínio e
// temor; ele faz paz nas suas alturas." Pergunta se as tropas do Todo-Poderoso
// têm número e sobre quem não se levanta a sua luz — e então repete, pela
// terceira vez no livro, a única coisa que os três sabem dizer: "como, pois,
// seria justo o homem para com Deus, e como seria puro aquele que nasce de
// mulher?" O fecho é o degrau em que o debate se despenha: "eis que até a LUA
// não resplandece, e as ESTRELAS não são puras aos seus olhos. E quanto menos o
// homem, que é um VERME, e o filho do homem, que é um VERMEZINHO!" Depois desta
// frase o suíta cala-se, e nem ele nem Zofar tornam a falar no livro inteiro.
//
// JÓ 26 — JÓ RESPONDE AO POUCO QUE SOBROU, e começa com a ironia mais afiada do
// livro: "como ajudaste aquele que não tinha força, e sustentaste o braço que
// não tinha vigor? Como aconselhaste aquele que não tinha sabedoria… A quem
// proferiste palavras, e de quem é o espírito que saiu de ti?" E então, como
// quem mostra ao amigo o que é falar de Deus a sério, sobe num hino cósmico de
// dez versículos: os MORTOS que tremem debaixo das águas com os seus
// moradores; o INFERNO nu perante ele, e sem coberta para a perdição; o NORTE
// estendido sobre o vazio e A TERRA SUSPENSA SOBRE O NADA; as águas presas nas
// nuvens sem que a nuvem se rasgue; a face do trono encoberta pela sua própria
// nuvem; o limite marcado em redor sobre a superfície das águas, até aos
// confins da luz e das trevas; AS COLUNAS DO CÉU QUE TREMEM e se espantam da
// sua ameaça; o mar fendido pela sua força; e a mão que ornou os céus e formou
// A SERPENTE ENROSCADIÇA. E o remate, que é o verso mais humilde do livro:
// "eis que isto são apenas as ORLAS dos seus caminhos; e quão pouco é o que
// temos ouvido dele! Quem, pois, entenderia o trovão do seu poder?"
//
// JÓ 27 — JÓ JURA. "Vive Deus, que desviou a minha causa, e o Todo-Poderoso,
// que amargurou a minha alma" — o juramento mais estranho da Bíblia, feito pela
// vida daquele mesmo que ele acusa. "Enquanto em mim houver alento, e o sopro
// de Deus nas minhas narinas, não falarão os meus lábios iniqüidade… até que eu
// expire, NUNCA APARTAREI DE MIM A MINHA INTEGRIDADE. À minha justiça me
// apegarei e não a largarei." Depois vira-se para a doutrina dos amigos e
// entrega-lhes o quinhão do ímpio com as próprias mãos deles: os filhos que se
// multiplicam para a ESPADA; os que ficarem enterrados na morte e as viúvas que
// não chorarão; a PRATA amontoada como pó e as roupas aparelhadas como lodo —
// que o justo é que vestirá e o inocente é que repartirá; a casa edificada COMO
// A TRAÇA e como A CABANA QUE O GUARDA FAZ; o rico que se deita e não será
// recolhido, abre os olhos e nada tem; os pavores que o tomam como águas e a
// tempestade que o arrebata de noite; O VENTO ORIENTAL que o leva e o varre com
// ímpeto do seu lugar; e o fim, que é uma vaia: "cada um baterá palmas contra
// ele e assobiará tirando-o do seu lugar".
//
// JÓ 28 — O POEMA DA SABEDORIA, e o capítulo mais desenhável do livro inteiro.
// Ninguém o contesta, ninguém responde, e ele não pertence ao debate: é uma
// descida à MINA. Há veios de onde se extrai a prata e lugar onde se refina o
// ouro; o ferro tira-se da terra e da pedra se funde o cobre. O homem PÕE FIM
// ÀS TREVAS e esquadrinha toda a extremidade, a pedra da escuridão e a da
// sombra da morte; ABRE UM POÇO DE MINA LONGE DOS HOMENS, em lugares esquecidos
// do pé, e ali fica pendente, oscilando de um lado para outro. Da terra procede
// o pão, mas por baixo é revolvida como por fogo; as suas pedras são o lugar da
// SAFIRA e tem pó de ouro. Essa vereda A AVE DE RAPINA A IGNORA e não a viram
// os olhos da gralha; nunca a pisaram filhos de animais altivos nem o feroz
// LEÃO passou por ela. Ele estende a mão contra o rochedo e revolve os montes
// desde as raízes; dos rochedos faz sair RIOS, e depois OS RIOS TAPA, e nem uma
// gota sai deles. Tudo isto o homem faz — e então vem a pergunta que o capítulo
// existe para fazer: "PORÉM ONDE SE ACHARÁ A SABEDORIA?" O ABISMO diz: não está
// em mim; e o MAR diz: ela não está comigo. Não se dá por ouro fino nem por
// prata pesada, nem pelo ouro de OFIR, nem pelo ônix, nem pela safira, nem pelo
// cristal, nem por CORAL nem PÉROLAS nem RUBIS nem pelo TOPÁZIO DA ETIÓPIA. Só
// Deus entende o seu caminho, porque ele vê as extremidades da terra: QUANDO
// DEU PESO AO VENTO E TOMOU A MEDIDA DAS ÁGUAS, quando prescreveu leis para a
// chuva e caminho para o relâmpago dos trovões, então a viu e a relatou. E
// disse ao homem a única definição que o livro dá: "EIS QUE O TEMOR DO SENHOR É
// A SABEDORIA, E APARTAR-SE DO MAL É A INTELIGÊNCIA."
//
// JÓ 29 — A LEMBRANÇA. "Ah! quem me dera ser como eu fui nos meses passados,
// como nos dias em que Deus me guardava! QUANDO FAZIA RESPLANDECER A SUA
// LÂMPADA SOBRE A MINHA CABEÇA, e quando eu pela sua luz caminhava pelas
// trevas." O segredo de Deus sobre a sua tenda, o Todo-Poderoso ainda com ele e
// os filhos em redor; OS PASSOS LAVADOS NA MANTEIGA e A ROCHA que lhe corria
// ribeiros de AZEITE. E o quadro de que o capítulo vive: "quando eu saía para a
// PORTA DA CIDADE, e na rua fazia preparar a minha CADEIRA — os moços me viam e
// se escondiam, e até os idosos se levantavam e se punham em pé; os príncipes
// continham as suas palavras e punham a mão sobre a sua boca; a voz dos nobres
// se calava". Ele livrava o miserável que clamava e o órfão sem socorro, fazia
// rejubilar o coração da VIÚVA, vestia-se da JUSTIÇA como manto e diadema, e
// era OS OLHOS DO CEGO E OS PÉS DO COXO. Dizia: "no meu NINHO expirarei, e
// multiplicarei os meus dias como a AREIA" — a raiz estendida junto às águas, o
// orvalho sobre os ramos, o ARCO que se reforçava na mão. E o fecho:
// "assentava-me como chefe, e habitava como rei entre as suas tropas".
//
// JÓ 30 — E TUDO SE INVERTE, no MESMO PORTÃO. "Agora, porém, se riem de mim os
// de MENOS IDADE DO QUE EU, cujos pais eu teria desdenhado de pôr com OS CÃES
// DO MEU REBANHO." Gente esgotada de míngua e fome, recolhida para lugares
// secos, tenebrosos, assolados e desertos, que APANHAVA MALVAS junto aos
// arbustos e comia RAÍZES DE ZIMBRO, expulsa do meio dos homens com gritaria de
// ladrão, a habitar nos barrancos dos vales e nas cavernas das rochas, a bramar
// entre os arbustos e a ajuntar-se debaixo das urtigas. "Agora sou a sua
// canção, e lhes sirvo de provérbio. Abominam-me, e fogem para longe de mim, e
// NO MEU ROSTO NÃO SE PRIVAM DE CUSPIR." A corda desatada e o freio sacudido;
// os moços que se levantam à direita e lhe empurram os pés; o caminho
// desbaratado; os que vêm como POR UMA GRANDE BRECHA; a honra perseguida como
// VENTO e a felicidade que passou como NUVEM; os ossos traspassados de noite; a
// veste desfigurada que o cinge como a gola da túnica; "LANÇOU-ME NA LAMA, e
// fiquei semelhante ao PÓ E À CINZA". E então a frase mais nua do livro:
// "CLAMO A TI, PORÉM, TU NÃO ME RESPONDES; ESTOU EM PÉ, PORÉM, PARA MIM NÃO
// ATENTAS." Ele lembra que chorou sobre o aflito e se angustiou pelo
// necessitado, e conclui: "aguardando eu o bem, então me veio o mal, esperando
// eu a luz, veio a escuridão"; irmão dos chacais e companheiro dos avestruzes;
// e "A MINHA HARPA SE TORNOU EM LUTO, E O MEU ÓRGÃO EM VOZ DOS QUE CHORAM".
//
// JÓ 31 — O JURAMENTO DE INOCÊNCIA: quarenta versículos de "se eu fiz isto, que
// me aconteça aquilo", e cada "se" é um quadro. A ALIANÇA COM OS OLHOS para não
// os fixar numa virgem; AS BALANÇAS FIÉIS em que ele pede para ser pesado; o
// passo desviado do caminho e a coisa apegada às mãos — "então semeie eu e
// outro coma"; o coração seduzido por uma mulher e a traição armada à PORTA DO
// PRÓXIMO; O DIREITO DO SERVO E DA SERVA que ele não desprezou — "aquele que me
// formou no ventre não o fez também a ele?"; os olhos da viúva que ele não fez
// desfalecer e O BOCADO que não comeu sozinho; o que perece por falta de ROUPA
// e os lombos que se aquentavam com AS PELES DOS SEUS CORDEIROS; a mão nunca
// levantada contra o órfão na porta; O OURO em que não pôs a esperança; O SOL
// que resplandece e A LUA caminhando gloriosa, e a boca que teria beijado a
// mão; a alegria que não teve com a desgraça do inimigo; AS PORTAS ABERTAS AO
// VIANDANTE, porque "o estrangeiro não passava a noite na rua"; a transgressão
// que ele não encobriu COMO ADÃO. E a assinatura, que é o pedido de um processo
// formal: "Ah! quem me dera um que me ouvisse! Eis que o meu desejo é que o
// Todo-Poderoso me responda, e que o meu adversário ESCREVA UM LIVRO. Por certo
// que o levaria sobre o meu OMBRO, sobre mim o ataria por COROA." E o fecho, que
// é a terra a depor: se os seus sulcos chorarem contra ele, "POR TRIGO ME
// PRODUZA CARDOS, E POR CEVADA JOIO. ACABARAM-SE AS PALAVRAS DE JÓ."
//
// A VOZ DE DEUS — nestes sete capítulos DEUS NÃO FALA UMA ÚNICA VEZ, e por isso
// não há nenhum `by:"deus"` em nenhum destes cento e sessenta e sete beats. É
// de propósito, e é a mesma regra do primeiro ciclo levada ao extremo: Jó jura
// PELA VIDA de Deus (27:2), pede que o Todo-Poderoso lhe responda (31:35) e
// grita-lhe na cara "clamo a ti, porém, tu não me respondes" (30:20) — e o céu
// continua calado até 38:1. Um balão dourado aqui arruinaria a construção
// inteira. Os únicos balões são de BILDADE (25) e de JÓ (26–31), e ambos são
// `patriarca`: por isso o `by` é sempre o `id` (`by:"bildade-o-suita"`,
// `by:"jo"`) e nunca o papel. Onde a fala descreve o que Deus faz — a terra
// suspensa, as colunas do céu, o mar fendido, o peso dado ao vento — a cena
// mostra a OBRA e nunca o Obreiro. E onde o texto põe boca em coisa nenhuma
// ("o abismo diz… e o mar diz", 28:14; "a perdição e a morte dizem", 28:22), o
// balão continua a ser de Jó, que é quem está a citá-las: o quadro é o abismo e
// o mar, e o crédito da voz é dele.
