// A VOZ DE DEUS — nestes sete capítulos DEUS NÃO FALA UMA ÚNICA VEZ, e por isso
// não há UM SÓ `by:"deus"` nestes cento e sessenta e oito beats, exatamente
// como no bloco anterior. É a regra da CLAUDE.md aplicada ao avesso: Zofar
// DESEJA que Deus fale ("quem dera que Deus falasse e abrisse os seus lábios
// contra ti", 11:5) e o céu continua fechado; Jó exige um tribunal e chama por
// nome ("chama, pois, e eu responderei", 13:22) e ninguém chama; em 16:19 ele
// diz que a sua testemunha ESTÁ no céu — e o quadro mostra o céu alto e vazio,
// com a glória subindo sobre a cabeça de um homem que não vê nada. Um balão
// dourado em qualquer um destes lugares roubaria do livro a coisa que ele está
// a construir. Onde a fala descreve o que Deus FAZ — as alturas e as
// profundezas de 11:8, o que derruba e ninguém edifica de 12:14, os
// conselheiros despojados, as águas que gastam as pedras — a cena mostra
// sempre a OBRA e nunca o Obreiro: a montanha, o casario caído, o cinto do rei
// desatado, a laje cavada pela água, e o falante pequeno na borda a olhar
// aquilo. E onde o texto põe um adversário com dentes e flechas (16:9-14), o
// que entra em cena são os HOMENS que zombam e os flecheiros — figuras de
// carne, jamais uma figura de Deus.
