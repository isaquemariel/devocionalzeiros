// JÓ 4–10 — CENA VIVA. O PRIMEIRO CICLO. Sete dias e sete noites de silêncio
// acabaram, Jó abriu a boca e amaldiçoou o seu dia — e agora os que vieram
// consolar começam a falar. São quatro discursos encaixados: Elifaz (4–5), Jó
// (6–7), Bildade (8), Jó outra vez (9–10). Nenhum deles se levanta do chão da
// cinza, e por isso o palco NÃO mostra quatro homens sentados cento e setenta e
// oito vezes: mostra o que a fala VÊ. O leão velho no covil, o espírito que
// passa na noite, a fagulha que sobe da fogueira, a molhada de trigo recolhida
// a seu tempo, o ribeiro que seca debaixo das caravanas de Temá, a cama em que
// a noite não acaba, o junco no lodo, a teia de aranha, a planta arrancada do
// jardim, os montes removidos, as estrelas seladas, o navio veleiro, a águia
// que se lança, o barro nas mãos que o formaram, o leite e o queijo. O falante
// fica na BORDA do quadro; a imagem dele ocupa o centro.
//
// JÓ 4 — ELIFAZ, O TEMANITA, fala primeiro, e começa com a cortesia mais
// educada da Bíblia: "Se intentarmos falar-te, enfadar-te-ás? Mas quem poderia
// conter as palavras?" Lembra-lhe o que ele foi — "eis que ensinaste a muitos,
// e tens fortalecido as mãos fracas… as tuas palavras firmaram os que
// tropeçavam" — e então vira a faca com uma pergunta: "qual é o inocente que
// jamais pereceu?" A doutrina dele cabe num sulco de arado: "os que lavram
// iniqüidade, e semeiam mal, segam o mesmo", e com o sopro da ira de Deus se
// consomem. Vem o leão — o rugido, a voz do leão feroz, os dentes dos
// leõezinhos quebrados, o leão velho que perece por falta de presa e os filhos
// da leoa dispersos —, e vem a peça de que ele mais se orgulha: A VISÃO
// NOTURNA. "Uma coisa me foi trazida em segredo; e os meus ouvidos perceberam
// um sussurro dela… entre pensamentos vindos de visões da noite, quando cai
// sobre os homens o sono profundo… então um espírito passou por diante de mim;
// FEZ-ME ARREPIAR OS CABELOS DA MINHA CARNE. Parou ele, porém não conheci a sua
// feição; um vulto estava diante dos meus olhos; houve silêncio, e ouvi uma
// voz." E a voz diz o argumento do capítulo inteiro: se Deus nem nos seus anjos
// confia, quanto menos nos que habitam em CASAS DE LODO, cujo fundamento está
// no pó, e são esmagados como a traça.
//
// JÓ 5 — o mesmo homem, e agora com exemplos. O louco que ele viu lançar raízes
// e cuja habitação amaldiçoou logo; os filhos desse louco despedaçados às
// portas, sem quem os livre; a messe que o faminto devora e tira até dentre os
// espinhos. A imagem que fica é da fogueira: "o homem nasce para a tribulação,
// COMO AS FAÍSCAS SE LEVANTAM PARA VOAR". Depois o hino do Deus que dá a chuva
// sobre a terra e envia águas sobre os campos, que põe os abatidos num lugar
// alto, que apanha os sábios na sua própria astúcia e faz com que ao meio-dia
// andem às apalpadelas como de noite. E o verso pelo qual este capítulo é
// lembrado: "bem-aventurado é o homem a quem Deus repreende… PORQUE ELE FAZ A
// CHAGA, E ELE MESMO A LIGA". Seis angústias e a sétima, a fome, a espada, o
// açoite da língua, as feras do campo em paz contigo, as pedras do campo em
// acordo contigo, a tenda em paz, a descendência como a erva — e o fecho, que é
// uma colheita: "na velhice irás à sepultura, COMO SE RECOLHE O FEIXE DE TRIGO
// A SEU TEMPO. Eis que isto já o havemos inquirido, e assim é."
//
// JÓ 6 — JÓ RESPONDE, e a primeira coisa que pede é uma balança: "Oh! se a
// minha mágoa retamente se pesasse, e a minha miséria juntamente se pusesse
// numa balança! Porque, na verdade, mais pesada seria, DO QUE A AREIA DOS
// MARES." As flechas do TodoPoderoso estão nele e o ardente veneno delas suga o
// seu espírito. Ele pergunta se o jumento montês zurra junto à relva e se o boi
// muge junto ao seu pasto — bicho satisfeito não grita; e se alguém come sem
// sal o que é insípido, ou acha gosto na clara do ovo. E então a grande imagem
// do capítulo, que é sobre os amigos: "MEUS IRMÃOS ALEIVOSAMENTE ME TRATARAM,
// COMO UM RIBEIRO, como a torrente dos ribeiros que passam" — encobertos de
// geada, com a neve escondida por baixo, e que no tempo do calor se derretem,
// se desfazem e desaparecem do seu lugar. Os caminhantes de Temá olham para
// eles, os passageiros de Sabá esperam por eles, sobem ao vácuo e perecem: e
// "ficam envergonhados, POR TEREM CONFIADO". No fim ele os desafia a mostrar-lhe
// o erro — "ensinai-me, e eu me calarei" — e acusa: "lançais sortes sobre o
// órfão; e cavais uma cova para o amigo".
//
// JÓ 7 — o mesmo discurso, virado de Deus para cima. "Porventura não tem o
// homem guerra sobre a terra? E não são os seus dias como os dias do
// jornaleiro?" — o servo que suspira pela sombra, o jornaleiro que espera pela
// sua paga. Meses de vaidade por herança e noites de trabalho preparadas: "mas
// comprida é a noite, e farto-me de me revolver na cama até à alva". A carne
// vestida de vermes e de torrões de pó, a pele gretada. Os dias mais velozes do
// que A LANÇADEIRA DO TECELÃO. A vida como o vento, a nuvem que se desfaz e
// passa, e aquele que desce à sepultura e nunca mais torna à sua casa. "Sou eu
// porventura o mar, ou a baleia, PARA QUE ME PONHAS UMA GUARDA?" Os sonhos que
// o espantam e as visões que o assombram, justamente na cama que devia
// consolá-lo. E o parafraseado amargo do salmo oitavo: "QUE É O HOMEM, para que
// tanto o engrandeças, e ponhas nele o teu coração, e cada manhã o visites?" —
// até que engula a saliva; e no fim, "agora me deitarei no pó, e de madrugada
// me buscarás, e não existirei mais".
//
// JÓ 8 — BILDADE, O SUÍTA: o discurso mais curto do ciclo e o mais duro. "Até
// quando falarás tais coisas, e as palavras da tua boca serão como um VENTO
// IMPETUOSO?" Ele não tem escrúpulo nenhum em usar os dez mortos: "se teus
// filhos pecaram contra ele, também ele os lançou na mão da sua transgressão".
// A saída que oferece é de madrugada: buscar a Deus, pedir misericórdia, e o
// último estado crescerá em extremo. A autoridade dele é a antiguidade —
// pergunta às gerações passadas, "porque nós somos de ontem, e nada sabemos;
// porquanto nossos dias sobre a terra são como a sombra". E vêm as três plantas
// que sustentam o capítulo: o JUNCO que não cresce sem lodo e a ESPADANA sem
// água, que ainda no seu verdor, não cortada, se seca antes de qualquer outra
// erva; a TEIA DE ARANHA, que é a confiança do hipócrita — "encostar-se-á à sua
// casa, mas ela não subsistirá"; e a PLANTA VIÇOSA perante o sol, cujos renovos
// saem sobre o jardim e cujas raízes se entrelaçam junto à fonte, mas que,
// consumida do seu lugar, é negada por ele: "Nunca te vi!" — "eis que este é a
// alegria do seu caminho, E OUTROS BROTARÃO DO PÓ".
//
// JÓ 9 — JÓ RESPONDE OUTRA VEZ, e o capítulo é cósmico. Ele concede tudo:
// "como se justificaria o homem para com Deus? Se quiser contender com ele, nem
// a uma de mil coisas lhe poderá responder." Aquele que remove os montes sem
// que o saibam e os transtorna no seu furor; que sacode a terra do seu lugar e
// as colunas dela estremecem; QUE FALA AO SOL E ELE NÃO NASCE, e sela as
// estrelas; que sozinho estende os céus e anda sobre os altos do mar; QUE FEZ A
// URSA, O ÓRION, E O SETE-ESTRELO, e as recâmaras do sul. "Eis que ele passa
// por diante de mim, e não o vejo; e torna a passar perante mim, e não o
// sinto." Os dias mais velozes do que um correio, que passam como NAVIOS
// VELEIROS, como ÁGUIA QUE SE LANÇA À COMIDA. "Ainda que me lave com água de
// neve, e purifique as minhas mãos com sabão, ainda me submergirás no fosso, e
// as minhas próprias vestes me abominarão." E a frase que fica, e que é o
// buraco no meio do livro: "porque ele não é homem, como eu, a quem eu responda,
// vindo juntamente a juízo. NÃO HÁ ENTRE NÓS ÁRBITRO QUE PONHA A MÃO SOBRE NÓS
// AMBOS."
//
// JÓ 10 — e então ele para de argumentar e fala com Deus na cara. "A minha alma
// tem tédio da minha vida… parece-te bem que me oprimas, que rejeites o
// trabalho das tuas mãos? TENS TU PORVENTURA OLHOS DE CARNE? VÊS TU COMO VÊ O
// HOMEM?" E vem a parte mais terna e mais terrível do primeiro ciclo, que é uma
// oficina: "AS TUAS MÃOS ME FIZERAM E ME FORMARAM completamente; contudo me
// consomes. Peço-te que te lembres de que COMO BARRO ME FORMASTE e me farás
// voltar ao pó. Porventura não me vazaste como leite, e como queijo não me
// coalhaste? DE PELE E CARNE ME VESTISTE, E DE OSSOS E NERVOS ME TECESTE." Ele
// reconhece o cuidado — "vida e misericórdia me concedeste" — e desconfia dele
// no mesmo fôlego. Vem a caçada: "tu me caças como a um leão feroz", as
// testemunhas renovadas, os reveses e o combate. E o fim, que é um pedido de
// trégua e um endereço: "porventura não são poucos os meus dias? Cessa, pois, e
// deixa-me, para que por um pouco eu tome alento; antes que eu vá para o lugar
// de que não voltarei, À TERRA DA ESCURIDÃO E DA SOMBRA DA MORTE; terra
// escuríssima… e onde a luz é como a escuridão."
//
// A VOZ DE DEUS — nestes sete capítulos DEUS NÃO FALA UMA ÚNICA VEZ, e por isso
// NÃO HÁ NENHUM `by:"deus"` em nenhum destes cento e setenta e oito beats. É de
// propósito, e é a regra da CLAUDE.md aplicada ao contrário: Jó fala COM Deus o
// tempo todo (7:12-21, 9:28-35, 10 inteiro) e o céu não responde — o silêncio é
// o assunto do primeiro ciclo, e um balão dourado aqui arruinaria o livro
// inteiro. A única coisa que se parece com revelação é a VISÃO NOTURNA DE
// ELIFAZ (4:12-16), e ela é DELE: o texto diz "os meus ouvidos perceberam", "um
// vulto estava diante dos MEUS olhos", "ouvi uma voz" — todo o balão de 4:12-21
// é `by:"elifaz-o-temanita"`, inclusive o de 4:17-21, que é ele repetindo o que
// diz ter ouvido. O vulto entra em cena como `anjo` COM `palette` escura e SEM
// `glow` (`espirito-que-passou-diante-de-elifaz`), pequeno e ao longe, porque o
// próprio Elifaz confessa que "não conheci a sua feição": é uma figura
// entrevista no escuro, não uma teofania. E onde Jó descreve o que Deus faz —
// os montes removidos, o sol que não nasce, as estrelas seladas, os céus
// estendidos, a Ursa e o Órion — a cena mostra a OBRA e nunca o Obreiro: o
// quadro é o monte, o céu vazio, o campo de estrelas, e Jó pequeno na borda
// olhando aquilo.
// ============================================================================

