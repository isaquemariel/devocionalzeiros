// ============================================================================
// JÓ 1–3 — CENA VIVA. O BLOCO DE ABERTURA, e o único do livro que é narrativa:
// um homem que era MAIOR DO QUE TODOS OS DO ORIENTE perde tudo em quatro
// notícias que chegam uma por cima da outra, senta-se na cinza fora do portão
// de Uz, e ali abre a boca pela primeira vez para amaldiçoar o seu dia. Daqui
// saem o vocabulário e os lugares que os outros seis blocos herdam: o MONTURO
// e a CINZA, o PORTÃO DE UZ, a CORTE CELESTIAL e o TRAJE DE SACO
// (`palette: "#6b5a4a"`, que apaga o traje próprio e a auréola) que Jó veste
// de 1:20 até 42:6.
//
// JÓ 1 — a terra de Uz, e um homem "íntegro, reto e temente a Deus" que se
// desviava do mal. Sete filhos e três filhas; sete mil ovelhas, três mil
// camelos, quinhentas juntas de bois, quinhentas jumentas e muitíssimos servos.
// Os filhos faziam banquetes cada um por sua vez, e o pai se levantava DE
// MADRUGADA e oferecia holocaustos segundo o número de todos eles, "porque
// dizia Jó: Porventura pecaram meus filhos" — ASSIM FAZIA JÓ CONTINUAMENTE.
// Então o quadro sobe: os filhos de Deus vêm apresentar-se perante o SENHOR, e
// SATANÁS vem entre eles — "De rodear a terra, e passear por ela". A acusação
// não é contra o homem, é contra a bondade do prêmio: "Porventura teme Jó a
// Deus DEBALDE? Porventura tu não cercaste de sebe, a ele, e a sua casa, e a
// tudo quanto tem?" A sebe é aberta, e descem as QUATRO NOTÍCIAS, cada uma
// chegando ENQUANTO A ANTERIOR AINDA FALA e cada uma acabando na mesma frase —
// "e só eu escapei para trazer-te a nova": os sabeus e os bois e as jumentas; o
// FOGO DE DEUS que caiu do céu e queimou as ovelhas e os servos; os caldeus em
// três tropas e os camelos; e o grande vento dalém do deserto que deu nos
// QUATRO CANTOS DA CASA e a fez cair sobre os jovens. Jó levanta-se, rasga o
// manto, rapa a cabeça, lança-se em terra e ADORA: "nu saí do ventre de minha
// mãe e nu tornarei para lá; o Senhor o deu, e o Senhor o tomou: bendito seja o
// nome do Senhor". E o capítulo fecha seco: "Em tudo isto Jó não pecou".
//
// JÓ 2 — a segunda corte, e a acusação encurtada: "e ainda retém a sua
// sinceridade". "PELE POR PELE, e tudo quanto o homem tem dará pela sua vida."
// Satanás sai da presença do SENHOR e fere Jó de úlceras malignas DESDE A
// PLANTA DO PÉ ATÉ AO ALTO DA CABEÇA. E então nasce o lugar em que o livro
// inteiro se passa: Jó toma um CACO para se raspar e ASSENTA-SE NO MEIO DA
// CINZA, fora do portão. A mulher diz a coisa mais curta e mais dura do
// capítulo — "Ainda reténs a tua sinceridade? Amaldiçoa a Deus, e morre" — e
// ele responde com a pergunta que ninguém mais no livro repete: "receberemos o
// bem de Deus, e não receberíamos o mal?" Vêm de longe os três amigos, cada um
// do seu lugar: ELIFAZ o temanita, BILDADE o suíta e ZOFAR o naamatita. De
// longe levantam os olhos E NÃO O CONHECEM; choram, rasgam os mantos, lançam pó
// ao ar sobre as cabeças — e assentam-se com ele na terra SETE DIAS E SETE
// NOITES sem lhe dizer palavra alguma, "porque viam que a dor era muito grande".
//
// JÓ 3 — depois de sete dias de silêncio, Jó abre a boca. Não amaldiçoa a Deus:
// amaldiçoa O SEU DIA. E o capítulo inteiro é imagem de trevas — o dia que se
// converta em trevas e não resplandeça sobre ele a luz; as nuvens que habitem
// sobre ele; a noite de que se apodere a escuridão e que não entre no número
// dos meses; as estrelas do crepúsculo que se escureçam, a luz que se espere e
// não venha, as pálpebras da alva que não se vejam. Depois vira para o outro
// lado e conta o SOSSEGO que a morte teria sido: os reis e conselheiros da
// terra que edificam casas nos lugares assolados, os príncipes que enchem as
// casas de prata, o aborto oculto — "ALI os maus cessam de perturbar, e ali
// repousam os cansados; ali os presos juntamente repousam e não ouvem a voz do
// exator; ali está o pequeno e o grande, e o servo livre de seu senhor". E o
// fecho, que é a chave de leitura do livro todo: "porque aquilo que temia me
// sobreveio, e o que receava me aconteceu. Nunca estive tranqüilo, nem
// sosseguei, nem repousei, mas veio sobre mim a perturbação".
//
// A VOZ DE DEUS — nestes três capítulos Deus fala QUATRO vezes (1:8, 1:12, 2:3,
// 2:6) e as quatro são na CORTE CELESTIAL, onde NÃO HÁ MEDIADOR VISÍVEL: é a
// voz do céu pura, `by: "deus"`, com `terrain: "glory"` e `glory` no auge, e
// Deus NÃO é desenhado — o que se vê é o trono vazio diante do qual os filhos
// de Deus se apresentam. Satanás está lá em cena e responde a essa voz, mas ele
// NÃO fala da parte de Deus: é `anjo` (ele vem entre os filhos de Deus, é da
// corte) com `palette: "#3a3546"`, que lhe tira a veste branca E A AURÉOLA — é
// assim que o adversário fica reconhecível sem ser desenhado como monstro, e é
// por isso que aqui ele não é `dragao` nem `serpente`. Fora da corte, ninguém
// fala pela boca de Deus: o "Fogo de Deus caiu do céu" de 1:16 é NOTÍCIA na
// boca de um mensageiro sobrevivente, e o balão é DELE, não do alto — o que
// domina o quadro é o traço do fogo (`campfire` grande), porque `env.fire` não
// desenha chama nenhuma. E em todo o capítulo 3 quem fala é JÓ: o palco mostra
// o que a fala VÊ (a noite, as casas assoladas dos reis, a cova que se cava, a
// sepultura que se acha com alegria) e Jó fica na BORDA do quadro, pequeno e
// curvado, olhando para dentro da própria imagem.
// ============================================================================

