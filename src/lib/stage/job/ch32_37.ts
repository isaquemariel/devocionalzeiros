// ============================================================================
// JÓ 32–37 — CENA VIVA. Os discursos de ELIÚ, filho de Baraquel, o buzita, da
// família de Rão: o quinto homem do monturo, que ninguém anunciou, que não
// veio com os três do capítulo 2 e que Deus não repreende no capítulo 42. O
// texto insiste em duas coisas sobre ele — esteve ali o tempo todo, CALADO, e
// é MOÇO. Por isso ele é `homem` entre quatro `patriarca`s: o único jovem no
// meio de quatro velhos, e é isso que o palco tem de mostrar.
//
// Jó 32 — A ENTRADA. "Então aqueles três homens cessaram de responder a Jó;
// porque era justo aos seus próprios olhos" — e o silêncio que se abre é a
// deixa de alguém que estava no fundo do quadro desde o capítulo 3. A ira de
// Eliú se acende duas vezes: contra Jó, "porque se justificava a si mesmo,
// mais do que a Deus", e contra os três amigos, "porque, não achando que
// responder, todavia condenavam a Jó". Ele explica por que esperou — "Eu sou
// de menos idade, e vós sois idosos" — e por que não espera mais: "Os grandes
// não são os sábios, nem os velhos entendem o que é direito". O capítulo
// termina na imagem mais física do bloco inteiro: "Eis que dentro de mim sou
// como o mosto, sem respiradouro, prestes a arrebentar, como odres novos". E
// o moço que arrebenta jura não bajular ninguém: "não sei usar de lisonjas;
// em breve me levaria o meu Criador".
//
// Jó 33 — AS DUAS MANEIRAS DE DEUS FALAR. Eliú chama Jó pelo nome, coisa que
// nenhum dos três fez, e se põe no mesmo barro: "Eis que vim de Deus, como
// tu; do barro também eu fui formado" — "não te perturbará o meu terror, nem
// será pesada sobre ti a minha mão". Cita Jó de cor ("Limpo estou, sem
// transgressão"; "Põe no tronco os meus pés, e observa todas as minhas
// veredas") e responde que Deus fala, sim, e de duas maneiras. A primeira é o
// SONHO: "Em sonho ou em visão noturna, quando cai sono profundo sobre os
// homens", quando ele abre o ouvido e SELA a instrução, "para apartar o homem
// daquilo que faz, e esconder do homem a soberba". A segunda é a DOR: "na sua
// cama é castigado com dores; e com incessante contenda nos seus ossos", a
// vida que abomina o pão, a carne que desaparece a olhos vistos e os ossos
// que não se viam e agora aparecem. E entre a cova e o homem entra o
// MENSAGEIRO INTÉRPRETE, "um entre milhares", com a palavra que fecha o
// capítulo: "Livra-o, para que não desça à cova; já achei resgate" — e a
// carne que se reverdece mais do que era na mocidade.
//
// Jó 34 — O TRIBUNAL. Eliú deixa de falar a Jó e fala aos SÁBIOS: "Porque o
// ouvido prova as palavras, como o paladar experimenta a comida". A tese é a
// justiça de Deus — "Longe de Deus esteja o praticar a maldade" — e o
// argumento mais assustador do bloco é um argumento de fôlego: "Se ele
// pusesse o seu coração contra o homem, e recolhesse para si o seu espírito e
// o seu fôlego, toda a carne juntamente expiraria, e o homem voltaria para o
// pó". Deus não faz acepção de príncipes, "nem estima o rico mais do que o
// pobre"; quebranta os fortes sem inquirição e põe outros no lugar deles; não
// há trevas nem sombra de morte onde se escondam os que praticam a
// iniquidade; e o clamor do pobre sobe até ele. O veredito sobre Jó é seco:
// "Jó falou sem conhecimento; e às suas palavras falta prudência".
//
// Jó 35 — O CAPÍTULO FRIO. O mais curto e o mais duro: "Atenta para os céus, e
// vê; e contempla as mais altas nuvens, que são mais altas do que tu. Se
// pecares, que efetuarás contra ele? … Se fores justo, que lhe darás?" O mal
// e o bem do homem atingem o homem, não o Altíssimo. Os oprimidos clamam por
// causa do braço dos grandes, mas ninguém faz a pergunta certa: "Onde está
// Deus que me criou, QUE DÁ SALMOS DURANTE A NOITE; que nos ensina mais do
// que aos animais da terra e nos faz mais sábios do que as aves dos céus?"
//
// Jó 36 — A VIRADA PARA O TEMPORAL. "Espera-me um pouco, e mostrar-te-ei que
// ainda há razões a favor de Deus." Deus é grande e a ninguém despreza; abre
// o ouvido do preso pela própria corda que o prende; e a quem ouve, "acabarão
// seus dias em bem", com a mesa cheia de gordura num lugar espaçoso onde não
// há aperto. Do v.27 em diante o discurso deixa de argumentar e vira HINO DA
// CHUVA — "faz miúdas as gotas das águas que, do seu vapor, derramam a
// chuva, a qual as nuvens destilam e gotejam sobre o homem abundantemente" —,
// as extensões das nuvens e os estalos da sua tenda, a luz estendida sobre
// elas e as profundezas do mar encobertas, e o gado que dá notícia do
// temporal que sobe.
//
// Jó 37 — O TROVÃO. Todo imagem, e todo vestíbulo do capítulo 38: "Sobre isto
// também treme o meu coração, e salta do seu lugar". A voz que é enviada por
// debaixo de todos os céus e a luz até aos confins da terra; a NEVE que
// recebe ordem — "Porque à neve diz: Cai sobre a terra" —, a garoa e a forte
// chuva; a mão de todo o homem selada, e as feras que entram nos seus
// esconderijos; o tufão da recâmara do sul e o frio do norte; a geada pelo
// sopro de Deus e as largas águas que se congelam; as nuvens que se espalham
// em redor para fazer o que ele ordena sobre a superfície do mundo. E o
// mandado: "A isto, ó Jó, inclina os teus ouvidos; PARA, e considera as
// maravilhas de Deus" — os céus firmes como espelho fundido, o esplendor de
// ouro que vem do norte, e o fecho: "Ao Todo-Poderoso não podemos alcançar;
// grande é em poder". No versículo seguinte já é o redemoinho que fala.
//
// A VOZ DE DEUS — NÃO HÁ NENHUM `by:"deus"` nestes seis capítulos, e isso é
// deliberado: Deus não abre a boca uma única vez de Jó 32 a Jó 37. Eliú fala
// SOBRE ele o tempo todo, inclusive quando reporta o que Deus diz no sonho
// (33:24) ou à neve (37:6) — a frase está dentro da boca do moço, e o balão
// continua sendo dele (`by:"eliu-filho-de-baraquel-o-buzita"`, sempre pelo
// `id`, nunca pelo papel, para o balão não cair no primeiro `homem` do
// elenco). O MENSAGEIRO INTÉRPRETE de 33:23 é o caso que mais tenta o erro:
// ele é `anjo` com `glow` no máximo e ocupa o CENTRO do quadro — mas é a
// imagem do que Eliú descreve, não uma aparição no monturo de Uz, e por isso
// o balão sai de Eliú, que está na borda a apontar para ele. O mesmo vale
// para toda a segunda metade do bloco: o trovão, a neve, o gelo e o
// redemoinho que se arma em 36-37 são o que a FALA vê. Deus só responderá em
// 38:1 — e é por isso que `env.storm` sobe capítulo a capítulo aqui, até o
// último beat de 37 entregar o palco já dentro do temporal.
//
// A DIREÇÃO — a regra deste bloco é a regra de Jó: o palco mostra o que a
// fala VÊ, não os cinco homens sentados. Eliú fica na BORDA (dx perto de
// ±300, dy baixo) e a imagem do versículo ocupa o centro; quando o versículo
// é abstrato, a cena volta ao monturo, mas a três monturos diferentes (o de
// meio-dia, o do cair da tarde e o que já está debaixo do temporal), com
// poses, posições e luz trocadas. Jó está de saco e cinza (`palette
// "#6b5a4a"`) o bloco inteiro e não tem um único balão; os três amigos já
// cessaram de responder e ficam em `bow`/`kneel`/`stand`, calados.
// ============================================================================

