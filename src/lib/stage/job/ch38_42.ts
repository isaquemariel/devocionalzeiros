// JÓ 38–42 — CENA VIVA. Depois de trinta e cinco capítulos de homens sentados
// na cinza a discutir, o SENHOR RESPONDE — e não responde nenhuma das perguntas
// de Jó. Responde com outras perguntas, e as perguntas são quase todas IMAGEM:
// o cordel estendido sobre a terra que ainda não existe, o mar que sai da madre
// e leva portas e ferrolhos, os tesouros da neve, a chuva no deserto onde não
// há ninguém, o Sete-estrelo, o covil do leão, o ninho da águia, o beemote na
// lama e o leviatã que faz do mar uma panela a ferver. É o trecho mais
// desenhável do livro inteiro, e aqui cada versículo é o seu próprio quadro.
//
// JÓ 38 — "Depois disto o SENHOR respondeu a Jó de um redemoinho". A primeira
// pergunta arrasa o pé do interrogado: "Onde estavas tu, quando eu fundava a
// terra? Faze-mo saber, se tens inteligência." Vêm as medidas e o cordel, as
// bases e a pedra de esquina, e o único versículo alegre da criação inteira —
// "quando as estrelas da alva juntas alegremente cantavam, e todos os filhos
// de Deus jubilavam". Depois o MAR, que rompeu e saiu da madre e recebeu
// nuvens por vestidura, escuridão por faixa, portas, ferrolhos e uma linha no
// chão: "Até aqui virás, e não mais adiante". A madrugada que pega nas
// extremidades da terra e sacode dela os ímpios; a terra que se transforma como
// o barro sob o selo. As origens do mar e o mais profundo do abismo; as portas
// da sombra da morte; as larguras da terra; a casa onde mora a luz e o lugar
// das trevas. Os tesouros da neve e da saraiva, RETIDOS até ao dia da peleja e
// da guerra. O leito aberto para a inundação e o caminho dos relâmpagos — "para
// chover sobre a terra, onde não há ninguém, e no deserto, em que não há
// homem", só "para fazer crescer os renovos da erva": Deus rega o que homem
// nenhum vai ver. As gotas do orvalho, o ventre de onde procedeu o gelo, o
// Sete-estrelo, os cordéis do Órion, a Ursa com seus filhos, os odres dos céus.
// E o capítulo desce dos astros para os bichos: a leoa à espreita nas covas, e
// os corvos, cujos filhotes GRITAM A DEUS e andam vagueando por não terem o que
// comer.
//
// JÓ 39 — o bestiário, um bicho por quadro, e todos eles são bichos que não
// servem para nada a ninguém. A cabra montesa que pare no rochedo e a cerva nas
// suas dores; os filhos que enrijam, saem e nunca mais tornam. O jumento montês
// a quem foi dado o ermo por casa e a terra salgada por morada, que RI-SE DO
// RUÍDO DA CIDADE e não ouve os gritos do condutor. O boi selvagem, que não
// fica no curral, não escava os vales atrás de ti e não recolhe nada na tua
// eira. A avestruz, que bate alegremente as asas, deixa os ovos na terra, os
// aquenta no pó e se esquece de que um pé os pode pisar — "porque Deus a privou
// de sabedoria" —, mas que, a seu tempo, se levanta ao alto e RI-SE DO CAVALO E
// DO QUE VAI MONTADO NELE. E o cavalo: o pescoço revestido de crinas, o
// respirar fogoso das ventas, a terra escavada, a aljava rangendo, a espada de
// que ele não torna atrás — "ao soar das buzinas diz: Eia! E cheira de longe a
// guerra, e o trovão dos capitàes, e o alarido". No fim, os dois voos: o gavião
// que estende as asas para o sul e a águia que põe no alto o seu ninho, mora na
// penha, avista a presa de longe — "e onde há mortos, ali está ela".
//
// JÓ 40 — "Porventura o contender contra o Todo-Poderoso é sabedoria?" E o
// homem que falou trinta capítulos responde em dois versículos: "Eis que sou
// vil; que te responderia eu? A MINHA MÃO PONHO À BOCA." Aí o redemoinho volta
// pela segunda vez, e a pergunta agora é sobre o juízo: "Porventura também
// tornarás tu vão o meu juízo, ou tu me condenarás, para te justificares?" —
// então orna-te de excelência e alteza, veste-te de majestade e de glória,
// derrama os furores da tua ira, olha para todo o soberbo e ABATE-O; "então
// também eu a ti confessarei que a tua mão direita te poderá salvar". E entra o
// BEEMOTE, que come a erva como o boi, cuja força está nos lombos, que move a
// cauda como cedro, cujos ossos são tubos de bronze, que se deita debaixo das
// árvores sombrias no esconderijo das canas e da lama — "eis que um rio
// transborda, E ELE NÃO SE APRESSA".
//
// JÓ 41 — trinta e quatro versículos para UM SÓ ANIMAL. O anzol, a corda na
// língua, o gancho na queixada; as súplicas que ele não fará e a aliança que
// não firmará; "brincarás com ele, como se fora um passarinho?". As fortes
// escamas do seu orgulho, "uma à outra se chega tão perto, que nem o ar passa
// por entre elas". Os espirros que fazem resplandecer a luz e os olhos como as
// pálpebras da alva; TOCHAS que saem da boca e faíscas de fogo; fumaça das
// narinas como de panela fervente; o hálito que incende os carvões. O coração
// firme como a mó de baixo; o ferro reputado por palha e o cobre por pau podre;
// a seta que não o faz fugir e as pedras das fundas que se lhe tornam em
// restolho. Faz ferver as profundezas como panela e torna o mar como vasilha de
// ungüento, e após si deixa UMA VEREDA LUMINOSA — "parece o abismo tornado em
// brancura de cãs". E o fecho: "na terra não há coisa que se lhe possa
// comparar… é rei sobre todos os filhos da soberba".
//
// JÓ 42 — Jó responde, e a resposta não é um argumento, é um par de olhos:
// "COM O OUVIR DOS MEUS OUVIDOS OUVI, MAS AGORA TE VÊEM OS MEUS OLHOS. POR ISSO
// ME ABOMINO E ME ARREPENDO NO PÓ E NA CINZA." Aí o SENHOR se vira para os
// consoladores: "A minha ira se acendeu contra ti, e contra os teus dois
// amigos, porque não falastes de mim o que era reto, COMO O MEU SERVO JÓ" —
// sete bezerros, sete carneiros, e o homem que eles acusaram durante trinta
// capítulos é quem tem de orar por eles. E o versículo dobradiça: "E o Senhor
// virou o cativeiro de Jó, QUANDO ORAVA PELOS SEUS AMIGOS". Vêm os irmãos e as
// irmãs e todos os que dantes o conheceram, comem pão com ele em sua casa, se
// condoem dele, e cada um lhe dá uma peça de dinheiro e um pendente de ouro.
// Catorze mil ovelhas, seis mil camelos, mil juntas de bois, mil jumentas; sete
// filhos e três filhas — Jemima, Quezia e Quéren-Hapuque —, "e em toda a terra
// não se acharam mulheres tão formosas como as filhas de Jó; e seu pai lhes deu
// herança entre seus irmãos". Cento e quarenta anos, quatro gerações, e a
// última linha: "Então morreu Jó, velho e farto de dias".
//
// A VOZ DE DEUS — em 38:1 e em 40:6 o texto diz que o SENHOR respondeu "de um
// redemoinho". O redemoinho é o MODO da voz, não um mensageiro: não há anjo,
// não há profeta, não há objeto que fale por Ele. Por isso os 105 beats de
// 38–41 e os dois de 42:7-8 são `by: "deus"` — o balão dourado, centralizado,
// SEM figura, exatamente como manda a CLAUDE.md para a voz sem mediador. E o
// traço do redemoinho é que domina o ambiente: `env.storm` no máximo, `clouds`
// grandes com `sky: true`, `night` médio-alto nos beats de moldura, e JÓ
// PEQUENO, na borda do quadro, curvado no pó (`scale` 0,7-0,85, `dy` alto,
// `palette: "#6b5a4a"` do saco e da cinza) enquanto o centro do palco é sempre
// a criatura ou o elemento de que a pergunta fala. Deus não é desenhado uma
// única vez; o que se vê é o mundo que Ele está a citar como testemunha.
// Quem fala fora disso é só Jó — 40:3-5 e 42:1-6, `by: "jo"`, em cena, curvado,
// e no versículo do arrependimento com a mão na boca e a glória a subir.
// A partir de 42:10 a `palette` do saco sai: o SENHOR virou o cativeiro, e o
// homem volta ao seu traje, à sua casa, à sua mesa e ao seu gado.
// ============================================================================

