// sete discursos: Bildade (18), Jó (19), Zofar (20), Jó (21), Elifaz (22), Jó
// (23) e Jó outra vez (24). Ninguém se levanta do chão da cinza, e por isso o
// palco NÃO mostra quatro homens sentados cento e oitenta e cinco vezes:
// mostra o que a fala VÊ. A lâmpada que se apaga na tenda, a corda escondida
// na vereda, o trono do rei dos terrores, a coroa caída da cabeça, a árvore
// arrancada pela raiz, a rocha em que as palavras seriam esculpidas com pena
// de ferro, o sonho que voa, o fel de áspides, os ribeiros de mel e manteiga,
// o arco de bronze, as crianças que saem saltando como um rebanho, os dois
// mortos lado a lado no mesmo pó, os penhores tomados aos irmãos, a altura
// das estrelas, o dilúvio sobre o fundamento, o tribunal a que Jó se chegaria,
// o ouro que sai do fogo, o jumento do órfão, os jumentos monteses que
// madrugam para a presa, o nu que abraça a rocha, o homicida de madrugada e o
// adúltero que espera o crepúsculo. O falante fica na BORDA do quadro; a
// imagem dele ocupa o centro.
//
// JÓ 18 — BILDADE, O SUÍTA, pela segunda vez, e é quase todo um só quadro: a
// ARMADILHA. Começa ofendido — "até quando poreis fim às palavras? Considerai
// bem, e então falaremos… por que somos tratados como animais, e como imundos
// aos vossos olhos?" — e pergunta se a terra será deixada por causa de Jó, se
// as rochas se removerão do seu lugar por ele. E então desenrola a caçada:
// "na verdade, A LUZ DOS ÍMPIOS SE APAGARÁ, e a chama do seu fogo não
// resplandecerá; a luz se escurecerá nas suas tendas, e a SUA LÂMPADA sobre
// ele se apagará". Os passos firmes se estreitarão e o próprio conselho o
// derrubará; "porque POR SEUS PRÓPRIOS PÉS é lançado na REDE, e andará nos
// fios enredados"; o LAÇO o apanhará pelo calcanhar e a ARMADILHA o prenderá;
// está escondida debaixo da terra uma CORDA, e uma armadilha na vereda. Os
// ASSOMBROS o espantarão de todos os lados e o perseguirão a cada passo; será
// faminto o seu vigor, e A DESTRUIÇÃO ESTÁ PRONTA AO SEU LADO; o PRIMOGÊNITO
// DA MORTE devorará os seus membros; a sua confiança será arrancada da tenda
// e isto o fará caminhar PARA O REI DOS TERRORES. Morará na sua tenda o que
// não lhe pertence, e ESPALHAR-SE-Á ENXOFRE sobre a sua habitação; por baixo
// se secarão as raízes e por cima serão cortados os ramos; A SUA MEMÓRIA
// PERECERÁ DA TERRA, e pelas praças não terá nome; da luz o lançarão nas
// trevas; não terá filho nem neto entre o seu povo; do seu dia se espantarão
// os do ocidente, assim como se espantam os do oriente.
//
// JÓ 19 — JÓ RESPONDE, e é O CAPÍTULO DO REDENTOR. Abre pelo cansaço: "até
// quando afligireis a minha alma, e me quebrantareis com palavras? JÁ DEZ
// VEZES ME VITUPERASTES." Depois vêm as imagens do cerco, uma a uma: Deus o
// transtornou e com a sua REDE o cercou; ele clama Violência! e não é ouvido;
// o caminho foi entrincheirado e nas veredas há trevas; "da minha honra me
// despojou; e TIROU-ME A COROA DA MINHA CABEÇA"; quebrou-o de todos os lados e
// ARRANCOU A SUA ESPERANÇA COMO A UMA ÁRVORE; as TROPAS vieram juntas e se
// acamparam ao redor da sua tenda. E então o pior, que não é Deus: os irmãos
// postos longe, os parentes que o deixaram, os conhecidos que se esqueceram,
// os domésticos e as servas que o têm por estranho, o criado que não responde
// quando chamado, o HÁLITO QUE SE FEZ ESTRANHO À SUA MULHER, os pequeninos que
// o desprezam, os homens da sua confidência que o abominam. E o corpo: "os
// meus ossos se apegaram à minha pele e à minha carne, E ESCAPEI SÓ COM A PELE
// DOS MEUS DENTES". Daí o pedido vira grito: "quem me dera agora, que as
// minhas palavras fossem escritas! quem me dera, fossem gravadas NUM LIVRO! e
// que, COM PENA DE FERRO, E COM CHUMBO, para sempre fossem esculpidas NA
// ROCHA" — e então o auge do livro inteiro: "PORQUE EU SEI QUE O MEU REDENTOR
// VIVE, e que por fim se levantará sobre a terra. E depois de consumida a
// minha pele, contudo ainda em minha carne verei a Deus; vê-lo-ei, por mim
// mesmo, e os meus olhos, e NÃO OUTROS o contemplarão." E fecha avisando os
// amigos: temei vós mesmos a ESPADA, para saberdes que há um juízo.
//
// JÓ 20 — ZOFAR, O NAAMATITA, PELA ÚLTIMA VEZ (ele não voltará no terceiro
// ciclo), e responde apressado porque se sentiu envergonhado. A tese: "o
// júbilo dos ímpios é breve, e a alegria dos hipócritas momentânea"; ainda que
// a altivez suba até ao céu e a cabeça chegue até às nuvens, "contudo, COMO O
// SEU PRÓPRIO ESTERCO, perecerá para sempre"; COMO UM SONHO VOARÁ, e será
// afugentado COMO UMA VISÃO DA NOITE. E o corpo do capítulo é uma só imagem
// crua, o pecado que é doce na boca e amargo nas entranhas: "ainda que o mal
// lhe seja doce na boca, e ele o esconda debaixo da sua língua… contudo a sua
// comida se mudará nas suas entranhas; FEL DE ÁSPIDES será interiormente.
// ENGOLIU RIQUEZAS, PORÉM VOMITÁ-LAS-Á; do seu ventre Deus as lançará."
// Veneno de áspides sorverá e a língua da víbora o matará; NÃO VERÁ AS
// CORRENTES, OS RIOS E OS RIBEIROS DE MEL E MANTEIGA; restituirá o trabalho e
// não o engolirá; oprimiu e desamparou os pobres e roubou a casa que não
// edificou; nada lhe sobejará do que coma; sendo plena a abastança, estará
// angustiado, e toda a força da miséria virá sobre ele; Deus mandará sobre ele
// o ardor da sua ira e a fará chover quando for comer; "ainda que fuja das
// armas de ferro, O ARCO DE BRONZE O ATRAVESSARÁ"; desembainhará a espada que
// sairá do seu corpo, e HAVERÁ SOBRE ELE ASSOMBROS; um FOGO NÃO ASSOPRADO o
// consumirá; OS CÉUS MANIFESTARÃO A SUA INIQÜIDADE E A TERRA SE LEVANTARÁ
// CONTRA ELE; as riquezas de sua casa serão transportadas no dia da sua ira.
//
// JÓ 21 — JÓ DESMONTA OS TRÊS DE UMA VEZ, e é o capítulo mais empírico da
// Bíblia. "Ouvi atentamente as minhas razões; e isto vos sirva de consolação…
// olhai para mim, e pasmai; e ponde a mão sobre a boca." E a pergunta: "POR
// QUE RAZÃO VIVEM OS ÍMPIOS, envelhecem, e ainda se robustecem em poder?" A
// cena inteira passa a ser a prosperidade deles: a descendência estabelecida
// perante a sua face, "as suas casas têm paz, sem temor; E A VARA DE DEUS NÃO
// ESTÁ SOBRE ELES", o touro que gera e não falha, a vaca que pare e não
// aborta, "fazem sair as suas crianças, COMO A UM REBANHO, e seus filhos
// ANDAM SALTANDO", a voz levantada ao som do TAMBORIL e da HARPA. "NA
// PROSPERIDADE GASTAM OS SEUS DIAS, E NUM MOMENTO DESCEM À SEPULTURA" — e
// ainda dizem a Deus: "Retira-te de nós… QUEM É O TODO-PODEROSO, PARA QUE NÓS
// O SIRVAMOS? e que nos aproveitará que lhe façamos orações?" Quantas vezes
// sucede, pergunta ele, que se apaga a lâmpada dos ímpios, que são como a
// PALHA diante do vento e como a PRAGANA que o redemoinho arrebata? E: Deus
// guarda a violência para os filhos dele — não: "SEUS OLHOS VERÃO A SUA RUÍNA,
// E ELE BEBERÁ DO FUROR DO TODO-PODEROSO". E o fim, com dois homens no mesmo
// pó: "um morre na força da sua plenitude, estando inteiramente sossegado e
// tranqüilo, com seus BALDES CHEIOS DE LEITE… e outro, ao contrário, morre na
// amargura do seu coração, não havendo provado do bem. JUNTAMENTE JAZEM NO PÓ,
// E OS VERMES OS COBREM." O ímpio é levado à sepultura com honra, vigiam-lhe o
// túmulo, e OS TORRÕES DO VALE LHE SÃO DOCES.
//
// JÓ 22 — ELIFAZ, O TEMANITA, PELA ÚLTIMA VEZ, e desta vez INVENTA pecados que
// o texto nunca imputou a Jó. Começa frio: "porventura será o homem de algum
// proveito a Deus?… ou te repreende, pelo temor que tem de ti?" E acusa:
// "PORVENTURA NÃO É GRANDE A TUA MALÍCIA, e sem termo as tuas iniqüidades?
// Porque SEM CAUSA PENHORASTE A TEUS IRMÃOS, e aos nus despojaste as vestes;
// não deste ao cansado água a beber, e ao faminto retiveste o pão… AS VIÚVAS
// DESPEDISTE VAZIAS, E OS BRAÇOS DOS ÓRFÃOS FORAM QUEBRADOS. Por isso é que
// estás cercado de LAÇOS, e te perturba um pavor repentino." Depois o céu:
// "porventura Deus não está na altura dos céus? OLHA PARA A ALTURA DAS
// ESTRELAS; quão elevadas estão" — e tu dizes: que sabe Deus? as nuvens são
// esconderijo para ele, e passeia pelo circuito dos céus. E a VEREDA ANTIGA
// que pisaram os homens iníquos, "arrebatados antes do seu tempo; sobre o seu
// fundamento UM DILÚVIO SE DERRAMOU". E no fim, a única coisa boa que sai da
// boca dos três em todo o livro: "APEGA-TE, POIS, A ELE, E TEM PAZ, e assim te
// sobrevirá o bem… e deitares o teu TESOURO NO PÓ, e O OURO DE OFIR NAS PEDRAS
// DOS RIBEIROS: então o TODO-PODEROSO SERÁ O TEU TESOURO, e a tua prata
// acumulada… determinarás tu algum negócio, e ser-te-á firme".
//
// JÓ 23 — JÓ, E É O CAPÍTULO DA BUSCA. "Ah, SE EU SOUBESSE ONDE O PODERIA
// ACHAR! Então me chegaria ao seu TRIBUNAL": exporia ante ele a causa e
// encheria a boca de argumentos, saberia as palavras com que ele responderia,
// e ali o reto pleitearia com ele. E então a busca de verdade, aos quatro
// pontos: "EIS QUE SE ME ADIANTO, ALI NÃO ESTÁ; se torno para trás, não o
// percebo; se opera à esquerda, não o vejo; se se encobre à direita, não o
// diviso." No meio de tudo, a certeza: "PORÉM ELE SABE O MEU CAMINHO;
// PROVANDO-ME ELE, SAIREI COMO O OURO. Nas suas pisadas os meus pés se
// afirmaram; guardei o seu caminho, e não me desviei dele. DO PRECEITO DE SEUS
// LÁBIOS NUNCA ME APARTEI, e as palavras da sua boca guardei mais do que a
// minha porção." E o pavor no fim: cumprirá o que está ordenado a meu
// respeito, "POR ISSO ME PERTURBO PERANTE ELE, e quando isto considero,
// TEMO-ME DELE… porque Deus macerou o meu coração".
//
// JÓ 24 — JÓ OUTRA VEZ, E É O CAPÍTULO DOS INVISÍVEIS, o mais social do livro.
// "Visto que do Todo-Poderoso não se encobriram os tempos, por que, os que o
// conhecem, não vêem os seus dias?" E então a galeria inteira: os que
// REMOVEM OS LIMITES e roubam os rebanhos e os apascentam; "DO ÓRFÃO LEVAM O
// JUMENTO; TOMAM EM PENHOR O BOI DA VIÚVA"; os necessitados desviados do
// caminho e os pobres da terra escondidos; "eis que, COMO JUMENTOS MONTESES NO
// DESERTO, saem à sua obra, MADRUGANDO PARA A PRESA; a campina dá mantimento a
// eles e aos seus filhos"; no campo segam o pasto alheio e VINDIMAM A VINHA DO
// ÍMPIO; "AO NU FAZEM PASSAR A NOITE SEM ROUPA, não tendo ele coberta contra o
// frio; pelas chuvas das montanhas são molhados e, NÃO TENDO REFÚGIO,
// ABRAÇAM-SE COM AS ROCHAS"; ao orfãozinho arrancam dos peitos; FAZEM COM QUE
// OS NUS VÃO SEM ROUPA E AOS FAMINTOS TIRAM AS ESPIGAS; dentro das paredes
// espremem o azeite e PISAM OS LAGARES, E AINDA TÊM SEDE. "DESDE AS CIDADES
// GEMEM OS HOMENS, e a alma dos feridos exclama, E CONTUDO DEUS LHO NÃO IMPUTA
// COMO LOUCURA." E os inimigos da luz, que é o quadro mais forte: "eles estão
// entre os que SE OPÕEM À LUZ… DE MADRUGADA SE LEVANTA O HOMICIDA, mata o
// pobre e necessitado, E DE NOITE É COMO O LADRÃO. Assim como O OLHO DO
// ADÚLTERO AGUARDA O CREPÚSCULO, dizendo: Não me verá olho nenhum; e oculta o
// rosto. Nas trevas MINAM AS CASAS que de dia se marcaram… A MANHÃ PARA TODOS
// ELES É COMO SOMBRA DE MORTE." E o fim: é ligeiro sobre a superfície DAS
// ÁGUAS, maldita é a sua parte sobre a terra; "A SECURA E O CALOR DESFAZEM AS
// ÁGUAS DA NEVE"; "A MADRE SE ESQUECERÁ DELE, OS VERMES O COMERÃO
// GOSTOSAMENTE, nunca mais haverá lembrança dele; e A INIQÜIDADE SE QUEBRARÁ
// COMO UMA ÁRVORE"; e a conclusão amarga: "se agora não é assim, quem me
// desmentirá e desfará as minhas razões?"
//
// A VOZ DE DEUS — nestes SETE capítulos DEUS NÃO FALA UMA ÚNICA VEZ, e por
// isso NÃO HÁ NENHUM `by:"deus"` em nenhum destes cento e oitenta e cinco
// beats. É de propósito e é a regra da CLAUDE.md cumprida ao pé da letra: o
// céu está calado desde o capítulo 2 e só se abrirá no 38, e um balão dourado
// aqui arruinaria o livro. Todo balão sai pelo `id` — `bildade-o-suita`,
// `jo`, `zofar-o-naamatita`, `elifaz-o-temanita` — porque quatro `patriarca`
// dividem a mesma cena e o papel não distinguiria quem fala. A única passagem
// que pede glória alta é 19:25-27, O AUGE DO LIVRO INTEIRO: ali a manhã abre,
// `glory` vai ao máximo, Jó levanta-se em `raise` no meio do palco — e mesmo
// ali DEUS NÃO É DESENHADO e o balão continua a ser de Jó, porque ele está a
// DIZER que verá, não a ver. Onde Jó e os amigos descrevem o que Deus faz — a
// rede com que o cercou, a vara que não está sobre os ímpios, o furor que se
// bebe, os céus que manifestam a iniqüidade, o dilúvio sobre o fundamento — a
// cena mostra A OBRA e nunca o Obreiro.
