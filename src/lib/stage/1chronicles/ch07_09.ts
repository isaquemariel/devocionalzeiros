// ============================================================================
// 1 CRÔNICAS 7–9 — CENA VIVA. Três capítulos que parecem uma lista de nomes e
// são, na verdade, um mapa: as tribos do norte contadas como EXÉRCITOS, a casa
// de Saul montada pedra por pedra até o trono, e — no fim — o único lugar da
// Escritura onde alguém abre a porta dos bastidores da casa de Deus e mostra
// quem varria, quem contava os vasos, quem moía as especiarias e quem cantava
// de madrugada.
//
// 1Cr 7 — AS TRIBOS DO NORTE, CONTADAS COMO EXÉRCITOS. O Cronista atravessa
// ISSACAR, BENJAMIM, NAFTALI, MANASSÉS, EFRAIM e ASER, e a régua com que mede
// cada casa é sempre a mesma: quantos HOMENS VALENTES ela põe em campo. Issacar
// dá vinte e dois mil e seiscentos nos dias de Davi, trinta e seis mil em
// tropas de guerra "porque tiveram muitas mulheres e filhos", oitenta e sete
// mil ao todo. Benjamim dá os seus chefes e as suas casas, e Jediael dezessete
// mil e duzentos "que saíam no exército à peleja". Manassés tem a concubina
// SÍRIA que concebeu Maquir, tem MAACA, a irmã de Hupim e Supim que Maquir tomou
// por mulher, e tem ZELOFEADE — de quem o texto diz só isto, e isto basta: "e
// Zelofeade teve filhas". No meio disso o capítulo abre um buraco escuro que
// não estava previsto: os filhos de Efraim, EZER e ELADE, descem para tomar
// gado e "os homens de Gate, naturais da terra, os mataram". E então o verso
// mais humano de todas as genealogias: "Por isso Efraim, seu pai, POR MUITOS
// DIAS OS CHOROU; e vieram seus irmãos para o consolar". Quando lhe nasce outro
// filho, o nome é a cicatriz: BERIAS, "porque ia mal na sua casa". E logo
// depois, na mesma casa e sem nenhuma cerimônia, a linha mais improvável do
// livro: "E sua filha foi SEERÁ, que edificou a Bete-Horom, a baixa e a alta,
// como também a Uzém-Seerá" — uma mulher que levanta três cidades. A linha de
// Efraim segue até NUM e JOSUÉ, e a possessão vira mapa: Betel, Naarã, Gezer,
// Siquém, Gaza, Bete-Seã, Taanaque, Megido, Dor. Aser fecha com o azeite da
// costa e vinte e seis mil "homens escolhidos e valentes, chefes dos príncipes".
//
// 1Cr 8 — BENJAMIM E A CASA DE SAUL. Benjamim é contado outra vez, agora não
// pelo exército, mas pelas CASAS e pelos LUGARES: os chefes de Geba que foram
// levados cativos a Manaate; SAARAIM, que "depois de os enviar" — depois de
// despedir Husim e Baara, suas mulheres — gera filhos na terra de Moabe; Semede,
// que edificou Ono e Lode; Berias e Sema, cabeças dos moradores de Aijalom, que
// "afugentaram os moradores de Gate"; e as fileiras de cabeças de pais que
// "habitaram em Jerusalém". Aí o capítulo sobe a GIBEÃO, onde mora o pai de
// Gibeão, e a mulher dele chama-se MAACA, e a linha desce sem pressa — Abdom,
// Zur, Quis, Baal, Nadabe, Gedor, Aiô, Zequer, Miclote — até bater na frase que
// o livro inteiro estava esperando: "E Ner gerou a Quis, e Quis gerou a SAUL; e
// Saul gerou a Jônatas, a Malquisua, a Abinadabe, e a Esbaal". Depois de Saul,
// um nome que dói: MERIBE-BAAL, o filho de Jônatas, aquele que a ama deixou cair
// aos cinco anos e que Davi mandou buscar em Lo-Debar. A casa continua a
// gerar por mais sete gerações até Azel e os seus seis filhos, e o capítulo
// termina de arco na mão: os filhos de Ulão, "homens heróis, valentes, e
// FLECHEIROS DESTROS", com filhos e netos, cento e cinqüenta.
//
// 1Cr 9 — OS QUE VOLTARAM, E O SERVIÇO DA CASA. O primeiro versículo é o corte
// que explica os oito capítulos anteriores: tudo foi contado por genealogias,
// "e os de Judá foram transportados a Babilônia, POR CAUSA DA SUA TRANSGRESSÃO".
// Depois disso o livro respira: "os primeiros habitantes, que moravam na sua
// possessão e nas suas cidades, foram os israelitas, os sacerdotes, os levitas,
// e os netineus". Judá, Benjamim, Efraim e Manassés voltam a Jerusalém, e o
// Cronista conta os que voltaram por casa e por número — seiscentos e noventa,
// novecentos e cinqüenta e seis, mil setecentos e sessenta "homens valentes
// para a obra do ministério da casa de Deus". E então o livro vira a página e
// mostra o TRABALHO, que é a coisa mais viva de todas as genealogias: os
// PORTEIROS — Salum, Acube, Talmom, Aimã — que "estavam de guarda à porta do
// rei, do lado do oriente"; Finéias, que "antes era líder entre eles; e o
// Senhor era com ele"; os duzentos e doze guardas das portas que DAVI E SAMUEL,
// O VIDENTE, constituíram nos seus cargos; os porteiros "aos quatro lados: ao
// oriente, ao ocidente, ao norte, e ao sul"; os irmãos que vinham das aldeias
// "por sete dias" para revezar; os quatro principais, com o encargo das câmaras
// e dos tesouros; e os que "de noite ficavam em redor da casa de Deus" e "tinham
// o encargo de abri-la cada manhã". Depois a despensa inteira: os utensílios do
// ministério, contados à entrada e à saída; a flor de farinha, o vinho, o
// azeite, o incenso e as especiarias; os filhos dos sacerdotes que eram "os
// obreiros da confecção das especiarias"; MATITIAS, o primogênito de Salum, com
// o encargo "da obra que se fazia em sertãs"; os coatitas, que preparavam "os
// pães da proposição para todos os sábados"; e, por fim, os CANTORES, chefes
// dos pais, "habitando nas câmaras, isentos de serviços; porque de dia e de
// noite estava a seu cargo ocuparem-se naquela obra". O capítulo fecha
// repetindo a casa de Saul — e a repetição não é descuido: é a porta do
// capítulo 10, onde essa casa cai em Gilboa.
//
// A VOZ DE DEUS — nestes três capítulos Deus NÃO FALA nenhuma vez. Não há
// oráculo, não há profeta com "assim diz o Senhor", não há teofania: por isso
// não existe aqui um único `by`, nem `by:"deus"`, nem balão de anjo, e todos os
// 124 beats são narração pura com `q` de frase-chave. Deus aparece nestes
// capítulos de outro jeito, três vezes, e a cena o diz pela luz e não por
// balão: em 9:1, quando Judá é transportado a Babilônia "por causa da sua
// transgressão" — o único quadro de trevas do trecho, com `night` no auge, sem
// glória e sem multidão, só figuras individuais saindo do enquadramento; em
// 9:20, quando o texto diz de Finéias "e o Senhor era com ele" — ali a glória
// sobe e o levita recebe `glow`, porque a presença é afirmada pelo narrador, não
// falada; e em toda a segunda metade de 9, onde a casa de Deus é servida de dia
// e de noite — a glória fica alta e constante sobre as câmaras, os vasos, as
// especiarias e os cantores, porque o Cronista está dizendo que o trabalho
// miúdo daquela gente É o culto. `glow` só entra em Finéias (9:20) e nos
// cantores da vigília (9:33); nunca nos homens de Gate que matam os filhos de
// Efraim, nunca nos que levam Geba cativa a Manaate.
// ============================================================================

