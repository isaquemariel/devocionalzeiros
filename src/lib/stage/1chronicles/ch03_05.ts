// ============================================================================
// 1 CRÔNICAS 3–5 — CENA VIVA. Três capítulos de nomes que, lidos de perto, são
// três mundos inteiros: a CASA DE DAVI da coroa de Hebrom até um homem preso na
// Babilônia; JUDÁ vista pelo lado do TRABALHO — o vale dos artífices, as casas
// do linho fino, os oleiros do rei — com a ORAÇÃO DE JABEZ no meio como um
// clarão; e as tribos do OUTRO LADO DO JORDÃO, ricas de gado, vitoriosas na
// peleja porque clamaram a Deus, e levadas cativas no fim porque O deixaram.
//
// 1Cr 3 — A ESPINHA DO LIVRO. O Cronista começa pelo trono e termina numa
// cadeia. Em HEBROM nascem seis filhos de Davi, cada um com o nome da mãe
// colado ao seu — Ainoã a jizreelita, Abigail a carmelita, Maaca filha de
// Talmai rei de Gesur, Hagite, Abital, Eglá — e ali ele reinou "sete anos e
// seis meses". Em JERUSALÉM reinou trinta e três, e ali nasceram os quatro de
// BATE-SUA, FILHA DE AMIEL, entre eles SALOMÃO. Nove mais depois, "afora os
// filhos das concubinas e TAMAR, IRMÃ DELES" — uma linha só para a moça cuja
// história o Cronista não conta e não esconde. Daí a lista vira dinastia:
// Roboão, Abias, Asa, Jeosafá, Jorão, Acazias, Joás, Amazias, Jotão, Acaz,
// Ezequias, Manassés, Amom, JOSIAS — e no filho de Josias a coroa se parte em
// quatro cabeças e acaba. Então vem o corte que o livro inteiro carrega:
// "E os filhos de JECONIAS: Assir, e seu filho Sealtiel" — o rei que a Babilônia
// levou preso, e cuja casa continua a nascer, gerar e ser contada DENTRO do
// cativeiro. De Pedaías sai ZOROBABEL, o que voltará para levantar o templo, e
// a lista desce por Hananias, Secanias, Semaías, Nearias, Elioenai até um último
// nome, ANANI. A luz do capítulo não pode ser a mesma do começo ao fim: em
// Hebrom é manhã de campo, em Jerusalém é ouro de casa real, no fim é lua de
// Babilônia sobre um zigurate — e só no último versículo o céu clareia de novo,
// porque a linhagem chegou inteira ao outro lado.
//
// 1Cr 4 — JUDÁ PELO LADO DA OFICINA. Aqui o Cronista larga os reis e desce à
// terra: os zoratitas, os pais das cidades pequenas (Etã, Gedor, Husá, Belém),
// as duas mulheres de Asur o pai de Tecoa. E no meio disso, sem aviso, dois
// versículos que ninguém esquece: "E foi JABEZ mais ilustre do que seus irmãos;
// e sua mãe deu-lhe o nome de Jabez, dizendo: PORQUANTO COM DORES O DEI À LUZ" —
// e o filho da dor abre a boca: "SE ME ABENÇOARES MUITÍSSIMO, E MEUS TERMOS
// AMPLIARES, E A TUA MÃO FOR COMIGO, E FIZERES QUE DO MAL NÃO SEJA AFLIGIDO!" —
// "E DEUS LHE CONCEDEU O QUE LHE TINHA PEDIDO". Depois o mapa dos ofícios: o
// VALE DOS ARTÍFICES, "porque os dali eram artífices"; as famílias da casa dos
// QUE FABRICAVAM LINHO FINO em casa de Asbéia; e os OLEIROS que "habitavam nas
// hortas e nos cerrados" e "ficaram ali COM O REI NA SUA OBRA". Depois SIMEÃO,
// a tribo pequena que "não se multiplicou tanto como as dos filhos de Judá",
// com as suas cidades do sul — Berseba, Ziclague, Bete-Marcabote (a casa dos
// carros), Hazar-Susim (o curral dos cavalos) — até Baal. E o fecho é um
// achado: os príncipes de Simeão "chegaram até à entrada de GEDOR, ao oriente
// do vale, A BUSCAR PASTO PARA OS SEUS REBANHOS. E ACHARAM PASTO FÉRTIL E TERRA
// ESPAÇOSA, E QUIETA, E DESCANSADA" — a terra seca acaba e começa o verde, e é
// a coisa mais parecida com o Éden que uma genealogia consegue dizer. Depois
// derrubam as tendas de quem estava ali, e quinhentos homens sobem às MONTANHAS
// DE SEIR e ferem o restante dos amalequitas que escapara.
//
// 1Cr 5 — DO OUTRO LADO DO JORDÃO. Rúben abre o capítulo perdendo: "ele era o
// primogênito; mas porque PROFANARA A CAMA DE SEU PAI, deu-se a sua
// primogenitura aos filhos de José" — e o cetro nem foi para José: "JUDÁ FOI
// PODEROSO ENTRE SEUS IRMÃOS, E DELE VEIO O SOBERANO". O que sobra a Rúben é
// terra e gado: Aroer, Nebo, Baal-Meom, e para o oriente "até à entrada do
// deserto, desde o rio Eufrates; PORQUE SEU GADO SE TINHA MULTIPLICADO NA TERRA
// DE GILEADE". Gade fica defronte, em Basã até Salcá; a meia tribo de Manassés
// sobe de Basã ao HERMOM. São quarenta e quatro mil setecentos e sessenta
// homens "que traziam escudo e espada, e entesavam o arco", e a guerra contra os
// hagarenos é ganha por um motivo só, escrito com todas as letras: "NA PELEJA,
// CLAMARAM A DEUS QUE LHES DEU OUVIDOS, PORQUANTO CONFIARAM NELE" — e o despojo
// vem contado cabeça por cabeça, cinquenta mil camelos, duzentas e cinquenta
// mil ovelhas, dois mil jumentos, cem mil almas, "PORQUE DE DEUS ERA A PELEJA".
// E o mesmo capítulo que mostra o que a confiança ganha mostra o que a
// infidelidade perde: "PORÉM TRANSGREDIRAM CONTRA O DEUS DE SEUS PAIS", e o
// Deus de Israel "SUSCITOU O ESPÍRITO DE PUL, REI DA ASSÍRIA, E O ESPÍRITO DE
// TIGLATE-PILNESER", que os levou a Hala, Habor, Hara e ao rio de Gozã, "até ao
// dia de hoje". Começa em pasto e acaba em estrada de deportação.
//
// A VOZ DE DEUS — nestes três capítulos Deus não abre a boca uma única vez, e
// por isso NÃO HÁ NENHUM `by:"deus"` aqui: não há voz do céu, não há profeta,
// não há anjo, não há teofania. As duas únicas falas do trecho são humanas, e
// as duas estão em 4:9-10: a da MÃE DE JABEZ, que dá o nome ao filho pela dor
// do parto (`by:"mulherComum"`, ela em cena e primeira do seu papel), e a de
// JABEZ, que invoca o Deus de Israel (`by:"homem"`, ele em cena e primeiro do
// seu papel). Deus responde às duas — mas responde CALADO: "e Deus lhe concedeu
// o que lhe tinha pedido" não é frase de balão, é luz. Por isso 4:10 é o quadro
// de glória mais alto dos três capítulos, com o homem de joelhos e as mãos
// erguidas e nada desenhado acima dele senão o dourado. O mesmo vale para
// 5:20 — "clamaram a Deus que lhes deu ouvidos" —, onde a resposta divina
// aparece como glória rompendo sobre o campo de batalha, sem balão nenhum, e
// para 5:26, onde Deus age SUSCITANDO O ESPÍRITO de dois reis pagãos: ali a
// mão de Deus é a noite fechada e a estrada para o norte, não uma voz.
// ============================================================================

