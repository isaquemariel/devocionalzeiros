// enterro: pula noventa anos de genealogia e cai direto no monte GILBOA, onde
// o primeiro rei de Israel morre com os três filhos e o escudeiro. Só depois
// disso a câmera vira, e o resto destes três capítulos é uma coisa só — TODO O
// ISRAEL indo a Hebrom fazer rei o pastor de Belém, e os homens que o
// carregaram até lá, um por um, com o nome do pai e o nome da aldeia.
//
// 1Cr 10 — GILBOA. "E os filisteus pelejaram com Israel; e os homens de Israel
// fugiram de diante dos filisteus, E CAÍRAM MORTOS NAS MONTANHAS DE GILBOA."
// Mataram Jônatas, Abinadabe e Malquisua; a peleja se agravou contra Saul, "e
// os flecheiros o alcançaram; e temeu muito aos flecheiros". O rei pede ao
// escudeiro que o atravesse "para que porventura não venham estes
// incircuncisos e escarneçam de mim" — e o escudeiro NÃO QUIS, PORQUE TEMIA
// MUITO. Então Saul toma a própria espada e se lança sobre ela, e o escudeiro
// faz o mesmo. Morreu o rei, morreram os três filhos, "e toda a sua casa
// morreu juntamente". Os homens do vale abandonam as cidades e os filisteus
// habitam nelas; no dia seguinte os saqueadores acham os corpos estirados na
// montanha, cortam a cabeça de Saul, tomam-lhe as armas e mandam a notícia
// correr a terra inteira "para o anunciarem a seus ídolos e ao povo". AS ARMAS
// FICAM NA CASA DO SEU DEUS E A CABEÇA É AFIXADA NA CASA DE DAGOM — o mesmo
// templo em que o ídolo caíra de bruços diante da arca (1Sm 5:4). Só JABES DE
// GILEADE se levanta: os homens valorosos da cidade que Saul salvou no seu
// primeiro dia de rei atravessam a noite, tomam os corpos, sepultam os ossos
// debaixo de um carvalho e jejuam sete dias. E o capítulo fecha com o veredito
// mais duro que a Escritura escreveu sobre um rei: "Assim morreu Saul por
// causa da transgressão que cometeu contra o Senhor… e também porque BUSCOU A
// ADIVINHADORA PARA A CONSULTAR. E NÃO BUSCOU AO SENHOR, QUE POR ISSO O MATOU,
// E TRANSFERIU O REINO A DAVI, FILHO DE JESSÉ."
//
// 1Cr 11 — O REI E OS VALENTES. Todo o Israel se ajunta em Hebrom com a frase
// que resume o dia: "EIS QUE SOMOS TEUS OSSOS E TUA CARNE". Ungem Davi rei
// "conforme a palavra do Senhor pelo ministério de Samuel", e a primeira coisa
// que ele faz é marchar sobre JERUSALÉM, QUE É JEBUS. Os moradores gritam do
// alto do muro a frase mais mal calculada da história da cidade — "TU NÃO
// ENTRARÁS AQUI" — e Davi toma a fortaleza de Sião. Promete o posto de chefe
// ao primeiro que ferir os jebuseus, e JOABE SOBE PRIMEIRO. Dali em diante o
// capítulo vira catálogo, e o catálogo é o coração do livro: JASOBEÃO,
// brandindo a lança contra trezentos de uma vez; ELEAZAR, FILHO DE DODÓ, que
// se planta no meio de um pedaço de campo cheio de cevada em Pas-Damim quando
// o povo já fugira, defende a parcela e vê o SENHOR efetuar "um grande
// livramento"; os TRÊS que, ouvindo o rei suspirar na caverna de Adulão —
// "QUEM ME DERA BEBER DA ÁGUA DO POÇO DE BELÉM, QUE ESTÁ JUNTO À PORTA!" —
// rompem pelo acampamento filisteu, tiram a água e a trazem, e o rei NÃO A
// QUER BEBER: derrama-a ao SENHOR, dizendo "Beberia eu o sangue destes homens
// com as suas vidas?". Depois ABISAI, e BENAIA, FILHO DE JOIADA, que feriu dois
// heróis de Moabe, DESCEU E FERIU UM LEÃO DENTRO DE UMA COVA NO TEMPO DA NEVE,
// e matou o egípcio de cinco côvados cuja lança era "como o órgão do tecelão"
// — descendo contra ele com uma vara, arrancando-lhe a lança da mão e matando-o
// com a sua própria lança. E o resto do capítulo é o rol dos trinta: trinta e
// tantos nomes, cada um com a sua aldeia — Belém, Tecoa, Anatote, Netofa, o
// ribeiro de Gaás, o Carmelo, Astarote, Aroer, a outra banda do Jordão —, e no
// meio deles, sem uma palavra de comentário, URIAS, O HETEU.
//
// 1Cr 12 — OS QUE VIERAM A DAVI. Antes de Hebrom houve ZICLAGUE, "estando ele
// ainda escondido, por causa de Saul": os primeiros a atravessar são os
// BENJAMITAS, IRMÃOS DE SAUL, ambidestros, "que atiravam com a mão direita e
// com a esquerda" pedras e flechas contra a própria tribo. Depois os GADITAS
// que desertam para o lugar forte no deserto, "e seus rostos eram como rostos
// de leões, e ligeiros como corças sobre os montes" — os que passaram o Jordão
// NO PRIMEIRO MÊS, QUANDO ELE TRANSBORDAVA POR TODAS AS SUAS RIBANCEIRAS. Vêm
// homens de Benjamim e de Judá, e Davi sai ao encontro deles com a espada na
// pergunta — "se é para me entregar aos meus inimigos… o Deus de nossos pais o
// veja e o repreenda" —, e a resposta não é de um homem: "ENTÃO VEIO O
// ESPÍRITO SOBRE AMASAI, CHEFE DE TRINTA, e disse: NÓS SOMOS TEUS, Ó DAVI, E
// CONTIGO ESTAMOS, Ó FILHO DE JESSÉ!". De Manassés passam sete capitães no dia
// em que os príncipes dos filisteus despedem Davi da batalha, "à custa de
// nossas cabeças". E dia após dia vinham, "até que se fez um grande exército,
// COMO O EXÉRCITO DE DEUS". A segunda metade é o rol de Hebrom, tribo por
// tribo, com números: Judá com escudo e lança, Simeão, Levi, Joiada dos de
// Arão, o jovem ZADOQUE, os três mil de Benjamim que ainda eram pela casa de
// Saul, Efraim, Manassés, e os duzentos chefes de ISSACAR, "DESTROS NA CIÊNCIA
// DOS TEMPOS, PARA SABEREM O QUE ISRAEL DEVIA FAZER". Fecha na mesa: três dias
// comendo e bebendo, jumentos, camelos, mulos e bois carregados de pão,
// farinha, pastas de figos, cachos de passas, vinho e azeite — "PORQUE HAVIA
// ALEGRIA EM ISRAEL".
//
// A VOZ DE DEUS — nestes três capítulos Deus NÃO FALA UMA ÚNICA VEZ em voz
// direta, e por isso não há nenhum `by:"deus"` aqui. Onde a palavra dele
// aparece, aparece SEMPRE por boca humana e no passado: em 11:2 são os anciãos
// de Israel que CITAM o que o SENHOR dissera a Davi ("Tu apascentarás o meu
// povo Israel") — o balão é do ANCIÃO, não do céu, porque é lembrança de
// aliança dita por homens em Hebrom; em 11:3 e 12:23 o texto diz "conforme a
// palavra do Senhor" sem pôr fala nenhuma na cena, e ali não há balão, só a
// unção e a glória subindo. As duas intervenções divinas visíveis são MUDAS:
// em 11:14, sobre a parcela de cevada de Pas-Damim, "o SENHOR efetuou um
// grande livramento" — glória no auge, dois homens de pé no meio do campo e
// nenhum balão; e em 10:14 é o próprio Cronista que sentencia que o SENHOR
// "matou" Saul e "transferiu o reino a Davi" — juízo narrado, não falado, e por
// isso a cena é de trono e coroa, sem voz. A única boca por onde o Espírito
// realmente irrompe é a de um homem: 12:18, "então veio o espírito sobre
// AMASAI, chefe de trinta, e disse" — ali o balão é dele (`by:"homem"`, glow
// alto e glória alta), porque o texto nomeia o mediador. É a regra do livro:
// onde há mediador, o balão sai do mediador.
// ============================================================================

