// 1 CRÔNICAS 13–16 — CENA VIVA. A ARCA VOLTA PARA CASA, e volta duas vezes:
// a primeira num carro novo, com música e alegria, e acaba com um homem morto
// na eira; a segunda aos ombros dos levitas, com as varas, "como Moisés tinha
// ordenado", e acaba com um cântico que faz o mar bramir e as árvores dos
// bosques jubilarem. Entre as duas subidas o Cronista mete a casa de cedro, os
// filhos nascidos em Jerusalém e duas batalhas no vale de Refaim — porque o
// reino de Davi se mede exatamente por isto: pelo que ele faz com a arca.
//
// 1Cr 13 — O CARRO NOVO E UZÁ. Davi não começa por decreto: "tomou conselho
// com os capitães dos milhares, e das centenas, e com todos os líderes", e põe
// a coisa em votação diante da congregação inteira — "SE BEM VOS PARECE, E SE
// ISTO VEM DO SENHOR NOSSO DEUS". O motivo é uma confissão: "E TORNEMOS A
// TRAZER PARA NÓS A ARCA DO NOSSO DEUS; PORQUE NÃO A BUSCAMOS NOS DIAS DE
// SAUL". Convoca Israel de ponta a ponta, "desde Sior do Egito até chegar a
// Hamate", e sobe a Baalá de Quiriate-Jearim buscar "a arca de Deus, o Senhor
// que habita entre os querubins". E aí está o erro, dito sem alarde no meio da
// festa: levaram a arca "SOBRE UM CARRO NOVO", com Uzá e Aiô guiando — carro
// novo é o que os filisteus tinham usado (1Sm 6:7), não o que a Lei mandava.
// O caminho é puro júbilo: "Davi e todo o Israel, alegraram-se perante Deus com
// todas as suas forças; com cânticos, e com harpas, e com saltérios, e com
// tamborins, e com címbalos, e com trombetas". Então a estrada chega à EIRA DE
// QUIDOM, os bois tropeçam, e a mão que se estende para segurar Deus é ferida:
// "E MORREU ALI PERANTE DEUS". Davi se enche de tristeza, chama o lugar
// PEREZ-UZÁ — a brecha de Uzá —, e a pergunta que fecha o capítulo é de um
// homem que perdeu o pé: "COMO TRAREI A MIM A ARCA DE DEUS?". A arca desvia
// para a casa de OBEDE-EDOM, o giteu, e fica três meses ali — e a casa do
// estrangeiro é abençoada, e tudo quanto ele tinha.
//
// 1Cr 14 — A CASA DE DAVI E OS FILISTEUS. Enquanto a arca espera em casa
// alheia, a casa do rei se levanta: Hirão de Tiro manda "madeira de cedro, e
// pedreiros, e carpinteiros", e Davi entende pela obra o que Deus fez — "que o
// Senhor o tinha confirmado rei sobre Israel". Nascem os filhos em Jerusalém, e
// o Cronista os enfileira com nome e ordem, Salomão entre eles. Aí os filisteus
// ouvem da unção e sobem: "se estenderam pelo vale de Refaim". Davi não sobe
// por instinto — CONSULTA: "Subirei contra os filisteus, e nas minhas mãos os
// entregarás?", e a resposta é curta, "SOBE, PORQUE OS ENTREGAREI NAS TUAS
// MÃOS". Fere-os em Baal-Perazim e nomeia a vitória pela imagem da água que
// arrebenta o dique: "POR MINHA MÃO DEUS DERROTOU A MEUS INIMIGOS, COMO SE
// ROMPEM AS ÁGUAS". Os ídolos que os filisteus largaram no campo são queimados
// a fogo. Eles voltam, e a segunda consulta recebe ORDEM DIFERENTE — e é aqui
// que o capítulo cresce: "NÃO SUBIRÁS ATRÁS DELES; MAS RODEIA-OS POR DETRÁS, E
// VEM A ELES POR DEFRONTE DAS AMOREIRAS". O sinal de atacar não é palavra
// nenhuma: é "UM RUÍDO DE MARCHA PELAS COPAS DAS AMOREIRAS", porque "Deus terá
// saído diante de ti". Davi faz como lhe foi ordenado, e a derrota dos
// filisteus se estende de Gibeom a Gezer.
//
// 1Cr 15 — A ARCA SUBINDO DIREITO. Três meses depois, Davi refaz tudo — e o que
// muda é a obediência ao detalhe. Arma uma tenda para a arca e diz a razão do
// primeiro desastre em voz alta: "NINGUÉM PODE LEVAR A ARCA DE DEUS, SENÃO OS
// LEVITAS; PORQUE O SENHOR OS ESCOLHEU". Reúne as seis casas de Levi com os
// seus chefes e os seus números — Uriel e cento e vinte, Asaías e duzentos e
// vinte, Joel e cento e trinta, Semaías e duzentos, Eliel e oitenta, Aminadabe
// e cento e doze —, chama Zadoque e Abiatar, e manda santificar-se, "PORQUANTO
// VÓS NÃO A LEVASTES NA PRIMEIRA VEZ, O SENHOR NOSSO DEUS FEZ ROTURA EM NÓS,
// PORQUE NÃO O BUSCAMOS SEGUNDO A ORDENANÇA". Desta vez não há carro nenhum:
// "os filhos dos levitas trouxeram a arca de Deus SOBRE OS SEUS OMBROS, PELAS
// VARAS QUE NELA HAVIA, COMO MOISÉS TINHA ORDENADO". E então o Cronista faz o
// que ninguém mais faz: escreve a escala inteira da música — Hemã, Asafe e Etã
// nos címbalos de metal, Zacarias e os seus nos alaúdes sobre Alamote,
// Matitias e os seus nas harpas sobre Seminite, QUENANIAS dirigindo o canto
// "porque era entendido", os porteiros da arca, e sete sacerdotes tocando as
// trombetas na frente. A arca sobe "com júbilo, e ao som de buzinas, e de
// trombetas, e de címbalos", Davi vestido de linho fino e éfode, dançando — e
// a última linha do capítulo é uma janela: "MICAL, A FILHA DE SAUL, OLHOU DE
// UMA JANELA, E, VENDO A DAVI DANÇAR E TOCAR, O DESPREZOU NO SEU CORAÇÃO".
//
// 1Cr 16 — O CÂNTICO DIANTE DA ARCA. A arca é posta "no meio da tenda", vêm os
// holocaustos e os pacíficos, e o rei abençoa o povo e reparte a cada um, homem
// e mulher, "UM PÃO, E UM BOM PEDAÇO DE CARNE, E UM FRASCO DE VINHO" — não há
// culto sem mesa. Postos os levitas por ministros perante a arca, Davi entrega
// naquele mesmo dia o SALMO, "pelo ministério de Asafe e de seus irmãos", e o
// salmo é um mapa do mundo inteiro convocado: os povos que hão de ouvir as
// obras, a aliança lembrada de Abraão a Isaque e a Jacó, os dias em que eram
// "poucos homens em número... e estrangeiros nela", os reis repreendidos por
// causa deles — "NÃO TOQUEIS OS MEUS UNGIDOS" —, os ídolos dos povos contra o
// Senhor que FEZ OS CÉUS, e o fecho em que a criação toda entra no coro:
// "ALEGREM-SE OS CÉUS, E REGOZIJE-SE A TERRA... BRAME O MAR COM A SUA
// PLENITUDE; EXULTE O CAMPO COM TUDO O QUE NELE HÁ; ENTÃO JUBILARÃO AS ÁRVORES
// DOS BOSQUES PERANTE O SENHOR". E todo o povo responde uma palavra só:
// "AMÉM!". O capítulo termina repartindo o serviço em dois lugares ao mesmo
// tempo — Asafe e os seus diante da arca em Sião, e Zadoque com os sacerdotes
// "diante do tabernáculo do Senhor, NO ALTO QUE ESTÁ EM GIBEOM", para o
// holocausto contínuo "pela manhã e à tarde" — até que um só templo os junte.
// E o rei, despedido o povo, "voltou para abençoar a sua casa".
//
// A VOZ DE DEUS — nestes quatro capítulos Deus fala DUAS vezes, e as duas sem
// mediador nenhum: em 14:10 e 14:14 Davi consulta e "o Senhor lhe disse" / "e
// disse-lhe Deus", sem profeta e sem anjo na frase. Só ali há `by:"deus"`, e as
// duas vezes com glória alta (`glory` ≥ 0.8) sustentando o balão dourado. Tudo
// o mais é boca de homem: Davi convocando a congregação (13:2-3), Davi com medo
// depois de Perez-Uzá (13:12), Davi dando a lei dos levitas e confessando a
// rotura da primeira vez (15:2,12-13), e o SALMO inteiro de 16:8-36, que é
// cantado — por isso os seus balões saem de DAVI e de ASAFE, o chefe dos
// cantores, que o texto nomeia como o ministério pelo qual o salmo é entoado, e
// nunca do céu: um salmo é palavra do homem para Deus. As duas ações mais
// divinas do trecho são, de novo, MUDAS: a ira que fere Uzá na eira (13:10) não
// tem balão — só escuridão, o carro parado e um homem no chão —, e o SINAL das
// amoreiras (14:15) não tem balão nenhum, porque não é fala: é "um ruído de
// marcha pelas copas", contado só pelo bosque e pelo vento (`storm` alto,
// `tree` grandes, ninguém falando). Onde Deus responde por ruído, Ele não
// argumenta.
// ============================================================================

