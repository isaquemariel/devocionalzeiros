// 1 CRÔNICAS 24–27 — CENA VIVA. Quatro ROLES DE ESCALA, e não quatro listas de
// nomes: o Cronista está fotografando um reino inteiro posto em ordem antes de
// o rei morrer. Cada turma que sai por sorte tem uma HORA, um LUGAR e um
// OFÍCIO — o altar ao romper do dia, o incenso atrás do véu, os pães que se
// trocam no sábado, a pia de bronze, o monte da cinza, a trombeta da lua nova,
// a vigília que atravessa a noite. É assim que estes cento e vinte e oito
// versículos se desenham: pelo trabalho, nunca pelo enfileiramento.
//
// 1Cr 24 — AS VINTE E QUATRO TURMAS DOS SACERDOTES. O capítulo abre num
// enterro antigo: dos quatro filhos de Arão, "morreram Nadabe e Abiú antes de
// seu pai, e não tiveram filhos" — e por isso todo o sacerdócio de Israel
// desce por dois homens só, ELEAZAR e ITAMAR. Davi, com Zadoque (da casa de
// Eleazar) e Aimeleque (da casa de Itamar), reparte os netos deles "segundo o
// seu ofício no seu ministério": dezesseis chefes de casas paternas de um
// lado, oito do outro. E o método não é a preferência do rei, é a SORTE — "e
// os repartiram por sortes, uns com os outros; porque houve governadores do
// santuário e governadores da casa de Deus, assim dentre os filhos de Eleazar,
// como dentre os filhos de Itamar". SEMAÍAS, FILHO DE NATANAEL, O ESCRIVÃO
// DENTRE OS LEVITAS, os registra perante o rei, os príncipes, os dois
// sacerdotes e os chefes dos pais: um homem de joelho no chão com o rolo
// aberto, escrevendo o ano litúrgico de Israel para os quinhentos anos
// seguintes. Saem então as vinte e quatro sortes, de JEOIARIBE a MAAZIAS —
// entre elas a oitava, ABIAS, a turma em que, muitos séculos depois, um velho
// sacerdote chamado Zacarias seria sorteado para queimar o incenso (Lc 1:5-9).
// O ofício de todas é o mesmo: "entrar na casa do Senhor, segundo lhes fora
// ordenado por Arão seu pai". E o capítulo fecha com o restante de Levi —
// Anrão, Reabias, os izaritas, os hebronitas, os uzielitas, Merari — lançando
// sorte do mesmo modo, "perante o rei Davi", com a linha que iguala a casa
// inteira: "assim fizeram, tanto os pais principais como os irmãos menores".
//
// 1Cr 25 — OS CANTORES. Davi, JUNTAMENTE COM OS CAPITÃES DO EXÉRCITO — os
// generais dando baixa a homens para o coro —, separa "para o ministério os
// filhos de Asafe, e de Hemã, e de Jedutum, PARA PROFETIZAREM com harpas, com
// címbalos, e com saltérios". Aqui o canto é profecia: Asafe "profetizava
// debaixo das ordens do rei Davi"; Jedutum "profetizava com a harpa, louvando
// e dando graças ao Senhor"; e HEMÃ é chamado "o vidente do rei nas palavras
// de Deus, PARA EXALTAR O SEU PODER" — e a Escritura conta a bênção dele em
// números de casa cheia: "porque Deus dera a Hemã catorze filhos e três
// filhas", todos sob a direção do pai, "para a música da casa do Senhor, com
// saltérios, címbalos e harpas". Eram duzentos e oitenta e oito, "todos eles
// mestres". E as sortes destes caem exatamente como as dos sacerdotes, com uma
// frase que é o retrato inteiro do capítulo: "assim o pequeno como o grande, o
// mestre juntamente com o discípulo" — o menino aprendiz sorteado no mesmo
// pote do velho mestre. Vinte e quatro turmas de doze homens cada: duzentos e
// oitenta e oito bocas, escaladas por ano inteiro.
//
// 1Cr 26 — OS PORTEIROS, OS TESOUROS E OS OFICIAIS. A porta da casa de Deus é
// posto de honra e de força: os filhos de Meselemias, e os de OBEDE-EDOM — o
// giteu em cuja casa a arca ficou três meses —, com oito filhos nomeados e a
// explicação em cinco palavras: "PORQUE DEUS O TINHA ABENÇOADO". O filho dele,
// Semaías, teve filhos "que dominaram sobre a casa de seu pai; porque foram
// homens valentes"; a casa toda soma sessenta e dois "homens valentes e de
// força para o ministério". Lançam sortes "assim os pequenos como os grandes"
// e as portas se repartem: o ORIENTE a Selemias, o NORTE ao filho Zacarias,
// "conselheiro entendido"; o SUL a Obede-Edom e aos seus filhos as casas dos
// depósitos; o OCIDENTE a Supim e Hosa, "junto à porta Salequete, perto do
// caminho da subida" — e a linha que resume a vigília: UMA GUARDA DEFRONTE DE
// OUTRA GUARDA. Seis levitas ao oriente por dia, quatro ao norte, quatro ao
// sul, dois a dois nos depósitos, quatro em Parbar. Depois as câmaras: Aías
// sobre os tesouros da casa de Deus, Sebuel (bisneto de MOISÉS) chefe dos
// tesouros, e SELOMITE sobre "todos os tesouros das coisas dedicadas" — o que
// Davi e os capitães consagraram DOS DESPOJOS DAS GUERRAS "para repararem a
// casa do Senhor", e o que Samuel, Saul, Abner e Joabe tinham dedicado, quatro
// gerações de espólio guardadas debaixo da mão de um homem só. Fecha do lado
// de fora: Quenanias e os filhos "sobre Israel como oficiais e como juízes,
// dos negócios externos"; mil e setecentos hebronitas a ocidente do Jordão, e
// dois mil e setecentos sobre os rubenitas, os gaditas e a meia tribo de
// Manassés, achados em JAZER DE GILEADE no ano quarenta do reino de Davi.
//
// 1Cr 27 — O EXÉRCITO, OS PRÍNCIPES E OS MORDOMOS. Doze turmas de vinte e
// quatro mil homens, "que entravam e saíam de mês em mês, em todos os meses do
// ano": o serviço militar de Israel é um calendário, e por isso estes doze
// beats são doze estações — a chuva serôdia do primeiro mês, a sega do
// trigo, o calor de Tamuz, a vindima, as cabanas do sétimo mês, a aradura, o
// frio, a saraiva, as amendoeiras em flor e a parição do fim do ano. Depois os
// príncipes das tribos, cada um na sua terra. Depois a nota mais escura do
// capítulo: "Joabe, filho de Zeruia, tinha começado a numerá-los, porém não
// acabou; porquanto viera por isso GRANDE IRA sobre Israel; assim o número não
// se pôs no registro das crônicas do rei Davi" — o único beat de noite deste
// capítulo, um rolo fechado que ninguém escreveu. E então a parte mais
// bonita: OS MORDOMOS DA FAZENDA DO REI, cada um com o seu domínio — os
// tesouros do rei e os tesouros dos campos, das cidades, das aldeias e das
// torres; os que faziam a obra do campo na lavoura da terra; as vinhas de
// Simei, o ramatita, e o que das vides entrava NAS ADEGAS DO VINHO; os olivais
// e os sicômoros das campinas, e os ARMAZÉNS DO AZEITE; os gados que pastavam
// em SAROM e os gados dos vales; os camelos do ismaelita, as jumentas do
// meronotita e o gado miúdo do hagrita. Fecha na câmara do conselho: Jônatas,
// tio de Davi, "homem entendido, e também escriba"; Aitofel; HUSAI, O ARQUITA,
// AMIGO DO REI; e Joabe, general do exército — os quatro nomes que a história
// de 2 Samuel já gastou, sentados juntos uma última vez.
//
// A VOZ DE DEUS — nestes quatro capítulos Deus NÃO FALA UMA ÚNICA VEZ, e por
// isso não há um só `by:"deus"` aqui. Ele aparece três vezes, e as três são
// MUDAS. Em 26:5, no meio da contagem dos filhos de Obede-Edom, o Cronista
// interrompe a lista para explicar por que aquela casa tem tantos: "porque
// Deus o tinha abençoado" — não há balão, há glória alta sobre um pátio cheio
// de crianças, e a bênção é o próprio quadro. Em 27:23 o texto diz que Davi
// não contou os de vinte anos para baixo "porquanto o Senhor tinha falado que
// havia de multiplicar a Israel como as estrelas do céu": é uma promessa
// CITADA pelo narrador, feita a Abraão séculos antes e sem mediador nenhum em
// cena — o certo aqui não é voz do céu, é o céu ele mesmo, `starfield` alto
// sobre os rapazes que ninguém numerou. E em 27:24 a ira de Deus é a razão de
// um número não existir: nenhuma voz, nenhuma figura, só a noite, o rolo
// fechado e Joabe de pé diante de uma conta que ele não teve licença de
// acabar. Onde há mediador humano, o balão sai dele: Semaías escrevendo
// perante o rei (24:6), Davi mandando (25:1-2), Hemã dirigindo os filhos
// (25:6). Onde não há, não há balão — e é o desenho que fala.
// ============================================================================

