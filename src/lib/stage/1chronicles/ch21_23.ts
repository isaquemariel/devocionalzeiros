// 1 CRÔNICAS 21–23 — CENA VIVA. Três capítulos que nascem de um pecado e
// terminam num templo: o censo que custou setenta mil homens, a eira comprada
// pelo seu valor integral, e a lista dos que iam servir naquele lugar cada
// manhã e cada tarde, para sempre. O Cronista não conta o adultério de Davi;
// conta ESTE pecado, porque foi dele que saiu o CHÃO da casa do SENHOR.
//
// 1Cr 21 — O CENSO, A PESTE E A EIRA DE ORNÃ. "Então SATANÁS se levantou contra
// Israel, e incitou Davi a numerar a Israel." Joabe resiste com a pergunta que
// desarma o rei — "porventura, ó rei meu senhor, não são todos servos de meu
// senhor? Por que procura isto o meu senhor? Porque seria isto causa de delito
// para com Israel" —, mas A PALAVRA DO REI PREVALECEU, e o capitão sai a contar
// a terra de Berseba até Dã. Volta com um milhão e cem mil homens que
// arrancavam da espada, e com uma omissão deliberada: OS DE LEVI E BENJAMIM NÃO
// CONTOU ENTRE ELES, PORQUE A PALAVRA DO REI FOI ABOMINÁVEL A JOABE. Deus fere
// Israel; Davi confessa — "gravemente pequei… procedi mui loucamente" —, e a
// palavra desce a GADE, O VIDENTE, com três coisas para escolher: três anos de
// fome, três meses de derrota, ou três dias da espada do SENHOR. O rei escolhe
// a mão que não é de homem: "caia eu, pois, nas mãos do Senhor, porque são
// muitíssimas as suas misericórdias". Caem setenta mil. E então o céu se abre
// sobre a cidade: O ANJO DO SENHOR ENTRE A TERRA E O CÉU, COM A ESPADA
// DESEMBAINHADA NA MÃO ESTENDIDA CONTRA JERUSALÉM, e debaixo dele Davi e os
// anciãos COBERTOS DE SACOS, prostrados sobre os seus rostos. O anjo manda
// levantar um altar na eira de ORNÃ, O JEBUSEU — que estava trilhando o trigo,
// vê o anjo e vê os quatro filhos se esconderem. Ornã quer dar tudo de graça,
// os bois para holocausto, os trilhos para lenha, o trigo para a oferta; e o
// rei recusa com a frase que fica: "NÃO TOMAREI O QUE É TEU, PARA O SENHOR,
// PARA QUE NÃO OFEREÇA HOLOCAUSTO SEM CUSTO". Paga seiscentos siclos de ouro,
// levanta o altar — e O SENHOR RESPONDE COM FOGO DO CÉU SOBRE O HOLOCAUSTO.
// A espada volta à bainha. E o capítulo fecha explicando por que o rei não
// desceu a Gibeom, onde estavam o tabernáculo de Moisés e o altar antigo: NÃO
// PODIA IR, PORQUE ESTAVA ATERRORIZADO POR CAUSA DA ESPADA DO ANJO.
//
// 1Cr 22 — OS PREPARATIVOS. A eira acaba de ser paga e Davi já sabe o que ela
// é: "ESTA SERÁ A CASA DO SENHOR DEUS, E ESTE SERÁ O ALTAR DO HOLOCAUSTO PARA
// ISRAEL." O resto do capítulo é canteiro de obras: os estrangeiros da terra
// ajuntados, cortadores lavrando pedras de cantaria, ferro em abundância para
// os pregos das portas, cobre QUE NÃO FOI PESADO, e madeira de cedro SEM CONTA,
// que os sidônios e os tírios traziam pelo mar. O motivo é o filho: "Salomão,
// meu filho, ainda é moço e tenro, e a casa que se há de edificar deve ser
// magnífica em excelência". Então o velho chama o moço e lhe conta o que ouviu:
// "TU DERRAMASTE SANGUE EM ABUNDÂNCIA, E FIZESTE GRANDES GUERRAS; NÃO
// EDIFICARÁS CASA AO MEU NOME" — mas nascerá um HOMEM DE REPOUSO, e o nome dele
// será SALOMÃO, "e paz e descanso darei a Israel nos seus dias". Vem então a
// conta mais alta da Escritura: CEM MIL TALENTOS DE OURO E UM MILHÃO DE
// TALENTOS DE PRATA, e cobre e ferro que não se pesou. E a ordem: "esforça-te,
// e tem bom ânimo; não temas, nem tenhas pavor… levanta-te, pois, e faze a
// obra". No fim ele se vira para os príncipes de Israel e manda que ajudem o
// moço, para que A ARCA DA ALIANÇA e os vasos sagrados entrem numa casa.
//
// 1Cr 23 — OS LEVITAS. "Sendo, pois, Davi já velho, e cheio de dias, fez a
// Salomão, seu filho, rei sobre Israel" — e a primeira coisa que o reino novo
// faz é contar quem vai servir: TRINTA E OITO MIL levitas de trinta anos para
// cima, repartidos diante dos nossos olhos como quem reparte um exército:
// VINTE E QUATRO MIL para a obra da casa, SEIS MIL POR OFICIAIS E JUÍZES,
// QUATRO MIL PORTEIROS, e QUATRO MIL PARA LOUVAREM AO SENHOR COM OS
// INSTRUMENTOS QUE EU FIZ PARA O LOUVAR, DISSE DAVI. Depois as três casas, uma
// por uma — GÉRSON com as cortinas, COATE com as coisas santas aos ombros,
// MERARI com as tábuas, as barras e as colunas —, e dentro delas as histórias
// miúdas que o Cronista não deixa cair: Jeús e Berias, que não tiveram muitos
// filhos e por isso foram contados juntos COMO UMA SÓ FAMÍLIA; Eliézer, que não
// teve outros filhos, e cuja casa mesmo assim ficou numerosa; e Eleazar, o
// merarita, QUE MORREU E NÃO TEVE FILHOS, PORÉM FILHAS, e os primos as tomaram
// por mulheres para que a herança não saísse da casa. O capítulo termina no
// encargo, que é a coisa mais bonita destes três: assistir aos filhos de Arão
// NOS ÁTRIOS E NAS CÂMARAS, cuidar dos pães da proposição e da flor de farinha,
// e ESTAR CADA MANHÃ EM PÉ PARA LOUVAR E CELEBRAR AO SENHOR, E SEMELHANTEMENTE
// À TARDE — todos os dias, para sempre, porque o tabernáculo não seria mais
// carregado: o SENHOR DEU REPOUSO AO SEU POVO, E HABITARÁ EM JERUSALÉM.
//
// A VOZ DE DEUS — este trecho tem a única TEOFANIA VISÍVEL do livro, e por isso
// a fala divina entra aqui de quatro maneiras diferentes, cada uma com o seu
// mediador. (1) Em 21:9-12 a palavra vem "a Gade, o vidente de Davi": o balão é
// de GADE (`by:"patriarca"`, id `gade-vidente`), com ele em cena — v.9 é a
// chegada da palavra e fica sem balão, v.10 é a ordem que ele recebe e v.11-12
// é ele mesmo pondo as três coisas diante do rei. (2) Em 21:15 quem fala é o
// SENHOR, e fala AO ANJO — o anjo é o destinatário, não o mediador, de modo que
// não há mediador nenhum e o balão é a voz do céu (`by:"deus"`, glória alta):
// pôr essa fala na boca do anjo seria fazê-lo mandar-se a si mesmo parar. (3)
// Em 21:18 é O ANJO DO SENHOR quem ordena, e o balão sai dele (`by:"anjo"`),
// com a figura em cena, `glow` no máximo e a espada desembainhada no ar — é o
// quadro mais alto destes três capítulos, e 21:16 o guarda sem balão nenhum,
// só o anjo entre a terra e o céu e, embaixo, o rei e os anciãos cobertos de
// sacos (`palette` cinza, que tira a coroa e o manto) prostrados em `bow`. (4)
// Em 21:26 Deus responde SEM PALAVRA: o fogo desce do céu sobre o holocausto, e
// a resposta é o `altar` com `fire` no máximo e a glória no auge — nenhum balão
// pode competir com isso. E em 22:8-10, quando Davi CITA o que o SENHOR lhe
// disse ("tu derramaste sangue em abundância… não edificarás casa ao meu
// nome"), o balão é DE DAVI, narrando ao filho: flashback citado por boca
// humana nunca vira voz do céu. Fora esses, o livro cala: em 21:7 Deus fere sem
// dizer nada, em 23:25 é Davi quem resume o que Deus fez, e o resto é ofício,
// nome e turno.
// ============================================================================

