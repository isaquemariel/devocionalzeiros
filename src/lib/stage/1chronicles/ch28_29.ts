// ============================================================================
// 1 CRÔNICAS 28–29 — CENA VIVA. O FIM DO LIVRO. Depois de vinte e sete
// capítulos de genealogias, guerras, turmas de porteiros e cantores, o
// Cronista fecha com dois capítulos que são um só ato: um rei velho de pé no
// meio da sua assembleia, entregando a obra da sua vida a um moço, e uma
// oração que é o cume de toda a Escritura sobre o que é dar a Deus o que já é
// dele.
//
// 1Cr 28 — A ASSEMBLEIA E A PLANTA DO TEMPLO. Davi ajunta em Jerusalém TODOS
// os príncipes de Israel, os príncipes das tribos, os capitães das turmas que
// serviam o rei, os capitães dos milhares e das centenas, os administradores
// de toda a fazenda e possessão do rei e de seus filhos, os oficiais, os
// poderosos e todo o homem valente. E então "PÔS-SE O REI DAVI EM PÉ" — um
// homem que já não se levanta com facilidade — e diz: "OUVI-ME, IRMÃOS MEUS, E
// POVO MEU". Em meu coração propus edificar uma casa de repouso para a arca da
// aliança do SENHOR e para o estrado dos pés do nosso Deus, e eu tinha feito o
// preparo para a edificar — "PORÉM DEUS ME DISSE: NÃO EDIFICARÁS CASA AO MEU
// NOME, PORQUE ÉS HOMEM DE GUERRA, E DERRAMASTE MUITO SANGUE". Conta então a
// cadeia inteira da escolha: de toda a casa de seu pai o SENHOR o escolheu, e
// de todos os seus filhos escolheu Salomão "PARA SE ASSENTAR NO TRONO DO REINO
// DO SENHOR SOBRE ISRAEL"; e diante de todo o Israel, congregação do SENHOR, e
// perante os ouvidos de nosso Deus, encarrega o moço com a frase que o livro
// inteiro estava esperando: "CONHECE O DEUS DE TEU PAI, E SERVE-O COM UM
// CORAÇÃO PERFEITO E COM UMA ALMA VOLUNTÁRIA; PORQUE ESQUADRINHA O SENHOR
// TODOS OS CORAÇÕES… SE O BUSCARES, SERÁ ACHADO DE TI; PORÉM, SE O DEIXARES,
// REJEITAR-TE-Á PARA SEMPRE". E aí entrega A PLANTA: o alpendre com as suas
// casas, as tesourarias, os cenáculos, as recâmaras interiores, a casa do
// propiciatório, os átrios e todas as câmaras ao redor. O peso do ouro e o
// peso da prata para cada utensílio de cada ministério; o peso dos castiçais
// de ouro e das suas candeias; o ouro das mesas da proposição; o ouro puro dos
// garfos, das bacias, dos jarros e das taças; o ouro purificado do altar do
// incenso — E O MODELO DO CARRO, A SABER, DOS QUERUBINS, QUE HAVIAM DE
// ESTENDER AS ASAS E COBRIR A ARCA DA ALIANÇA DO SENHOR. E o velho diz de onde
// veio o risco: "TUDO ISTO FEZ-ME ENTENDER O SENHOR, POR ESCRITO DA SUA MÃO".
// Fecha com a bênção do encarregamento: "ESFORÇA-TE E TEM BOM ÂNIMO, E FAZE A
// OBRA; NÃO TEMAS, NEM TE APAVORES", porque as turmas dos sacerdotes e dos
// levitas, os voluntários com sabedoria de toda a espécie, os príncipes e todo
// o povo já estão contigo para todos os teus mandados.
//
// 1Cr 29 — A OFERTA VOLUNTÁRIA E A ORAÇÃO. Davi diz à congregação que Salomão,
// a quem só Deus escolheu, é ainda MOÇO E TENRO e a obra é grande, "PORQUE NÃO
// É O PALÁCIO PARA HOMEM, MAS PARA O SENHOR DEUS". Conta o que já preparou —
// ouro, prata, cobre, ferro, madeira, ônix, pedras de engaste, pedras
// ornamentais, pedras de diversas cores, mármore em abundância — e então faz o
// que nenhum rei do livro fez: abre o SEU tesouro particular e dá TRÊS MIL
// TALENTOS DE OURO DE OFIR E SETE MIL TALENTOS DE PRATA PURIFICADA para cobrir
// as paredes das casas. E pergunta: "QUEM, POIS, ESTÁ DISPOSTO A ENCHER A SUA
// MÃO, PARA OFERECER HOJE VOLUNTARIAMENTE AO SENHOR?". Então os chefes dos
// pais, os príncipes das tribos, os capitães de mil e de cem e os chefes da
// obra do rei contribuíram voluntariamente — cinco mil talentos e dez mil
// dracmas de ouro, dez mil de prata, dezoito mil de cobre, cem mil de ferro —,
// e quem tinha pedras preciosas deu-as ao tesouro a cargo de Jeiel, o
// gersonita. "E O POVO SE ALEGROU PORQUE CONTRIBUÍRAM VOLUNTARIAMENTE; PORQUE,
// COM CORAÇÃO PERFEITO, VOLUNTARIAMENTE DERAM AO SENHOR; E TAMBÉM O REI DAVI
// SE ALEGROU COM GRANDE ALEGRIA." E vem a oração, que é o cume do livro:
// "BENDITO ÉS TU, SENHOR DEUS DE ISRAEL, NOSSO PAI, DE ETERNIDADE EM
// ETERNIDADE"; "TUA É, SENHOR, A MAGNIFICÊNCIA, E O PODER, E A HONRA, E A
// VITÓRIA, E A MAJESTADE; PORQUE TEU É TUDO QUANTO HÁ NOS CÉUS E NA TERRA";
// "PORQUE TUDO VEM DE TI, E DO QUE É TEU TO DAMOS"; "PORQUE SOMOS
// ESTRANGEIROS DIANTE DE TI, E PEREGRINOS COMO TODOS OS NOSSOS PAIS; COMO A
// SOMBRA SÃO OS NOSSOS DIAS SOBRE A TERRA, E SEM TI NÃO HÁ ESPERANÇA". No dia
// seguinte imolam MIL BEZERROS, MIL CARNEIROS E MIL CORDEIROS com as suas
// libações, e comem e bebem perante o SENHOR com grande gozo, e fazem SEGUNDA
// VEZ rei a Salomão e o ungem ao SENHOR por líder, e a Zadoque por sacerdote.
// Salomão se assenta no TRONO DO SENHOR, e o SENHOR o magnifica
// grandissimamente perante os olhos de todo o Israel. E o livro termina como
// um epitáfio sem uma sombra: quarenta anos de reinado, sete em Hebrom e trinta
// e três em Jerusalém, "E MORREU NUMA BOA VELHICE, CHEIO DE DIAS, RIQUEZAS E
// GLÓRIA" — com os atos, os primeiros e os últimos, escritos nas crônicas de
// Samuel, o vidente, do profeta Natã e de Gade, o vidente.
//
// A VOZ DE DEUS — nestes dois capítulos Deus NÃO FALA UMA ÚNICA VEZ em voz
// direta, e por isso não há nenhum `by:"deus"` aqui. Em 28:3 e 28:6-7 o texto
// põe a palavra dele na boca de Davi no PASSADO — "porém Deus me disse", "e me
// disse" —: é FLASHBACK CITADO diante de uma assembleia, e o balão é DO REI,
// que está de pé em cena narrando. Pôr voz do céu num flashback citado seria
// fazer Deus falar duas vezes o que ele falou uma. Em 28:19 acontece a coisa
// mais próxima de uma teofania destes capítulos, e ainda assim é MUDA: "tudo
// isto fez-me entender o SENHOR, POR ESCRITO DA SUA MÃO" — a palavra veio como
// RISCO, não como voz, e por isso o beat é o rolo aberto com glória alta e o
// balão do rei, não do céu. Em 28:18 os QUERUBINS DE ASAS ESTENDIDAS cobrindo
// a arca são o ponto mais alto do capítulo, e ali também ninguém fala: a
// glória sobe ao máximo e o desenho carrega a cena sozinho. Em 29:10-19 Davi
// fala COM Deus, e não por Deus: dez beats de oração em que o balão é sempre
// do rei e a resposta do céu é só a luz subindo estrofe a estrofe — com a
// única queda em 29:14-15, "como a sombra são os nossos dias sobre a terra",
// onde a cena sai de Jerusalém para a estrada dos peregrinos, o sol quase no
// horizonte e a glória no chão, antes de voltar a subir em 29:16. É a regra do
// livro inteiro: onde não há mediador nem voz, a presença se conta pela luz.
// ============================================================================

