// 1 CRÔNICAS 17–20 — CENA VIVA. Quatro capítulos que são um só arco: a PROMESSA
// e o que ela produz. Primeiro Deus recusa a casa que Davi queria construir e
// promete construir a casa DELE; depois o reino cresce em todas as direções, e
// as nações que cercavam Israel vão caindo uma a uma — filisteus, moabitas,
// sírios, edomitas, amonitas — até os últimos gigantes de Gate.
//
// 1Cr 17 — O CONCERTO COM DAVI. O rei já mora em casa de cedro, e a frase que
// abre o capítulo é o incômodo de um homem confortável: "EIS QUE MORO EM CASA
// DE CEDRO, MAS A ARCA DA ALIANÇA DO SENHOR ESTÁ DEBAIXO DE CORTINAS." Natã
// responde de improviso — "tudo quanto tens no teu coração faze, porque Deus é
// contigo" — e naquela MESMA NOITE a palavra de Deus vem ao profeta e desfaz o
// conselho: "Tu não me edificarás uma casa para eu morar". A razão é a coisa
// mais desarmante do Antigo Testamento: Deus nunca pediu casa. "Porque em casa
// nenhuma morei, desde o dia em que fiz subir a Israel até ao dia de hoje; mas
// FUI DE TENDA EM TENDA, E DE TABERNÁCULO EM TABERNÁCULO"; e a nenhum dos
// juízes Ele jamais perguntou "por que não me edificais uma casa de cedro?".
// Então a frase vira do avesso: "EU TE TIREI DO CURRAL, DE DETRÁS DAS OVELHAS",
// "de diante de ti exterminei todos os teus inimigos", "ordenarei um lugar para
// o meu povo Israel, e o plantarei" — e, no meio, o trocadilho que sustenta o
// resto da Bíblia: "TAMBÉM TE FAÇO SABER QUE O SENHOR TE EDIFICARÁ UMA CASA".
// Não a casa de pedra: a casa de descendência. Um dos filhos virá, "ESTE ME
// EDIFICARÁ CASA; E EU CONFIRMAREI O SEU TRONO PARA SEMPRE", "eu lhe serei por
// pai, e ele me será por filho". E aí vem o beat mais quieto de todo o trecho:
// "ENTÃO ENTROU O REI DAVI, E FICOU PERANTE O SENHOR" — um homem sozinho no
// chão, diante de uma tenda, sem coroa na frase: "QUEM SOU EU, SENHOR DEUS? E
// QUAL É A MINHA CASA, PARA QUE ME TENHAS TRAZIDO ATÉ AQUI?" A oração atravessa
// doze versículos e passa uma vez pela memória do Egito — "quem há como o teu
// povo Israel, única gente na terra, a quem Deus foi resgatar" — e termina em
// bênção: "porque tu, Senhor, a abençoaste, e ficará abençoada para sempre."
//
// 1Cr 18 — AS VITÓRIAS. Capítulo de mapa: Davi derrota os filisteus e toma
// GATE; derrota MOABE, que fica pagando tributo; derrota HADAR-EZER, REI DE
// ZOBÁ, junto a Hamate, "quando ele ia estabelecer o seu domínio sobre o rio
// Eufrates", e lhe toma mil carros, sete mil cavaleiros e vinte mil homens de
// pé — E JARRETA TODOS OS CAVALOS DOS CARROS, reservando apenas cem, porque
// Israel não quis a cavalaria das nações. Os sírios de Damasco vêm socorrer
// Hadar-Ezer e caem vinte e dois mil; ficam as guarnições, e o texto para para
// dizer duas vezes a mesma coisa: "E O SENHOR GUARDAVA A DAVI, POR ONDE QUER
// QUE IA". Os ESCUDOS DE OURO dos servos de Hadar-Ezer sobem a Jerusalém, e o
// muitíssimo cobre de Tibate e de Cum vira, uma geração depois, o MAR DE COBRE,
// as colunas e os utensílios do templo de Salomão — o bronze do inimigo virando
// material do culto. TOÍ, REI DE HAMATE, que era guerreado por Hadar-Ezer,
// manda o filho Hadorão com vasos de ouro, prata e cobre, e Davi consagra tudo
// ao SENHOR. Abisai fere dezoito mil edomeus no VALE DO SAL, e o capítulo fecha
// no trono e na lista dos oficiais: Joabe sobre o exército, Jeosafá cronista,
// Zadoque e Abimeleque sacerdotes, Savsa escrivão, Benaia sobre os quereteus e
// peleteus, e os filhos de Davi "os primeiros junto ao rei".
//
// 1Cr 19 — A AFRONTA DOS AMONITAS. Morre Naás, e Davi, que lhe devia uma
// gentileza antiga, manda consoladores ao filho HANUM. Os príncipes de Amom
// leem a bondade como reconhecimento: "Pensas porventura, que foi para honrar
// teu pai aos teus olhos, que Davi te mandou consoladores? Não vieram seus
// servos a ti, A ESQUADRINHAR, E A TRANSTORNAR, E A ESPIAR A TERRA?" Hanum
// escuta, e faz aos embaixadores o que se faz a um cativo: RASPA-LHES A BARBA
// E CORTA-LHES AS VESTES NO MEIO ATÉ À COXA DA PERNA, e os despede. Davi não
// os manda entrar: "DEIXAI-VOS FICAR EM JERICÓ, ATÉ QUE VOS TORNE A CRESCER A
// BARBA, E ENTÃO VOLTAI" — a única cortesia possível é dar-lhes tempo. Amom
// paga mil talentos de prata e aluga TRINTA E DOIS MIL CARROS e o rei de Maaca;
// e Joabe se acha com a batalha "PELA FRENTE E PELA RETAGUARDA". Divide o povo
// com o irmão, combina o socorro mútuo e diz a frase que é a teologia militar
// inteira do Cronista: "ESFORÇA-TE, E ESFORCEMO-NOS PELO NOSSO POVO, E PELAS
// CIDADES DO NOSSO DEUS, E FAÇA O SENHOR O QUE PARECER BEM AOS SEUS OLHOS."
// Os sírios fogem, os amonitas se fecham na cidade; os sírios de além do rio
// voltam com Sofaque à frente, e Davi passa o Jordão em pessoa e acaba a
// guerra: sete mil carros, quarenta mil homens de pé, e Sofaque morto.
//
// 1Cr 20 — RABÁ E OS GIGANTES. No tempo em que os reis saem para a guerra,
// Joabe destrói Rabá — "porém Davi ficou em Jerusalém", e o Cronista não conta
// o que aconteceu em Jerusalém naquele ano. Davi tira A COROA DA CABEÇA DO REI
// DELES, "e achou nela o peso de um talento de ouro, e havia nela pedras
// preciosas", e ela é posta sobre a sua cabeça. Depois, três golpes secos
// contra a raça que sobrou de Gate: SIBECAI, O HUSATITA, fere a SIPAI, dos
// filhos do gigante; EL-HANÃ, FILHO DE JAIR, fere a LAMI, IRMÃO DE GOLIAS, "o
// giteu, cuja haste da lança era como órgão de tecelão"; e em Gate aparece o
// último — UM HOMEM DE GRANDE ESTATURA, "E TINHA VINTE E QUATRO DEDOS, SEIS EM
// CADA MÃO, E SEIS EM CADA PÉ" — que injuria a Israel e cai pela mão de
// Jônatas, filho de Simei, IRMÃO DE DAVI. "Estes nasceram ao gigante em Gate; e
// caíram pela mão de Davi e pela mão dos seus servos."
//
// A VOZ DE DEUS — Deus fala uma vez só neste trecho, e fala por MEDIADOR. Em
// 17:3 "a palavra de Deus veio a Natã", e é NATÃ quem a leva a Davi: por isso
// os balões de 17:4-14 são todos do profeta (`by:"patriarca"`, id
// `nata-profeta`, com `glow` alto), e NÃO há um único `by:"deus"` em 1Cr 17-20.
// A cena acompanha a palavra em vez de repetir o quarto do profeta: a visão
// abre o tabernáculo do deserto quando Ele diz que foi "de tenda em tenda"
// (v.5-6), abre o curral de Belém quando diz "eu te tirei do curral, de detrás
// das ovelhas" (v.7-8), abre a terra plantada (v.9-10) e a casa que o filho
// edificará (v.11-14) — e só então volta ao pátio do rei, onde "conforme toda
// esta visão, assim falou Natã a Davi" (v.15). A oração de 17:16-27 é de DAVI
// (`by:"rei"`), não de Deus; e as duas linhas em que o SENHOR age em 18:6 e
// 18:13 — "e o Senhor guardava a Davi, por onde quer que ia" — são NARRATIVAS,
// sem balão nenhum: ali a intervenção divina é só a glória subindo no ambiente
// enquanto as guarnições se plantam. Em 19:5 o balão é do MENSAGEIRO que leva
// a Jericó a palavra do rei (`by:"servo"`), porque o rei está em Jerusalém e a
// cena é a vergonha dos embaixadores debaixo das palmeiras — arauto em cena
// vale mais do que voz creditada na barra do narrador. E em 19:13, quando
// Joabe diz "faça o SENHOR o que parecer bem aos seus olhos", o balão é de
// JOABE: é um homem entregando a Deus o resultado, não Deus falando.
// ============================================================================

