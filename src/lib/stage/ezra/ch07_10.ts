// ESDRAS 7–10 — CENA VIVA. Cinquenta e oito anos depois de acabada a casa,
// entra um homem que não traz pedreiro nenhum: traz um ROLO. E o livro, que
// começou com fundamentos e trombetas, acaba com uma lista de nomes debaixo de
// chuva e sem consolo nenhum no último versículo.
//
// Esdras 7 — o texto apresenta o homem subindo a sua própria genealogia, de
// degrau em degrau, até parar em ARÃO, O SUMO SACERDOTE: é filho de sacerdote,
// e por isso o rolo na mão dele tem direito de estar ali. "Este Esdras subiu de
// babilônia; e era escriba hábil na lei de Moisés" — e a viagem inteira, quatro
// meses de estrada, é resumida por uma coisa só que não se desenha: "segundo a
// boa mão do seu Deus sobre ele". Aí vem o versículo que governa o livro
// inteiro e que é a razão de tudo o mais: "PORQUE ESDRAS TINHA PREPARADO O SEU
// CORAÇÃO PARA BUSCAR A LEI DO SENHOR E PARA CUMPRI-LA E PARA ENSINAR EM ISRAEL
// OS SEUS ESTATUTOS E OS SEUS JUÍZOS" (7:10) — buscar, cumprir, ensinar, nessa
// ordem, e o resto do livro é a conta dessa ordem sendo paga. Depois o texto
// abre a CARTA de Artaxerxes por extenso, do "rei dos reis" ao último item:
// quem quiser ir, vá; a prata e o ouro voluntários; o que se há de comprar com
// o dinheiro — novilhos, carneiros, cordeiros, ofertas de alimentos e libações;
// os utensílios restituídos; a conta aberta na casa dos tesouros do rei, até
// cem talentos de prata e SAL À VONTADE; a isenção de tributo para sacerdotes,
// levitas, cantores, porteiros e servidores do templo; e a autoridade para
// nomear magistrados e juízes. E o capítulo fecha na boca de Esdras, que não
// bendiz o rei: "Bendito seja o Senhor Deus de nossos pais, QUE TAL INSPIROU AO
// CORAÇÃO DO REI".
//
// Esdras 8 — a lista dos chefes das casas paternas que sobem com ele não é
// arquivo: é gente carregando fardo, casa por casa, do portão do rio até o
// último que chegou de tarde. Então o RIO QUE VAI A AAVA, três dias de
// acampamento, e um homem que ATENTA PARA O POVO e descobre um buraco no meio
// dele: "não achei ali nenhum dos filhos de Levi". Manda onze chefes a Casifia,
// a Ido, e voltam com Serebias e Hasabias e duzentos e vinte servidores do
// templo. E aí o jejum junto ao rio, "para nos humilharmos diante da face de
// nosso Deus, para lhe pedirmos caminho seguro" — porque ele TEVE VERGONHA de
// pedir ao rei exército e cavaleiros, tendo dito ao rei, na cara, que a mão do
// seu Deus é sobre todos os que o buscam. A prata, o ouro e os vasos são
// PESADOS na mão de doze sacerdotes ("Vós sois santos ao Senhor, e são santos
// estes utensílios"), viajam quatro meses sem guarda armada, e são pesados
// OUTRA VEZ na chegada: "Tudo foi contado e pesado". Nada faltou.
//
// Esdras 9 — e o chão cede. Os príncipes chegam com a notícia de que o povo,
// os sacerdotes e os levitas não se separaram das abominações das terras, e a
// frase que corta é a última: "até os príncipes e magistrados foram os
// primeiros nesta transgressão". Esdras rasga as vestes e o manto, ARRANCA os
// cabelos da cabeça e da barba e SENTA-SE ATÔNITO — e fica ali, sem falar, até
// o sacrifício da tarde. Só então se levanta, põe-se de joelhos, estende as
// mãos e ora a oração que não pede nada: "Meu Deus! Estou confuso e
// envergonhado, para levantar a ti a minha face". Fala de "um pequeno momento"
// de graça, de "uma estaca no seu santo lugar", de "uma parede de proteção em
// Judá e em Jerusalém" — e termina sem pedido, só com a posição: "eis que
// estamos diante de ti, na nossa culpa".
//
// Esdras 10 — enquanto ele ora prostrado diante da casa de Deus, ajunta-se uma
// GRANDE congregação de homens, mulheres e crianças, "pois o povo chorava com
// grande choro". Quem fala primeiro não é ele: é SECANIAS, FILHO DE JEIEL, que
// diz a única palavra de esperança do capítulo — "ainda há esperança para
// Israel" — e manda o velho levantar-se: "Levanta-te, pois, porque te pertence
// este negócio". Pregão por Judá e Jerusalém, três dias de prazo, e então o
// quadro que o capítulo guarda para si: nono mês, aos vinte dias, todo o povo
// assentado na praça da casa de Deus, TREMENDO POR ESTE NEGÓCIO E POR CAUSA DAS
// GRANDES CHUVAS — gente encharcada, tremendo de frio e de medo ao mesmo tempo,
// e a resposta honesta de que aquilo não se resolve num dia nem em dois. Quatro
// homens se opõem. A comissão senta no primeiro dia do décimo mês e só acaba no
// primeiro dia do primeiro mês. E aí a lista: casa por casa, ofício por ofício,
// sacerdotes, levitas, cantores, porteiros e Israel — até o versículo 44, que
// é o fim do livro e não tem consolo nenhum: "Todos estes tomaram mulheres
// estrangeiras; e alguns deles tinham mulheres de quem tiveram filhos".
//
// A VOZ DE DEUS — em Esdras 7–10 Deus NÃO fala uma única vez, nem do céu nem
// por profeta, e por isso NÃO HÁ NENHUM `by:"deus"` neste arquivo. Ele age
// calado, e o texto o diz sempre pela mesma imagem: A MÃO. "segundo a mão do
// SENHOR seu Deus, que estava sobre ele" (7:6), "segundo a boa mão do seu Deus
// sobre ele" (7:9), "segundo a boa mão de Deus sobre nós" (8:18), "a mão do
// nosso Deus estava sobre nós, e livrou-nos" (8:31) — mão que não se desenha,
// e por isso a cena a conta por GLÓRIA subindo sem figura nenhuma no alto e por
// gente que chega inteira onde não devia chegar. Os balões grandes do trecho
// são de três bocas humanas: ESDRAS (`by:"patriarca"`, id `esdras-o-escriba`) na
// bênção de 7:27-28, na entrega dos utensílios de 8:28-29, na oração de joelhos
// de 9:6-15 e no discurso da chuva de 10:10-11 — sempre com `glow`, nunca com
// voz do céu, porque quem fala é o homem; os PRÍNCIPES que trazem a denúncia de
// 9:1-2 (`by:"anciao"`); e SECANIAS em 10:2-4 (`by:"homem"`), que é quem tem a
// única palavra de esperança. A CARTA de Artaxerxes (7:12-26) é o caso do
// MEDIADOR DE OBJETO: o balão sai de quem a dita e a lê — o próprio rei
// (`by:"rei"`, id `artaxerxes-rei-da-persia`) — e o `scroll` domina o quadro em
// `scale` 2 ou mais, do trono ao tesouro, do mercado do portão à mão de Esdras.
// A congregação de 10:12-14 responde por uma voz só (`by:"homem"`, id
// `voz-da-congregacao-debaixo-da-chuva`), nunca por `multidao`: aquela gente
// está tremendo de frio, e `multidao` só sabe comemorar.
// ============================================================================

