// ESDRAS 1–6 — CENA VIVA. O livro começa exatamente onde 2 Crônicas parou: o
// mesmo pregão, o mesmo rei persa, o mesmo rolo — só que agora visto do lado de
// cá, do lado de quem ouviu e arrumou a trouxa. Seis capítulos que vão do
// decreto de Ciro à páscoa comida dentro de uma casa acabada, e que passam, no
// meio, por uma lista de setenta versículos, por um choro que ninguém conseguia
// distinguir do júbilo, e por dezesseis anos de obra parada.
//
// Esdras 1 — O DECRETO, DO LADO DE CÁ. "No primeiro ano de Ciro, rei da Pérsia
// (para que se cumprisse a palavra do SENHOR, pela boca de Jeremias), despertou
// o SENHOR o espírito de Ciro" — e o pregão sai por todo o reino, "como também
// por escrito". A frase que muda tudo é curta: "QUEM HÁ ENTRE VÓS… E SUBA A
// JERUSALÉM". Levantam-se os chefes dos pais de Judá e Benjamim, os sacerdotes,
// os levitas, "com todos aqueles cujo espírito Deus despertou" — e os vizinhos,
// que não sobem, firmam-lhes as mãos com prata, ouro, bens, gado e coisas
// preciosas. Então Ciro manda abrir a casa dos seus próprios deuses e tira de lá
// os UTENSÍLIOS que Nabucodonosor tinha trazido de Jerusalém: pela mão de
// Mitredate, o tesoureiro, entregues CONTADOS a Sesbazar, príncipe de Judá —
// trinta travessas de ouro, mil de prata, vinte e nove facas, trinta bacias de
// ouro, quatrocentas e dez de prata, mil outros utensílios; cinco mil e
// quatrocentos ao todo. O capítulo acaba com esses números a caminho de casa.
//
// Esdras 2 — A LISTA. Setenta versículos de nomes e de contas, e a tentação de
// desenhar "o povo" setenta vezes. Mas a lista não é uma multidão: é um mapa. É
// um mapa de CASAS PATERNAS (os filhos de Parós, de Sefatias, de Ará, de
// Paate-Moabe), de CIDADES (Belém, Netofá, Anatote, Micmás, Betel e Ai, Lode,
// Hadide e Ono, Jericó, Senaá) e de OFÍCIOS: os sacerdotes por casas, os levitas,
// os cantores filhos de Asafe, os PORTEIROS — Salum, Ater, Talmom, Acube,
// Hatita, Sobai —, os NETININS nome por nome, e os filhos dos servos de
// Salomão. No meio dela há um drama pequeno e duro: os que subiram de Tel-Melá e
// Tel-Harsa e não puderam provar a linhagem, e os filhos dos sacerdotes que
// procuraram o seu registro "mas não se acharam nelas" e foram excluídos do
// sacerdócio até que houvesse sacerdote "com Urim e com Tumim". E o fecho é
// aritmética que vira gente: quarenta e dois mil trezentos e sessenta, mais sete
// mil trezentos e trinta e sete servos, duzentos cantores e cantoras, setecentos
// e trinta e seis cavalos, duzentos e quarenta e cinco mulos, quatrocentos e
// trinta e cinco camelos, seis mil setecentos e vinte jumentos — e as ofertas
// voluntárias dos chefes "para a estabelecerem no seu lugar".
//
// Esdras 3 — O SÉTIMO MÊS. Ajunta-se o povo "como um só homem" em Jerusalém.
// Jesuá, filho de Jozadaque, com os sacerdotes, e Zorobabel, filho de Sealtiel,
// edificam o ALTAR antes de qualquer parede — e o firmam sobre as suas bases
// "porque o terror estava sobre eles, por causa dos povos das terras". Vêm os
// holocaustos da manhã e da tarde, a festa dos tabernáculos, o dinheiro aos
// pedreiros e carpinteiros, e os cedros do Líbano descendo ao mar para Jope
// "segundo a concessão que lhes tinha feito Ciro". No segundo ano, no segundo
// mês, começa a obra; e quando os edificadores lançam os alicerces, os
// sacerdotes aparecem vestidos e com trombetas e os levitas filhos de Asafe com
// címbalos, e cantam "porque é bom; porque a sua benignidade dura para sempre
// sobre Israel". Aí vem o quadro mais difícil do livro: os velhos que viram a
// primeira casa CHORAM EM ALTAS VOZES enquanto os outros jubilam — e "não
// discernia o povo as vozes do júbilo de alegria das vozes do choro do povo".
//
// Esdras 4 — A OBRA PARADA. Os adversários chegam com uma frase mansa —
// "Deixai-nos edificar convosco, porque, como vós, buscaremos a vosso Deus" — e
// levam um não. Então mudam de arma: debilitam as mãos do povo, alugam
// conselheiros, e escrevem. Escrevem no reinado de Assuero; escrevem nos dias de
// Artaxerxes, em caracteres siríacos; e escrevem, Reum, o chanceler, e Sinsai, o
// escrivão, a carta que chama Jerusalém de "aquela rebelde e malvada cidade" e
// avisa o rei que, se ela se reedificar, "não terás porção alguma deste lado do
// rio". A resposta volta em rolo: buscaram nas crônicas, acharam a rebelião
// antiga, e o rei manda impedir. Reum e Sinsai vão a Jerusalém "apressadamente"
// e param a obra "à força e com violência" — e ela fica parada até ao ano
// segundo do reinado de Dario. As cartas, aqui, são o verdadeiro personagem: o
// balão sai de quem as lê, e o rolo domina o quadro.
//
// Esdras 5 — DOIS PROFETAS. O que destrava a obra não é um decreto: são duas
// bocas. "E os profetas Ageu e Zacarias, filho de Ido, profetizaram aos judeus…
// em nome do Deus de Israel lhes profetizaram" — e Zorobabel e Jesuá se
// levantam e recomeçam, "e com eles os profetas de Deus, que os ajudavam".
// Tatenai, governador dalém do rio, e Setar-Bozenai aparecem com a pergunta de
// sempre: "Quem vos deu ordem para reedificardes esta casa?" — e pedem até os
// nomes dos construtores. Mas "os olhos de Deus estavam sobre os anciãos dos
// judeus, e não os impediram". A carta que Tatenai escreve a Dario é honesta:
// descreve as grandes pedras e a madeira já posta nas paredes, repete a resposta
// dos anciãos — "Nós somos servos do Deus dos céus e da terra" —, conta
// Nabucodonosor, conta Ciro, conta Sesbazar, e termina pedindo que se busque na
// casa dos tesouros se aquele decreto existe mesmo.
//
// Esdras 6 — O ROLO ACHADO. Buscaram — e em ACMETA, no palácio da província de
// Média, acharam um rolo com o memorial de Ciro: sessenta côvados de altura,
// sessenta de largura, três carreiras de grandes pedras e uma de madeira nova, e
// a despesa por conta da casa do rei. Dario despacha por cima: apartai-vos dali,
// deixai que se faça a obra, pague-se da fazenda do rei, e dê-se o necessário —
// bezerros, carneiros, cordeiros, trigo, sal, vinho e azeite — "de dia em dia,
// para que não haja falta". Quem mudar o decreto será pendurado num madeiro da
// própria casa. Tatenai obedece diligentemente; os anciãos vão edificando "pela
// profecia do profeta Ageu, e de Zacarias, filho de Ido"; e a casa acaba no
// terceiro dia do mês de Adar, no sexto ano de Dario. A dedicação sai com cem
// novilhos, duzentos carneiros, quatrocentos cordeiros e doze cabritos, um por
// tribo. E no dia catorze do primeiro mês os filhos do cativeiro comem a páscoa,
// com todos os que se apartaram da imundícia dos gentios da terra — sete dias de
// pães ázimos com alegria, "porque o Senhor os tinha alegrado".
//
// A VOZ DE DEUS — em Esdras 1–6 Deus NÃO fala uma única vez sem mediador, e por
// isso NÃO HÁ NENHUM `by:"deus"` neste arquivo. Em 1:1 Ele age calado e por
// dentro — "despertou o SENHOR o espírito de Ciro" —, e o quadro tem de dizer
// isso sem balão: a glória alta em cima de um rei pagão que escreve, e o rolo na
// mesa. Em 5:1-2 a palavra tem boca e tem nome: AGEU e ZACARIAS, FILHO DE IDO,
// estão em cena (`patriarca`, ids `ageu-profeta` e `zacarias-filho-de-ido`) com
// `glow` alto, e o balão sai DELES, nunca do céu. Em 5:5 "os olhos de Deus
// estavam sobre os anciãos dos judeus" é a mesma coisa por outro meio: glória no
// zênite em cima de velhos que continuam trabalhando, sem figura nenhuma. Os
// outros mediadores do livro são de PAPEL: o pregão de Ciro (1:2-4), a carta de
// Reum e Sinsai (4:11-16), a resposta de Artaxerxes (4:17-22), a carta de
// Tatenai (5:7-17) e o rolo de Acmeta (6:2-12). Em todos eles quem fala é quem
// LÊ — o arauto, o chanceler, o escrivão, o governador, o rei —, e o `scroll`
// entra grande, em `scale` 1,9 a 2,4, porque naquele versículo o objeto é o
// personagem.
// ============================================================================

