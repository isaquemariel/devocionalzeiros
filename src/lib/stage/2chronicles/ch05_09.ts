// 2 CRÔNICAS 5–9 — CENA VIVA. O ponto mais alto do livro e o ponto mais alto de
// Israel: a arca entra na casa, os cantores fazem "ouvir uma só voz", a nuvem
// derruba o ministério dos sacerdotes, o fogo desce do céu diante de todo o
// povo, e um rei de joelhos sobre um púlpito de bronze faz a oração mais longa
// da Escritura. Depois vem a riqueza — e é dela que o livro se despede.
//
// 2Cr 5 — A OBRA ACABADA E A NUVEM. O capítulo abre fechando: "assim se acabou
// toda a obra que Salomão fez para a casa do SENHOR", e o que sobra da prata,
// do ouro e dos objetos que Davi consagrara vai para os tesouros. Então o rei
// congrega em Jerusalém os anciãos, os chefes das tribos e os chefes dos pais
// para fazerem subir A ARCA da cidade de Davi, que é Sião — na festa do sétimo
// mês. Os levitas levantam a arca; sobem com ela A TENDA DA CONGREGAÇÃO e todos
// os objetos sagrados; e no caminho se sacrificam carneiros e bois "que não se
// podiam contar, nem numerar, por causa da sua abundância". A arca desce ao
// oráculo, ao lugar santíssimo, "até debaixo das asas dos querubins", que a
// cobrem por cima com as duas asas; os varais sobressaem tanto que as pontas se
// veem de dentro e não de fora — "e ali tem estado até ao dia de hoje". E então
// o inventário mais curto e mais pesado do livro: "NA ARCA NÃO HAVIA COISA
// ALGUMA SENÃO AS DUAS TÁBUAS, QUE MOISÉS TINHA POSTO EM HOREBE". Saindo os
// sacerdotes do santuário — todos santificados, sem respeitarem as suas turmas,
// porque naquele dia não havia escala que coubesse —, vem o quadro mais alto:
// OS LEVITAS CANTORES, todos eles, de Asafe, de Hemã e de Jedutum, VESTIDOS DE
// LINHO FINO, com címbalos, saltérios e harpas, em pé para o oriente do altar,
// "e com eles até cento e vinte sacerdotes, que tocavam as trombetas". Tocam
// uniformemente, "PARA FAZEREM OUVIR UMA SÓ VOZ", louvando: "porque ele é bom,
// porque a sua benignidade dura para sempre" — e a casa se enche de UMA NUVEM,
// e os sacerdotes não podem permanecer em pé para ministrar, "porque a glória
// do SENHOR encheu a casa de Deus". O culto para porque Deus chegou.
//
// 2Cr 6 — A ORAÇÃO SOBRE O PÚLPITO DE BRONZE. Quarenta e dois versículos, e o
// palco é uma peça só: "Salomão tinha feito uma plataforma de metal, de cinco
// côvados de comprimento, de cinco de largura e de três de altura, e a tinha
// posto no meio do pátio" — e é ali que ele se ajoelha diante de toda a
// congregação e estende as mãos para o céu. Começa reconhecendo o paradoxo:
// "o SENHOR disse que habitaria nas trevas — e eu te tenho edificado uma casa".
// Bendiz a Deus pela promessa a Davi, lembra que não foi escolhida cidade
// alguma até Jerusalém nem homem algum até Davi, e que o pai teve no coração
// edificar a casa e ouviu "BEM FIZESTE DE TER ISTO NO TEU CORAÇÃO — contudo tu
// não edificarás". Depois vem a pergunta que nenhuma dedicação de templo ousou
// fazer: "MAS, NA VERDADE, HABITARÁ DEUS COM OS HOMENS NA TERRA? EIS QUE OS
// CÉUS, E O CÉU DOS CÉUS, NÃO TE PODEM CONTER, QUANTO MENOS ESTA CASA QUE TENHO
// EDIFICADO?". E a oração se abre em SETE CASOS concretos, cada um com a sua
// desgraça e a sua porta de volta: o que peca contra o próximo e é levado a
// jurar diante do altar; o povo ferido diante do inimigo; O CÉU FECHADO SEM
// CHUVA; a fome, a peste, a queima de seara, a ferrugem, OS GAFANHOTOS e a
// lagarta; O ESTRANGEIRO que "vier de terras remotas por amor do teu grande
// nome"; o povo que sai à guerra pelo caminho que Deus o enviar; e o povo
// levado cativo que cai em si e ORA PARA O LADO DA SUA TERRA. O fecho não é
// pedido: é convite — "Levanta-te, pois, agora, SENHOR Deus, para o teu
// repouso, tu e a arca da tua fortaleza", e o último apelo é ao nome de um
// morto: "lembra-te das misericórdias de Davi teu servo".
//
// 2Cr 7 — O FOGO, A FESTA E A PALAVRA DA NOITE. "E acabando Salomão de orar,
// DESCEU O FOGO DO CÉU, E CONSUMIU O HOLOCAUSTO E OS SACRIFÍCIOS; e a glória do
// SENHOR encheu a casa" — os sacerdotes não conseguem sequer entrar, e todos os
// filhos de Israel, vendo descer o fogo, "ENCURVARAM-SE COM O ROSTO EM TERRA
// SOBRE O PAVIMENTO", adorando com a mesma antífona dos cantores. Sacrificam-se
// vinte e dois mil bois e cento e vinte mil ovelhas; o meio do átrio é
// santificado porque o altar de metal não dá conta; a festa dura sete dias, e
// mais sete, com uma congregação "desde a entrada de Hamate até ao rio do
// Egito", e no vigésimo terceiro dia do sétimo mês o povo volta às suas tendas
// "alegres e de bom ânimo". Então, de noite, o SENHOR aparece outra vez a
// Salomão, e diz a frase que é o coração de 2 Crônicas inteiro: "SE O MEU POVO,
// QUE SE CHAMA PELO MEU NOME, SE HUMILHAR, E ORAR, E BUSCAR A MINHA FACE E SE
// CONVERTER DOS SEUS MAUS CAMINHOS, ENTÃO EU OUVIREI DOS CÉUS, E PERDOAREI OS
// SEUS PECADOS, E SARAREI A SUA TERRA" (7:14) — resposta direta e ponto por
// ponto à oração do púlpito. Mas o oráculo não acaba em bênção: se o povo se
// desviar e servir a outros deuses, a casa "tão exaltada" vira espanto e
// provérbio, e quem passar por ela perguntará por quê — e a resposta já está
// escrita antes de a pergunta existir.
//
// 2Cr 8 — AS CIDADES, AS TURMAS E A FROTA. Vinte anos de obra terminam e o
// reino se espalha: as cidades que Hirão lhe dera, Hamate-Zobá tomada, TADMOR
// no deserto, as cidades de provisões, a alta e a baixa Bete-Horom "com muros,
// portas e ferrolhos", Baalate, as cidades dos carros e as dos cavaleiros. Os
// que restaram dos heteus, amorreus, perizeus, heveus e jebuseus são postos a
// tributo — mas dos filhos de Israel nenhum é feito servo: são homens de
// guerra, capitães, condutores de carros. A filha de Faraó é mudada da cidade
// de Davi para a casa que lhe fora edificada, e a razão é litúrgica, não
// conjugal: "PORQUANTO SANTOS SÃO OS LUGARES NOS QUAIS ENTROU A ARCA DO
// SENHOR". Os holocaustos passam a correr conforme o mandamento de Moisés, e as
// turmas dos sacerdotes, dos levitas e dos porteiros conforme a ordem de Davi,
// "o homem de Deus" — e ninguém se desvia do mandado, "nem acerca dos
// tesouros". Por fim o rei desce a Eziom-Geber e a Elote, À PRAIA DO MAR, na
// terra de Edom, e a frota de Hirão leva os seus servos a OFIR e volta com
// quatrocentos e cinqüenta talentos de ouro.
//
// 2Cr 9 — A RAINHA DE SABÁ E O FIM DE SALOMÃO. Ela vem "para prová-lo com
// questões difíceis, com um grande séquito, e com camelos carregados de
// especiarias", e fala com ele "de tudo o que tinha no seu coração" — e não há
// nada que ele não lhe possa esclarecer. Vendo a sabedoria, a casa, as iguarias
// da mesa, o assentar dos servos, o estar dos criados e as vestes deles, os
// copeiros, e A SUBIDA PELA QUAL ELE CHEGAVA À CASA DO SENHOR, "ela ficou como
// fora de si": "não me disseram a metade da grandeza da tua sabedoria". Dá cento
// e vinte talentos de ouro e especiarias como nunca houve; recebe de volta tudo
// quanto desejou, e volta para a sua terra. Depois o inventário do apogeu:
// seiscentos e sessenta e seis talentos de ouro por ano, os duzentos paveses e
// os trezentos escudos de ouro batido na casa do bosque do Líbano, o GRANDE
// TRONO DE MARFIM revestido de ouro puro, com seis degraus, estrado de ouro,
// dois leões junto aos encostos e doze leões sobre os degraus — "outro tal não
// se fez em nenhum reino". A prata "reputava-se por nada"; os navios de Társis
// voltavam de três em três anos com ouro, prata, marfim, bugios e pavões; a
// prata em Jerusalém era como pedras e os cedros como as figueiras bravas das
// campinas. E aí, sem transição, o livro fecha o homem: reinou quarenta anos,
// dormiu com seus pais, foi sepultado na cidade de Davi seu pai — e Roboão, seu
// filho, reinou em seu lugar. O apogeu e o começo da divisão na mesma frase.
//
// A VOZ DE DEUS — nestes cinco capítulos Deus fala em cena UMA vez, e é sem
// mediador nenhum: em 7:12-20 "o SENHOR APARECEU DE NOITE a Salomão" — visão,
// sem profeta, sem anjo, sem objeto —, e por isso ali o balão é `by:"deus"`,
// dourado e sem figura, com a noite alta e a glória alta ao mesmo tempo, do
// jeito que a regra pede. Em 7:21-22 o próprio oráculo cita o diálogo dos que
// hão de passar diante da casa assolada e perguntar "por que fez o SENHOR
// assim?" — essa é fala de gente, e por isso sai da boca do VIAJANTE em cena,
// não da voz do céu. Em todo o resto Deus é falado, não fala: em 5:13-14 e 7:1-3
// Ele responde por NUVEM e por FOGO, e as duas respostas são MUDAS — não há
// balão nenhum, só glória no auge, `altar` com `fire` no máximo (porque
// `env.fire` não desenha chama) e homens que não conseguem ficar de pé. Em 6:5-9
// Salomão CITA o que o SENHOR disse a Davi: a citação está na boca do rei
// (`by:"rei"`, id `salomao`, sempre o primeiro `rei` do elenco), com Davi ao
// lado no quadro de memória, porque quem fala ali é quem está no púlpito. É a
// regra da casa: voz do céu só onde não há mediador; e onde a resposta de Deus é
// fogo, silêncio.
// ============================================================================

import type { StageScript, StageBeat, CastPlacement, StagePropSpec } from "@/lib/rpgStage";

const C = (role: string, dx: number, pose?: string, extra: Partial<CastPlacement> = {}): CastPlacement =>
  ({ role, dx, pose, ...extra });
const P = (kind: string, dx: number, scale = 1, fire?: number, dy?: number): StagePropSpec =>
  ({ kind, dx, scale, ...(fire != null ? { fire } : {}), ...(dy != null ? { dy } : {}) });
const b = (v: number, extra: Partial<StageBeat> = {}): StageBeat => ({ v, ...extra });

// O PÚLPITO DE BRONZE não tem prop próprio na whitelist: a "plataforma de metal,
// de cinco côvados de comprimento, de cinco de largura e de três de altura"
// (6:13) é um BLOCO, e o único bloco que o motor sabe desenhar sem mentir sobre
// a sua função é o `crate` — caixa maciça, sem fogo e sem lenha, ao contrário do
// `altar`, que já é outra coisa no mesmo pátio. Fica com etiqueta própria e
// aparece em todos os quadros da oração, para o leitor saber de onde ela sai.
const PULPITO = (dx: number, scale = 1.45, dy = 0.52): StagePropSpec =>
  ({ ...P("crate", dx, scale, undefined, dy), tag: "pulpito-de-bronze-de-salomao" });

