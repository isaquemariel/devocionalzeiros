// 2 CRÔNICAS 1–4 — CENA VIVA. O rei novo sobe ao ALTO DE GIBEOM, onde ficou a
// tenda que Moisés fizera no deserto, queima MIL HOLOCAUSTOS sobre o altar de
// cobre de Bezaleel e, naquela mesma noite, recebe a pergunta mais perigosa que
// um homem já ouviu — "PEDE O QUE QUERES QUE EU TE DÊ". Depois disso o livro
// vira canteiro de obras: a carta a Tiro, os cedros descendo do Líbano em
// jangadas, o monte Moriá, as duas colunas com nome próprio e o inventário de
// cobre e de ouro peça por peça.
//
// 2Cr 1 — O Cronista abre com uma frase de balanço, não de coroação: "Salomão,
// filho de Davi, FORTALECEU-SE no seu reino; e o SENHOR seu Deus era com ele, e
// o engrandeceu sobremaneira". Convocado todo o Israel — capitães de mil e de
// cem, juízes, governadores, chefes das famílias —, o rei sobe com a
// congregação inteira AO ALTO QUE ESTAVA EM GIBEOM, "porque ali estava a tenda
// da congregação de Deus, que Moisés, servo do Senhor, tinha feito no deserto".
// O texto abre então um parêntese que explica o Israel partido em dois
// santuários: a ARCA já não está lá — Davi a fizera subir de Quiriate-Jearim e
// lhe armara uma tenda em Jerusalém. Em Gibeom ficou o TABERNÁCULO com o ALTAR
// DE COBRE QUE BEZALEEL, FILHO DE URI, FILHO DE HUR, FIZERA; e é sobre ele que
// Salomão oferece MIL HOLOCAUSTOS. Naquela mesma noite Deus lhe aparece, e a
// oferta de mil bois é respondida com uma pergunta de uma linha. Salomão não
// pede o que qualquer rei pediria. Ele conta primeiro a dívida ("tu usaste de
// grande benignidade com meu pai Davi"), depois o tamanho do encargo ("um povo
// numeroso como o pó da terra"), e só então formula o pedido: "DÁ-ME, POIS,
// AGORA, SABEDORIA E CONHECIMENTO, PARA QUE POSSA SAIR E ENTRAR PERANTE ESTE
// POVO; POIS QUEM PODERIA JULGAR A ESTE TÃO GRANDE POVO?". A resposta enumera
// tudo o que ele NÃO pediu — riquezas, bens, honra, a morte dos inimigos, muitos
// dias de vida — e lhe dá as duas coisas de graça. O capítulo fecha mostrando o
// juro do dom: mil e quatrocentos carros, doze mil cavaleiros, ouro e prata em
// Jerusalém COMO PEDRAS, cedros como figueiras bravas das campinas, e os
// cavalos do Egito revendidos por tropas aos reis dos heteus e da Síria.
//
// 2Cr 2 — A OBRA É ENCOMENDADA, e o Cronista faz questão de mostrar a logística
// antes da arquitetura: setenta mil homens de carga, oitenta mil talhando pedra
// na montanha, três mil e seiscentos inspetores. A carta a HIRÃO, REI DE TIRO,
// é o texto mais concreto do capítulo — e o mais teológico. Salomão pede
// madeira como o pai pedira, mas explica para quê: incenso aromático, o PÃO DA
// PROPOSIÇÃO apresentado continuamente, os holocaustos da manhã e da tarde, os
// sábados, as luas novas, as festividades — "o que é obrigação perpétua de
// Israel". E, antes de encomendar um prego, confessa o limite do projeto
// inteiro: "quem seria capaz de lhe edificar uma casa, VISTO QUE OS CÉUS E ATÉ
// OS CÉUS DOS CÉUS O NÃO PODEM CONTER?". Pede então UM HOMEM HÁBIL para lavrar
// em ouro, prata, bronze, ferro, púrpura, carmesim e azul, e que saiba lavrar
// ao buril; cedro, cipreste e algumins do Líbano; e promete o mantimento em
// coros e batos — vinte mil de trigo, vinte mil de cevada, vinte mil batos de
// vinho e vinte mil de azeite. Hirão responde POR ESCRITO, e a carta de um rei
// fenício bendiz o Deus de Israel: "Bendito seja o Senhor Deus de Israel, que
// fez os céus e a terra". Manda HIRÃO ABIÚ, filho de uma mulher das filhas de
// DÃ com um homem de Tiro — o artífice que sabe tudo, do ouro ao linho fino — e
// combina a entrega: a madeira desce em JANGADAS pelo mar até JOPE, e de lá
// sobe a Jerusalém. O capítulo termina no censo dos estrangeiros da terra,
// cento e cinqüenta e três mil e seiscentos, repartidos outra vez em setenta
// mil, oitenta mil e três mil e seiscentos.
//
// 2Cr 3 — A CASA COMEÇA, e o endereço é uma confissão de fé: NO MONTE MORIÁ,
// "onde o SENHOR aparecera a Davi seu pai, no lugar que Davi tinha preparado na
// eira de Ornã, o jebuseu". O templo não nasce num terreno comprado por
// conveniência: nasce onde a peste parou. Segundo mês, segundo dia, ano quarto
// do reinado. Sessenta côvados de comprimento por vinte de largura, o pórtico
// de cento e vinte de altura revestido de ouro puro por dentro; a casa grande
// forrada de faia e coberta de ouro fino, com PALMAS E CADEIAS lavradas; pedras
// preciosas por ornamento e OURO DE PARVAIM; traves, umbrais, paredes e portas
// de ouro, e QUERUBINS LAVRADOS NAS PAREDES. O lugar santíssimo, vinte por
// vinte, leva seiscentos talentos de ouro fino, e até os pregos pesam cinqüenta
// siclos. Ali dentro ficam OS DOIS QUERUBINS DE OBRA MÓVEL, cobertos de ouro,
// com as asas medindo vinte côvados de ponta a ponta: cinco côvados tocando a
// parede de um lado, cinco tocando a asa do companheiro no meio, e os dois "em
// pé, e os seus rostos virados para a casa". O véu é de azul, púrpura, carmesim
// e linho fino, com querubins sobre ele. E diante da casa sobem DUAS COLUNAS de
// trinta e cinco côvados, com capitéis de cinco, cadeias no alto e CEM ROMÃS
// entre as cadeias — a da direita chamada JAQUIM, a da esquerda BOAZ.
//
// 2Cr 4 — O INVENTÁRIO. O altar de metal de vinte côvados por vinte por dez; o
// MAR DE FUNDIÇÃO, dez côvados de borda a borda, perfeitamente redondo, cinco
// de altura, um cordão de trinta em volta, figuras de bois fundidas por baixo
// da borda em duas fileiras — e o tanque inteiro POSTO SOBRE DOZE BOIS: três
// olhando para o norte, três para o ocidente, três para o sul, três para o
// oriente, com as partes posteriores todas para dentro. Um palmo de grossura,
// a borda como a de um copo, como uma flor-de-lis, três mil batos. Dez pias,
// cinco à direita e cinco à esquerda, para lavar o que era do holocausto —
// porque o mar era só para os sacerdotes se lavarem. Dez castiçais de ouro,
// dez mesas, cem bacias de ouro; o pátio dos sacerdotes e o grande átrio, com
// as portas revestidas de cobre. E tudo o que HIRÃO ABIÚ fundiu — caldeiras,
// pás, garfos, bacias — saiu de COBRE POLIDO, moldado NA CAMPINA DO JORDÃO, na
// terra argilosa entre SUCOTE E ZEREDÁ, em tanta abundância que "não se podia
// averiguar o peso do cobre". O fecho é o ouro do interior: o altar de ouro, as
// mesas dos pães da proposição, os castiçais com as lâmpadas acesas perante o
// oráculo, as flores, os espevitadores, os apagadores, as colheres, os
// incensários — e as portas do lugar santíssimo, de ouro.
//
// A VOZ DE DEUS — nestes quatro capítulos o SENHOR fala UMA vez só, e é a única
// vez do trecho em que não há mediador nenhum: 1:7-12, "NAQUELA MESMA NOITE
// Deus apareceu a Salomão". É sonho/visão de noite — sem profeta, sem anjo, sem
// objeto —, e por isso é o único `by:"deus"` daqui: balão de voz do céu, sem
// figura, com o rei deitado diante da tenda de Moisés, a noite alta e a glória
// mais alta ainda (night 0.6 / glory 0.78), como manda a regra da voz do céu.
// Do capítulo 2 em diante NÃO HÁ mais oráculo: quem fala é Salomão ditando a
// carta, o arauto lendo-a em Tiro e Hirão respondendo por escrito — os três com
// balão de gente, em cena, nunca do alto. E os capítulos 3 e 4 não têm uma
// linha de discurso direto: são o escrivão da obra medindo, pesando e contando.
// Ali a presença de Deus é encenada só onde o texto a encena — na eira de Ornã
// "onde o SENHOR aparecera a Davi" (3:1), nos querubins do lugar santíssimo
// (3:10-13), no levantar de Jaquim e Boaz (3:17) e no ouro das portas do
// oráculo (4:22) —, e o risco destes dois capítulos não é teológico: é o quadro
// congelado. Por isso cada peça do inventário ganha o SEU enquadramento — o
// altar de vinte côvados, o mar sobre os doze bois, as dez pias em duas alas,
// os dez castiçais, as dez mesas, os moldes de barro da campina do Jordão —, e
// a câmera nunca fica no mesmo lugar dois versículos seguidos sem mudar de
// altura, de luz ou de gente.
// ============================================================================

