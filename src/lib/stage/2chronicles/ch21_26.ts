// 2 CRÔNICAS 21–26 — CENA VIVA. Seis reis de Judá em seis mundos diferentes: o
// irmão que abre o reinado matando os seis irmãos e recebe UMA CARTA DE ELIAS;
// o filho aconselhado pela mãe para proceder impiamente; a avó que destrói a
// descendência real e o bebê furtado para a CÂMARA DOS LEITOS; o sacerdote que
// se anima e coroa um menino de sete anos; o rei que devolve cem talentos de
// prata e depois se encurva diante dos deuses de quem ele acabou de vencer; e o
// REI LAVRADOR, que cava poços no deserto porque era amigo da agricultura, e
// que termina leproso numa casa separada por ter querido queimar incenso.
//
// 2Cr 21 — JEORÃO. Jeosafá dorme com seus pais e o primogênito herda o reino;
// os outros seis filhos — Azarias, Jeiel, Zacarias, Asarias, Micael e Sefatias
// — herdam prata, ouro, coisas preciosíssimas e cidades fortificadas. Firmado
// no trono, Jeorão "matou a todos os seus irmãos à espada, como também a alguns
// dos príncipes de Israel": a primeira coisa que faz com o poder é apagar os
// que tinham o mesmo pai. Andou no caminho dos reis de Israel "porque tinha a
// filha de Acabe por mulher" — Atalia entra na casa de Davi por casamento e vai
// custar quase a linhagem inteira. Ainda assim o SENHOR não quis destruir a
// casa de Davi, "porque também tinha falado que lhe daria por todos os dias uma
// lâmpada, a ele e a seus filhos": a promessa é mais antiga que a maldade do
// rei da vez. Edom se revolta e constitui rei próprio; Jeorão sai de noite com
// todos os carros e escapa por pouco; Libna também se revolta, "porque deixara
// ao Senhor Deus de seus pais". Ele faz altos nos montes de Judá e faz a cidade
// prostituir-se. E então acontece o que não acontece em mais nenhum lugar da
// Escritura: "Então lhe veio um escrito da parte de Elias, o profeta". O
// profeta do Norte, que nunca pôs os pés nesta narrativa, escreve uma carta a
// um rei do Sul, e o texto a transcreve inteira — a única palavra ESCRITA de
// Elias que temos. Ela diz o que ele fez ("mataste a teus irmãos da casa de teu
// pai, melhores do que tu") e o que vai acontecer: um grande flagelo sobre o
// povo, os filhos e as mulheres, e "grande enfermidade por causa de uma doença
// em tuas entranhas, até que elas saiam, de dia em dia". Cumpre-se letra por
// letra: filisteus e árabes levam os bens, os filhos e as mulheres, deixando só
// Jeoacaz, o mais moço; e ao fim de dois anos saem-lhe as entranhas e ele morre
// da mesma doença. O epitáfio é de quatro palavras e é o mais duro do livro:
// "e foi sem deixar de si saudades" — e não o puseram nos sepulcros dos reis.
//
// 2Cr 22 — ACAZIAS E ATALIA. Os moradores de Jerusalém fazem rei o filho mais
// moço porque a tropa dos árabes matara todos os mais velhos: a casa de Davi
// chega ao trono pelo resto. "Era o nome de sua mãe Atalia, filha de Onri", e o
// narrador não deixa dúvida sobre a fonte do mal — "porque sua mãe era sua
// conselheira, para proceder impiamente". Reina um ano. Vai com Jorão de Israel
// a Ramote de Gileade contra Hazael, desce a Jizreel para visitar o ferido, e
// ali é apanhado pelo juízo que varre a casa de Acabe: Jeú acha os príncipes de
// Judá e os filhos dos irmãos de Acazias e os mata; depois busca o rei
// escondido em Samaria, e o mata — e o sepulta, mesmo assim, "porque disseram:
// Filho é de Jeosafá, que buscou ao Senhor com todo o seu coração". A avó vê o
// filho morto e faz o que nenhum inimigo estrangeiro conseguira: "destruiu toda
// a descendência real da casa de Judá". A lâmpada de Davi cabe, naquele
// instante, num só bebê — e é uma mulher da própria casa que o salva:
// Jeosabeate, filha do rei, mulher do sacerdote Joiada, furta Joás DENTRE OS
// FILHOS DO REI AOS QUAIS MATAVAM e o põe com a sua ama NA CÂMARA DOS LEITOS.
// Seis anos escondido na casa de Deus, enquanto Atalia reina sobre a terra.
//
// 2Cr 23 — JOIADA. "Porém no sétimo ano Joiada se animou": o verbo é esse, e é
// o eixo do capítulo. Faz aliança com cinco chefes de cem, manda percorrer Judá
// e ajuntar os levitas de todas as cidades e os chefes dos pais, e diante da
// congregação inteira MOSTRA O FILHO DO REI: "Eis que o filho do rei reinará,
// como o Senhor falou a respeito dos filhos de Davi". Depois dá as ordens de
// posto com precisão de quem preparou isto por seis anos — três turmas: às
// portas, na casa do rei, à porta do fundamento; e a linha que protege o
// santuário no meio de um golpe de estado: "Porém ninguém entre na casa do
// Senhor, senão os sacerdotes e os levitas que ministram". Arma os centuriões
// com AS LANÇAS, OS ESCUDOS E AS RODELAS QUE FORAM DO REI DAVI, guardadas na
// casa de Deus — armas de museu que voltam ao serviço no dia em que a casa de
// Davi volta ao trono. Põem a coroa no menino, dão-lhe O TESTEMUNHO, ungem-no,
// e o grito é o mais curto e o mais alegre do livro: "Viva o rei!" Atalia ouve
// o barulho, vem à casa do SENHOR e vê o que não podia existir: "o rei estava
// junto à sua coluna, à entrada", com as trombetas e os cantores. Rasga os
// vestidos e grita "Traição, traição!" — e Joiada, que não deixa o sangue dela
// manchar o santuário, manda tirá-la para fora das fileiras; ela é morta à
// entrada da porta dos cavalos. Refeita a aliança, o povo derruba a casa de
// Baal, quebra os altares e as imagens, e mata Matã, o sacerdote de Baal,
// diante dos altares. E a cidade fica em paz.
//
// 2Cr 24 — JOÁS. "E fez Joás o que era reto aos olhos do Senhor, TODOS OS DIAS
// DO SACERDOTE JOIADA" — a ressalva é o capítulo inteiro. O rei resolve renovar
// a casa do SENHOR, manda os levitas levantar dinheiro pelas cidades, e os
// levitas não se apressam; então ele chama Joiada e cobra. A solução é uma
// caixa: "fizeram um cofre, e o puseram fora, à porta da casa do Senhor" — e o
// que anos de ordens não conseguiram, um cofre à vista de quem entra resolveu.
// "Então todos os príncipes e todo o povo se alegraram, e o trouxeram e o
// lançaram no cofre, até que ficou cheio", e de dia em dia o escrivão do rei e
// o oficial do sumo sacerdote o esvaziavam e o punham de volta. Pedreiros,
// carpinteiros, ferreiros e serralheiros; a casa restaurada no seu estado; e do
// resto do dinheiro, colheres e vasos de ouro e de prata. Então Joiada morre,
// com cento e trinta anos, e é sepultado com os reis "porque tinha feito bem em
// Israel". E tudo desaba num versículo: "depois da morte de Joiada vieram os
// príncipes de Judá e prostraram-se perante o rei; e o rei os ouviu". Deixam a
// casa do SENHOR e servem aos bosques e aos ídolos. Deus manda profetas; não
// dão ouvidos. Então "o Espírito de Deus revestiu a Zacarias, filho do sacerdote
// Joiada, o qual se pôs em pé acima do povo": o filho do homem que criou o rei
// pergunta por que transgridem — e o apedrejam NO PÁTIO DA CASA DO SENHOR, por
// mandado do rei. Morrendo, diz seis palavras que atravessam o Antigo
// Testamento: "O Senhor o verá, e o requererá". Um ano depois sobe o exército
// da Síria COM POUCOS HOMENS e destrói os príncipes de Judá; Joás fica
// gravemente ferido, e os seus próprios servos o ferem na cama, "por causa do
// sangue do filho do sacerdote Joiada". Também ele não vai para os sepulcros
// dos reis.
//
// 2Cr 25 — AMAZIAS. "E fez o que era reto aos olhos do Senhor, PORÉM NÃO COM
// INTEIREZA DE CORAÇÃO" — e o capítulo mostra o que isso quer dizer na prática.
// Mata os que mataram o pai, mas não os filhos deles, "porque assim está
// escrito na lei, no livro de Moisés". Conta trezentos mil homens de Judá e
// contrata mais cem mil de Israel por cem talentos de prata; um homem de Deus
// manda despedi-los, e a objeção do rei é uma calculadora: "Que se fará, pois,
// dos cem talentos de prata que dei às tropas de Israel?" A resposta é a frase
// que resume a economia da fé: "Mais tem o Senhor que te dar do que isso". Ele
// os despede, e eles voltam para casa ARDENDO EM IRA, e saqueiam as cidades de
// Judá no caminho. Amazias fere dez mil de Seir no Vale do Sal e leva outros
// dez mil vivos ao cume da rocha — "e do mais alto da rocha os lançaram abaixo,
// e todos se despedaçaram". E então faz a coisa mais absurda do livro: traz
// consigo OS DEUSES DOS FILHOS DE SEIR, toma-os por seus deuses, prostra-se
// diante deles e queima-lhes incenso. O profeta faz a pergunta que não tem
// resposta: "Por que buscaste deuses deste povo, os quais não livraram o seu
// próprio povo da tua mão?" O rei manda calar: "Puseram-te por conselheiro do
// rei? Cala-te!" Envaidecido, desafia Jeoás de Israel — "Vem, vejamo-nos face a
// face" — e recebe de volta a parábola do CARDO e do CEDRO: o cardo do Líbano
// pediu a filha do cedro para o seu filho, e um bicho do campo passou e pisou o
// cardo. Não ouve; é ferido em Bete-Semes, preso, e vê quatrocentos côvados do
// muro de Jerusalém irem ao chão. Acaba como o pai: conspiração, fuga para
// Laquis, morte, e o corpo trazido de volta sobre cavalos.
//
// 2Cr 26 — UZIAS. O reinado mais longo e mais próspero da série, e o que
// termina atrás de uma porta fechada. Feito rei aos dezesseis anos, reinou
// cinquenta e dois; "deu-se a buscar a Deus nos dias de Zacarias, que era
// entendido nas visões de Deus; e nos dias em que buscou ao Senhor, Deus o fez
// prosperar". Quebra o muro de Gate, de Jabne e de Asdode; é ajudado contra os
// árabes de Gur-Baal e contra os meunitas; recebe presentes dos amonitas e o
// nome espalha-se até à entrada do Egito. Edifica torres em Jerusalém e — a
// imagem mais bonita do trecho — TORRES NO DESERTO, e cava muitos poços,
// "porque tinha muito gado, tanto nos vales como nas campinas; tinha lavradores
// e vinhateiros, nos montes e nos campos férteis; PORQUE ERA AMIGO DA
// AGRICULTURA". Um rei que constrói cisternas. Depois vêm o exército de
// trezentos e sete mil e quinhentos, o arsenal de escudos, lanças, capacetes,
// couraças, arcos e fundas, e as MÁQUINAS DA INVENÇÃO DE ENGENHEIROS para as
// torres e os cantos, "para atirarem flechas e grandes pedras". E a frase que
// vira a página: "Mas, havendo-se já fortificado, exaltou-se o seu coração até
// se corromper" — entrou no templo do SENHOR para queimar incenso no altar do
// incenso. Azarias, o sacerdote, entra atrás dele com oitenta sacerdotes
// valentes e lhe resiste na cara: "A ti, Uzias, não compete queimar incenso
// perante o Senhor". Ele se indigna COM O INCENSÁRIO NA MÃO — e ali mesmo, no
// meio da indignação, "a lepra lhe saiu à testa perante os sacerdotes, na casa
// do Senhor, junto ao altar do incenso". Lançam-no fora às pressas, e ele
// próprio se apressa a sair, "visto que o Senhor o ferira". Morou numa casa
// separada até morrer, e foi sepultado no campo do sepulcro dos reis, e não com
// eles, "porque disseram: Leproso é".
//
// A VOZ DE DEUS — nestes seis capítulos Deus fala quatro vezes, e NENHUMA delas
// é voz do céu sem mediador: por isso não há um único `by:"deus"` aqui. Em
// 21:12-15 o mediador é um OBJETO — a CARTA DE ELIAS. O balão sai de quem a lê
// em voz alta diante do rei (`by:"servo"`, id `leitor-da-carta-de-elias`), o
// `scroll` domina o quadro com `tag` própria, e ELIAS NÃO APARECE: o profeta
// está a centenas de quilômetros e o que chegou a Jerusalém foi papel escrito.
// Em 24:20 o mediador é um homem sobre quem "o Espírito de Deus revestiu":
// ZACARIAS, FILHO DE JOIADA (`patriarca`, id `zacarias-filho-de-joiada`), em pé
// ACIMA DO POVO sobre a pedra do átrio, com `glow` no auge — e apedrejado no
// beat seguinte, no mesmo lugar, com a glória apagando. Em 25:7-9 e 25:15-16
// falam o HOMEM DE DEUS e o PROFETA sem nome mandados a Amazias, os dois com
// `glow` alto e o rei diante deles. Fora isso, o SENHOR aparece só como sujeito
// da narração — "Despertou, pois, o Senhor, contra Jeorão o espírito dos
// filisteus" (21:16), "o Senhor entregou na sua mão um exército mui numeroso"
// (24:24), "porque isto vinha de Deus" (25:20), "visto que o Senhor o ferira"
// (26:20) —, e narração se desenha com AMBIENTE, não com balão: a glória sobe
// ou a noite fecha sem que nada seja desenhado no alto. As outras bocas são
// humanas e estão sempre em cena: JOIADA (`anciao`), ATALIA (`mulherComum`,
// NUNCA `mulher`, que o motor desenha sempre dourada e em pé), os reis JOÁS,
// AMAZIAS, JEOÁS DE ISRAEL e UZIAS (`rei`), e AZARIAS, O SACERDOTE (`anciao`).
//
// (Notas de grafia da ARC, seguidas letra por letra nos `q`: "cinqüenta" com
// trema, "capitàes" com crase, "Jeosabeate" e não Jeoseba, "descendência real"
// e não semente real, "escrito da parte de Elias" e não carta, "edomeus" em
// 21:9 ao lado de "edomitas" em 21:8, e "Vale do Sal" com maiúsculas.)
// ============================================================================

