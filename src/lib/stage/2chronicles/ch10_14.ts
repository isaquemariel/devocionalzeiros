// 2 CRÔNICAS 10–14 — CENA VIVA. O reino de Salomão parte-se em Siquém por causa
// de um conselho de rapazes; o Egito sobe e leva os escudos de ouro do templo,
// que voltam feitos de cobre; um rei de Judá grita do alto de um monte contra
// oitocentos mil homens; e um outro clama do fundo de um vale contra um milhão.
//
// 2Cr 10 — SIQUÉM. Roboão vai ser feito rei no lugar onde Israel sempre tratou
// as suas contas, e a congregação inteira o espera com uma queixa concreta:
// "Teu pai fez duro o nosso jugo; agora, pois, alivia tu a dura servidão de teu
// pai". Jeroboão, que fugira para o Egito da presença de Salomão, volta de lá
// para ser a boca desse pedido. O rei pede três dias e ouve DOIS CONSELHOS em
// duas salas diferentes. Os ANCIÃOS que estiveram perante Salomão dão-lhe o
// retrato do reinado que salva: "Se te fizeres benigno e afável para com este
// povo, e lhes falares boas palavras, todos os dias serão teus servos". Ele
// deixa esse conselho e vai à sua própria geração — OS JOVENS QUE HAVIAM
// CRESCIDO COM ELE, que lhe põem na boca a frase mais tola já dita por um rei
// de Israel: "O meu dedo mínimo é mais grosso do que os lombos de meu pai", e a
// ameaça que a segue, "meu pai vos castigou com açoites, porém eu vos
// castigarei com escorpiões". Ao terceiro dia ele responde asperamente, e o
// povo responde com o velho grito da secessão: "Que parte temos nós com Davi?
// Já não temos herança no filho de Jessé. Cada um à sua tenda, ó Israel!". A
// praça esvazia-se e o rei, sem entender ainda o tamanho do que fez, manda
// HADORÃO, o dos tributos — o cobrador, não o negociador. Israel o apedreja na
// rua, e Roboão "se esforçou para subir ao seu carro, e fugiu para Jerusalém".
//
// 2Cr 11 — A GUERRA QUE NÃO HOUVE, E O REINO QUE SE FORTIFICA. Roboão junta
// cento e oitenta mil escolhidos para reconquistar as dez tribos à força, e a
// palavra do SENHOR o para pela boca de SEMAÍAS, HOMEM DE DEUS: "Não subireis,
// nem pelejareis contra os vossos irmãos; volte cada um à sua casa; porque de
// mim proveio isto". E eles ouviram — o único momento inteiramente obediente do
// reinado. O que sobra do capítulo é construção: quinze cidades fortes
// nomeadas uma a uma, com capitães, armazéns de víveres, de azeite e de vinho,
// paveses e lanças em cada uma. E vem a migração que o Norte provocou: OS
// SACERDOTES E OS LEVITAS de todo o Israel deixam os seus arrabaldes e a sua
// possessão e descem para Judá, porque Jeroboão os lançou fora e "constituiu
// para si sacerdotes, para os altos, para os demônios, e para os bezerros, que
// fizera". Atrás deles vêm, de todas as tribos, "os que deram o seu coração a
// buscarem ao Senhor Deus de Israel". O capítulo fecha dentro de casa: dezoito
// mulheres, sessenta concubinas, vinte e oito filhos, sessenta filhas — e
// MAACA, FILHA DE ABSALÃO, a quem ele amou mais que a todas, e cujo filho Abias
// ele designa para reinar.
//
// 2Cr 12 — O QUINTO ANO, E O OURO QUE VIRA COBRE. "Havendo Roboão confirmado o
// reino, e havendo-se fortalecido, deixou a lei do SENHOR" — a força foi o
// perigo, não a fraqueza. Sobe então SISAQUE, REI DO EGITO, com mil e duzentos
// carros, sessenta mil cavaleiros e povo sem conta de líbios, suquitas e
// etíopes; toma as cidades fortificadas que Judá tinha e chega até Jerusalém.
// Semaías traz a sentença — "Vós me deixastes a mim, por isso também eu vos
// deixei na mão de Sisaque" — e acontece a única coisa que muda um juízo: "se
// humilharam os príncipes de Israel, e o rei, e disseram: O Senhor é justo".
// Deus não os destrói, mas também não os livra: "Porém serão seus servos; para
// que conheçam a diferença da minha servidão e da servidão dos reinos da
// terra". E o capítulo dá então a imagem mais exata de um reino rebaixado: o
// Egito leva OS ESCUDOS DE OURO QUE SALOMÃO FIZERA, e Roboão manda fazer, em
// lugar deles, ESCUDOS DE COBRE, que os da guarda tiram da câmara quando o rei
// entra na casa do SENHOR e tornam a guardar assim que ele sai. A pompa
// continua; o metal, não.
//
// 2Cr 13 — O SERMÃO NO ALTO DO MONTE. Abias enfrenta oitocentos mil homens com
// quatrocentos mil, e antes da batalha faz o que nenhum outro rei fez: PÕE-SE
// EM PÉ EM CIMA DO MONTE DE ZEMARAIM e prega ao exército inimigo. O argumento é
// inteiro teológico — a aliança de sal dada a Davi, a rebelião de um servo de
// Salomão, os homens vadios e filhos de Belial que o seguiram, os bezerros de
// ouro por deuses, o sacerdócio comprado "com um novilho e sete carneiros" — e
// termina no altar de Jerusalém, onde se queimam holocaustos cada manhã e cada
// tarde, com os pães da proposição sobre a mesa pura e o castiçal de ouro. E a
// conclusão: "eis que Deus está conosco, à nossa frente, como também os seus
// sacerdotes, tocando com as trombetas, para dar alarme contra vós". A resposta
// de Jeroboão é uma EMBOSCADA pela retaguarda: Judá olha e vê que tem de
// pelejar por diante e por detrás. "Então clamaram ao Senhor; e os sacerdotes
// tocaram as trombetas" — e é o alarme, não a espada, que abre a batalha. Deus
// fere Jeroboão diante de Abias, caem quinhentos mil escolhidos, e o rei do
// Norte "não recobrou mais o seu poder nos dias de Abias".
//
// 2Cr 14 — ASA, E O CLAMOR NO VALE DE ZEFATÁ. Dez anos de paz, e um rei que os
// usa: tira os altares dos deuses estranhos e os altos, quebra as imagens,
// corta os bosques, manda Judá buscar ao SENHOR e observar a lei, e edifica
// cidades — "cerquemo-las de muros e torres, portas e ferrolhos, enquanto a
// terra ainda é nossa". Tem trezentos mil de Judá com pavês e lança e duzentos
// e oitenta mil de Benjamim com escudo e arco. E então sobe ZERÁ, O ETÍOPE, com
// um exército de um milhão e trezentos carros, e chega até Maressa. Asa não
// conta os seus: "Senhor, nada para ti é ajudar, quer o poderoso quer o de
// nenhuma força; ajuda-nos, pois, Senhor nosso Deus, porque em ti confiamos".
// Os etíopes caem sem resistência alguma, Judá persegue até Gerar, saqueia as
// cidades onde caiu o terror do SENHOR, fere as malhadas do gado e volta para
// Jerusalém com ovelhas em abundância.
//
// A VOZ DE DEUS — nestes cinco capítulos Deus fala três vezes, e as TRÊS por um
// MEDIADOR NOMEADO: não há aqui um único `by:"deus"`. Em 11:2-4 e em 12:5,7-8 o
// texto põe o nome na frase — "a palavra do Senhor veio a Semaías, homem de
// Deus" — e por isso o balão sai de SEMAÍAS em cena (`by:"patriarca"`, id
// `semaias-homem-de-deus`, com `glow` alto), nunca da voz do céu sem figura. O
// mesmo vale para o sermão de Abias em 13:5-12: quem fala é o REI, de pé no
// monte, e o que o apoia é a glória subindo no céu de Zemaraim, não um balão
// dourado sem dono. As duas ações mais divinas destes capítulos são MUDAS: em
// 13:15 "Deus feriu a Jeroboão e a todo o Israel" e em 14:12 "o Senhor feriu os
// etíopes diante de Asa" — ali não há balão nenhum, só glória no auge, trombeta
// no ar e homens caídos, porque quando Deus responde à guerra Ele não discute.
// Nos dois desastres — o apedrejamento de Hadorão (10:18) e os quinhentos mil
// de Israel (13:17) — o chão é de FIGURAS INDIVIDUAIS em `lie`, jamais de
// `multidao`, que o motor desenha sempre comemorando de braços erguidos.
// ============================================================================

