// desce nenhuma vez do céu: ela entra pela boca de cinco homens que atravessam
// a praça e se plantam diante do rei — AZARIAS, HANANI, MICAÍAS, JEÚ e JAAZIEL.
// Dois reis, pai e filho, recebem cada um a sua visita: um prende o vidente na
// casa do tronco e morre buscando médicos; o outro se prostra com o rosto em
// terra e manda os cantores saírem ADIANTE do exército.
//
// 2Cr 15 — Asa volta do despojo de Zerá e, na estrada, o Espírito de Deus cai
// sobre AZARIAS, FILHO DE ODEDE, que lhe diz a frase que governa o livro
// inteiro: "O Senhor está convosco, enquanto vós estais com ele, e, se o
// buscardes, o achareis; porém, se o deixardes, vos deixará". E abre diante do
// rei o retrato dos dias sem lei — "Israel esteve por muitos dias sem o
// verdadeiro Deus, e sem sacerdote que o ensinasse, e sem lei", nação contra
// nação e cidade contra cidade se despedaçando. Asa "cobrou ânimo": tira as
// abominações de Judá, de Benjamim e das cidades tomadas nas montanhas de
// Efraim, e RENOVA O ALTAR do SENHOR que estava diante do pórtico. No terceiro
// mês o povo se ajunta em Jerusalém e sacrifica DO DESPOJO — setecentos bois e
// sete mil ovelhas —, e entra na aliança de buscar ao SENHOR com todo o
// coração, jurando "em alta voz, com júbilo e com trombetas e buzinas". E vem
// então o gesto que quase nenhum rei tem estômago para fazer: depõe a PRÓPRIA
// MÃE, Maaca, do posto de rainha, por causa do horrível ídolo de Aserá, e
// destrói, despedaça e QUEIMA o ídolo junto ao ribeiro de Cedrom. Os altos,
// porém, ficaram — o limite de toda reforma feita por um homem só.
//
// 2Cr 16 — Trinta e cinco anos de paz e, no trigésimo sexto, Baasa sobe e
// edifica Ramá para asfixiar Judá. Asa, que uma vez venceu um milhão de
// etíopes de mãos vazias, agora esvazia os tesouros da casa do SENHOR e da casa
// do rei e compra a espada de BEN-HADADE em Damasco. Funciona: os sírios ferem
// Ijom, Dã, Abel-Maim e as cidades-armazéns de Naftali, Baasa larga a obra, e
// Asa carrega as pedras e a madeira de Ramá para edificar Geba e Mizpá. E é
// exatamente no dia da vitória comprada que chega HANANI, O VIDENTE:
// "Porquanto confiaste no rei da Síria, e não confiaste no Senhor teu Deus, por
// isso o exército do rei da Síria escapou da tua mão" — e a frase larga do
// capítulo: "quanto ao Senhor, seus olhos passam por toda a terra, para
// mostrar-se forte para com aqueles cujo coração é perfeito para com ele". O
// rei que depusera a própria mãe por causa de um ídolo não suporta uma
// repreensão: indigna-se, LANÇA O VIDENTE NA CASA DO TRONCO e oprime alguns do
// povo. Três anos depois adoece dos pés, "e na sua enfermidade não buscou ao
// Senhor, mas antes os médicos" — a mesma troca, agora no próprio corpo.
// Sepultam-no numa cama cheia de perfumes e especiarias, e lhe fazem uma
// QUEIMA MUITO GRANDE.
//
// 2Cr 17 — Jeosafá se fortifica, e o cronista para o relato militar para
// contar a coisa mais original que um rei de Judá fez: no terceiro ano ENVIA OS
// SEUS PRÍNCIPES — Bene-Hail, Obadias, Zacarias, Natanael e Micaías — e com
// eles nove levitas e dois sacerdotes "para ensinarem nas cidades de Judá". E
// "ensinaram em Judá, LEVANDO CONSIGO O LIVRO DA LEI DO SENHOR; e foram a todas
// as cidades de Judá, ensinando entre o povo". Não é uma campanha, é uma
// escola itinerante. O resultado não é conquista: é que "veio o temor do Senhor
// sobre todos os reinos das terras, que estavam ao redor de Judá, e não
// guerrearam contra Jeosafá" — e os filisteus trazem presentes e prata de
// tributo, e os árabes sete mil e setecentos carneiros e sete mil e setecentos
// bodes. Fecha com o rol dos homens de guerra, chefe por chefe: Adna com
// trezentos mil, Joanã com duzentos e oitenta mil, Amasias filho de Zicri "que
// voluntariamente se entregou ao Senhor" com duzentos mil, Eliada com duzentos
// mil armados de arco e escudo, Jozabade com cento e oitenta mil.
//
// 2Cr 18 — E o rei que mandou ensinar a lei se aparenta com ACABE. Desce a
// Samaria, come as ovelhas e os bois abatidos em abundância e é persuadido a
// subir a Ramote de Gileade. Pede — sozinho — que se consulte a palavra do
// SENHOR, e ouve quatrocentos profetas em coro; ZEDEQUIAS, FILHO DE QUENAANÁ,
// faz para si CHIFRES DE FERRO e usa a fórmula sagrada para dizer o que o rei
// quer ouvir. Jeosafá insiste, e vem MICAÍAS, FILHO DE INLÁ, "que nunca
// profetiza de mim o que é bom": primeiro a ironia ("Subi, e triunfarás"),
// depois a visão — "Vi a todo o Israel disperso pelos montes, como ovelhas que
// não têm pastor" —, e depois a sala do trono do céu, com todo o exército
// celestial em pé à direita e à esquerda, e o espírito que se oferece para ser
// ESPÍRITO DE MENTIRA na boca dos profetas. Leva uma bofetada no queixo e vai
// para a casa do cárcere com PÃO DE ANGÚSTIA E ÁGUA DE ANGÚSTIA, gritando da
// porta: "Se voltares em paz, o Senhor não tem falado por mim". Acabe se
// disfarça e manda Jeosafá vestido de rei; os capitães dos carros cercam o
// homem errado, Jeosafá clama e Deus os desvia; e então UM HOMEM ARMA O ARCO E
// ATIRA A ESMO e acerta o rei disfarçado entre as junturas e a couraça. Ele
// fica encostado, em pé no carro, defronte dos sírios ATÉ À TARDE, e morre ao
// tempo do pôr do sol.
//
// 2Cr 19 — Jeosafá volta vivo, e à porta de casa está JEÚ, FILHO DE HANANI, O
// VIDENTE — filho do homem que o pai dele prendeu no tronco: "Devias tu ajudar
// ao ímpio, e amar aqueles que odeiam ao Senhor?". Mas o oráculo não é só ira:
// "Boas coisas contudo se acharam em ti". E o rei responde à repreensão do
// único modo que presta: torna a passar pelo povo desde Berseba até as
// montanhas de Efraim e ESTABELECE JUÍZES na terra, de cidade em cidade, com a
// instrução que fez tribunal em Judá: "Vede o que fazeis; porque não julgais da
// parte do homem, senão da parte do Senhor" — e em Jerusalém põe levitas,
// sacerdotes e chefes dos pais, com Amarias, o sumo sacerdote, sobre o negócio
// do SENHOR, e Zebadias, filho de Ismael, sobre o negócio do rei.
//
// 2Cr 20 — Vêm moabitas, amonitas e maonitas dalém do mar, e já estão em
// En-Gedi. Jeosafá teme — e o medo dele vira jejum em todo o Judá. Em pé
// diante do PÁTIO NOVO, ora a oração mais desarmada de um rei na Escritura:
// "em nós não há força perante esta grande multidão que vem contra nós, e não
// sabemos o que faremos; porém os nossos olhos estão postos em ti". E todo o
// Judá está em pé perante o SENHOR, "como também as suas crianças, as suas
// mulheres, e os seus filhos". Então o Espírito do SENHOR cai NO MEIO DA
// CONGREGAÇÃO sobre JAAZIEL, levita dos filhos de Asafe: "a peleja não é vossa,
// mas de Deus… postai-vos, ficai parados, e vede a salvação do Senhor". De
// manhã cedo saem ao deserto de Tecoa, e o rei faz a coisa mais estranha que um
// comandante pode fazer: põe OS CANTORES ADIANTE DOS ARMADOS, louvando à
// Majestade santa — "Louvai ao Senhor porque a sua benignidade dura para
// sempre". E "quando começaram a cantar e a dar louvores, o Senhor pôs
// emboscadas": os invasores se levantam uns contra os outros e se destroem, e
// quando Judá chega à atalaia do deserto só há corpos mortos, e nenhum
// escapou. Três dias saqueando, e ao quarto se ajuntam no VALE DE BERACA — o
// vale da bênção — e voltam a Jerusalém com saltérios, com harpas e com
// trombetas. O fim do reinado, porém, repete o erro: alia-se com Acazias para
// fazer navios que fossem a Társis, e ELIÉZER, FILHO DE DODAVA, profetiza — e
// os navios se quebram em Eziom-Geber.
//
// A VOZ DE DEUS. Nestes seis capítulos Deus fala em toda página e NÃO HÁ UM
// ÚNICO `by: "deus"`. A regra da CLAUDE.md decide sozinha: há mediador visível
// em cena em todos os oráculos, e por isso o balão sai SEMPRE do mediador, com
// ele no palco e `glow` alto — Azarias na estrada do despojo (15:2-7), Hanani
// no pátio (16:7-9), Micaías na praça da porta de Samaria e na visão do trono
// (18:13-27), Jeú à volta de Ramote (19:2-3), Jaaziel no meio da congregação
// (20:15-17) e Eliézer sobre os navios quebrados (20:37). Em 18:18-21 Micaías
// descreve o SENHOR assentado no seu trono com todo o exército celestial: o
// trono é desenhado VAZIO E EM GLÓRIA, os anjos estão em pé à direita e à
// esquerda, e quem fala continua sendo Micaías — Deus não é figura em cena
// nenhuma. Zedequias, filho de Quenaaná, usa a fórmula "Assim diz o Senhor" com
// chifres de ferro na mão e é o único "profeta" do arquivo SEM `glow`: a luz
// não acompanha a mentira.
