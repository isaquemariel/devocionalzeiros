// 2 CRÔNICAS 32–36 — CENA VIVA. O FIM DO LIVRO E O FIM DO REINO. Cinco
// capítulos em que Judá é livrado por um anjo, afunda com o pior dos seus
// reis, é levantado outra vez por um menino que acha um livro, e acaba com a
// casa de Deus em chamas e os muros de Jerusalém no chão — até que um rei
// estrangeiro, no primeiro ano do seu reinado, manda passar pregão e diz:
// "Quem há entre vós, de todo o seu povo… e suba".
//
// 2Cr 32 — SENAQUERIBE sobe. Ezequias não espera: toma conselho com os seus
// príncipes e TAPA AS FONTES de fora da cidade — "Por que viriam os reis da
// Assíria, e achariam tantas águas?" —, edifica o muro quebrado até às torres,
// levanta OUTRO MURO POR FORA, fortifica a Milo e faz "armas e escudos em
// abundância". Depois reúne o povo NA PRAÇA DA PORTA DA CIDADE e fala-lhes AO
// CORAÇÃO: "Com ele está o braço de carne, mas conosco o Senhor nosso Deus,
// para nos ajudar, e para guerrear por nós" — e o povo DESCANSOU nas palavras
// do rei. Senaqueribe, que está diante de Laquis, manda os seus servos, e eles
// gritam EM ALTA VOZ EM JUDAICO contra a gente que está em cima do muro,
// pondo o SENHOR na mesma prateleira dos deuses das nações — "obras das mãos
// dos homens". O rei e o profeta ISAÍAS oram e CLAMAM AO CÉU; e então vem o
// versículo que decide tudo: "Então o Senhor enviou um anjo que destruiu a
// todos os homens valentes… no arraial do rei da Assíria" — e o rei da Assíria
// volta envergonhado e é morto à espada, dentro da casa do seu próprio deus,
// pelos seus próprios filhos. Depois disso o capítulo vira para dentro:
// Ezequias adoece mortalmente, ora, recebe um SINAL, e o coração se lhe
// exalta; humilha-se; enche as tesourarias de prata, ouro e especiarias;
// TAPA O MANANCIAL SUPERIOR DAS ÁGUAS DE GIOM e as faz correr por baixo para o
// ocidente da cidade de Davi; e, quando chegam os embaixadores de Babilônia,
// "Deus o desamparou, para tentá-lo, para saber tudo o que havia no seu
// coração".
//
// 2Cr 33 — MANASSÉS, doze anos de idade e cinqüenta e cinco de reinado: o mais
// longo e o pior. Reedifica os altos que o pai derrubara, levanta altares aos
// Baalins, faz bosques, PROSTRA-SE DIANTE DE TODO O EXÉRCITO DOS CÉUS, edifica
// altares dentro da casa do SENHOR e em AMBOS OS ÁTRIOS dela, faz passar os
// filhos pelo fogo no vale do filho de Hinom, usa de adivinhações, agouros e
// feitiçarias, e põe UMA IMAGEM DE ESCULTURA dentro da casa de que Deus dissera
// "porei o meu nome para sempre". Deus fala, e não dão ouvidos. E aí vem a
// coisa mais estranha da história de Judá: os capitães da Assíria prendem o rei
// COM GANCHOS, amarram-no COM CADEIAS e o levam a Babilônia — e ali, no fundo,
// "ele, angustiado, orou deveras ao Senhor seu Deus, e humilhou-se muito", e
// "Deus se aplacou para com ele, e ouviu a sua súplica, e tornou a trazê-lo a
// Jerusalém". "ENTÃO CONHECEU MANASSÉS QUE O SENHOR ERA DEUS." Volta, levanta o
// muro de fora bem alto, tira da casa do SENHOR os deuses estranhos e o ídolo,
// e repara o altar. O filho AMOM faz o mesmo mal e não faz o arrependimento —
// "não se humilhou perante o Senhor, como Manassés, seu pai, se humilhara" — e
// morre dentro de casa, pela mão dos próprios servos.
//
// 2Cr 34 — JOSIAS, oito anos de idade. Aos dezesseis "começou a buscar o Deus
// de Davi, seu pai"; aos vinte começa a purificar: os altares dos Baalins são
// DERRUBADOS PERANTE ELE, as imagens são quebradas e REDUZIDAS A PÓ, e o pó é
// ESPARGIDO SOBRE AS SEPULTURAS dos que lhes tinham sacrificado; os ossos dos
// sacerdotes são queimados sobre os seus próprios altares. Aos vinte e seis
// manda reparar a casa — e no meio da obra, tirando o dinheiro, HILQUIAS ACHA
// O LIVRO DA LEI DO SENHOR, DADA PELA MÃO DE MOISÉS. Safã leva o livro ao rei e
// LÊ NELE PERANTE ELE; e o rei, ouvindo as palavras da lei, RASGA AS SUAS
// VESTES. Manda cinco homens consultar o SENHOR, e eles vão ter com HULDA, A
// PROFETISA, mulher de Salum, que habitava em Jerusalém na segunda parte: dela
// vem o mal sobre o lugar e a misericórdia sobre o rei — "porquanto o teu
// coração se enterneceu… os teus olhos não verão todo o mal". Depois o rei sobe
// à casa com todo o povo, DESDE O MAIOR ATÉ AO MENOR, e lê aos ouvidos deles
// todas as palavras do livro da aliança.
//
// 2Cr 35 — A PÁSCOA DE JOSIAS, a maior desde Samuel. A arca sagrada volta para
// a casa e os levitas são dispensados da carga aos ombros; as turmas se põem
// nos seus postos; o rei tira DA SUA PRÓPRIA FAZENDA trinta mil cordeiros e
// cabritos e três mil bois; os príncipes e os chefes dos levitas dão os seus; o
// sangue é espargido, as reses esfoladas, a páscoa ASSADA NO FOGO e as ofertas
// sagradas cozidas EM PANELAS, EM CALDEIRÕES E EM SERTÃS; os cantores, filhos
// de Asafe, ficam no seu posto e os porteiros a cada porta, e não precisam
// sair dali. E então o fim absurdo: NECÓ sobe a Carquemis, Josias lhe sai ao
// encontro, e o egípcio lhe manda dizer que a palavra é "da boca de Deus" —
// "guarda-te de te opores a Deus, que é comigo". Josias não vira o rosto:
// DISFARÇA-SE e vai pelejar no vale de Megido. Os flecheiros atiram nele, ele
// pede aos servos que o tirem dali, é posto NO SEGUNDO CARRO, e morre. E
// JEREMIAS faz uma lamentação sobre ele, que os cantores e as cantoras cantam
// "até ao dia de hoje".
//
// 2Cr 36 — o desmoronamento em vinte e três versículos. JEOACAZ reina três
// meses e o rei do Egito o depõe e condena a terra à contribuição. JEOIAQUIM é
// amarrado COM CADEIAS por Nabucodonosor, e alguns vasos da casa do SENHOR vão
// para o templo de Babilônia. JOAQUIM reina três meses e dez dias e é levado
// com OS MAIS PRECIOSOS VASOS. ZEDEQUIAS "nem se humilhou perante o profeta
// Jeremias", rebela-se, endurece a cerviz. Os chefes dos sacerdotes e o povo
// contaminam a casa; Deus fala CONSTANTEMENTE por intermédio dos mensageiros,
// "porque se compadeceu do seu povo e da sua habitação" — e eles zombam,
// desprezam e mofam, "até que o furor do Senhor tanto subiu contra o seu povo,
// que MAIS NENHUM REMÉDIO HOUVE". Então os caldeus matam no santuário, levam
// todos os vasos, QUEIMAM A CASA DE DEUS, DERRUBAM OS MUROS DE JERUSALÉM e
// queimam a fogo todos os palácios. A terra fica vazia e "repousou, até que os
// setenta anos se cumpriram". E o livro acaba com um decreto de fora: no
// primeiro ano de CIRO, rei da Pérsia, o SENHOR desperta o espírito do rei, e
// o pregão sai por todo o reino — "Quem há entre vós, de todo o seu povo, o
// Senhor seu Deus seja com ele, e suba".
//
// A VOZ DE DEUS — nestes cinco capítulos Deus nunca fala sem mediador, e por
// isso NÃO HÁ NENHUM `by:"deus"` aqui. Ele age e fala por quatro mediadores
// visíveis, cada um com o seu tratamento próprio:
//  • 32:21 — o ANJO no arraial da Assíria. Não é voz do céu: é figura em cena
//    (`role:"anjo"`, `glow` no máximo, glória alta sobre um acampamento de
//    noite), com os valentes e os capitães em `lie` no chão à volta dela. O
//    anjo não abre a boca — o texto não lhe põe palavra nenhuma —, e é por isso
//    que o beat é de narração pura: a cena inteira é o argumento.
//  • 34:22-28 — HULDA, a profetisa. O balão é DELA (`by:"mulherComum"`, id
//    `hulda`, sempre a PRIMEIRA mulherComum do cast), na sua casa, com os cinco
//    enviados do rei em volta e o `glow` subindo conforme o oráculo passa do
//    juízo sobre o lugar para a misericórdia sobre o rei.
//  • 35:21-22 — NECÓ. O texto diz literalmente que Josias "não deu ouvidos às
//    palavras de Neco, QUE SAÍRAM DA BOCA DE DEUS": o mediador é um rei pagão
//    em cena, e o balão é dele (`by:"rei"`, id `farao-neco`, o primeiro rei do
//    cast). Sem glória de teofania — a palavra vem certa por uma boca errada.
//  • 36:12,15-16,21-22 — JEREMIAS e "os mensageiros de Deus". Jeremias está em
//    cena diante de Zedequias (`patriarca`, id `jeremias-profeta`, `glow`) sem
//    balão, porque o versículo não lhe cita palavra: o que se vê é o rei que
//    NÃO SE HUMILHA diante dele. Em 36:15-16 os mensageiros são figuras
//    individuais com o rolo na mão, e a cena é o escárnio; e em 36:21-22 é "a
//    palavra do Senhor PELA BOCA DE JEREMIAS" que fica de pé sobre uma terra
//    vazia e depois desperta o espírito de Ciro.
//  • 33:4,7-8 — as promessas antigas sobre a casa ("porei o meu nome para
//    sempre") são CITAÇÃO, não fala de cena: entram como narração, com o traço
//    do lugar (a casa, as tábuas da lei) dominando o quadro, e sem balão. Pôr
//    voz do céu num átrio de Manassés seria dar glória ao pior capítulo do
//    livro.
// ============================================================================

