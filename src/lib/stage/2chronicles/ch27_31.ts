// 2 CRÔNICAS 27–31 — CENA VIVA. Cinco capítulos que descem ao fundo do poço e
// voltam: um rei que se fortifica calado (JOTÃO), um rei que queima os próprios
// filhos e FECHA AS PORTAS DA CASA DO SENHOR (ACAZ), e um rei que, no primeiro
// mês do primeiro ano, ABRE AS MESMAS PORTAS e passa dezesseis dias tirando
// entulho de dentro do templo (EZEQUIAS) — até a terra ficar coberta de MONTÕES
// de trigo, mosto, azeite e mel que começam no terceiro mês e só acabam no
// sétimo.
//
// 2Cr 27 — JOTÃO reina dezesseis anos e o cronista o resume por uma frase de
// engenharia: "Ele edificou a porta superior da casa do Senhor, e também
// edificou muitas obras sobre o muro de Ofel". Edifica cidades nas montanhas de
// Judá, e CASTELOS E TORRES NOS BOSQUES. Guerreia contra o rei dos filhos de
// Amom e prevalece, e Amom lhe paga CEM TALENTOS DE PRATA, DEZ MIL COROS DE
// TRIGO E DEZ MIL DE CEVADA — e paga de novo no segundo e no terceiro ano. O
// veredito é limpo e é sobre direção, não sobre talento: "Assim se fortificou
// Jotão, PORQUE DIRIGIU OS SEUS CAMINHOS na presença do Senhor seu Deus". Mas o
// capítulo guarda duas ressalvas que fazem sombra no resto do trecho: o pai
// Uzias entrara no templo e saíra leproso, e por isso este "não entrou no
// templo do Senhor" — e, apesar do rei reto, "O POVO AINDA SE CORROMPIA". A casa
// estava de pé e a gente já estava indo embora.
//
// 2Cr 28 — ACAZ, e o fundo do poço. Faz IMAGENS FUNDIDAS A BAALINS, queima
// incenso no VALE DO FILHO DE HINOM e "queimou a seus filhos no fogo, conforme
// as abominações dos gentios". O SENHOR o entrega à mão da Síria, que leva presos
// a Damasco, e à mão de Israel: PECA, FILHO DE REMALIAS, mata cento e vinte mil
// em Judá num só dia, e ZICRI, VALENTE DE EFRAIM, mata em pessoa o filho do rei,
// o mordomo e o segundo depois do rei. Israel leva DUZENTOS MIL cativos —
// mulheres, filhos e filhas — a caminho de Samaria. E então acontece a coisa
// mais inesperada do livro: um profeta chamado OBEDE sai ao encontro do próprio
// exército vencedor e o acusa — "vós os matastes com uma raiva tal, que chegou
// até aos céus" —, quatro homens de Efraim são nomeados um a um e se levantam
// contra os que voltavam da batalha, e os soldados largam os cativos e o
// despojo no chão. Aí vem o versículo 15, que não tem paralelo: os inimigos
// VESTEM do despojo os que estavam nus, CALÇAM-NOS, dão-lhes de comer e de
// beber, UNGEM-NOS, e a todos os que estavam fracos LEVAM SOBRE JUMENTOS até
// Jericó, a cidade das palmeiras. Acaz, do outro lado, faz o contrário de tudo:
// pede socorro à Assíria, é apertado por Tiglate-Pileser, sacrifica aos deuses
// de Damasco QUE O FERIRAM — "visto que os deuses dos reis da Síria os ajudam"
// —, quebra em pedaços os utensílios da casa de Deus e FECHA AS PORTAS. É
// sepultado na cidade, mas não nos sepulcros dos reis.
//
// 2Cr 29 — EZEQUIAS, e o primeiro ato do reinado é uma dobradiça: "Ele, no
// primeiro ano do seu reinado, no primeiro mês, ABRIU AS PORTAS DA CASA DO
// SENHOR, e as reparou". Ajunta sacerdotes e levitas na praça oriental e lhes
// prega o diagnóstico inteiro — nossos pais fecharam as portas do alpendre,
// apagaram as lâmpadas, viraram as costas ao tabernáculo — e o remédio: "tirai
// do santuário a IMUNDÍCIA". Catorze levitas são nomeados um a um, e o trabalho
// é braçal: os sacerdotes tiram tudo para o pátio e OS LEVITAS CARREGAM ATÉ O
// RIBEIRO DE CEDROM, do primeiro dia ao décimo sexto do primeiro mês. Depois
// vem o culto: sete novilhos, sete carneiros, sete cordeiros e sete bodes; os
// levitas em pé COM OS INSTRUMENTOS DE DAVI e os sacerdotes COM AS TROMBETAS; e
// "ao tempo em que começou o holocausto, começou também o canto do Senhor".
// Setenta bois, cem carneiros, duzentos cordeiros — e os sacerdotes eram tão
// poucos que os levitas tiveram de ajudar a esfolar. O fecho é de alívio:
// "Ezequias, e todo o povo se alegraram… PORQUE APRESSURADAMENTE SE FEZ ESTA
// OBRA".
//
// 2Cr 30 — A PÁSCOA DO SEGUNDO MÊS, celebrada fora do prazo porque no prazo
// certo não havia sacerdotes santificados nem povo ajuntado. Ezequias escreve
// CARTAS a Efraim e Manassés e manda passar pregão desde Berseba até Dã, e os
// CORREIOS saem com o convite mais largo do livro: "convertei-vos ao Senhor
// Deus de Abraão, de Isaque e de Israel". Eles vão passando de cidade em cidade
// pela terra de Efraim e Manassés até Zebulom — "PORÉM RIRAM-SE E ZOMBARAM
// DELES". Mesmo assim alguns de Aser, de Manassés e de Zebulom SE HUMILHARAM e
// vieram. Em Jerusalém tiram os altares e os lançam no Cedrom; muitos comem a
// páscoa sem se ter purificado, e o rei ora por eles — "O Senhor, que é bom,
// perdoa todo aquele que tem preparado o seu coração" — e "OUVIU O SENHOR A
// EZEQUIAS, E SAROU O POVO". A festa de sete dias vira festa de catorze, e o
// cronista mede a alegria por Salomão: "desde os dias de Salomão… tal não houve
// em Jerusalém".
//
// 2Cr 31 — Acabada a festa, o povo não volta para casa: SAI. Quebra as
// estátuas, corta os bosques e derruba os altos e os altares por Judá,
// Benjamim, Efraim e Manassés, "até que tudo destruíram". Ezequias restabelece
// as turmas, separa a parte da fazenda do rei para os holocaustos e ordena ao
// povo que dê a porção dos sacerdotes e levitas "PARA QUE ELES PUDESSEM SE
// DEDICAR À LEI DO SENHOR". E aí o texto explode em abundância: primícias de
// trigo, mosto, azeite, mel e de todo o produto do campo, dízimos dos bois e
// das ovelhas — "e fizeram MUITOS MONTÕES", montões que começam no terceiro mês
// e só acabam no sétimo. Ezequias vê os montões e pergunta o que é aquilo, e
// AZARIAS, o sumo sacerdote da casa de Zadoque, responde a frase que fecha o
// trecho: "desde que se começou a trazer estas ofertas à casa do Senhor, temos
// comido e temos fartado, E AINDA SOBEJOU EM ABUNDÂNCIA". Preparam câmaras,
// nomeiam guardas fiéis, registram por genealogias até as crianças de três anos
// — e o último verso é o resumo do homem: "toda a obra… ele a fez de todo o seu
// coração, e prosperou".
//
// A VOZ DE DEUS — nestes cinco capítulos Deus NÃO fala uma única vez sem
// mediador, e por isso NÃO HÁ NENHUM `by:"deus"` aqui. A única boca profética do
// trecho é a de OBEDE, o profeta do SENHOR em Samaria (28:9-11): o texto diz
// "estava ali um profeta do Senhor… e lhe disse", então o balão sai DELE
// (`by:"patriarca"`, id `odede-profeta`, figura em cena com `glow` alto e a
// glória subindo em cima de um exército vitorioso — a luz não está com quem
// venceu, está com quem acusa). Nos outros lugares em que Deus age, Ele age
// CALADO, e a cena tem de dizer isso sem balão: em 29:20-28 o fogo do
// holocausto sobe junto com o cântico e as trombetas (`altar` com `fire` no
// máximo, `harp`, `trumpet`, glória no auge, e nenhuma fala do alto); em 30:20
// "ouviu o Senhor a Ezequias, e sarou o povo" é resposta pura — glória em cima
// do povo levantando-se, sem nenhuma figura divina; e em 30:27 a oração é que
// SOBE, "até aos céus", com os sacerdotes de braços erguidos e o dourado no
// zênite. Onde o rei fala por Deus (29:5-11, 30:18-19) o balão é do REI, porque
// é a boca dele que o texto põe na frase. E as CARTAS de 30:1-9 são um mediador
// de papel: quem fala é o CORREIO que as lê em voz alta (`by:"homem"`), com o
// `scroll` etiquetado dominando o quadro — Ezequias não aparece na estrada.
// ============================================================================

