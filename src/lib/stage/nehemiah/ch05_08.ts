// NEEMIAS 5–8 — CENA VIVA. O bloco em que o livro vira do avesso duas vezes: o
// inimigo deixa de estar do lado de fora do muro e passa a estar dentro de casa
// (5); volta para fora e tenta cinco armadilhas seguidas (6); o muro acaba e a
// cidade aparece VAZIA (7); e então, na praça da porta das águas, um homem sobe
// num púlpito de madeira, abre um rolo, e o povo inteiro se põe de pé (8).
//
// Ne 5 — o GRANDE CLAMOR DO POVO E DE SUAS MULHERES, e é o único capítulo do
// livro em que a queixa é CONTRA OS SEUS IRMÃOS JUDEUS. Três vozes se erguem no
// mesmo largo: "nós, nossos filhos e nossas filhas, somos muitos; então tomemos
// trigo, para que comamos e vivamos"; "as nossas terras, as nossas vinhas e as
// nossas casas EMPENHAMOS, para tomarmos trigo nesta fome"; e a terceira, que é
// a que fecha o círculo — "tomamos emprestado dinheiro ATÉ PARA O TRIBUTO DO
// REI, sobre as nossas terras e as nossas vinhas". E o remate: "a nossa carne é
// como a carne de nossos irmãos, e nossos filhos como seus filhos; e eis que
// SUJEITAMOS NOSSOS FILHOS E NOSSAS FILHAS para serem servos… e não está no
// poder de nossas mãos, e OUTROS TÊM as nossas terras e as nossas vinhas". A
// resposta de Neemias é uma linha só: "muito me indignei". Ele considera
// consigo mesmo, peleja com os nobres e com os magistrados — "SOIS USURÁRIOS
// cada um para com seu irmão" —, convoca CONTRA ELES uma grande assembléia, e
// os cala: "então se calaram, e não acharam que responder". Deixa o próprio
// ganho ("também eu, meus irmãos e meus servos, a juros lhes temos emprestado
// dinheiro e trigo. DEIXEMOS ESTE GANHO"), manda restituir hoje as terras, as
// vinhas, os olivais, as casas e a centésima parte do dinheiro, do trigo, do
// mosto e do azeite; faz os sacerdotes jurarem — e então SACODE AS ABAS DA
// VESTE: "assim sacuda Deus todo o homem da sua casa e do seu trabalho que não
// confirmar esta palavra, e assim seja sacudido e vazio". E toda a congregação
// disse: AMÉM! E o capítulo acaba no retrato do governador que não come o pão
// do governo: doze anos, do ano vinte ao ano trinta e dois de Artaxerxes, sem
// tomar o pão do governador; os primeiros governadores oprimiam e tomavam
// quarenta siclos de prata, "porém eu assim não fiz, POR CAUSA DO TEMOR DE
// DEUS"; cento e cinqüenta homens dos judeus e dos magistrados à sua mesa, além
// dos que vinham das nações; um boi, seis ovelhas escolhidas e aves cada dia, e
// vinho de dez em dez dias — "e nem por isso exigi o pão do governador,
// porquanto a servidão deste povo era grande". E o pedido de uma linha:
// "lembra-te de mim para bem, ó meu Deus".
//
// Ne 6 — as CINCO ARMADILHAS, uma atrás da outra, todas contra um homem só.
// (1) O convite ao VALE DE ONO, longe da obra, quatro vezes, e quatro vezes a
// mesma resposta, que é a frase que sustenta o livro: "FAÇO UMA GRANDE OBRA, de
// modo que não poderei descer; por que cessaria esta obra, enquanto eu a
// deixasse, e fosse ter convosco?" (2) A quinta vez, a CARTA ABERTA na mão do
// moço — aberta de propósito, para todos lerem no caminho: "entre os gentios se
// ouviu, e Gasmu diz: tu e os judeus intentais rebelar-vos… e tu te farás rei
// deles… vem, pois, agora, e consultemos juntamente". E a resposta: "de tudo o
// que dizes coisa nenhuma sucedeu; mas TU, DO TEU CORAÇÃO, O INVENTAS" — porque
// todos procuravam atemorizá-los, dizendo "as suas mãos largarão a obra".
// (3) SEMAÍAS, filho de Delaías, ENCERRADO em casa, que o quer levar ao meio do
// templo e fechar as portas "porque virão matar-te; sim, de noite virão
// matar-te" — e Neemias: "UM HOMEM COMO EU FUGIRIA? e quem há, como eu, que
// entre no templo para que viva? De maneira nenhuma entrarei". E percebe que
// não era Deus quem o enviara: Tobias e Sambalate o tinham SUBORNADO, para que
// ele pecasse e tivessem causa para o infamar. (4) A profetisa NOADIA e os mais
// profetas que procuravam atemorizá-lo. (5) As cartas que iam e vinham, porque
// muitos em Judá eram AJURAMENTADOS a Tobias — genro de Secanias, filho de Ará,
// e sogro do filho de Mesulão, filho de Berequias — e contavam as boas ações
// dele diante de Neemias e levavam a Tobias as palavras dele. E no meio disso
// tudo, a linha que fecha a conta: "ACABOU-SE, POIS, O MURO aos vinte e cinco
// do mês de Elul; EM CINQÜENTA E DOIS DIAS" — e todos os povos em redor temeram
// e abateram-se muito a seus próprios olhos, "porque reconheceram que O NOSSO
// DEUS FIZERA ESTA OBRA".
//
// Ne 7 — o muro edificado, as portas levantadas, os porteiros, os cantores e os
// levitas estabelecidos; Hanani e Hananias, o maioral da fortaleza, postos
// sobre Jerusalém; e a ordem sobre os portais: "não se abram as portas de
// Jerusalém até que O SOL AQUEÇA… e ponham-se guardas dos moradores de
// Jerusalém, cada um na sua guarda, e cada um DIANTE DA SUA CASA". E então a
// frase que explica o capítulo inteiro: "era a cidade LARGA DE ESPAÇO, E
// GRANDE, porém POUCO POVO havia dentro dela; e ainda AS CASAS NÃO ESTAVAM
// EDIFICADAS". Deus lhe põe no coração ajuntar os nobres para registrar as
// genealogias — e ele ACHA UM ROLO: "o livro da genealogia dos que subiram
// primeiro". Setenta e três versículos que repetem quase palavra por palavra a
// lista de Esdras 2 — mas por um motivo OPOSTO. Em Esdras a lista é de quem
// estava a CHEGAR, e a paisagem dela é a estrada, a eira, o lagar, o adro dos
// que se apresentam. Aqui é um rolo ACHADO por um governador dentro de uma
// cidade vazia, lido para saber QUEM HÁ DE POVOAR JERUSALÉM — e por isso a
// paisagem deste capítulo é o LUGAR VAZIO: o risco das casas marcado no chão
// nu, a rua sem telhado, a soleira sem porta, o pátio do poço seco, o terraço
// por cobrir, o adro dos sacerdotes sem turno, o estrado dos cantores com as
// harpas encostadas, as seis soleiras dos porteiros sem porteiro nenhum. Cada
// casa paterna que o rolo nomeia é um espaço que ainda não tem gente, e o rolo
// é o único objeto grande do capítulo. No fim há o que Esdras 2 não tem por
// igual: a oferta do TIRSATA — mil dracmas de ouro, cinqüenta bacias e
// quinhentas e trinta vestes sacerdotais —, a dos chefes dos pais e a do resto
// do povo, postas no TESOURO DA OBRA. E a última linha enche tudo o que estava
// vazio: "e habitaram os sacerdotes, os levitas, os porteiros, os cantores,
// alguns do povo, os servidores do templo, e todo o Israel NAS SUAS CIDADES".
//
// Ne 8 — e o livro muda de tom por completo. Chegado o sétimo mês, todo o povo
// se ajunta COMO UM SÓ HOMEM na praça diante da PORTA DAS ÁGUAS e pede a
// ESDRAS, o escriba, o LIVRO DA LEI DE MOISÉS. Ele o traz perante a
// congregação, "tanto de homens como de mulheres, e todos os que podiam ouvir
// com entendimento", e lê nele DESDE A ALVA ATÉ AO MEIO-DIA — "e os ouvidos de
// todo o povo estavam atentos ao livro da lei". Esdras está SOBRE UM PÚLPITO DE
// MADEIRA que fizeram para aquele fim, com seis homens à sua mão direita e sete
// à esquerda. "E ESDRAS ABRIU O LIVRO PERANTE À VISTA DE TODO O POVO; PORQUE
// ESTAVA ACIMA DE TODO O POVO; E, ABRINDO-O ELE, TODO O POVO SE PÔS EM PÉ." Ele
// louva ao SENHOR, e o povo responde AMÉM, AMÉM, levantando as mãos, e adora
// com os rostos em terra. Treze levitas ensinam o povo na lei, "e o povo estava
// no seu lugar": "e leram no livro, na lei de Deus; e DECLARANDO, E EXPLICANDO
// O SENTIDO, faziam que, lendo, se entendesse". E como o povo chorava ouvindo
// as palavras da lei, Neemias, Esdras e os levitas dizem: "este dia é consagrado
// ao SENHOR vosso Deus, então não vos lamenteis, nem choreis… ide, comei as
// gorduras, e bebei as doçuras, e ENVIAI PORÇÕES aos que não têm nada preparado
// para si… porque A ALEGRIA DO SENHOR É A VOSSA FORÇA". No dia seguinte acham
// escrito na lei a festa das CABANAS, e o pregão sai por todas as cidades: "saí
// ao monte, e trazei ramos de oliveiras, e ramos de zambujeiros, e ramos de
// murtas, e ramos de palmeiras, e ramos de árvores espessas, para fazer
// cabanas" — e fizeram cabanas cada um no seu terraço, nos seus pátios, nos
// átrios da casa de Deus, na praça da porta das águas e na praça da porta de
// Efraim. "Porque nunca fizeram assim os filhos de Israel, desde os dias de
// Jesua, filho de Num, até àquele dia; e HOUVE MUI GRANDE ALEGRIA."
//
// A VOZ DE DEUS — nestes quatro capítulos DEUS NÃO FALA UMA ÚNICA VEZ, e por
// isso não existe neste arquivo nenhum `by:"deus"` e nenhum balão dourado sem
// figura. As três orações de Neemias (5:19, 6:9, 6:14) são balões DELE, em
// cena, com `glow` baixo e a glória subindo no ambiente. Em 6:10 quem fala é
// SEMAÍAS, e o texto do versículo seguinte diz expressamente que "não era Deus
// quem o enviara" — por isso o balão é do homem e ele NÃO tem `glow` nenhum:
// desenhar luz nele seria contradizer o versículo 12. E em Ne 8 o mediador é o
// LIVRO: Esdras está SOBRE O PÚLPITO, acima de todo o povo, com o rolo aberto
// na mão — o balão é dele (`by: "esdras-o-escriba"`), e o `scroll` domina o
// quadro em `scale` 2,2–2,6, porque o que fala ali é a lei que ele lê. A
// providência do bloco é dita em narração e desenhada em luz: "o meu Deus me
// pôs no coração" (7:5) e "reconheceram que o nosso Deus fizera esta obra"
// (6:16) sobem a glória no `env` sem que ninguém fale do alto.
// ============================================================================

