// ============================================================================
// NEEMIAS 1–4 — CENA VIVA. Quatro capítulos que vão de um homem chorando
// sozinho num palácio de inverno até um canteiro de obra inteiro trabalhando de
// espada cingida aos lombos. É o livro da RECONSTRUÇÃO, e o motor dele não é um
// milagre: é um copeiro que pergunta, chora, jejua, ora, mede o estrago de
// noite montado num jumento, e só então abre a boca.
//
// Ne 1 — SUSÃ, A FORTALEZA, no mês de Quislev, no ano vigésimo. Chega HANANI,
// um dos irmãos de Neemias, com alguns de Judá, e ele pergunta o que ninguém
// mais parecia perguntar: pelos judeus que escaparam, pelos que restaram do
// cativeiro, e "acerca de Jerusalém". A resposta é uma frase de demolição:
// "estão em grande miséria e desprezo; e o MURO de Jerusalém FENDIDO e as suas
// PORTAS QUEIMADAS A FOGO". E o que ele faz com a notícia é o resto do
// capítulo: "assentei-me e chorei, e lamentei por alguns dias; e estive
// jejuando e orando perante o Deus dos céus". A oração é uma escada de cinco
// degraus — a aliança ("Deus grande e terrível! Que guarda a aliança"), a
// confissão que não terceiriza culpa ("também EU E A CASA DE MEU PAI temos
// pecado"), a palavra dada a Moisés ("Vós transgredireis, e eu vos espalharei
// entre os povos"), a promessa de volta ("ainda que os vossos rejeitados
// estejam na extremidade do céu, de lá os ajuntarei"), e o pedido, que só se
// entende no versículo seguinte: "dá-lhe graça perante ESTE HOMEM. Então era eu
// COPEIRO DO REI".
//
// Ne 2 — o mês de NISÃ, quatro meses depois. Está posto vinho diante do rei,
// Neemias pega a taça e a dá — "porém eu nunca estivera triste diante dele". O
// rei repara: "Por que está triste o teu rosto, pois não estás doente? Não é
// isto senão TRISTEZA DE CORAÇÃO" — e a linha seguinte é a mais honesta do
// livro: "então temi sobremaneira". Ele responde com a fórmula da corte e com a
// verdade juntas: "Viva o rei para sempre! Como não estaria triste o meu rosto,
// estando a cidade, o lugar dos SEPULCROS DE MEUS PAIS, assolada?" O rei
// pergunta o que ele quer, e no meio de uma audiência real cabe uma oração de
// um segundo: "ENTÃO OREI AO DEUS DOS CÉUS". Pede envio, pede cartas para os
// governadores dalém do rio, pede uma carta para ASAFE, guarda da floresta do
// rei, por causa da MADEIRA — "e o rei mas deu, SEGUNDO A BOA MÃO DE DEUS SOBRE
// MIM". Na estrada aparecem SAMBALATE, o horonita, e TOBIAS, o servo amonita, a
// quem "desagradou extremamente que alguém viesse a procurar o bem dos filhos
// de Israel". E então a cena mais secreta do Antigo Testamento: três dias
// calado, e de NOITE ele se levanta com poucos homens, sem declarar a ninguém o
// que Deus lhe pusera no coração, sem animal nenhum senão aquele em que ia
// montado — a porta do vale, a fonte do dragão, a porta do monturo, a porta da
// fonte, o tanque do rei, "e NÃO HAVIA LUGAR POR ONDE PUDESSE PASSAR O ANIMAL".
// Sobe pelo ribeiro, contempla o muro, volta a entrar pela porta do vale, e os
// magistrados não souberam de nada. Só aí ele fala: "vinde, pois, e
// reedifiquemos o muro de Jerusalém, e não sejamos mais um opróbrio" — e o povo
// responde com três palavras: "LEVANTEMO-NOS, E EDIFIQUEMOS".
//
// Ne 3 — a lista dos construtores, e é o capítulo mais desenhável do livro:
// não é um rol de nomes, é um MAPA DE OFÍCIOS, porta por porta, dando a volta
// completa na cidade. Começa em ELIASIBE, o sumo sacerdote, que consagra a
// PORTA DO GADO e levanta as suas portas até à torre de Meá e à torre de
// Hananel; passa pelos homens de Jericó, pela PORTA DO PEIXE dos filhos de
// Hassenaá com as suas fechaduras e ferrolhos, pelos TECOÍTAS — "porém os seus
// nobres NÃO SUBMETERAM A CERVIZ ao serviço de seu Senhor" —, pela PORTA VELHA;
// e então entram os ofícios, um a um: UZIEL, UM DOS OURIVES; HANANIAS, FILHO DE
// UM DOS BOTICÁRIOS; a TORRE DOS FORNOS; SALUM, filho de Haloés, "ELE E SUAS
// FILHAS"; a PORTA DO VALE e mil côvados de muro; a PORTA DO MONTURO; a PORTA
// DA FONTE com o tanque de Hasselá ao pé do jardim do rei; os LEVITAS; a subida
// à CASA DAS ARMAS; os sacerdotes da campina; a torre que sai da casa real
// junto ao pátio da prisão; os SERVIDORES DO TEMPLO em Ofel; a PORTA DOS
// CAVALOS; a PORTA ORIENTAL; a PORTA DE MIFCADE; e fecha o círculo onde ele
// começou — "entre a câmara do canto e a PORTA DO GADO, repararam os OURIVES e
// os MERCADORES". Ao longo dos trinta e dois quadros o muro CRESCE: começa em
// pedra solta no chão e acaba com o casario inteiro de pé atrás dele.
//
// Ne 4 — a oposição fica séria. Sambalate arde em ira diante do exército de
// Samaria: "Que fazem estes FRACOS JUDEUS? … Vivificarão dos montões do pó as
// pedras que foram queimadas?" E Tobias completa com a piada que virou
// provérbio: "ainda que edifiquem, contudo, vindo uma RAPOSA, derrubará
// facilmente o seu muro de pedra". A resposta de Neemias não é revide, é
// oração — e o muro sobe: "todo o muro se fechou ATÉ SUA METADE; porque o
// coração do povo se inclinava a trabalhar". Então árabes, amonitas e asdoditas
// se ligam para vir guerrear, e vem o cansaço, que é pior que a espada: "Já
// desfaleceram as forças dos carregadores, E O PÓ É MUITO, e nós não poderemos
// edificar o muro"; e os inimigos: "Nada saberão disto, nem verão, até que
// entremos no meio deles"; e os judeus de fora vindo DEZ VEZES dizer "de todos
// os lugares, tornarão contra nós". E aí nasce a imagem que define o livro:
// o povo posto por famílias com as suas ESPADAS, LANÇAS e ARCOS; "cada um com
// UMA DAS MÃOS FAZIA A OBRA E NA OUTRA TINHA AS ARMAS"; cada edificador com a
// espada cingida aos lombos; e o que tocava a TROMBETA junto de Neemias — "no
// lugar onde ouvirdes o som da buzina, ali vos ajuntareis conosco; O NOSSO DEUS
// PELEJARÁ POR NÓS". Metade com as lanças "desde a subida da alva até ao sair
// das estrelas", e ninguém largando as vestes: "cada um tinha suas armas e
// água".
//
// A VOZ DE DEUS — nestes quatro capítulos DEUS NÃO FALA UMA ÚNICA VEZ. Não há
// profeta, não há anjo, não há voz do céu, não há sonho: por isso NÃO existe
// nenhum `by:"deus"` neste arquivo, e nenhum balão dourado sem figura. O que há
// é o CONTRÁRIO — o homem falando com Deus, e por isso todas as orações são
// balões DE NEEMIAS, em cena, de joelhos ou de braços erguidos (1:5-11, 2:4,
// 4:4-5), com `glow` baixo e a glória subindo no ambiente, nunca nele. A
// providência deste livro é dita em narração e desenhada em luz: "segundo a boa
// mão de Deus sobre mim" (2:8), "como a mão do meu Deus me fora favorável"
// (2:18), "Deus tinha dissipado o conselho deles" (4:15) — em cada um desses
// versículos a glória sobe no `env` sem que ninguém fale do alto. E em 4:20 a
// única frase teológica do capítulo sai da boca de um homem no meio do
// canteiro, com a buzina ao lado: "o nosso Deus pelejará por nós".
// ============================================================================

