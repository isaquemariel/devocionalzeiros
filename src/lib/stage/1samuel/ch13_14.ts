// Gibeá, Saul toca a trombeta por toda a terra ("Ouçam os hebreus"), e o
// resultado é uma frase que pesa: ISRAEL SE FEZ ABOMINÁVEL AOS FILISTEUS. A
// resposta desce como avalanche — TRINTA MIL CARROS, SEIS MIL CAVALEIROS e povo
// como A AREIA À BEIRA DO MAR, acampados em Micmás, ao oriente de Bete-Áven. O
// povo de Israel, em apuros, se esconde pelas CAVERNAS, pelos ESPINHAIS, pelos
// PENHASCOS, pelas fortificações e pelas COVAS; alguns hebreus passam o JORDÃO
// para Gade e Gileade, e os que ficam vão atrás de Saul TREMENDO. Em GILGAL
// Saul espera SETE DIAS, o prazo que Samuel determinara; Samuel não vem e o povo
// se dispersa dele. Então o rei manda trazer o holocausto — e O OFERECE ELE
// MESMO. Acabando de oferecer, ⭐ EIS QUE SAMUEL CHEGA. "Que fizeste?" Saul se
// explica: o povo se espalhava, tu não vinhas, os filisteus já em Micmás,
// "CONSTRANGI-ME, E OFERECI HOLOCAUSTO". E vem a sentença: procedeste
// nesciamente; AGORA NÃO SUBSISTIRÁ O TEU REINO; JÁ TEM BUSCADO O SENHOR PARA SI
// UM HOMEM SEGUNDO O SEU CORAÇÃO. Samuel sobe de Gilgal a Gibeá, e Saul conta o
// que lhe resta: UNS SEISCENTOS HOMENS. Os saqueadores filisteus saem em TRÊS
// COMPANHIAS — Ofra, Bete-Horom, o vale de Zeboim. E o capítulo fecha com o
// detalhe mais humilhante da opressão: EM TODA A TERRA DE ISRAEL NEM UM FERREIRO
// SE ACHAVA, porque os filisteus tinham dito "para que os hebreus não façam
// espada nem lança"; cada israelita tinha de DESCER AOS FILISTEUS para amolar a
// relha, a enxada, o machado e o sacho, e pagar pela LIMA. No dia da peleja não
// havia espada nem lança na mão do povo: só na de Saul e de Jônatas.
//
// 1Sm 14 — Um dia Jônatas diz ao PAJEM DE ARMAS: passemos à guarnição do outro
// lado — E NÃO O FAZ SABER A SEU PAI. Saul está à extremidade de Gibeá, debaixo
// da ROMEIRA de Migrom, com os seiscentos, e AÍAS, bisneto de Eli, TRAZ O ÉFODE.
