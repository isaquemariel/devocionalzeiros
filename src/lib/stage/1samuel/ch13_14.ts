// filisteus dizem exatamente isso. Jônatas sobe COM OS PÉS E COM AS MÃOS, o
// pajem atrás, e caem uns VINTE HOMENS em meia jeira de terra. Então há TREMOR
// no arraial, no campo e em todo o povo, e até a terra se estremece: TREMOR DE
// DEUS. As sentinelas de Gibeá veem a multidão se dissolvendo; Saul manda contar
// quem saiu, e faltam Jônatas e o pajem. Pede a arca a Aías — e, com o alvoroço
// crescendo, corta a consulta: "RETIRA A TUA MÃO". Os hebreus que estavam com os
// filisteus voltam o lado; os escondidos da montanha de EFRAIM saem das covas; e
// o SENHOR livra Israel naquele dia. Mas Saul CONJURA o povo: MALDITO O HOMEM
// QUE COMER PÃO ATÉ À TARDE. O povo chega a um BOSQUE onde o MEL corre pelo
// chão, e ninguém toca — só Jônatas, que não ouvira o juramento, molha a ponta
// da VARA no favo, e SE LHE ACLARAM OS OLHOS. Exaustos, ao fim do dia os homens
// se lançam ao despojo e comem A CARNE COM O SANGUE; Saul manda rolar uma GRANDE
// PEDRA para degolarem ali, e edifica o PRIMEIRO ALTAR que edificou ao SENHOR. À
// consulta da noite, porém, ⭐ DEUS NÃO RESPONDE. As sortes caem sobre Jônatas —
// "eis que devo morrer?" — e é O POVO quem o resgata: "não lhe há de cair no
// chão um só cabelo da sua cabeça". O capítulo fecha com o resumo do reinado: as
// guerras em redor, os filhos, as filhas, Ainoã, Abner filho de Ner, e a FORTE
// GUERRA contra os filisteus todos os dias de Saul.
//
// A VOZ DE DEUS (regra do projeto): nestes dois capítulos DEUS NÃO FALA — nem do
// céu, nem por mediador. Em 13:13-14 a sentença sobre o reino sai da boca de
// SAMUEL (`by:"patriarca"`), não de voz do céu: a palavra é do SENHOR, a boca é
// do profeta. Em 14:37 acontece o contrário e é preciso senti-lo no palco: Saul
// consulta e "aquele dia não lhe respondeu" — o SILÊNCIO é encenado com a glória
// CAINDO (0.5 → 0.12) e a noite SUBINDO, sem balão nenhum. A única manifestação
// direta do SENHOR é o TREMOR de 14:15, que é `storm` no auge com glória média,
// e não prop nem figura. FOGO: só o `altar` com `fire` de Gilgal e o `campfire`
// da FORJA filisteia (13:19-21) desenham chama de verdade — `env.fire` é só
// ambiência. MULTIDÃO: nas cavernas (13:6), no exército desfalecido (14:24-31) e
// nos mortos da peleja usam-se figuras INDIVIDUAIS em `bow`/`kneel`/`lie`, pois
// `multidao` é sempre desenhada comemorando — ela só entra onde há de fato festa
// (o povo que resgata Jônatas, 14:45).
// ============================================================================

