// 1 SAMUEL 13–14 — CENA VIVA. O HOLOCAUSTO QUE SAUL NÃO PODIA OFERECER, a
// TERRA SEM FERREIRO, e a subida de JÔNATAS entre BOZEZ e SENÉ.
//
// 1Sm 13 — Saul reina, e do povo todo escolhe TRÊS MIL homens: dois mil com ele
// em MICMÁS e na montanha de BETEL, mil com JÔNATAS em GIBEÁ DE BENJAMIM — o
