// 1 SAMUEL 15–16 — CENA VIVA. AMALEQUE e a capa rasgada ("o obedecer é melhor
// do que o sacrificar"), e o CHIFRE DE AZEITE que desce a Belém.
//
// 1Sm 15 — Samuel volta a Saul com uma ordem inteira, sem margem: "enviou-me o
// SENHOR a ungir-te rei… ouve, pois, agora a voz das palavras do SENHOR".
// A conta que se abre é antiga — AMALEQUE, que se opôs a Israel NO CAMINHO,
// quando subia do Egito. Vai, fere, e DESTRÓI TOTALMENTE. Saul convoca o povo e
// o conta em TELAIM: duzentos mil homens de pé e dez mil de Judá. Chega à
// cidade de Amaleque e põe emboscada no vale — mas antes manda um recado que o
// texto guarda com cuidado: os QUENEUS que se retirem do meio dos amalequitas,
// PORQUE USARAM DE MISERICÓRDIA com os filhos de Israel quando subiram do
// Egito. A memória de Deus não esquece o mal nem a bondade. Saul fere desde
// HAVILÁ até SUR, defronte do Egito, e toma vivo AGAGUE — e aqui a ordem se
// parte pelo meio: pouparam Agague, e o melhor das ovelhas e das vacas, e as da
// segunda ordem, e os cordeiros, e tudo o que era bom; só a coisa VIL E
// DESPREZÍVEL destruíram totalmente. De noite vem a palavra: ⭐ "ARREPENDO-ME DE
// HAVER POSTO A SAUL COMO REI" — e Samuel se contrista e clama a noite inteira.
// De madrugada corre atrás do rei, e recebe a notícia que já é o retrato do
// homem: Saul chegou ao CARMELO e LEVANTOU PARA SI UMA COLUNA. Descem a GILGAL,
// e o rei o recebe com um cumprimento que a própria cena desmente: "bendito
// sejas tu do Senhor; CUMPRI a palavra do Senhor" — e Samuel responde apontando
// para o som: "QUE BALIDO, POIS, DE OVELHAS É ESTE AOS MEUS OUVIDOS, e o mugido
// de vacas que ouço?". Saul culpa o povo e batiza a desobediência de culto —
// pouparam "para as oferecer ao SENHOR TEU DEUS" (teu, já não meu). Então vem a
// sentença que atravessa a Bíblia inteira: ⭐ "TEM PORVENTURA O SENHOR TANTO
// PRAZER EM HOLOCAUSTOS E SACRIFÍCIOS, COMO EM QUE SE OBEDEÇA À PALAVRA DO
// SENHOR? EIS QUE O OBEDECER É MELHOR DO QUE O SACRIFICAR" — e a REBELIÃO é
// como o pecado de FEITIÇARIA. Saul confessa ("temi ao povo") e pede perdão;
// Samuel se vira para ir embora, e o rei se agarra à ORLA DA CAPA e A RASGA —
// e o pano rasgado na mão vira o sinal: "O SENHOR TEM RASGADO DE TI HOJE O
// REINO DE ISRAEL, e o tem dado ao teu próximo, MELHOR DO QUE TU". Saul só pede
// que o honrem diante dos anciãos, e Samuel volta — mas para acabar o serviço
// que o rei não fez: manda trazer AGAGUE, que vem animosamente ("já passou a
// amargura da morte"), e o despedaça PERANTE O SENHOR EM GILGAL. Depois cada um
// sobe para o seu lado: Samuel a RAMÁ, Saul a GIBEÁ — e nunca mais se viram até
// ao dia da morte do profeta, que contudo tinha DÓ dele.
//
// 1Sm 16 — O luto do profeta é interrompido por uma pergunta: "ATÉ QUANDO TERÁS
// DÓ DE SAUL, havendo-o eu rejeitado?". Enche um CHIFRE DE AZEITE e vai a JESSÉ,
// o belemita — dentre os filhos dele o SENHOR já se proveu de um rei. Samuel tem
// medo de morrer ("ouvindo-o Saul, me matará") e recebe uma cobertura simples:
// leva uma BEZERRA e diz que veio sacrificar. Em BELÉM os anciãos da cidade lhe
// saem ao encontro TREMENDO — "é de paz a tua vinda?" — e ele santifica Jessé e
// os filhos. Então começa o desfile: ELIABE entra, alto, e o profeta já decide
// por ele — "certamente está perante o Senhor o seu ungido". E leva a maior
// correção do capítulo: ⭐ "O HOMEM VÊ O QUE ESTÁ DIANTE DOS OLHOS, PORÉM O
// SENHOR OLHA PARA O CORAÇÃO". Passam ABINADABE, SAMA, os sete — nenhum. E a
// pergunta que abre a porta: "ACABARAM-SE OS MOÇOS?". Ainda falta o MENOR, que
// está apascentando as ovelhas; e ninguém se assenta até que ele venha. Entra o
// ruivo, formoso de semblante e de boa presença, e a voz decide: "levanta-te, e
// unge-o, PORQUE É ESTE MESMO". Samuel o unge NO MEIO DE SEUS IRMÃOS, e desde
// aquele dia em diante o ESPÍRITO DO SENHOR se apodera de Davi. No mesmo fôlego
// o texto vira a moeda: o Espírito do SENHOR SE RETIRA DE SAUL, e um espírito
// mau o atormenta. Os criados propõem um tangedor de HARPA; um dos moços já
// tinha visto o homem — filho de Jessé, o belemita, que sabe tocar, valente,
// homem de guerra, prudente em palavras e de gentil presença, "e O SENHOR É COM
// ELE". Jessé manda um JUMENTO CARREGADO DE PÃO, um ODRE DE VINHO e um CABRITO
// pela mão do filho, e Davi entra na corte do rei que ele há de suceder: fica
// seu pajem de armas, acha graça aos olhos dele — e quando o espírito mau vinha,
// tomava a harpa, "então Saul SENTIA ALÍVIO, e se achava melhor".
//
// A VOZ DE DEUS (regra do projeto): neste trecho o SENHOR fala das duas formas.
// SEM MEDIADOR — `by:"deus"`, glória alta e nenhuma figura dourada em cena — em
// 15:11 (a palavra da noite a Samuel, sozinho no escuro) e em 16:1,2,3,7,12 (a
// missão a Belém e o veredicto sobre cada filho de Jessé). 15:10 é NARRAÇÃO pura
// ("veio a palavra do Senhor a Samuel, dizendo:" — o versículo acaba nos dois
// pontos e não traz fala): fica sem balão, só com a glória subindo na noite, e a
// fala entra no v.11. Onde a palavra do SENHOR passa pela BOCA DE SAMUEL — 15:1,
// 2, 3 ("assim diz o Senhor dos Exércitos" é ele quem diz), 15:16-19, 22-23, 26,
// 28-29, 33 e 16:5,6,8-11 — o balão é DO PROFETA (`by:"patriarca"`), nunca voz
// do céu. A CAPA RASGADA (15:27) não vira prop: não há no motor peça alguma que
// não mentisse sobre um manto, e forçar uma `tag` artificial é pior do que a
// cena honesta — o versículo é contado pela POSE (Saul de joelhos agarrado,
// Samuel já de saída, andando). O único fogo desenhado do trecho é o `altar` com
// `fire` do sacrifício de Belém: `env.fire` é só ambiência.
// ============================================================================

import type { StageScript, StageBeat, CastPlacement, StagePropSpec } from "@/lib/rpgStage";

const C = (role: string, dx: number, pose?: string, extra: Partial<CastPlacement> = {}): CastPlacement =>
  ({ role, dx, pose, ...extra });
const P = (kind: string, dx: number, scale = 1, fire?: number, dy?: number): StagePropSpec =>
  ({ kind, dx, scale, ...(fire != null ? { fire } : {}), ...(dy != null ? { dy } : {}) });
const b = (v: number, extra: Partial<StageBeat> = {}): StageBeat => ({ v, ...extra });

