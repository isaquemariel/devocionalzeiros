// ============================================================================
// 1 SAMUEL 29–31 — CENA VIVA. A dispensa de AFEQUE, o fogo de ZICLAGUE e a
// noite de GILBOA: o fecho do livro, com Davi salvando tudo e Saul perdendo
// tudo no mesmo par de dias.
//
// 1Sm 29 — Os filisteus ajuntam TODOS os seus exércitos em AFEQUE, e Israel se
// acampa junto à FONTE que está em JIZREEL. Os príncipes passam em revista com
// CENTENAS e com MILHARES — e, na RETAGUARDA, atrás de tudo, vêm Davi e os
// seus homens marchando com AQUIS. A pergunta cai como pedra: "que fazem aqui
// estes hebreus?". Aquis defende o seu vassalo com a lealdade sincera de quem
// nunca entendeu quem hospedava — "não é este Davi, o servo de Saul... coisa
// nenhuma achei nele desde o dia em que se revoltou, até ao dia de hoje". Mas
// os príncipes se indignam e dão o argumento que ninguém consegue responder:
// faze-o voltar, "pois, com que poderia este agradar a seu Senhor? Porventura
// não seria com as cabeças destes homens?". E então o canto das mulheres, que
// já custara a Davi o favor de Saul, o condena outra vez, agora do lado
// inimigo: "Saul feriu os seus milhares, porém Davi os seus dez milhares". A
// dispensa vem embrulhada em elogio — "tu és reto... aos meus olhos és bom
// como um anjo de Deus" — e com ordem de partir de MADRUGADA, havendo luz. É
// providência vestida de política: Deus tira Davi do campo em que ele teria de
// erguer a espada contra o próprio povo, e o tira pela boca dos que o odeiam.
//
// 1Sm 30 — A conta chega ao TERCEIRO DIA: ZICLAGUE QUEIMADA A FOGO, as
// mulheres e os filhos levados cativos pelos amalequitas — e, detalhe que só
// se enxerga depois, A NINGUÉM MATARAM. Davi e o povo choram até que neles não
// houve mais forças para chorar. As duas mulheres de Davi, AINOÃ e ABIGAIL,
// estão entre as cativas. E a amargura vira ameaça: o povo fala de
// APEDREJÁ-LO. A frase que salva o capítulo é a menor dele — "todavia Davi se
// fortaleceu no Senhor seu Deus". Pede o ÉFODE a ABIATAR e consulta: perseguirei
// eu a esta tropa? alcançá-la-ei? A resposta é limpa: "persegue-a, porque
// decerto a alcançarás e tudo libertarás". Seiscentos partem; no RIBEIRO DE
// BESOR duzentos ficam, cansados demais para passar, e quatrocentos seguem. No
// campo acham um EGÍPCIO abandonado pelo seu senhor amalequita, três dias e
// três noites sem pão nem água; pão, água, massa de figos e dois cachos de
// passas lhe voltam o espírito, e sob juramento ele guia. O bando está
// espalhado sobre a face de TODA a terra — comendo, bebendo e dançando pelo
// grande despojo. Davi os fere do crepúsculo até à tarde do dia seguinte;
// escapam só quatrocentos moços em CAMELOS. E o texto faz questão do inventário
// da graça: "ninguém lhes faltou, desde o menor até ao maior... tudo Davi
// tornou a trazer". No caminho de volta, os FILHOS DE BELIAL querem negar
// despojo aos duzentos cansados, e Davi funda ali um ESTATUTO E DIREITO em
// Israel até ao dia de hoje: "qual é a parte dos que desceram à peleja, tal
// também será a parte dos que ficaram com a bagagem". Depois manda bênção do
// despojo aos ANCIÃOS DE JUDÁ, de BETEL a HEBROM — a política paciente de um
// rei que ainda não é rei.
//
// 1Sm 31 — GILBOA. No mesmo relógio em que Davi recupera tudo, Saul perde
// tudo. Israel foge e cai morto na montanha; os filisteus alcançam Saul e os
// seus filhos e matam JÔNATAS, ABINADABE e MALQUISUA. A peleja se agrava, os
// FLECHEIROS o alcançam, e o rei pede ao PAJEM DE ARMAS o golpe que o poupe do
// escárnio dos incircuncisos. O pajem não quis, porque temia muito — e Saul
// toma a espada e se lança sobre ela; o pajem morre com ele. "Assim faleceu
// Saul, e seus três filhos, e o seu pajem de armas, e também todos os seus
// homens morreram juntamente naquele dia." As cidades do vale e do Jordão são
// abandonadas, e os filisteus habitam nelas. No dia seguinte cortam a cabeça de
// Saul, mandam as armas por toda a terra a anunciá-lo no templo dos ídolos,
// põem as armas na CASA DE ASTAROTE e AFIXAM O CORPO NO MURO DE BETE-SÃ. O
// último gesto do livro é de gratidão: os valentes de JABES-GILEADE — a cidade
// que Saul salvou no seu primeiro dia de rei (cap. 11) — caminham a noite
// toda, tiram os corpos do muro, os queimam em Jabes, sepultam os ossos debaixo
// de um ARVOREDO e jejuam sete dias. A dívida do primeiro capítulo do reinado é
// paga no último.
//
// A VOZ DE DEUS (regra do projeto): neste trecho o SENHOR fala UMA única vez —
// 30:8, a resposta ao éfode. Não há mediador humano falando: Abiatar traz o
// éfode e CALA; a palavra vem sem boca em cena. Por isso ali, e só ali, é
// `by:"deus"`, com `env.glory` em 0.9, nenhuma figura dourada no palco e
// Abiatar de pé segurando o éfode ao lado de Davi ajoelhado. Em todo o resto
// quem fala é gente: Aquis, os príncipes, Davi, o moço egípcio, os filhos de
// Belial, Saul. Em 30:6 Deus não fala — Davi se fortalece NELE, e isso é glória
// subindo no ambiente com Davi de joelhos, nunca balão.
// FOGO: só os `campfire` desenham chama de verdade — as fogueiras entre as
// casas arruinadas de Ziclague (30:1-6), as do arraial amalequita em festa
// (30:16-17) e a de Jabes no jejum (31:13). `env.fire` é só ambiência e não
// acende nada.
// LUTO: o capítulo 31 é luto puro e NÃO usa `multidao` em beat nenhum — a
// multidão é sempre desenhada comemorando, de braços erguidos, e Gilboa é o
// avesso exato da festa de Gilgal do cap. 11. Ali só figuras individuais em
// `lie`, `bow` e `kneel`, com `night` alto, `storm` presente e `glory` no chão.
// ============================================================================

