// definitiva: "bendito sejas tu, meu filho Davi" — cada um segue o seu
// caminho, e não tornam a ver-se.
//
// A VOZ DE DEUS (regra do projeto): nestes DOIS capítulos DEUS NÃO FALA — não
// há um só balão `by:"deus"` aqui, e isso é proposital. Ele AGE, e a cena
// mostra a ação pelo AMBIENTE, nunca por voz do céu: em 25:38 ("feriu o Senhor
// a Nabal") o palco escurece com `storm` alto e um `glory` frio de juízo sobre
// o homem em `lie`; em 26:12 ("da parte do Senhor havia caído sobre eles um
// profundo sono") a `night` vai a 0.92 e uma `glory` baixa e estranha cobre o
// arraial inteiro deitado. Onde a palavra do SENHOR aparece, ela vem de BOCA
// HUMANA e o balão é da pessoa: a profecia de ABIGAIL (25:26-31, `mulherComum`)
// e o juramento de DAVI pelo ungido (26:9-11,23, `homem`).
// FOGO: só o `campfire` do banquete de Nabal e os do arraial de Haquilá
// desenham chama — `env.fire` é apenas ambiência.
// ============================================================================

import type { StageScript, StageBeat, CastPlacement, StagePropSpec } from "@/lib/rpgStage";

const C = (role: string, dx: number, pose?: string, extra: Partial<CastPlacement> = {}): CastPlacement =>
  ({ role, dx, pose, ...extra });
const P = (kind: string, dx: number, scale = 1, fire?: number, dy?: number): StagePropSpec =>
  ({ kind, dx, scale, ...(fire != null ? { fire } : {}), ...(dy != null ? { dy } : {}) });
const b = (v: number, extra: Partial<StageBeat> = {}): StageBeat => ({ v, ...extra });
// (sem `dv` aqui: em 1Sm 25–26 Deus não fala — Ele age, e a ação é ambiente.)

