// dos criados de meu senhor". O capítulo fecha com duas notas secas: Ainoã de
// Jizreel também é mulher de Davi, e MICAL, mulher de Davi, foi dada por Saul
// a Palti, filho de Laís, de Galim.
//
// 1Sm 26 — Os ZIFEUS delatam outra vez, agora em GIBEÁ: Davi está escondido no
// OUTEIRO DE HAQUILÁ, defronte de Jesimom. Saul desce com TRÊS MIL ESCOLHIDOS
// e acampa junto ao caminho; Davi, do alto, VÊ o lugar e manda espias. De
// noite ele desce ao arraial com ABISAI, filho de Zeruia (Aimeleque, o heteu,
// é convidado e cala). Saul dorme DENTRO DO LUGAR DOS CARROS, A LANÇA FINCADA
// NA TERRA À SUA CABECEIRA, Abner e o povo deitados em roda. Abisai vê nisso a
// entrega de Deus: "deixa-me encravá-lo com a lança DE UMA VEZ, e não o
// ferirei segunda vez". A recusa de Davi é a espinha dorsal do capítulo: QUEM
// ESTENDEU A SUA MÃO CONTRA O UNGIDO DO SENHOR, E FICOU INOCENTE? O SENHOR o
// ferirá, ou o seu dia chegará, ou descerá para a batalha e perecerá — mas não
// a minha mão. Levam a LANÇA e a BILHA DE ÁGUA da cabeceira, e ninguém acorda,
// porque DA PARTE DO SENHOR caíra sobre eles um PROFUNDO SONO. Do CUME DO
// MONTE, ao longe, Davi brada a ABNER: "não és tu homem? e quem há em Israel
// como tu? por que não guardaste o rei, teu senhor?… sois dignos de morte" —
// e a prova está na sua mão. Saul reconhece a voz: "não é esta a tua voz, meu
// filho Davi?". Davi alega a expulsão da HERANÇA DO SENHOR e o absurdo da
// caçada: "saiu o rei de Israel em busca de UMA PULGA, como quem persegue uma
// PERDIZ nos montes". Saul confessa: "PEQUEI… procedi loucamente, e errei
