// de Saul no outeiro de HAQUILÁ.
//
// 1Sm 25 — O capítulo abre com um enterro: FALECE SAMUEL, e TODO O ISRAEL se
// ajunta, o pranteia e o sepulta NA SUA CASA, EM RAMÁ — o último elo entre
// Davi e a autoridade profética se rompe, e Davi se levanta e DESCE AO DESERTO
// DE PARÃ. Em MAOM há um homem com possessões no CARMELO: TRÊS MIL OVELHAS E
// MIL CABRAS, riquíssimo — NABAL, "duro e maligno nas obras", da casa de
// Calebe; a mulher dele, ABIGAIL, é "de bom entendimento e formosa". É tempo
// de TOSQUIA (tempo de banquete e de fartura), e Davi manda DEZ MOÇOS com uma
// saudação de paz tripla: "paz tenhas, e que a tua casa tenha paz, e tudo o
// que tens tenha paz". O pedido é humilde — os pastores de Nabal estiveram com
// os homens de Davi e nada lhes faltou; dá, pois, o que achares à mão. A
// resposta é o desprezo: "QUEM É DAVI, E QUEM É O FILHO DE JESSÉ?… tomaria eu
// o meu pão, e a minha água, e a carne das minhas reses… e o daria a homens
// que eu não sei donde vêm?". Davi cinge a espada, e QUATROCENTOS sobem atrás
// dele. Um dos moços corre a Abigail com o testemunho que salva a casa: "DE
// MURO EM REDOR NOS SERVIRAM, assim de dia como de noite". Abigail se apressa:
// duzentos pães, dois odres de vinho, cinco ovelhas guisadas, cinco medidas de
// trigo tostado, cem cachos de passas, duzentas pastas de figos — tudo sobre
// jumentos, E NÃO DECLAROU A SEU MARIDO. No ENCOBERTO DO MONTE ela topa com a
// coluna armada, desce do jumento e se prostra com o rosto em terra. O
// discurso dela é PROFECIA: o SENHOR fará casa firme a meu senhor, porque meu
// senhor guerreia as guerras do SENHOR; a vida de meu senhor será ATADA NO
// FEIXE DOS QUE VIVEM com o SENHOR teu Deus, e a dos teus inimigos ele
// arrojará ao longe COMO DO MEIO DO CÔNCAVO DE UMA FUNDA (a imagem é a arma do
// próprio Davi, virada contra o inimigo por Deus, não por ele). Davi a bendiz
// — "bendito o teu conselho, e bendita tu" — e aceita a face dela. Em casa,
// NABAL BANQUETEIA COMO REI, alegre e embriagado; ela cala até à luz da manhã.
// Pela manhã, sem o vinho, ouve tudo: amortece-se-lhe o coração E FICA COMO
