// e a ORLA DO MANTO cortada na caverna de EN-GEDI.
//
// 1Sm 22 — Fugido de Gate, Davi escapa para a CAVERNA DE ADULÃO, e a primeira
// gente que desce a ele é a sua própria casa: os irmãos e o pai. Depois vem o
// resto — "todo o homem que se achava em aperto, e todo o homem endividado, e
// todo o homem de espírito desgostoso": quatrocentos falidos e amargurados, e o
// ungido do SENHOR por CAPITÃO deles. Antes de tudo Davi cuida dos velhos: leva
// pai e mãe a MIZPÁ DOS MOABITAS e os deixa aos cuidados do rei "até que saiba
// o que Deus há de fazer de mim". O profeta GADE o tira do lugar forte — "vai,
// e entra na terra de Judá" — e Davi entra no BOSQUE DE HERETE. Do outro lado,
// SAUL está sentado em GIBEÁ, debaixo de um arvoredo, no outeiro, COM A LANÇA
// NA MÃO e todos os criados em roda; e o discurso é o de um homem que já não
// confia em ninguém: prometei-vos terras e vinhas o filho de Jessé? ninguém há
// que me dê aviso, ninguém que se doa de mim. Então DOEGUE, O EDOMEU, abre a
// boca e conta o que viu em NOBE: o filho de Jessé chegou a Aimeleque, que
// consultou por ele ao SENHOR, deu-lhe mantimento e a ESPADA DE GOLIAS. O rei
// manda chamar o sacerdote e TODA A CASA DE SEU PAI, e Aimeleque responde com
// a coragem dos inocentes: "quem, entre todos os teus criados, há tão fiel como
// Davi… o teu servo não soube nada de tudo isso, nem muito nem pouco". A
// sentença cai mesmo assim; mas ⭐ OS CRIADOS DO REI NÃO QUISERAM ESTENDER AS
// MÃOS contra os sacerdotes do SENHOR — e é o estrangeiro que se vira e mata
// sozinho OITENTA E CINCO HOMENS QUE VESTIAM ÉFODE DE LINHO, e depois passa a
// cidade inteira a fio de espada, "desde o homem até à mulher, desde os meninos
// até aos de peito, e até os bois, jumentos e ovelhas". Escapa um só: ABIATAR,
// filho de Aimeleque, que foge para Davi — e Davi toma a culpa sobre si: "eu
// dei ocasião contra todas as almas da casa de teu pai. Fica comigo, não temas".
//
// 1Sm 23 — Chega a notícia: os filisteus pelejam contra QUEILA e SAQUEIAM AS
// EIRAS. Davi CONSULTA o SENHOR e ouve "vai"; os homens têm medo, e ele
