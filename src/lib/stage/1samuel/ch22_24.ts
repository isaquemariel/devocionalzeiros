// caçada aperta no deserto de MAOM, com Saul de um lado do monte e Davi do
// outro, já cercado — e no último instante chega um mensageiro: "apressa-te…
// os filisteus com ímpeto entraram na terra". O lugar ficou chamado ROCHEDO DAS
// DIVISÕES, e Davi subiu aos lugares fortes de EN-GEDI.
//
// 1Sm 24 — Voltando dos filisteus, Saul toma TRÊS MIL ESCOLHIDOS e sobe aos
// cumes das PENHAS DAS CABRAS MONTESAS. No caminho há uns currais de ovelhas e
// uma CAVERNA; Saul entra nela a cobrir os pés — e Davi e os seus homens estão
// nos fundos. Os homens sussurram que é o dia entregue pelo SENHOR; Davi
// levanta-se e MANSAMENTE CORTA A ORLA DO MANTO — e depois o coração lhe dói,
// por ter cortado a orla do manto do ungido. Contém os homens, e deixa Saul
// sair. Então grita da boca da caverna: "REI, MEU SENHOR!", e se prostra com o
// rosto em terra. O discurso é inteiro: por que dás ouvidos aos que dizem que
// Davi procura o teu mal? eis a orla do teu manto NA MINHA MÃO — cortei-a e não
// te matei. "Julgue o Senhor entre mim e ti… porém a minha mão não será contra
// ti"; "dos ímpios procede a impiedade"; "após quem saiu o rei de Israel? a quem
// persegues? a um cão morto? a uma pulga?". E Saul levanta a voz e CHORA: "mais
// justo és do que eu, pois tu me recompensaste com bem… bem sei que certamente
// hás de reinar" — e faz jurar que Davi não desarraigará a sua descendência
// depois dele. Então cada um segue o seu caminho: Saul para casa, Davi para o
// lugar forte.
//
// A VOZ DE DEUS (regra do projeto): neste trecho o SENHOR fala em QUATRO beats
// e só neles — 23:2, 23:4, 23:11 e 23:12. Em todos, o texto diz "e disse o
// Senhor" sem boca humana na frase: é ORÁCULO, e por isso `by:"deus"`, com
// `env.glory` no alto e NENHUMA figura dourada em cena. ABIATAR fica no elenco
// segurando o ÉFODE (o `censer` com tag `efode-de-abiatar`) porque é por ele
// que Davi pergunta — mas o balão não sai do sacerdote: o éfode é o meio de
// consulta, não um mediador que fala. Fora desses quatro, tudo o que se diz
// sobre Deus está em boca de gente: Gade (22:5) fala como profeta e o balão é
// dele; Saul (23:7) atribui a Deus a sua própria caçada; Jônatas (23:17) e Davi
// (24:6,12,15) falam do SENHOR em terceira pessoa. Nenhum desses é voz do céu.
// FOGO: nenhum é desenhado aqui — o altar de Nobe aparece com brasa baixa antes
// do juízo e APAGADO depois; `env.fire` é só ambiência.
// ============================================================================

import type { StageScript, StageBeat, CastPlacement, StagePropSpec } from "@/lib/rpgStage";

const C = (role: string, dx: number, pose?: string, extra: Partial<CastPlacement> = {}): CastPlacement =>
  ({ role, dx, pose, ...extra });
const P = (kind: string, dx: number, scale = 1, fire?: number, dy?: number): StagePropSpec =>
  ({ kind, dx, scale, ...(fire != null ? { fire } : {}), ...(dy != null ? { dy } : {}) });
const b = (v: number, extra: Partial<StageBeat> = {}): StageBeat => ({ v, ...extra });

