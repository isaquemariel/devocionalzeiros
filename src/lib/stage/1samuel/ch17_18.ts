// 1 SAMUEL 17–18 — CENA VIVA. GOLIAS DE GATE e a funda do pastor; e depois do
// duelo, a ALMA DE JÔNATAS ligada à de Davi e a LANÇA de Saul contra a parede.
//
// 1Sm 17 — Os filisteus ajuntam as suas forças em SOCÓ de Judá e acampam entre
// Socó e Azeca, no termo de DAMIM; Saul e os homens de Israel acampam no VALE
// DO CARVALHO. Um monte de um lado, outro monte do outro — E O VALE ESTAVA
// ENTRE ELES. Do arraial filisteu sai o HOMEM GUERREIRO: GOLIAS, DE GATE, seis
// côvados e um palmo de altura, capacete de bronze na cabeça, couraça de
// escamas de cinco mil siclos, grevas de bronze por cima dos pés, escudo de
// bronze entre os ombros, a haste da lança como o EIXO DO TECELÃO e a ponta de
// seiscentos siclos de ferro — e diante dele ia o ESCUDEIRO. O desafio é o
// mesmo todos os dias: "escolhei dentre vós um homem que desça a mim… se eu o
// vencer, a nós sereis por servos". Saul e todo o Israel se espantam e temem
// muito, e o filisteu se apresenta PELA MANHÃ E À TARDE, POR QUARENTA DIAS.
// Longe dali, em BELÉM, JESSÉ, o efrateu, já velho, tem oito filhos: os três
// mais velhos — ELIABE, ABINADABE e SAMA — seguiram a Saul à guerra, e o menor
// ia e voltava para apascentar as ovelhas. Jessé o manda ao arraial com um EFA
// DE GRÃO TOSTADO, DEZ PÃES para os irmãos e DEZ QUEIJOS DE LEITE para o
// capitão de mil. Davi se levanta de madrugada, deixa as ovelhas com um guarda,
// chega ao lugar dos carros quando o exército saía em ordem de batalha, deixa a
// carga na mão do GUARDA DA BAGAGEM e CORRE à peleja. Ouve o desafio, vê Israel
// fugir, e pergunta pelo prêmio — grandes riquezas, a filha do rei, a casa do
// pai livre em Israel — e pergunta a coisa que ninguém perguntou: "QUEM É, POIS,
// ESTE INCIRCUNCISO FILISTEU, PARA AFRONTAR OS EXÉRCITOS DO DEUS VIVO?". A ira
// de Eliabe se acende ("com quem deixaste aquelas poucas ovelhas no deserto?"),
// mas as palavras chegam a Saul. Diante do rei, o argumento não é bravata, é
// memória de pastor: o LEÃO e o URSO, a barba agarrada, a ovelha tirada da boca
// — "o Senhor me livrou das garras do leão, e das do urso; ele me livrará da
// mão deste filisteu". Saul o veste das suas vestes, do capacete de bronze e da
// couraça; Davi cinge a espada, tenta andar, e tira aquilo de sobre si: NUNCA O
// EXPERIMENTARA. Toma o CAJADO, escolhe CINCO SEIXOS DO RIBEIRO, põe-nos no
// alforje de pastor e lança mão da FUNDA. O gigante o despreza — moço, ruivo, de
// gentil aspecto — e o amaldiçoa pelos seus deuses: "sou eu algum cão, para tu
// vires a mim com paus?". E vem a resposta que é o coração do livro inteiro: ⭐
// "TU VENS A MIM COM ESPADA, E COM LANÇA, E COM ESCUDO; PORÉM EU VENHO A TI EM
// NOME DO SENHOR DOS EXÉRCITOS… E SABERÁ TODA ESTA CONGREGAÇÃO QUE O SENHOR
// SALVA, NÃO COM ESPADA, NEM COM LANÇA; PORQUE DO SENHOR É A GUERRA". Davi
// APRESSA-SE e CORRE ao combate, a pedra se encrava na testa do filisteu, e o
// gigante cai SOBRE O SEU ROSTO EM TERRA — sem que Davi tivesse uma espada na
// mão. Então Davi corre, põe-se em pé sobre ele, tira a ESPADA DA BAINHA e lhe
// corta com ela a cabeça. Os filisteus fogem; Israel os persegue pelo caminho de
// Saaraim até Gate e até Ecrom, e volta a despojar os arraiais. A cabeça vai a
// Jerusalém, as armas ficam na tenda de Davi — e Saul, que o vira sair, pergunta
// a ABNER: "de quem é filho este moço?".
//
// 1Sm 18 — Acabando ele de falar com Saul, A ALMA DE JÔNATAS SE LIGOU COM A
// ALMA DE DAVI, e o filho do rei o amou como à sua própria alma: fazem ALIANÇA,
// e Jônatas se despoja da CAPA que trazia sobre si, das VESTES, até da ESPADA,
// do ARCO e do CINTO, e dá tudo ao pastor. Davi sai aonde quer que Saul o envie
// e se conduz com prudência; é posto sobre os homens de guerra, aceito aos olhos
// de todo o povo e até dos servos do rei. Mas na volta da peleja as MULHERES DE
// TODAS AS CIDADES saem ao encontro do rei com ADUFES, com alegria e com
// instrumentos de música, e cantam respondendo umas às outras: ⭐ "SAUL FERIU OS
// SEUS MILHARES, PORÉM DAVI OS SEUS DEZ MILHARES". Aquela palavra parece mal aos
// olhos de Saul: "que lhe falta, senão só o reino?" — e desde aquele dia em
// diante ele tem Davi em suspeita, olhando-o de esguelha. No outro dia o mau
// espírito se apodera do rei; Davi toca a harpa como nos outros dias, Saul tem
// na mão uma LANÇA e a atira: "encravarei a Davi na parede" — e Davi se desvia
// dele POR DUAS VEZES. Saul teme a Davi, PORQUE O SENHOR ERA COM ELE E SE TINHA
// RETIRADO DE SAUL; então o desvia de si e o põe por CAPITÃO DE MIL — promoção
// que é armadilha, para que caia pela mão dos filisteus. MERABE, a filha mais
// velha, é prometida e dada a outro, a Adriel, o meolatita. MICAL ama a Davi, e
// o rei vê nisso um LAÇO: o dote não é dinheiro, são CEM PREPÚCIOS DE FILISTEUS
// — o preço que devia matá-lo. Davi parte e traz DUZENTOS, e o rei lhe dá a
// filha por mulher. E o capítulo fecha ao contrário do que Saul queria: ele viu
// que o SENHOR era com Davi, TEMEU MUITO MAIS, e foi todos os seus dias inimigo
// dele — enquanto o nome de Davi era MUITO ESTIMADO.
//
// A VOZ DE DEUS (regra do projeto): nestes dois capítulos o SENHOR NÃO FALA —
// nem do céu, nem por mediador. Não há um único `by:"deus"` aqui, e isso é
// deliberado: TODA a teologia do trecho sai da BOCA DE DAVI (17:26,36,37,45-47)
// e da constatação do narrador (18:12,14,28 — "o Senhor era com ele"). O que o
// palco faz no lugar de uma voz é a GLÓRIA: ela sobe quando Davi nomeia o Deus
// vivo e chega ao auge em 17:45-47 e 17:49, e desaba (night alto, glory baixo)
// quando o medo governa o arraial (17:11,24) ou quando o ciúme governa o rei
// (18:8-11,29). FOGO desenhado só pelo `campfire` dos arraiais — `env.fire` é
// ambiência. Golias é sempre `homem` com `scale` 2.0–2.2 e `dy` mais à frente
// que os israelitas: a diferença de tamanho tem de ser vista, não explicada.
// ============================================================================

