// ============================================================================
// 1 SAMUEL 19–21 — CENA VIVA. A CAÇADA COMEÇA: a lança contra a parede, a
// janela de Mical, o campo das três flechas e o pão sagrado de Nobe.
//
// 1Sm 19 — Saul deixa de disfarçar: fala a JÔNATAS e a todos os seus servos
// PARA QUE MATASSEM A DAVI. Mas o filho está "mui afeiçoado" ao genro do pai, e
// o avisa: guarda-te pela manhã, esconde-te; eu estarei à mão de meu pai no
// campo e falarei de ti. E fala — a mais limpa intercessão do livro: ⭐ "NÃO
// PEQUE O REI CONTRA SEU SERVO DAVI, porque ele não pecou contra ti"; expôs a
// sua vida, feriu os filisteus, o SENHOR fez por ele um grande livramento a
// todo o Israel — TU MESMO O VISTE, E TE ALEGRASTE. Saul dá ouvidos e jura:
// "VIVE O SENHOR, QUE NÃO MORRERÁ". A paz dura o tempo de uma guerra: Davi sai,
// fere os filisteus com grande matança — e o ESPÍRITO MAU torna sobre Saul, que
// está assentado em casa COM A LANÇA NA MÃO enquanto Davi toca a harpa. A lança
// voa, crava a PAREDE, e Davi escapa naquela mesma noite. Saul cerca a casa; e
// então MICAL, sua própria filha, desce o marido POR UMA JANELA, toma uma
// ESTÁTUA (os terafins domésticos), deita-a na cama, põe-lhe à cabeceira uma
// PELE DE CABRA e a cobre com uma coberta. Aos mensageiros: "está doente". A
// Saul: "ele me disse: DEIXA-ME IR, POR QUE HEI DE EU MATAR-TE?". Davi foge a
// RAMÁ, a SAMUEL, e os dois ficam em NAIOTE. Saul manda buscá-lo três vezes, e
// três vezes os mensageiros, ao ver a congregação de profetas com Samuel
// presidindo, começam eles mesmos a PROFETIZAR. Por fim vai ele — pergunta no
// POÇO GRANDE DE SECU, e no caminho o mesmo Espírito o alcança: despe as
// vestes, profetiza diante de Samuel e fica NU POR TERRA todo aquele dia e toda
// aquela noite. Donde o provérbio: ⭐ "ESTÁ TAMBÉM SAUL ENTRE OS PROFETAS?".
//
// 1Sm 20 — Davi foge de Naiote e procura o amigo com a pergunta de quem já não
// entende a própria vida: "QUE FIZ EU? QUAL É O MEU CRIME?"; e, jurando, ⭐ "HÁ
// APENAS UM PASSO ENTRE MIM E A MORTE". Jônatas não acredita — o pai nada faz
// sem lhe informar. Combinam a prova: amanhã é a LUA NOVA, e Davi, que costuma
// assentar-se com o rei, se esconderá no campo até à tarde do terceiro dia; se
// Saul perguntar, Jônatas dirá que ele desceu a BELÉM ao sacrifício anual da
// linhagem. Saem ambos ao campo e renovam a ALIANÇA: "o Senhor Deus de Israel
// seja testemunha!" — e o pedido que atravessará o livro de Samuel inteiro até
// Mefibosete: ⭐ "NEM TAMPOUCO CORTARÁS DA MINHA CASA A TUA BENEFICÊNCIA
// ETERNAMENTE". O sinal serão TRÊS FLECHAS e o que Jônatas gritar ao moço que
// as for buscar: "para cá de ti" é paz; "PARA LÁ DE TI" é fuga. À mesa da lua
// nova o assento de Davi aparece vazio dois dias; ao segundo, Saul pergunta, e
// à resposta do filho se acende: "FILHO DA MULHER PERVERSA E REBELDE… enquanto o
// filho de Jessé viver sobre a terra, NEM TU ESTARÁS SEGURO, NEM O TEU REINO" —
// e atira A LANÇA contra o próprio filho. Jônatas se levanta da mesa TODO
// ENCOLERIZADO e não come pão, magoado por causa de Davi. Pela manhã, o campo:
// o moço corre, a flecha passa além dele, o grito combinado cai como sentença,
// e o menino volta com as armas sem entender coisa alguma. Então os dois a sós:
// Davi se levanta do LADO DO SUL, prostra-se e se inclina TRÊS VEZES, beijam-se
// e choram juntos — MAS DAVI CHOROU MUITO MAIS. "Vai-te em paz: ⭐ O SENHOR
// SEJA ENTRE MIM E TI, E ENTRE A MINHA DESCENDÊNCIA E A TUA DESCENDÊNCIA."
//
// 1Sm 21 — Davi chega SÓ a NOBE, a cidade dos sacerdotes, e AIMELEQUE sai ao
// encontro TREMENDO: "por que vens só, e ninguém contigo?". Davi mente — o rei
// me encomendou um negócio secreto — e pede pão. Não há pão comum: há PÃO
// SAGRADO, os PÃES DA PROPOSIÇÃO tirados de diante do SENHOR, e o sacerdote os
// dá sob a condição da pureza dos moços (o mesmo episódio que o Senhor Jesus
// citaria em Mt 12:3-4). E ali, naquele dia, estava DETIDO PERANTE O SENHOR um
// criado de Saul: DOEGUE, o edomeu, o mais poderoso dos pastores do rei — a
// testemunha calada que, dois capítulos adiante, custará oitenta e cinco
// sacerdotes e a cidade inteira. Davi pede também arma, e ouve a resposta que
// fecha o círculo do vale do carvalho: ⭐ "A ESPADA DE GOLIAS, O FILISTEU… ESTÁ
// AQUI ENVOLTA NUM PANO DETRÁS DO ÉFODE" — "não há outra semelhante; dá-ma".
// Com a espada do gigante na mão, o ungido foge para a cidade do gigante: GATE,
// a Aquis. Os criados o reconhecem — "não é este Davi, o rei da terra? não se
// cantava deste nas danças?" — e o medo faz o resto: ⭐ DAVI SE FINGE DOIDO,
// ESGRAVATA NAS PORTAS DE ENTRADA e deixa correr a saliva pela barba, até Aquis
// despachá-lo com desprezo: "faltam-me a mim doidos?".
//
// A VOZ DE DEUS (regra do projeto): nestes três capítulos DEUS NÃO FALA — não
// há um só balão `by:"deus"`, e isso é próprio do trecho: o SENHOR age em
// silêncio. Em 19:20-24 o ESPÍRITO DE DEUS vem sobre os mensageiros e sobre o
// próprio Saul SEM UMA PALAVRA — por isso a cena é dita só com `env.glory` no
// auge e as figuras em `raise`, com `glow` em Samuel (o profeta que preside),
// nunca com voz do céu. Em 19:9 o "espírito mau da parte do Senhor" é o
// contrário exato: `night` e `storm` altos, `glory` no chão, e NENHUM `glow` em
// Saul. Onde o nome do SENHOR aparece (o juramento de 19:6, a aliança de
// 20:12-23,42), quem fala é o HOMEM que jura — o balão sai de Saul ou de
// Jônatas, jamais do céu.
// FOGO: nenhum destes capítulos tem chama de verdade — não há `campfire`,
// `pillar` nem `altar` com `fire`; o `altar` de Nobe está apagado, servindo à
// mesa dos pães. Onde há `env.fire`, é só ambiência de lucerna e de ira.
// ARMAS: o motor não tem prop de lança, de espada nem de flecha — o mais
// próximo de uma haste é `rod`, e é ele que faz, sempre COM `tag` própria, a
// lança de Saul, as três flechas de Jônatas e a espada de Golias.
// ============================================================================

import type { StageScript, StageBeat, CastPlacement, StagePropSpec } from "@/lib/rpgStage";

const C = (role: string, dx: number, pose?: string, extra: Partial<CastPlacement> = {}): CastPlacement =>
  ({ role, dx, pose, ...extra });
const P = (kind: string, dx: number, scale = 1, fire?: number, dy?: number): StagePropSpec =>
  ({ kind, dx, scale, ...(fire != null ? { fire } : {}), ...(dy != null ? { dy } : {}) });
const b = (v: number, extra: Partial<StageBeat> = {}): StageBeat => ({ v, ...extra });
// (sem `dv` aqui: em 1Sm 19–21 Deus NÃO fala — nenhum beat leva `by:"deus"`.)

