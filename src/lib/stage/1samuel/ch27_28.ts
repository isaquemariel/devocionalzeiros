// 1 SAMUEL 27–28 — CENA VIVA. A FUGA DE DAVI PARA GATE e a NOITE DE EN-DOR: os
// dois capítulos em que o herói se esconde na mentira e o rei rejeitado bate à
// porta dos mortos.
//
// 1Sm 27 — Depois de poupar Saul pela segunda vez em Haquilá, Davi não fala com
// Deus: fala CONSIGO MESMO. ⭐ "DISSE, PORÉM, DAVI NO SEU CORAÇÃO: ora, algum
// dia ainda perecerei pela mão de Saul; não há coisa melhor para mim do que
// escapar apressadamente para a terra dos filisteus" — é uma decisão de MEDO, e
// o texto a registra sem uma palavra de elogio: nem oráculo, nem éfode, nem
// Gade. Levanta-se e PASSA, com os SEISCENTOS HOMENS, a AQUIS, FILHO DE MAOQUE,
// REI DE GATE — o mesmo Aquis diante de quem, no capítulo 21, ele se fingira
// louco. Desta vez vai com casa e família: cada um dos seus com a sua casa, e
// Davi com AMBAS AS SUAS MULHERES, AINOÃ, A JIZREELITA, e ABIGAIL, A MULHER DE
// NABAL, o carmelita. O cálculo dá certo: avisado de que Davi fugira para Gate,
// SAUL NÃO CUIDOU MAIS DE BUSCÁ-LO — a caçada acaba, mas acaba pelo lado errado.
// Davi pede a Aquis uma cidade DO CAMPO ("por que razão habitaria o teu servo
// contigo na cidade real?") e recebe ZICLAGUE — e o narrador levanta os olhos do
// tempo dele para o nosso: "POR ISSO ZICLAGUE PERTENCE AOS REIS DE JUDÁ, ATÉ AO
// DIA DE HOJE". Ali habita UM ANO E QUATRO MESES. E dali sai o lado sombrio do
// capítulo: sobe com os seus homens sobre os GESURITAS, os GERSITAS e os
// AMALEQUITAS, moradores antigos da terra na direção de SUR até ao EGITO; fere
// aquela terra e NÃO DÁ VIDA NEM A HOMEM NEM A MULHER — e volta com ovelhas,
// vacas, jumentos, camelos e vestes. Aquis pergunta "onde atacastes hoje?" e
// Davi mente com precisão de mapa: "sobre o sul de JUDÁ, sobre o sul dos
// JERAMEELITAS, sobre o sul dos QUENEUS". Não deixa vivo homem nem mulher
// justamente PARA QUE NINGUÉM O DENUNCIE — e este era o seu costume todos os
// dias em que habitou na terra dos filisteus. O capítulo fecha na ironia:
// ⭐ AQUIS CONFIAVA NELE — "fez-se ele por certo aborrecível para com o seu povo
// em Israel; por isso me será por servo para sempre".
//
// 1Sm 28 — Os filisteus ajuntam os exércitos, e a mentira cobra o preço: "SABE
// DE CERTO QUE COMIGO SAIRÁS AO ARRAIAL, TU E OS TEUS HOMENS" — e Aquis promete
// a Davi o posto de GUARDA DA SUA PESSOA para sempre. Então o narrador para a
// história e coloca duas lápides na estrada: SAMUEL JÁ ESTAVA MORTO, todo o
// Israel o chorara e o sepultara em RAMÁ, sua cidade; e SAUL TINHA DESTERRADO
// DA TERRA os adivinhos e os encantadores. Guarde as duas: o rei vai precisar do
// profeta que enterrou e do ofício que proibiu. Os filisteus acampam em SUNÉM,
// Israel em GILBOA; e vendo o arraial inimigo, Saul TEMEU E ESTREMECEU MUITO O
// SEU CORAÇÃO. Pergunta ao SENHOR — ⭐ "PORÉM O SENHOR NÃO LHE RESPONDEU, NEM
// POR SONHOS, NEM POR URIM, NEM POR PROFETAS": o céu fecha as três portas de uma
// vez. Então manda buscar UMA MULHER QUE TENHA O ESPÍRITO DE ADIVINHAR, e há uma
// em EN-DOR. SAUL SE DISFARÇA, veste outras roupas e vai DE NOITE com DOIS
// HOMENS. A mulher desconfia — "por que me armas um laço à minha vida, para me
// fazeres morrer?" — e o próprio rei que baniu os adivinhos jura PELO SENHOR
// que nenhum mal lhe sobrevirá. "A quem te farei subir?" — ⭐ "FAZE-ME SUBIR A
// SAMUEL". Ela GRITA COM ALTA VOZ, porque vê e reconhece o rei: "por que me tens
// enganado? pois tu mesmo és Saul". "Que é que vês?" — "VEJO DEUSES QUE SOBEM DA
// TERRA"; "como é a sua figura?" — "VEM SUBINDO UM HOMEM ANCIÃO, E ESTÁ ENVOLTO
// NUMA CAPA". Saul entende, inclina o rosto em terra e se prostra. E vem a
// palavra dura: "POR QUE ME INQUIETASTE, FAZENDO-ME SUBIR?". Saul se queixa —
// "Deus se tem desviado de mim, e não me responde mais" — e ouve a sentença: o
// SENHOR se fez teu INIMIGO, RASGOU O REINO DA TUA MÃO E O DEU AO TEU PRÓXIMO,
// A DAVI, porque não executaste o fervor da sua ira contra AMALEQUE. E o golpe
// final: ⭐ "AMANHÃ TU E TEUS FILHOS ESTAREIS COMIGO; e o arraial de Israel o
// Senhor entregará na mão dos filisteus". Saul cai ESTENDIDO POR TERRA, sem
// força nenhuma, porque não comera pão o dia todo nem a noite toda. E então
// acontece a coisa mais estranha do capítulo: a feiticeira proscrita tem
// COMPAIXÃO do rei que a proscreveu — mata depressa o BEZERRO CEVADO que tinha
// em casa, amassa farinha, coze BOLOS ÁZIMOS, e o rei e os seus criados comem e
// se levantam e partem NAQUELA MESMA NOITE.
//
// A VOZ DE DEUS (regra do projeto): neste trecho DEUS NÃO FALA — e é isso que
// tem de aparecer no palco. Em 1Sm 27 Davi decide sem consultar ninguém (nem
// éfode, nem profeta): `glory` no chão do começo ao fim. Em 1Sm 28 o silêncio é
// o próprio tema — 28:6 diz que o SENHOR não respondeu "nem por sonhos, nem por
// Urim, nem por profetas", e 28:15 é Saul se queixando disso. Por isso NÃO HÁ
// UM ÚNICO `by:"deus"` nestes dois capítulos, e `env.glory` fica em 0.04–0.08
// nos beats da consulta sem resposta. Na aparição de EN-DOR quem fala é SAMUEL,
// não Deus: `by:"patriarca"`, com a figura em cena (id `samuel-endor`), `glow`
// alto e uma luz que sobe MUITO POUCO e FRIA (0.16–0.24) — glória de juízo, não
// de bênção. FOGO: só o `campfire` do arraial e o da casa de En-Dor desenham
// chama; `env.fire` é ambiência. E a noite de En-Dor é `night` 0.86–0.94 com
// `moon`/`starfield` em `sky:true`, sobre terreno `field`/`city` — nunca
// `mountain`, que escureceria o céu e apagaria a leitura da cena.
// ============================================================================

import type { StageScript, StageBeat, CastPlacement, StagePropSpec } from "@/lib/rpgStage";

const C = (role: string, dx: number, pose?: string, extra: Partial<CastPlacement> = {}): CastPlacement =>
  ({ role, dx, pose, ...extra });
const P = (kind: string, dx: number, scale = 1, fire?: number, dy?: number): StagePropSpec =>
  ({ kind, dx, scale, ...(fire != null ? { fire } : {}), ...(dy != null ? { dy } : {}) });
const b = (v: number, extra: Partial<StageBeat> = {}): StageBeat => ({ v, ...extra });
// (sem `dv` aqui: em 1Sm 27–28 Deus está CALADO — nenhum beat usa by:"deus".)

